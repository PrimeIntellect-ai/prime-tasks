#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import hashlib
import os
import random
import re
import secrets
import sqlite3
import stat
import subprocess

import pytest

HOME = "/home/user"
DB = os.path.join(HOME, "data.db")
INPUT = os.path.join(HOME, "input.csv")
OUTPUT = os.path.join(HOME, "output.csv")
SOURCE = os.path.join(HOME, "process.c")
EXECUTABLE = os.path.join(HOME, "process")
COMPILED = "/tmp/process_from_submitted_source"

EXPECTED_ORIGINAL = (
    "user_id,login_count,purchase_count\n"
    "102,2,1\n"
    "104,2,1\n"
    "201,2,2\n"
    "202,2,2\n"
)


def normalized_output():
    assert os.path.isfile(OUTPUT), f"Output file missing at {OUTPUT}"
    with open(OUTPUT, "r", encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n").strip() + "\n"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def run_program(path, expected):
    before = sha256(DB)
    if os.path.exists(OUTPUT):
        os.remove(OUTPUT)
    subprocess.run([path], cwd=HOME, check=True, timeout=20)
    assert sha256(DB) == before, f"{path} modified the database"
    actual = normalized_output()
    assert actual == expected, (
        f"Output generated by {path} is incorrect.\n"
        f"Expected:\n{expected}\nActual:\n{actual}"
    )


def expected_original_rows():
    rows = []
    event_id = 1
    for user_id in [101, 102, 103, 104, 105, 201, 202]:
        events = [
            ("login", 1000),
            ("purchase", 1005),
            ("login", 1010),
            ("logout", 1015),
        ]
        if user_id > 200:
            events.append(("purchase", 1020))
        for event_type, timestamp in events:
            rows.append((event_id, user_id, event_type, timestamp))
            event_id += 1
    return rows


def validate_original_database():
    assert os.path.isfile(DB), f"Database file missing at {DB}"
    mode = oct(os.stat(DB).st_mode)[-3:]
    assert mode in ["444", "400", "644"], (
        "Database permissions suggest it might have been modified or recreated incorrectly"
    )

    conn = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    try:
        table_sql = conn.execute(
            "SELECT sql FROM sqlite_master WHERE type='table' AND name='events'"
        ).fetchone()
        index_sql = conn.execute(
            "SELECT sql FROM sqlite_master WHERE type='index' AND name='idx_user_event'"
        ).fetchone()
        assert table_sql is not None
        assert index_sql is not None
        rows = conn.execute(
            "SELECT id,user_id,event_type,timestamp FROM events NOT INDEXED ORDER BY id"
        ).fetchall()
        assert rows == expected_original_rows(), "The main events table was modified"

        with pytest.raises(sqlite3.DatabaseError):
            conn.execute(
                "SELECT count(*) FROM events "
                "WHERE user_id=102 AND event_type='login'"
            ).fetchone()
    finally:
        conn.close()


def create_dynamic_corrupt_database(path):
    rng = random.Random(secrets.randbits(128))
    selected_users = rng.sample(range(10000, 90000), 5)
    counts = {}

    conn = sqlite3.connect(path)
    cur = conn.cursor()
    cur.execute(
        "CREATE TABLE events(id INTEGER PRIMARY KEY, user_id INTEGER, "
        "event_type TEXT, timestamp INTEGER)"
    )
    cur.execute("CREATE INDEX idx_user_event ON events(user_id, event_type)")

    timestamp = rng.randrange(100000, 900000)
    for user_id in selected_users:
        login_count = rng.randint(1, 5)
        purchase_count = rng.randint(0, 4)
        counts[user_id] = (login_count, purchase_count)
        event_types = (
            ["login"] * login_count
            + ["purchase"] * purchase_count
            + ["logout"] * rng.randint(1, 3)
        )
        rng.shuffle(event_types)
        for event_type in event_types:
            timestamp += rng.randint(1, 20)
            cur.execute(
                "INSERT INTO events(user_id,event_type,timestamp) VALUES(?,?,?)",
                (user_id, event_type, timestamp),
            )

    # Add unrelated rows so answers cannot be inferred from the original fixture.
    for filler in range(80):
        user_id = 900000 + filler
        for event_type in ("login", "purchase", "logout"):
            timestamp += 1
            cur.execute(
                "INSERT INTO events(user_id,event_type,timestamp) VALUES(?,?,?)",
                (user_id, event_type, timestamp),
            )

    conn.commit()
    rootpage = cur.execute(
        "SELECT rootpage FROM sqlite_master "
        "WHERE type='index' AND name='idx_user_event'"
    ).fetchone()[0]
    page_size = cur.execute("PRAGMA page_size").fetchone()[0]
    conn.close()

    with open(path, "r+b") as f:
        f.seek((rootpage - 1) * page_size)
        f.write(b"\x00" * 100)

    absent_user = rng.randrange(91000, 99000)
    requested = selected_users[:] + [selected_users[1], absent_user]
    rng.shuffle(requested)
    expected_lines = ["user_id,login_count,purchase_count"]
    for user_id in requested:
        login_count, purchase_count = counts.get(user_id, (0, 0))
        expected_lines.append(f"{user_id},{login_count},{purchase_count}")
    expected = "\n".join(expected_lines) + "\n"
    input_content = "user_id\n" + "\n".join(map(str, requested)) + "\n"
    return input_content, expected


def test_complete_solution():
    # Preserve all original artifact and fixed-output assertions.
    assert os.path.isfile(OUTPUT), f"Output file missing at {OUTPUT}"
    assert normalized_output() == EXPECTED_ORIGINAL
    assert os.path.isfile(SOURCE), f"C source file missing at {SOURCE}"
    assert os.path.isfile(EXECUTABLE), f"Compiled executable missing at {EXECUTABLE}"
    assert os.access(EXECUTABLE, os.X_OK), f"File at {EXECUTABLE} is not executable"
    validate_original_database()

    with open(SOURCE, "r", encoding="utf-8", errors="replace") as f:
        source_text = f.read()
    assert re.search(r"#\s*include\s*[<\"]sqlite3\.h[>\"]", source_text), (
        "process.c must use sqlite3.h"
    )
    assert re.search(r"\bsqlite3_(?:open|open_v2)\s*\(", source_text), (
        "process.c must open the database through the SQLite3 C API"
    )
    assert re.search(r"\bsqlite3_(?:prepare(?:_v2|_v3)?|exec)\s*\(", source_text), (
        "process.c must issue queries through the SQLite3 C API"
    )

    subprocess.run(
        ["gcc", SOURCE, "-o", COMPILED, "-lsqlite3"],
        cwd=HOME,
        check=True,
        timeout=30,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    assert open(EXECUTABLE, "rb").read(4) == b"\x7fELF", (
        "/home/user/process is not a compiled executable"
    )

    # Execute both the submitted executable and a fresh build from process.c.
    run_program(EXECUTABLE, EXPECTED_ORIGINAL)
    run_program(COMPILED, EXPECTED_ORIGINAL)

    with open(INPUT, "rb") as f:
        original_input = f.read()
    with open(OUTPUT, "rb") as f:
        original_output = f.read()
    original_mode = stat.S_IMODE(os.stat(DB).st_mode)
    backup_db = f"{DB}.verifier-backup-{secrets.token_hex(8)}"

    os.replace(DB, backup_db)
    try:
        dynamic_input, dynamic_expected = create_dynamic_corrupt_database(DB)
        os.chmod(DB, 0o444)
        with open(INPUT, "w", encoding="utf-8", newline="") as f:
            f.write(dynamic_input)

        # Randomized data and order force both artifacts to query the corrupt-index
        # database correctly rather than emit the fixture's hardcoded CSV.
        run_program(EXECUTABLE, dynamic_expected)
        run_program(COMPILED, dynamic_expected)
    finally:
        if os.path.exists(DB):
            os.chmod(DB, 0o644)
            os.remove(DB)
        os.replace(backup_db, DB)
        os.chmod(DB, original_mode)
        with open(INPUT, "wb") as f:
            f.write(original_input)
        with open(OUTPUT, "wb") as f:
            f.write(original_output)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
