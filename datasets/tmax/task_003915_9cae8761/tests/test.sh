def _run_pipeline():
    return subprocess.run(
        ['/home/user/run_pipeline.sh'],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        timeout=600,
        check=False,
    )


def _assert_predictions_correct(dataset_path, weights_path, predictions_path):
    assert os.path.isfile(predictions_path), f"Predictions file not found at {predictions_path}"

    with open(weights_path, 'r') as f:
        w_data = json.load(f)
    weights = w_data['weights']
    bias = w_data['bias']

    expected_preds = {}
    with open(dataset_path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            score = (float(row['f1']) * weights[0] +
                     float(row['f2']) * weights[1] +
                     float(row['f3']) * weights[2] +
                     float(row['f4']) * weights[3] + bias)
            pred = 1 if score > 0 else 0
            expected_preds[row['id']] = str(pred)

    actual_preds = {}
    with open(predictions_path, 'r') as f:
        reader = csv.reader(f)
        header = next(reader)
        assert header == ['id', 'prediction'], f"Incorrect header in predictions.csv: {header}"
        for row in reader:
            if not row:
                continue
            assert len(row) == 2, f"Malformed prediction row: {row}"
            assert row[0] not in actual_preds, f"Duplicate prediction for id {row[0]}"
            actual_preds[row[0]] = row[1]

    assert len(actual_preds) == len(expected_preds), f"Expected {len(expected_preds)} predictions, found {len(actual_preds)}"
    for pid, expected_pred in expected_preds.items():
        assert pid in actual_preds, f"Prediction for id {pid} missing"
        assert actual_preds[pid] == expected_pred, f"Incorrect prediction for id {pid}: expected {expected_pred}, got {actual_preds[pid]}"


def test_00_pipeline_runs_end_to_end_on_derived_inputs():
    pipeline = '/home/user/run_pipeline.sh'
    predict = '/home/user/predict.py'
    dataset = '/home/user/dataset.csv'
    weights = '/home/user/weights.json'
    predictions = '/home/user/predictions.csv'
    metrics = '/home/user/metrics.txt'
    venv = '/home/user/venv'

    assert os.path.isfile(pipeline), f"Bash script not found at {pipeline}"
    assert os.access(pipeline, os.X_OK), f"Bash script {pipeline} is not executable"
    assert os.path.isfile(predict), f"Python script not found at {predict}"

    token = secrets.token_hex(12)
    work = f'/tmp/pipeline-audit-{token}'
    os.makedirs(work)
    dataset_backup = os.path.join(work, 'dataset.csv')
    weights_backup = os.path.join(work, 'weights.json')
    predict_backup = os.path.join(work, 'original_predict.py')
    marker = os.path.join(work, 'predict-marker.json')
    old_venv = os.path.join(work, 'old-venv')
    shutil.copy2(dataset, dataset_backup)
    shutil.copy2(weights, weights_backup)
    shutil.copy2(predict, predict_backup)

    # Challenge weights are generated by the verifier, so stale/precomputed output cannot pass.
    challenge_weights = [
        (secrets.randbelow(18001) - 9000) / 1000.0 or 0.731,
        (secrets.randbelow(18001) - 9000) / 1000.0 or -1.137,
        (secrets.randbelow(18001) - 9000) / 1000.0 or 2.219,
        (secrets.randbelow(18001) - 9000) / 1000.0 or -0.853,
    ]
    challenge_bias = (secrets.randbelow(10001) - 5000) / 1000.0
    with open(weights, 'w') as f:
        json.dump({'weights': challenge_weights, 'bias': challenge_bias}, f)

    # This transparent wrapper proves that run_pipeline.sh actually invokes predict.py,
    # and records whether that prediction process loaded both required libraries.
    wrapper = textwrap.dedent(f'''\
        #!/usr/bin/env python3
        import json
        import runpy
        import sys
        try:
            runpy.run_path({predict_backup!r}, run_name='__main__')
        finally:
            loaded = {{
                'numpy': any(n == 'numpy' or n.startswith('numpy.') for n in sys.modules),
                'pandas': any(n == 'pandas' or n.startswith('pandas.') for n in sys.modules),
            }}
            with open({marker!r}, 'w') as marker_file:
                json.dump(loaded, marker_file)
    ''')
    with open(predict, 'w') as f:
        f.write(wrapper)
    os.chmod(predict, 0o755)

    if os.path.lexists(venv):
        os.rename(venv, old_venv)
    for path in (predictions, metrics):
        if os.path.lexists(path):
            if os.path.isdir(path) and not os.path.islink(path):
                shutil.rmtree(path)
            else:
                os.unlink(path)

    challenge_succeeded = False
    try:
        result = _run_pipeline()
        assert result.returncode == 0, f"run_pipeline.sh failed:\n{result.stdout}"
        assert os.path.isfile(marker), "run_pipeline.sh did not execute /home/user/predict.py"
        with open(marker) as f:
            loaded = json.load(f)
        assert loaded.get('numpy') is True, "predict.py did not load/use NumPy"
        assert loaded.get('pandas') is True, "predict.py did not load/use pandas"

        python_path = os.path.join(venv, 'bin', 'python')
        if not os.path.isfile(python_path):
            python_path = os.path.join(venv, 'bin', 'python3')
        assert os.path.isfile(python_path), "Pipeline did not create a Python virtual environment"
        package_check = subprocess.run(
            [python_path, '-c', 'import json,numpy,pandas; print(json.dumps([numpy.__file__, pandas.__file__]))'],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=60,
            check=False,
        )
        assert package_check.returncode == 0, f"NumPy and pandas are not importable from the created venv:\n{package_check.stdout}"
        package_paths = json.loads(package_check.stdout.strip().splitlines()[-1])
        venv_real = os.path.realpath(venv) + os.sep
        assert all(os.path.realpath(p).startswith(venv_real) for p in package_paths), \
            f"NumPy and pandas were not installed in /home/user/venv: {package_paths}"

        _assert_predictions_correct(dataset, weights, predictions)

        assert os.path.isfile(metrics), f"Metrics log not found at {metrics}"
        with open(metrics) as f:
            metric_content = f.read().strip()
        match = re.fullmatch(r'inference_time_ms:(\d+(?:\.\d+)?)', metric_content)
        assert match is not None, f"Fresh metrics output has incorrect format: {metric_content!r}"
        measured = float(match.group(1))
        assert math.isfinite(measured) and measured > 0, f"Inference time must be a positive measured value, got {measured}"
        challenge_succeeded = True
    finally:
        shutil.copy2(dataset_backup, dataset)
        shutil.copy2(weights_backup, weights)
        shutil.copy2(predict_backup, predict)

    # Leave the required final outputs corresponding to the original task inputs.
    if challenge_succeeded:
        for path in (predictions, metrics):
            if os.path.lexists(path):
                if os.path.isdir(path) and not os.path.islink(path):
                    shutil.rmtree(path)
                else:
                    os.unlink(path)
        final_result = _run_pipeline()
        assert final_result.returncode == 0, f"Pipeline failed on the original inputs:\n{final_result.stdout}"


def test_run_pipeline_script_exists_and_executable():
