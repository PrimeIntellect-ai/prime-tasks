#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import base64
import os
from pathlib import Path
import random
import secrets
import subprocess
import tempfile

import pytest

LIB_ROOT = Path('/app/libb64-1.2')
LIB_EXE = LIB_ROOT / 'base64/base64'
SANITIZER_SOURCE = Path('/home/user/sanitizer.c')
SANITIZER_EXE = Path('/home/user/sanitizer')


def run_checked(command, **kwargs):
    return subprocess.run(command, capture_output=True, timeout=10, **kwargs)


def assert_elf(path):
    assert path.is_file(), f'Expected regular file not found: {path}'
    with path.open('rb') as stream:
        assert stream.read(4) == b'\x7fELF', f'{path} is not a compiled ELF file'


def test_libb64_compilation():
    """A clean invocation of make must produce a real, working libb64 executable."""
    # Remove prior build products so make cannot pass by relying on a pre-existing
    # executable or object files.
    for pattern in ('*.o', '*.a', '*.so', '*.so.*'):
        for artifact in LIB_ROOT.rglob(pattern):
            if artifact.is_file() or artifact.is_symlink():
                artifact.unlink()
    if LIB_EXE.exists() or LIB_EXE.is_symlink():
        LIB_EXE.unlink()

    result = subprocess.run(
        ['make'], cwd=str(LIB_ROOT), capture_output=True, text=True, timeout=60
    )
    assert result.returncode == 0, (
        f'Compilation of libb64 failed. Make output:\n{result.stderr}\n{result.stdout}'
    )

    assert os.path.exists(LIB_EXE), f'Expected compiled executable not found at {LIB_EXE}'
    assert os.access(LIB_EXE, os.X_OK), f'File {LIB_EXE} is not executable'
    assert_elf(LIB_EXE)

    compiled_objects = list(LIB_ROOT.rglob('*.o'))
    libraries = list(LIB_ROOT.rglob('*.a'))
    assert compiled_objects, 'make did not produce any compiled object files'
    assert libraries, 'make did not produce the libb64 static library'
    for obj in compiled_objects:
        assert_elf(obj)
    for library in libraries:
        with library.open('rb') as stream:
            assert stream.read(8) == b'!<arch>\n', f'{library} is not a static archive'

    # Exercise both decoding and encoding using data generated by the verifier.
    rng = random.Random(secrets.randbits(128))
    raw = bytes(rng.randrange(256) for _ in range(1027))
    with tempfile.TemporaryDirectory(prefix='libb64-check-') as tmp:
        tmpdir = Path(tmp)
        encoded_input = tmpdir / secrets.token_hex(8)
        decoded_output = tmpdir / secrets.token_hex(8)
        encoded_input.write_bytes(base64.b64encode(raw) + b'\n')

        decoded = run_checked(
            [str(LIB_EXE), '-d', str(encoded_input), str(decoded_output)]
        )
        assert decoded.returncode == 0, decoded.stderr.decode(errors='replace')
        assert decoded_output.read_bytes() == raw, 'libb64 decoded data incorrectly'

        raw_input = tmpdir / secrets.token_hex(8)
        encoded_output = tmpdir / secrets.token_hex(8)
        raw_input.write_bytes(raw)
        encoded = run_checked(
            [str(LIB_EXE), '-e', str(raw_input), str(encoded_output)]
        )
        assert encoded.returncode == 0, encoded.stderr.decode(errors='replace')
        try:
            round_trip = base64.b64decode(encoded_output.read_bytes(), validate=False)
        except Exception as exc:
            pytest.fail(f'libb64 produced invalid base64: {exc}')
        assert round_trip == raw, 'libb64 encoded data incorrectly'


def test_sanitizer_exists():
    """The requested C source and compiled sanitizer must both exist."""
    assert SANITIZER_SOURCE.is_file(), f'Sanitizer source not found at {SANITIZER_SOURCE}'
    assert SANITIZER_EXE.exists(), f'Sanitizer executable not found at {SANITIZER_EXE}'
    assert os.access(SANITIZER_EXE, os.X_OK), f'Sanitizer at {SANITIZER_EXE} is not executable'
    assert_elf(SANITIZER_EXE)


def test_sanitizer_clean_corpus():
    """Test that the submitted sanitizer accepts all supplied clean files."""
    clean_dir = '/app/corpus/clean/'
    clean_files = [f for f in os.listdir(clean_dir) if os.path.isfile(os.path.join(clean_dir, f))]
    assert len(clean_files) > 0, 'No files found in clean corpus.'

    failed_files = []
    for filename in clean_files:
        filepath = os.path.join(clean_dir, filename)
        result = run_checked([str(SANITIZER_EXE), filepath])
        if result.returncode != 0:
            failed_files.append(filename)

    if failed_files:
        pytest.fail(
            f'{len(failed_files)} of {len(clean_files)} clean modified/rejected. '
            f"Offending files: {', '.join(failed_files)}"
        )


def test_sanitizer_evil_corpus():
    """Test that the submitted sanitizer rejects all supplied evil files."""
    evil_dir = '/app/corpus/evil/'
    evil_files = [f for f in os.listdir(evil_dir) if os.path.isfile(os.path.join(evil_dir, f))]
    assert len(evil_files) > 0, 'No files found in evil corpus.'

    failed_files = []
    for filename in evil_files:
        filepath = os.path.join(evil_dir, filename)
        result = run_checked([str(SANITIZER_EXE), filepath])
        if result.returncode != 1:
            failed_files.append(filename)

    if failed_files:
        pytest.fail(
            f'{len(failed_files)} of {len(evil_files)} evil bypassed. '
            f"Offending files: {', '.join(failed_files)}"
        )


def test_sanitizer_source_and_hidden_content_cases():
    """Compile the submitted source and test content at one unpredictable path."""
    with tempfile.TemporaryDirectory(prefix='sanitizer-check-') as tmp:
        tmpdir = Path(tmp)
        rebuilt = tmpdir / secrets.token_hex(12)
        build = subprocess.run(
            [
                'gcc', '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                str(SANITIZER_SOURCE), '-o', str(rebuilt),
            ],
            capture_output=True,
            text=True,
            timeout=30,
        )
        assert build.returncode == 0, (
            f'sanitizer.c does not compile cleanly:\n{build.stderr}\n{build.stdout}'
        )
        assert_elf(rebuilt)

        # Reuse exactly the same randomized path for accepted and rejected data,
        # preventing classification based on corpus directory or filename.
        sample = tmpdir / secrets.token_hex(12)
        allowed = b'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=\n\r '
        rng = random.Random(secrets.randbits(128))
        clean_cases = [
            b'',
            allowed,
            bytes(rng.choice(allowed) for _ in range(4096)),
        ]
        disallowed = [value for value in range(256) if value not in set(allowed)]

        for executable in (SANITIZER_EXE, rebuilt):
            for content in clean_cases:
                sample.write_bytes(content)
                result = run_checked([str(executable), str(sample)])
                assert result.returncode == 0, (
                    f'{executable} rejected verifier-generated safe content '
                    f'with exit code {result.returncode}'
                )

            # Every byte outside the specified alphabet must cause exit code 1.
            for bad_byte in disallowed:
                prefix = bytes(rng.choice(allowed) for _ in range(rng.randrange(0, 80)))
                suffix = bytes(rng.choice(allowed) for _ in range(rng.randrange(0, 80)))
                sample.write_bytes(prefix + bytes([bad_byte]) + suffix)
                result = run_checked([str(executable), str(sample)])
                assert result.returncode == 1, (
                    f'{executable} failed to reject byte 0x{bad_byte:02x}; '
                    f'exit code was {result.returncode}'
                )

            # It must accept exactly one path argument.
            assert run_checked([str(executable)]).returncode != 0
            assert run_checked([str(executable), str(sample), str(sample)]).returncode != 0
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
