mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
# test_final_state.py
import os
import csv
import random
import secrets
import subprocess

SCRIPT_PATH = "/home/user/process.sh"
DATA_PATH = "/home/user/data.csv"
TRAIN_PATH = "/home/user/train_processed.csv"
TEST_PATH = "/home/user/test_processed.csv"


def test_script_exists_and_executable():
    script_path = "/home/user/process.sh"
    assert os.path.isfile(script_path), f"Script {script_path} does not exist."
    assert os.access(script_path, os.X_OK), f"Script {script_path} is not executable."


def test_processed_files_exist():
    assert os.path.isfile("/home/user/train_processed.csv"), "/home/user/train_processed.csv is missing."
    assert os.path.isfile("/home/user/test_processed.csv"), "/home/user/test_processed.csv is missing."


def test_data_leakage_and_preprocessing():
    data_path = "/home/user/data.csv"
    assert os.path.isfile(data_path), f"Original data file {data_path} is missing."

    with open(data_path, "r") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = list(reader)

    assert len(rows) == 100, f"Expected 100 data rows in original dataset, found {len(rows)}."

    train_rows = rows[:80]
    test_rows = rows[80:]

    # Calculate train statistics
    train_values = [float(row[1]) for row in train_rows if row[1].strip() != ""]
    train_mean = sum(train_values) / len(train_values)
    train_min = min(train_values)
    train_max = max(train_values)

    def process_row(row):
        val_str = row[1].strip()
        val = float(val_str) if val_str != "" else train_mean
        scaled = (val - train_min) / (train_max - train_min)
        return [row[0], f"{scaled:.4f}"]

    expected_train = [process_row(row) for row in train_rows]
    expected_test = [process_row(row) for row in test_rows]

    # Check train_processed.csv
    with open("/home/user/train_processed.csv", "r") as f:
        reader = csv.reader(f)
        train_out_header = next(reader)
        train_out_rows = list(reader)

    assert train_out_header == ["id", "value"], "train_processed.csv header is incorrect."
    assert len(train_out_rows) == 80, f"Expected 80 data rows in train_processed.csv, found {len(train_out_rows)}."

    for i, (expected, actual) in enumerate(zip(expected_train, train_out_rows)):
        assert actual == expected, f"Train row {i+1} mismatch. Expected {expected}, got {actual}."

    # Check test_processed.csv
    with open("/home/user/test_processed.csv", "r") as f:
        reader = csv.reader(f)
        test_out_header = next(reader)
        test_out_rows = list(reader)

    assert test_out_header == ["id", "value"], "test_processed.csv header is incorrect."
    assert len(test_out_rows) == 20, f"Expected 20 data rows in test_processed.csv, found {len(test_out_rows)}."

    for i, (expected, actual) in enumerate(zip(expected_test, test_out_rows)):
        assert actual == expected, f"Test row {i+1} mismatch. Expected {expected}, got {actual}."


def _expected(rows):
    train_rows = rows[:80]
    train_values = [float(row[1]) for row in train_rows if row[1] != ""]
    train_mean = sum(train_values) / len(train_values)
    train_min = min(train_values)
    train_max = max(train_values)

    def process(row):
        value = float(row[1]) if row[1] != "" else train_mean
        scaled = (value - train_min) / (train_max - train_min)
        return [row[0], f"{scaled:.4f}"]

    return [process(row) for row in rows[:80]], [process(row) for row in rows[80:]]


def _read_output(path, expected_count):
    assert os.path.isfile(path), f"{path} was not generated by process.sh."
    with open(path, "r", newline="") as f:
        reader = csv.reader(f)
        try:
            header = next(reader)
        except StopIteration:
            raise AssertionError(f"{path} is empty.")
        rows = list(reader)
    assert header == ["id", "value"], f"{path} header is incorrect."
    assert len(rows) == expected_count, f"Expected {expected_count} data rows in {path}, found {len(rows)}."
    return rows


def _make_random_dataset(trial):
    rng = random.SystemRandom()
    center = rng.randint(-500, 500)
    half_span = rng.choice([50, 100, 200, 250, 500])

    # Seventy valid training values in symmetric pairs make the exact training
    # mean center. Ten additional training entries are missing.
    distances = [half_span] + [rng.randint(1, half_span - 1) for _ in range(34)]
    train_values = []
    for distance in distances:
        train_values.extend([center - distance, center + distance])
    train_values.extend([None] * 10)
    rng.shuffle(train_values)

    test_values = [None, None, None]
    test_values.extend(center + rng.randint(-2 * half_span, 2 * half_span) for _ in range(17))
    rng.shuffle(test_values)

    values = train_values + test_values
    base_id = secrets.randbelow(900000) + trial * 1000000
    return [[str(base_id + i + 1), "" if value is None else str(value)] for i, value in enumerate(values)]


def test_process_script_executes_and_handles_unseen_data():
    with open(DATA_PATH, "rb") as f:
        original_data = f.read()

    try:
        for trial in range(3):
            rows = _make_random_dataset(trial)
            expected_train, expected_test = _expected(rows)

            with open(DATA_PATH, "w", newline="") as f:
                writer = csv.writer(f, lineterminator="\n")
                writer.writerow(["id", "value"])
                writer.writerows(rows)

            for path in (TRAIN_PATH, TEST_PATH):
                if os.path.exists(path):
                    os.remove(path)

            result = subprocess.run(
                [SCRIPT_PATH],
                cwd="/home/user",
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                timeout=15,
            )
            assert result.returncode == 0, (
                f"process.sh failed on an unseen valid dataset with exit code {result.returncode}. "
                f"stderr: {result.stderr}"
            )

            actual_train = _read_output(TRAIN_PATH, 80)
            actual_test = _read_output(TEST_PATH, 20)
            assert actual_train == expected_train, "process.sh produced incorrect training output on unseen data."
            assert actual_test == expected_test, "process.sh produced incorrect test output on unseen data."
    finally:
        with open(DATA_PATH, "wb") as f:
            f.write(original_data)
        # Restore the required final outputs for the original supplied dataset.
        subprocess.run(
            [SCRIPT_PATH],
            cwd="/home/user",
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=15,
            check=False,
        )
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
