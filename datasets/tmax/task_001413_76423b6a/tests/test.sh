#!/bin/bash
# --- runtime-defect fix: the verifier's own imports are not in this image ---
# Without this, pytest dies at collection with ModuleNotFoundError and the task
# scores 0 regardless of what the agent did. Pre-existing: the original verifier
# imports the same modules. `|| true` so a network-less run is no worse than before.
for _m in "scipy:scipy"; do
  python3 -c "import ${_m%%:*}" >/dev/null 2>&1 && continue
  # Bounded and fully detached from the parent's pipes. Without `timeout` and the
  # </dev/null + >/dev/null redirects this hangs: the harness captures output, so
  # subprocess.run blocks until every writer closes the pipe, and a slow pip then
  # wedges the whole episode past its deadline. Measured: episodes stopped
  # finishing entirely until this was bounded.
  timeout 90 pip install --quiet --disable-pip-version-check --no-input       "${_m##*:}" </dev/null >/dev/null 2>&1 || true
done
# --- end fix ---
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import subprocess

import numpy as np
import pytest
from scipy.stats import multivariate_normal

SCRIPT_PATH = "/home/user/evaluate_models.py"
RESULTS_PATH = "/home/user/results.json"
VENV_PYTHON = "/home/user/venv/bin/python"


def test_evaluate_models_end_to_end():
    assert os.path.isfile(SCRIPT_PATH), f"The script {SCRIPT_PATH} was not created."
    assert os.path.isfile(VENV_PYTHON), f"The virtual environment Python {VENV_PYTHON} was not created."

    # Ensure results are generated by the submitted script rather than accepted stale.
    if os.path.lexists(RESULTS_PATH):
        os.remove(RESULTS_PATH)

    completed = subprocess.run(
        [VENV_PYTHON, SCRIPT_PATH],
        cwd="/home/user",
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=120,
    )
    assert completed.returncode == 0, (
        f"evaluate_models.py failed with exit code {completed.returncode}.\n"
        f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    )
    assert os.path.isfile(RESULTS_PATH), (
        f"Executing {SCRIPT_PATH} did not create {RESULTS_PATH}."
    )

    try:
        with open(RESULTS_PATH, "r") as f:
            results = json.load(f)
    except json.JSONDecodeError as exc:
        pytest.fail(f"The file {RESULTS_PATH} does not contain valid JSON: {exc}")

    expected_keys = {
        "lambda_extracted",
        "bic_model1_full_reg",
        "bic_model2_diag",
        "best_model_test_nll",
    }
    assert set(results.keys()) == expected_keys, (
        f"results.json must contain exactly {sorted(expected_keys)}, "
        f"but contains {sorted(results.keys())}"
    )

    for key in expected_keys:
        value = results[key]
        assert isinstance(value, (int, float)) and not isinstance(value, bool), (
            f"{key} must be a JSON number, got {type(value).__name__}."
        )
        assert np.isfinite(value), f"{key} must be finite, got {value}."

    lambda_extracted = results["lambda_extracted"]
    assert np.isclose(lambda_extracted, 0.035, atol=1e-5), (
        f"Incorrect lambda extracted. Expected ~0.035, got {lambda_extracted}"
    )

    train_data_path = "/app/train_data.npy"
    test_data_path = "/app/test_data.npy"
    assert os.path.isfile(train_data_path), f"Missing {train_data_path}"
    assert os.path.isfile(test_data_path), f"Missing {test_data_path}"

    X_train = np.load(train_data_path)
    X_test = np.load(test_data_path)
    N, D = X_train.shape

    mu = np.mean(X_train, axis=0)
    cov_sample = np.cov(X_train, rowvar=False, bias=True)
    cov_reg = cov_sample + 0.035 * np.eye(D)
    variances = np.var(X_train, axis=0, ddof=0)
    cov_diag = np.diag(variances)

    mvn_reg = multivariate_normal(mean=mu, cov=cov_reg)
    mvn_diag = multivariate_normal(mean=mu, cov=cov_diag)

    log_likelihood_reg = np.sum(mvn_reg.logpdf(X_train))
    log_likelihood_diag = np.sum(mvn_diag.logpdf(X_train))

    k_reg = D + D * (D + 1) / 2
    k_diag = D + D
    target_bic_reg = k_reg * np.log(N) - 2 * log_likelihood_reg
    target_bic_diag = k_diag * np.log(N) - 2 * log_likelihood_diag

    assert np.isclose(results["bic_model1_full_reg"], target_bic_reg, atol=0.05, rtol=1e-7), (
        "Incorrect BIC for the regularized full-covariance model. "
        f"Expected ~{target_bic_reg}, got {results['bic_model1_full_reg']}"
    )
    assert np.isclose(results["bic_model2_diag"], target_bic_diag, atol=0.05, rtol=1e-7), (
        "Incorrect BIC for the diagonal-covariance model. "
        f"Expected ~{target_bic_diag}, got {results['bic_model2_diag']}"
    )

    if target_bic_reg < target_bic_diag:
        target_nll = -np.sum(mvn_reg.logpdf(X_test))
    else:
        target_nll = -np.sum(mvn_diag.logpdf(X_test))

    agent_nll = results["best_model_test_nll"]
    error = abs(agent_nll - target_nll)
    assert error <= 2.0, (
        f"NLL error {error} exceeds threshold of 2.0. The NLL must be computed "
        f"using the model with lower BIC; expected ~{target_nll}, got {agent_nll}"
    )
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
