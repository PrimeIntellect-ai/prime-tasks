#!/bin/bash
# --- runtime-defect fix: the verifier's own imports are not in this image ---
# Without this, pytest dies at collection with ModuleNotFoundError and the task
# scores 0 regardless of what the agent did. Pre-existing: the original verifier
# imports the same modules. `|| true` so a network-less run is no worse than before.
for _m in "requests:requests"; do
  python3 -c "import ${_m%%:*}" >/dev/null 2>&1 && continue
  # Bounded and fully detached from the parent's pipes. Without `timeout` and the
  # </dev/null + >/dev/null redirects this hangs: the harness captures output, so
  # subprocess.run blocks until every writer closes the pipe, and a slow pip then
  # wedges the whole episode past its deadline. Measured: episodes stopped
  # finishing entirely until this was bounded.
  timeout 90 pip install --quiet --disable-pip-version-check --no-input       "${_m##*:}" </dev/null >/dev/null 2>&1 || true
done
# --- end fix ---
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import math
import os
import re
import subprocess
from pathlib import Path

import pytest
import requests

BASE = "http://127.0.0.1:8080"
VIDEO = "/app/broadcast.mp4"


def run(cmd):
    return subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)


def get_expected_brightness(sec):
    cmd = [
        "ffmpeg", "-y", "-ss", str(sec), "-i", VIDEO,
        "-vframes", "1", "-f", "image2pipe", "-vcodec", "rawvideo",
        "-pix_fmt", "gray", "-"
    ]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    if proc.returncode != 0 or not proc.stdout:
        return None
    return sum(proc.stdout) / len(proc.stdout)


def video_seconds():
    proc = run([
        "ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "default=noprint_wrappers=1:nokey=1", VIDEO
    ])
    assert proc.returncode == 0, proc.stderr.decode(errors="replace")
    duration = float(proc.stdout.decode().strip())
    assert duration > 0
    return list(range(int(math.ceil(duration - 1e-6))))


def parse_timestamp(value):
    match = re.fullmatch(r"(\d+):(\d+):(\d+)[,.](\d+)", value.strip())
    assert match, f"Invalid SRT timestamp generated by ffmpeg: {value!r}"
    hours, minutes, seconds, millis = map(int, match.groups())
    return hours * 3600 + minutes * 60 + seconds + millis / 1000.0


def expected_payloads(seconds):
    probe = run([
        "ffprobe", "-v", "error", "-select_streams", "s:0",
        "-show_entries", "stream=index", "-of", "csv=p=0", VIDEO
    ])
    assert probe.returncode == 0, probe.stderr.decode(errors="replace")
    if not probe.stdout.strip():
        return {sec: "" for sec in seconds}

    srt_path = "/tmp/verifier_subtitles.srt"
    proc = run([
        "ffmpeg", "-y", "-v", "error", "-i", VIDEO,
        "-map", "0:s:0", "-c:s", "srt", srt_path
    ])
    assert proc.returncode == 0, proc.stderr.decode(errors="replace")
    raw = Path(srt_path).read_text(encoding="utf-8-sig")

    cues = []
    for block in re.split(r"\r?\n\s*\r?\n", raw.strip()):
        lines = block.splitlines()
        timing_index = next((i for i, line in enumerate(lines) if "-->" in line), None)
        if timing_index is None:
            continue
        start_text, end_text = [part.strip() for part in lines[timing_index].split("-->", 1)]
        subtitle_text = "\n".join(lines[timing_index + 1:]).strip()
        match = re.search(
            r"\[MSGID:\s*[^\]]+\]\s*Source:\s*.*?\s*-\s*Payload:\s*(.*)\Z",
            subtitle_text,
            flags=re.DOTALL,
        )
        assert match, f"Subtitle does not have the required structured format: {subtitle_text!r}"
        cues.append((parse_timestamp(start_text), parse_timestamp(end_text), match.group(1).strip()))

    result = {}
    for sec in seconds:
        active = [payload for start, end, payload in cues if start <= sec < end]
        result[sec] = active[0] if active else ""
    return result


SECONDS = video_seconds()
EXPECTED_PAYLOADS = expected_payloads(SECONDS)


def listening_pids():
    inodes = set()
    for table in ("/proc/net/tcp", "/proc/net/tcp6"):
        try:
            lines = Path(table).read_text().splitlines()[1:]
        except OSError:
            continue
        for line in lines:
            fields = line.split()
            local_address, state = fields[1], fields[3]
            port = int(local_address.rsplit(":", 1)[1], 16)
            if port == 8080 and state == "0A":
                inodes.add(fields[9])

    pids = set()
    for proc_dir in Path("/proc").glob("[0-9]*"):
        fd_dir = proc_dir / "fd"
        try:
            for fd in fd_dir.iterdir():
                try:
                    target = os.readlink(fd)
                except OSError:
                    continue
                match = re.fullmatch(r"socket:\[(\d+)\]", target)
                if match and match.group(1) in inodes:
                    pids.add(int(proc_dir.name))
                    break
        except OSError:
            continue
    return pids


def test_server_is_running_go_artifact():
    try:
        resp = requests.get(BASE + "/report", timeout=2)
        assert resp.status_code == 200, f"Expected status code 200, got {resp.status_code}"
    except requests.exceptions.RequestException as exc:
        pytest.fail(f"Could not connect to Go server on 127.0.0.1:8080. Is it running? Error: {exc}")

    pids = listening_pids()
    assert pids, "No process owns the listening socket on port 8080"
    go_process = False
    for pid in pids:
        proc = run(["go", "version", "-m", f"/proc/{pid}/exe"])
        output = (proc.stdout + proc.stderr).decode(errors="replace")
        if proc.returncode == 0 and ("go1." in output or "path\t" in output):
            go_process = True
            break
    assert go_process, "The server listening on port 8080 is not a Go executable"

    sources = list(Path("/app").rglob("*.go"))
    assert sources, "No Go source file was written under /app"
    source_text = "\n".join(path.read_text(errors="replace") for path in sources)
    assert re.search(r'["`]text/template["`]', source_text), "Go source does not use text/template"


def test_api_data_endpoint_original_second_two_assertions():
    try:
        resp = requests.get(BASE + "/api/data?sec=2", timeout=2)
        assert resp.status_code == 200, f"Expected status code 200, got {resp.status_code}"
        try:
            data = resp.json()
        except json.JSONDecodeError:
            pytest.fail(f"Response from /api/data?sec=2 is not valid JSON. Response text: {resp.text}")

        assert "second" in data, "Missing 'second' key in JSON response"
        assert data["second"] == 2, f"Expected 'second' to be 2, got {data['second']}"
        assert "brightness" in data, "Missing 'brightness' key in JSON response"
        assert isinstance(data["brightness"], (int, float)) and not isinstance(data["brightness"], bool), "Brightness must be a number"
        assert "payload" in data, "Missing 'payload' key in JSON response"
        assert isinstance(data["payload"], str), "Payload must be a string"

        expected_brightness = get_expected_brightness(2)
        if expected_brightness is not None:
            assert abs(data["brightness"] - expected_brightness) < 5.0, \
                f"Brightness value {data['brightness']} is too far from expected {expected_brightness}"
    except requests.exceptions.RequestException as exc:
        pytest.fail(f"Request to /api/data?sec=2 failed: {exc}")


def test_api_all_seconds_brightness_and_subtitle_correlation():
    assert SECONDS, "Video yielded no whole-second samples"
    for sec in SECONDS:
        resp = requests.get(BASE + f"/api/data?sec={sec}", timeout=2)
        assert resp.status_code == 200, f"Second {sec}: expected status 200, got {resp.status_code}"
        data = resp.json()
        assert data.get("second") == sec, f"Second {sec}: incorrect second field: {data!r}"
        assert isinstance(data.get("brightness"), (int, float)) and not isinstance(data.get("brightness"), bool)
        assert isinstance(data.get("payload"), str)

        expected_brightness = get_expected_brightness(sec)
        assert expected_brightness is not None, f"Could not derive frame brightness for second {sec}"
        assert 0 <= data["brightness"] <= 255
        assert abs(data["brightness"] - expected_brightness) < 5.0, \
            f"Second {sec}: brightness {data['brightness']} differs from {expected_brightness}"
        assert data["payload"] == EXPECTED_PAYLOADS[sec], \
            f"Second {sec}: expected payload {EXPECTED_PAYLOADS[sec]!r}, got {data['payload']!r}"


def test_report_endpoint_complete_template_output():
    try:
        resp = requests.get(BASE + "/report", timeout=2)
        assert resp.status_code == 200, f"Expected status code 200, got {resp.status_code}"
        text = resp.text
        assert text.strip(), "Report response is empty"
        lines = [line for line in text.split("\n") if line.strip()]
        assert any(line.startswith("Sec ") for line in lines), "Report does not contain lines starting with 'Sec '"
        assert any("Brightness" in line for line in lines), "Report does not contain 'Brightness'"
        assert any("Payload:" in line for line in lines), "Report does not contain 'Payload:'"

        assert len(lines) == len(SECONDS), \
            f"Report must contain exactly one line for every second; got {len(lines)}, expected {len(SECONDS)}"
        pattern = re.compile(r"^Sec (\d+): Brightness (-?\d+\.\d{2}), Payload: (.*)$")
        for expected_sec, line in zip(SECONDS, lines):
            match = pattern.fullmatch(line)
            assert match, f"Report line has incorrect format or brightness is not rounded to 2 decimals: {line!r}"
            sec = int(match.group(1))
            report_brightness = float(match.group(2))
            payload = match.group(3)
            assert sec == expected_sec, f"Report seconds are incomplete or out of order at line {line!r}"
            assert payload == EXPECTED_PAYLOADS[sec], \
                f"Report second {sec}: expected payload {EXPECTED_PAYLOADS[sec]!r}, got {payload!r}"

            api_data = requests.get(BASE + f"/api/data?sec={sec}", timeout=2).json()
            assert abs(report_brightness - float(api_data["brightness"])) < 0.011, \
                f"Report brightness for second {sec} does not match API data"
    except requests.exceptions.RequestException as exc:
        pytest.fail(f"Request to /report failed: {exc}")
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
