#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import random
import string
import subprocess
import tempfile

REPO = "/home/user/repo"
SOURCE = f"{REPO}/interpreter.rs"
BUILD = f"{REPO}/build.sh"
RUN = f"{REPO}/run.sh"
BINARY = f"{REPO}/interpreter_bin"
OUTPUT = "/home/user/decoded_message.txt"


def run_checked(argv, timeout=20):
    result = subprocess.run(argv, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout)
    assert result.returncode == 0, (
        f"Command {argv!r} failed with exit code {result.returncode}. "
        f"stdout={result.stdout!r}, stderr={result.stderr!r}"
    )
    return result


def expected_output(program):
    state = 0
    output = []
    for char in program:
        if char == "^":
            state ^= 42
        elif char == ".":
            output.append(chr(state))
        else:
            state = ord(char) & 0xff
    return "".join(output).encode("utf-8") + b"\n"


def make_cases():
    cases = ["A..^^.", "z^.^.", "0.^.^..", "abc...^^."]
    rng = random.SystemRandom()
    alphabet = string.ascii_letters + string.digits
    for _ in range(5):
        pieces = []
        for _ in range(rng.randint(8, 24)):
            pieces.append(rng.choice(alphabet))
            pieces.append("^" * rng.randint(0, 3))
            pieces.append("." * rng.randint(1, 3))
        cases.append("".join(pieces))
    return cases


def test_00_build_script_really_compiles_binary():
    assert os.path.isfile(SOURCE), f"Rust source {SOURCE} does not exist."
    assert os.path.isfile(BUILD), f"Build script {BUILD} does not exist."
    if os.path.lexists(BINARY):
        os.remove(BINARY)

    run_checked([BUILD])

    assert os.path.isfile(BINARY), f"Build script did not create {BINARY}."
    assert os.access(BINARY, os.X_OK), f"Built interpreter {BINARY} is not executable."


def test_01_interpreter_source_compiles_and_implements_opcode_logic():
    direct_binary = "/tmp/verifier_interpreter_bin"
    if os.path.lexists(direct_binary):
        os.remove(direct_binary)

    run_checked(["rustc", SOURCE, "-o", direct_binary])
    assert os.path.isfile(direct_binary) and os.access(direct_binary, os.X_OK)

    for index, program in enumerate(make_cases()):
        input_path = f"/tmp/verifier_direct_{index}.enc"
        with open(input_path, "w", encoding="ascii", newline="") as handle:
            handle.write(program)
        result = run_checked([direct_binary, input_path])
        assert result.stdout == expected_output(program), (
            f"Interpreter source produced the wrong output for generated bytecode. "
            f"Expected {expected_output(program)!r}, got {result.stdout!r}"
        )


def test_02_wrapper_executes_built_interpreter_on_generated_inputs():
    assert os.path.isfile(RUN), f"Wrapper script {RUN} does not exist."
    for index, program in enumerate(make_cases()):
        input_path = f"/tmp/verifier_wrapper_{index}.enc"
        with open(input_path, "w", encoding="ascii", newline="") as handle:
            handle.write(program)
        result = run_checked([RUN, input_path])
        assert result.stdout == expected_output(program), (
            f"run.sh produced the wrong output for generated bytecode. "
            f"Expected {expected_output(program)!r}, got {result.stdout!r}"
        )


def test_03_decoded_message_exists_and_correct_and_matches_run():
    assert os.path.isfile(OUTPUT), (
        f"Output file {OUTPUT} does not exist. Did you save the standard output of run.sh?"
    )
    with open(OUTPUT, "rb") as handle:
        content = handle.read()

    assert content == b"CORRECT\n", (
        f"The decoded message in {OUTPUT} is incorrect. "
        f"Expected 'CORRECT\\n', got {content!r}"
    )

    actual = run_checked([RUN, f"{REPO}/data.enc"]).stdout
    assert actual == content, (
        f"{OUTPUT} does not exactly match the standard output produced by "
        f"run.sh on data.enc: saved={content!r}, actual={actual!r}"
    )


def test_04_interpreter_binary_exists():
    assert os.path.isfile(BINARY), (
        f"Interpreter binary {BINARY} does not exist. "
        "Did you successfully compile the Rust code using build.sh?"
    )
    assert os.access(BINARY, os.X_OK), f"Interpreter binary {BINARY} is not executable."
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
