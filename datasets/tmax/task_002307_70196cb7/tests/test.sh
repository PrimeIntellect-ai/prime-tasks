#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import math
import os
import re
import stat
import subprocess
import pytest

SOURCE = "/home/user/optimizer.cpp"
PARAMS = "/home/user/optimized_params.txt"
BINARY = "/tmp/submission_optimizer"


def simulate_trajectory(Cd, vx0, vy0, frames=300, dt=1.0/60.0):
    x, y = 0.0, 0.0
    vx, vy = vx0, vy0
    trajectory = []
    for _ in range(frames):
        trajectory.append((x, y))
        v_mag = math.sqrt(vx**2 + vy**2)
        ax = -Cd * v_mag * vx
        ay = 9.81 - Cd * v_mag * vy
        vx += ax * dt
        vy += ay * dt
        x += vx * dt
        y += vy * dt
    return trajectory


def strip_comments_and_literals(source):
    pattern = re.compile(
        r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
        re.DOTALL,
    )
    return pattern.sub(' ', source)


def test_cpp_pipeline_and_optimized_params_mse():
    assert os.path.exists(SOURCE), f"File {SOURCE} does not exist."
    assert stat.S_ISREG(os.lstat(SOURCE).st_mode), f"{SOURCE} must be a regular C++ source file."

    with open(SOURCE, "r", encoding="utf-8", errors="replace") as f:
        source = f.read()
    assert source.strip(), f"{SOURCE} is empty."

    code = strip_comments_and_literals(source).lower()
    loop_count = len(re.findall(r'\b(?:for|while)\s*\(', code))
    assert loop_count >= 2, "optimizer.cpp does not show both trajectory integration and iterative optimization loops."

    ode_signals = [
        re.search(r'\b(?:vx|vy|velocity)\b', code),
        re.search(r'\b(?:ax|ay|accel(?:eration)?)\b', code),
        re.search(r'\b(?:cd|drag)\b', code),
        re.search(r'\b(?:dt|timestep|time_step)\b', code),
        re.search(r'\b(?:sqrt|hypot|norm)\s*\(', code),
        re.search(r'\b(?:trajectory|simulate|integrat|euler|rk4)\w*\b', code),
    ]
    assert sum(bool(x) for x in ode_signals) >= 5, \
        "optimizer.cpp does not contain sufficient evidence of a quadratic-drag ODE trajectory integrator."

    objective_signal = re.search(r'\b(?:objective|loss|error|mse|cost|fitness|residual)\w*\b', code)
    search_signal = re.search(
        r'\b(?:optim\w*|minimi\w*|gradient\w*|simplex\w*|nelder\w*|genetic\w*|candidate\w*|best\w*|iteration\w*)\b',
        code,
    )
    assert objective_signal and search_signal, \
        "optimizer.cpp does not contain sufficient evidence of an iterative parameter optimization algorithm."

    compile_result = subprocess.run(
        ["g++", "-std=c++17", "-O2", SOURCE, "-o", BINARY],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        timeout=120,
    )
    assert compile_result.returncode == 0, f"Failed to compile optimizer.cpp:\n{compile_result.stdout}"
    assert os.path.isfile(BINARY) and os.access(BINARY, os.X_OK), "Compilation did not produce an executable."

    if os.path.lexists(PARAMS):
        if os.path.isdir(PARAMS) and not os.path.islink(PARAMS):
            pytest.fail(f"{PARAMS} is a directory and cannot be regenerated by the optimizer.")
        os.unlink(PARAMS)

    try:
        run_result = subprocess.run(
            [BINARY],
            cwd="/home/user",
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=180,
        )
    except subprocess.TimeoutExpired as e:
        pytest.fail(f"Compiled optimizer timed out. Output:\n{e.stdout or ''}")

    assert run_result.returncode == 0, f"Compiled optimizer failed:\n{run_result.stdout}"
    assert os.path.exists(PARAMS), f"Running optimizer.cpp did not create {PARAMS}."
    assert stat.S_ISREG(os.lstat(PARAMS).st_mode), f"{PARAMS} must be a regular file."

    with open(PARAMS, "r", encoding="utf-8") as f:
        content = f.read()

    assert re.fullmatch(
        r'[ \t]*[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?[ \t]*,'
        r'[ \t]*[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?[ \t]*,'
        r'[ \t]*[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?[ \t]*(?:\n)?',
        content,
    ), f"{PARAMS} must contain exactly three comma-separated floating-point numbers on one line."

    try:
        params = content.strip().split(',')
        Cd_pred, vx0_pred, vy0_pred = map(float, params)
    except Exception as e:
        pytest.fail(f"Could not parse {PARAMS}. Expected 3 comma-separated floats. Error: {e}")

    assert all(math.isfinite(v) for v in (Cd_pred, vx0_pred, vy0_pred)), "Optimized parameters must be finite."

    gt_traj = simulate_trajectory(0.05, 15.0, -20.0)
    pred_traj = simulate_trajectory(Cd_pred, vx0_pred, vy0_pred)

    mse = 0.0
    for (gt_x, gt_y), (p_x, p_y) in zip(gt_traj, pred_traj):
        px_gt_x, px_gt_y = gt_x * 100, gt_y * 100
        px_p_x, px_p_y = p_x * 100, p_y * 100
        mse += (px_gt_x - px_p_x)**2 + (px_gt_y - px_p_y)**2
    mse /= len(gt_traj)

    assert mse <= 10.0, f"MSE is {mse:.2f}, which is greater than the threshold of 10.0"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
