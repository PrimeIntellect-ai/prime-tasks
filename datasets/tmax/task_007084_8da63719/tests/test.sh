import json
import math
import os
import subprocess
import tempfile

CSV_PATH = "/home/user/sensor_data.csv"
JSON_PATH = "/home/user/results.json"


def compute_expected(csv_text):
    lines = csv_text.strip().split('\n')
    valid_rows = []
    for line in lines[1:]:
        if not line.strip():
            continue
        parts = line.split(',')
        sensor_1 = float(parts[1])
        if sensor_1 > 50.0:
            continue
        sensor_2_str = parts[2].strip()
        valid_rows.append({
            "sensor_1": sensor_1,
            "sensor_2": float(sensor_2_str) if sensor_2_str else None,
            "sensor_3": int(parts[3]),
            "outcome": int(parts[4]),
        })

    present = [r["sensor_2"] for r in valid_rows if r["sensor_2"] is not None]
    mean_sensor_2 = sum(present) / len(present) if present else 0.0
    for row in valid_rows:
        if row["sensor_2"] is None:
            row["sensor_2"] = mean_sensor_2

    n = len(valid_rows)
    mean_sensor_1 = sum(r["sensor_1"] for r in valid_rows) / n
    covariance = sum(
        (r["sensor_1"] - mean_sensor_1) * (r["sensor_2"] - mean_sensor_2)
        for r in valid_rows
    ) / n

    conditioned = [r for r in valid_rows if r["sensor_3"] == 1]
    prob = (sum(r["outcome"] == 1 for r in conditioned) / len(conditioned)) if conditioned else 0.0
    return mean_sensor_2, covariance, prob


def assert_output_matches(csv_text):
    assert os.path.isfile(JSON_PATH), f"The file {JSON_PATH} does not exist."
    with open(JSON_PATH, "r") as f:
        data = json.load(f)

    expected = compute_expected(csv_text)
    keys = (
        "imputed_mean_sensor_2",
        "covariance_1_2",
        "prob_outcome_given_sensor_3",
    )
    for key, value in zip(keys, expected):
        assert key in data, f"Missing '{key}' in JSON."
        assert isinstance(data[key], (int, float)) and not isinstance(data[key], bool)
        assert math.isfinite(float(data[key]))
        assert math.isclose(float(data[key]), value, rel_tol=1e-3, abs_tol=1e-9), \
            f"Expected {key} to be close to {value}, got {data[key]}"


def rust_sources():
    sources = []
    for root, dirs, files in os.walk("/home/user"):
        dirs[:] = [d for d in dirs if d not in {"target", ".cargo", ".rustup"}]
        for name in files:
            path = os.path.join(root, name)
            if name.endswith(".rs") and os.path.isfile(path):
                sources.append(path)
    return sorted(sources)


def test_00_standalone_rust_program_compiles_and_runs_on_derived_input():
    assert os.path.isfile(CSV_PATH), f"The file {CSV_PATH} is missing."
    sources = rust_sources()
    assert sources, "No standalone Rust source file was found under /home/user."

    with open(CSV_PATH, "r") as f:
        original_csv = f.read()

    challenge_csv = """id,sensor_1,sensor_2,sensor_3,outcome
1,50.0,,1,0
2,2.0,4.0,1,1
3,100.0,999.0,1,1
4,-2.0,8.0,0,1
5,6.0,,1,1
"""

    errors = []
    selected_executable = None
    try:
        with tempfile.TemporaryDirectory() as build_dir:
            for index, source in enumerate(sources):
                executable = os.path.join(build_dir, f"submission_{index}")
                try:
                    subprocess.run(
                        ["rustc", "--edition=2021", source, "-O", "-o", executable],
                        cwd="/home/user", check=True, timeout=30,
                        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                    )

                    for csv_text in (original_csv, challenge_csv):
                        with open(CSV_PATH, "w") as f:
                            f.write(csv_text)
                        if os.path.exists(JSON_PATH):
                            os.remove(JSON_PATH)
                        subprocess.run(
                            [executable], cwd="/home/user", check=True, timeout=10,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                        )
                        assert_output_matches(csv_text)

                    selected_executable = executable
                    break
                except Exception as exc:
                    errors.append(f"{source}: {exc}")

            assert selected_executable is not None, \
                "No Rust source compiled with rustc alone and correctly processed both datasets. " + "; ".join(errors)

            # Leave the required output freshly generated by the verified Rust program
            # against the original dataset for the original assertions below.
            with open(CSV_PATH, "w") as f:
                f.write(original_csv)
            if os.path.exists(JSON_PATH):
                os.remove(JSON_PATH)
            subprocess.run(
                [selected_executable], cwd="/home/user", check=True, timeout=10,
                stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
            )
            assert_output_matches(original_csv)
    finally:
        with open(CSV_PATH, "w") as f:
            f.write(original_csv)


