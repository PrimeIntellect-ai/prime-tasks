#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'PY_EOF' > /tmp/test_final_state.py
import os
import re
import stat
import subprocess
import tempfile

answer_path = "/home/user/bottleneck_function.txt"
executable_path = "/home/user/align_calc"
expected = "numerical_integration_pdf"

# Preserve and strengthen the original existence/content assertions.
assert os.path.isfile(answer_path), (
    f"File {answer_path} is missing. Did you write the bottleneck function name to this file?"
)
with open(answer_path, "rb") as f:
    raw_answer = f.read()
assert raw_answer in (expected.encode(), (expected + "\n").encode()), (
    f"The file {answer_path} must contain only the exact bottleneck function name. "
    f"Found: {raw_answer!r}"
)
answer = raw_answer.decode().rstrip("\n")
assert expected in answer, (
    f"The file {answer_path} does not contain the correct bottleneck function name. "
    f"Found: {answer!r}"
)

# The requested artifact must be an executable ELF binary, not a script or text file.
assert os.path.isfile(executable_path), f"Compiled executable {executable_path} is missing."
mode = os.stat(executable_path).st_mode
assert stat.S_ISREG(mode) and mode & 0o111, f"{executable_path} is not an executable regular file."
with open(executable_path, "rb") as f:
    assert f.read(4) == b"\x7fELF", f"{executable_path} is not an ELF executable."

# Execute the submitted binary in a fresh directory so profiling data must be
# generated by this run rather than supplied in advance.
with tempfile.TemporaryDirectory(prefix="verify_profile_") as workdir:
    env = os.environ.copy()
    env.pop("GMON_OUT_PREFIX", None)
    run = subprocess.run(
        [executable_path], cwd=workdir, env=env,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        timeout=120, text=True
    )
    assert run.returncode == 0, (
        f"{executable_path} exited with status {run.returncode}. stderr: {run.stderr}"
    )

    gmon_path = os.path.join(workdir, "gmon.out")
    assert os.path.isfile(gmon_path) and os.path.getsize(gmon_path) > 0, (
        "Running align_calc did not generate a nonempty gmon.out; it may not have been compiled with gprof instrumentation."
    )

    profile = subprocess.run(
        ["gprof", "-b", "-p", executable_path, gmon_path],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        timeout=60, text=True
    )
    assert profile.returncode == 0, f"gprof failed: {profile.stderr}"

# Parse the ordered rows of gprof's flat profile and independently obtain the
# highest-runtime function other than main.
rows = []
in_table = False
for line in profile.stdout.splitlines():
    if not in_table:
        if re.search(r"\bname\s*$", line) and "%" in line:
            in_table = True
        continue
    if not line.strip():
        if rows:
            break
        continue
    match = re.match(
        r"^\s*([0-9]+(?:\.[0-9]+)?)\s+\S+\s+\S+\s+"
        r"(?:(?:[0-9]+)\s+\S+\s+\S+\s+)?(.+?)\s*$",
        line,
    )
    if match:
        rows.append((float(match.group(1)), match.group(2).strip()))

assert rows, "gprof produced no parseable flat-profile rows."

def function_name(display_name):
    match = re.match(r"^([A-Za-z_][A-Za-z0-9_:~]*)\s*\(", display_name)
    return match.group(1) if match else display_name.split()[0]

profiled_names = [function_name(name) for _, name in rows]
non_main = [name for name in profiled_names if name != "main"]
assert non_main, "The gprof flat profile contains no function other than main."
profile_bottleneck = non_main[0]
assert profile_bottleneck == expected, (
    f"The submitted executable's flat-profile bottleneck is {profile_bottleneck!r}, not {expected!r}."
)
assert answer == profile_bottleneck, (
    f"The answer file says {answer!r}, but the executed artifact's gprof flat profile says {profile_bottleneck!r}."
)
PY_EOF

if python3 /tmp/test_final_state.py 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
