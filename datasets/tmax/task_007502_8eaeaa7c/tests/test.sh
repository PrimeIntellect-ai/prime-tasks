#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import fcntl
import itertools
import os
import re
import secrets
import shutil
import subprocess
import time

import pytest

SOURCE = "/home/user/archive_tool.c"
BACKUP = "/home/user/safe_backup.txt"
DATA_DIR = "/home/user/data"
EXPECTED = {}


@pytest.fixture(scope="session", autouse=True)
def build_and_run_submission():
    assert os.path.isfile(SOURCE), f"{SOURCE} does not exist."

    # Compile the submitted source so the tested output must be produced by it.
    executable = "/tmp/archive_tool_verified"
    result = subprocess.run(
        ["gcc", "-std=gnu11", "-O2", SOURCE, "-o", executable],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20,
    )
    assert result.returncode == 0, f"archive_tool.c did not compile:\n{result.stderr}"

    # Recreate the documented fixture and add unpredictable files so a hard-coded
    # archive cannot pass. Expected output is derived from these bytes.
    shutil.rmtree(DATA_DIR, ignore_errors=True)
    os.makedirs(DATA_DIR, mode=0o777)

    files = {
        "report1.log": b"System report 1: Error occurred at connection \xA9 - requires immediate attention. Padding out the file so it is safely over 50 bytes long.",
        "report2.log": b"System report 2: The network interface \xE6 failed to initialize properly. Padding out the file so it is safely over 50 bytes long.",
        "tiny.log": b"Too short \xA9.",
        "ignore.txt": b"Not a log file. Not a log file. Not a log file. Not a log file.",
    }

    locked_name = f"live_{secrets.token_hex(8)}.log"
    other_name = f"audit_{secrets.token_hex(8)}.log"
    files[locked_name] = (
        f"Live randomized record {secrets.token_hex(24)} with Latin-1 markers ".encode("ascii")
        + b"\xA9 and \xE6; this record is intentionally longer than fifty bytes."
    )
    files[other_name] = (
        f"Independent randomized record {secrets.token_hex(24)} ".encode("ascii")
        + b"contains \xD1 and enough padding to exceed the required size threshold."
    )
    files[f"short_{secrets.token_hex(5)}.log"] = b"short \xA9"
    files[f"wrong_{secrets.token_hex(5)}.txt"] = b"x" * 100

    for name, raw in files.items():
        with open(os.path.join(DATA_DIR, name), "wb") as f:
            f.write(raw)
        os.chmod(os.path.join(DATA_DIR, name), 0o666)

    global EXPECTED
    EXPECTED = {
        name: raw.decode("iso-8859-1").encode("utf-8")
        for name, raw in files.items()
        if name.endswith(".log") and len(raw) > 50
    }

    try:
        os.remove(BACKUP)
    except FileNotFoundError:
        pass

    # Hold an exclusive lock on one valid input. A conforming program requesting
    # LOCK_SH must appear as a blocked FLOCK reader until this verifier releases it.
    lock_file = open(os.path.join(DATA_DIR, locked_name), "rb")
    fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
    proc = subprocess.Popen(
        [executable],
        cwd="/home/user",
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )

    saw_blocked_shared_flock = False
    try:
        deadline = time.time() + 3
        while time.time() < deadline and proc.poll() is None:
            try:
                with open("/proc/locks", "r", encoding="ascii") as f:
                    locks = f.read()
                pattern = rf"->\s+FLOCK\s+ADVISORY\s+READ\s+{proc.pid}\b"
                if re.search(pattern, locks):
                    saw_blocked_shared_flock = True
                    break
            except OSError:
                pass
            time.sleep(0.05)
    finally:
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)
        lock_file.close()

    try:
        stdout, stderr = proc.communicate(timeout=10)
    except subprocess.TimeoutExpired:
        proc.kill()
        stdout, stderr = proc.communicate()
        pytest.fail("Compiled archive tool did not terminate after the lock was released.")

    assert saw_blocked_shared_flock, "The program did not acquire a shared flock() on the live log file."
    assert proc.returncode == 0, f"Compiled archive tool failed:\nstdout: {stdout}\nstderr: {stderr}"
    assert os.path.isfile(BACKUP), "/home/user/safe_backup.txt was not generated by the compiled program."

    with open(BACKUP, "rb") as f:
        actual = f.read()

    # Check the complete archive, allowing directory traversal in any order and
    # an optional single formatting newline after each converted file body.
    records = {
        name: f"--- {name} ---\n".encode("utf-8") + body
        for name, body in EXPECTED.items()
    }
    valid_archives = set()
    names = tuple(records)
    for order in itertools.permutations(names):
        for trailing_newlines in itertools.product((b"", b"\n"), repeat=len(order)):
            valid_archives.add(b"".join(records[name] + nl for name, nl in zip(order, trailing_newlines)))

    assert actual in valid_archives, (
        "safe_backup.txt does not exactly contain every eligible log's fully converted contents, "
        "or it contains excluded/extra data."
    )


def test_safe_backup_exists():
    """Verify that /home/user/safe_backup.txt exists."""
    assert os.path.isfile(BACKUP), "/home/user/safe_backup.txt was not generated."


def test_safe_backup_contents():
    """Preserve the original archive assertions."""
    with open(BACKUP, "rb") as f:
        content_bytes = f.read()

    try:
        content_str = content_bytes.decode("utf-8")
    except UnicodeDecodeError:
        pytest.fail("/home/user/safe_backup.txt does not contain valid UTF-8.")

    assert "--- report1.log ---" in content_str, "report1.log was not included in the backup."
    assert "--- report2.log ---" in content_str, "report2.log was not included in the backup."
    assert "tiny.log" not in content_str, "tiny.log should not be included (size < 50 bytes)."
    assert "ignore.txt" not in content_str, "ignore.txt should not be included (wrong extension)."
    assert "©" in content_str, "ISO-8859-1 '\\xA9' was not correctly converted to UTF-8 '©'."
    assert "æ" in content_str, "ISO-8859-1 '\\xE6' was not correctly converted to UTF-8 'æ'."


def test_c_source_exists_and_contents():
    """Preserve the original source assertions."""
    assert os.path.isfile(SOURCE), f"{SOURCE} does not exist."
    with open(SOURCE, "r", encoding="utf-8", errors="ignore") as f:
        source_code = f.read()
    assert "flock" in source_code, f"{SOURCE} does not contain 'flock'."
    assert "iconv_open" in source_code, f"{SOURCE} does not contain 'iconv_open'."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
