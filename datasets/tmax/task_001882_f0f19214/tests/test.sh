#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import glob
import json
import os
import random
import re
import stat
import subprocess
import tempfile
import time
import uuid

import pytest

DETECT_SCRIPT = "/home/user/detect_anomaly.sh"
BENCH_SCRIPT = "/home/user/bootstrap_bench.sh"
BENCH_LOG = "/home/user/bench.log"
CLEAN_CORPUS = "/app/corpus/clean"
EVIL_CORPUS = "/app/corpus/evil"


def test_detect_anomaly_exists_and_executable():
    assert os.path.isfile(DETECT_SCRIPT), f"{DETECT_SCRIPT} does not exist."
    assert os.access(DETECT_SCRIPT, os.X_OK), f"{DETECT_SCRIPT} is not executable."


def test_bootstrap_bench_exists_and_executable():
    assert os.path.isfile(BENCH_SCRIPT), f"{BENCH_SCRIPT} does not exist."
    assert os.access(BENCH_SCRIPT, os.X_OK), f"{BENCH_SCRIPT} is not executable."


def test_adversarial_corpus():
    clean_files = glob.glob(os.path.join(CLEAN_CORPUS, "*.json"))
    evil_files = glob.glob(os.path.join(EVIL_CORPUS, "*.json"))

    assert len(clean_files) > 0, f"No clean JSON files found in {CLEAN_CORPUS}."
    assert len(evil_files) > 0, f"No evil JSON files found in {EVIL_CORPUS}."

    bypassed_evil = []
    modified_clean = []

    for f in evil_files:
        res = subprocess.run([DETECT_SCRIPT, f], capture_output=True)
        if res.returncode != 1:
            bypassed_evil.append(os.path.basename(f))

    for f in clean_files:
        res = subprocess.run([DETECT_SCRIPT, f], capture_output=True)
        if res.returncode != 0:
            modified_clean.append(os.path.basename(f))

    error_msg = []
    if bypassed_evil:
        error_msg.append(f"{len(bypassed_evil)} of {len(evil_files)} evil bypassed: {', '.join(bypassed_evil)}")
    if modified_clean:
        error_msg.append(f"{len(modified_clean)} of {len(clean_files)} clean modified (rejected): {', '.join(modified_clean)}")
    if error_msg:
        pytest.fail(" | ".join(error_msg))


def test_detector_on_generated_inputs():
    rng = random.SystemRandom()
    cases = [
        (1.8, 0.0),       # exactly on the anomaly threshold
        (1.79, 0.0),
        (2.0, 1.0),
        (2.4, 1.0),
        (-3.0, -9.0),
        (7.25, 4.5),
    ]
    for _ in range(30):
        cases.append((round(rng.uniform(-20, 20), 4), round(rng.uniform(-20, 20), 4)))

    with tempfile.TemporaryDirectory(prefix="detector_cases_") as case_dir:
        saw_clean = False
        saw_anomaly = False
        for x, y in cases:
            score = 2.5 * x - 1.5 * y + 0.5
            expected = 1 if score >= 5.0 else 0
            saw_anomaly |= expected == 1
            saw_clean |= expected == 0
            path = os.path.join(case_dir, f"sample_{uuid.uuid4().hex}.json")
            with open(path, "w") as f:
                json.dump({"x": x, "y": y}, f)
            res = subprocess.run([DETECT_SCRIPT, path], capture_output=True, timeout=5)
            assert res.returncode == expected, (
                f"Wrong result for x={x}, y={y}: expected exit {expected}, got {res.returncode}"
            )
            assert res.stdout == b"", f"Detector wrote unexpected stdout for x={x}, y={y}: {res.stdout!r}"
        assert saw_clean and saw_anomaly


def _read_numeric_bench_log():
    assert os.path.isfile(BENCH_LOG), f"{BENCH_LOG} was not generated by {BENCH_SCRIPT}."
    with open(BENCH_LOG, "r") as f:
        content = f.read().strip()
    assert re.fullmatch(r"\d+(\.\d+)?", content), (
        f"Expected a numeric value (milliseconds) in {BENCH_LOG}, but got: '{content}'"
    )
    return float(content)


def test_bootstrap_bench_execution_and_sampling():
    original = open(DETECT_SCRIPT, "rb").read()
    original_mode = stat.S_IMODE(os.stat(DETECT_SCRIPT).st_mode)

    wrapper = b'''#!/bin/bash
printf '%s\\t%s\\n' "$PWD" "$1" >> "$BENCH_TRACE"
sleep "$DETECT_DELAY"
exit 0
'''

    runs = []
    try:
        with tempfile.TemporaryDirectory(prefix="bench_corpus_") as corpus_dir:
            valid_paths = set()
            for i in range(3):
                path = os.path.join(corpus_dir, f"item_{uuid.uuid4().hex}.json")
                with open(path, "w") as f:
                    json.dump({"x": i, "y": i + 1}, f)
                valid_paths.add(os.path.realpath(path))

            with open(DETECT_SCRIPT, "wb") as f:
                f.write(wrapper)
            os.chmod(DETECT_SCRIPT, 0o755)

            for delay in (0.004, 0.018):
                trace = os.path.join(corpus_dir, f"trace_{uuid.uuid4().hex}.log")
                env = os.environ.copy()
                env["BENCH_TRACE"] = trace
                env["DETECT_DELAY"] = str(delay)
                if os.path.exists(BENCH_LOG):
                    os.remove(BENCH_LOG)

                started = time.monotonic()
                res = subprocess.run(
                    [BENCH_SCRIPT, corpus_dir],
                    cwd="/home/user",
                    capture_output=True,
                    text=True,
                    env=env,
                    timeout=20,
                )
                elapsed_ms = (time.monotonic() - started) * 1000.0
                assert res.returncode == 0, (
                    f"{BENCH_SCRIPT} failed with exit code {res.returncode}. Stderr: {res.stderr}"
                )
                reported_ms = _read_numeric_bench_log()

                assert os.path.isfile(trace), "The benchmark never invoked ./detect_anomaly.sh"
                with open(trace, "r") as f:
                    lines = [line.rstrip("\n") for line in f if line.rstrip("\n")]
                assert len(lines) == 50, f"Expected exactly 50 detector invocations, got {len(lines)}"

                sampled = []
                for line in lines:
                    cwd, sep, argument = line.partition("\t")
                    assert sep and argument, f"Detector was invoked without a JSON path: {line!r}"
                    resolved = os.path.realpath(argument if os.path.isabs(argument) else os.path.join(cwd, argument))
                    assert resolved in valid_paths, f"Benchmark sampled a file outside its input directory: {argument}"
                    sampled.append(resolved)

                assert len(set(sampled)) < 50, "Sampling did not operate with replacement"
                assert len(set(sampled)) >= 2, "Sampling repeatedly selected only one file"

                forced_ms = delay * 50 * 1000.0
                assert reported_ms >= forced_ms * 0.75, (
                    f"Reported time {reported_ms} ms is too small for 50 timed detector calls"
                )
                assert reported_ms <= elapsed_ms + 250.0, (
                    f"Reported time {reported_ms} ms exceeds the measured benchmark runtime {elapsed_ms:.1f} ms"
                )
                runs.append((sampled, reported_ms))

            assert runs[0][0] != runs[1][0], "Two bootstrap runs produced the identical sample sequence"
            assert runs[1][1] > runs[0][1] * 1.7, (
                "bench.log did not reflect the substantially different detector inference times"
            )
    finally:
        with open(DETECT_SCRIPT, "wb") as f:
            f.write(original)
        os.chmod(DETECT_SCRIPT, original_mode)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
