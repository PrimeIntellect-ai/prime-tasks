cat << 'TEST_EOF' > /tmp/test_final_state.py
import atexit
import csv
import json
import os
import random
import re
import secrets
import string
import subprocess

import pytest

ETL = "/home/user/etl.go"
NODES = "/home/user/data/nodes.csv"
EDGES = "/home/user/data/edges.csv"
OUTPUT = "/home/user/output.json"

_original_files = {}
for path in (NODES, EDGES, OUTPUT):
    if os.path.exists(path):
        with open(path, "rb") as f:
            _original_files[path] = f.read()
    else:
        _original_files[path] = None


def restore_files():
    for path, content in _original_files.items():
        if content is None:
            try:
                os.remove(path)
            except FileNotFoundError:
                pass
        else:
            with open(path, "wb") as f:
                f.write(content)


atexit.register(restore_files)


def run_etl():
    try:
        os.remove(OUTPUT)
    except FileNotFoundError:
        pass
    env = os.environ.copy()
    env["CGO_ENABLED"] = "1"
    result = subprocess.run(
        ["go", "run", ETL],
        cwd="/home/user",
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=120,
    )
    assert result.returncode == 0, (
        "go run /home/user/etl.go failed.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    assert os.path.isfile(OUTPUT), "/home/user/output.json was not generated by the Go program."


def load_output_strict():
    with open(OUTPUT, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail("/home/user/output.json is not a valid JSON file.")
    assert type(data) is dict
    assert set(data) == {"top_nodes"}, "The JSON root must contain only the 'top_nodes' key."
    assert type(data["top_nodes"]) is list, "'top_nodes' must be a list."
    for row in data["top_nodes"]:
        assert type(row) is dict
        assert set(row) == {"id", "category", "in_weight", "rank"}
        assert type(row["id"]) is str
        assert type(row["category"]) is str
        assert type(row["in_weight"]) is int
        assert type(row["rank"]) is int
    return data


def write_csv(path, header, rows):
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)


def test_etl_go_exists():
    assert os.path.isfile(ETL), "/home/user/etl.go does not exist. The task requires writing the Go program."


def test_source_uses_in_memory_sqlite_and_window_query():
    with open(ETL, "r", encoding="utf-8") as f:
        source = f.read()
    assert re.search(r"sqlite", source, re.I), "The Go program must use a SQLite driver."
    assert re.search(r":memory:|mode\s*=\s*memory", source, re.I), "SQLite must be configured as an in-memory database."
    assert re.search(r"database/sql", source), "The program must execute its SQLite work through Go's SQL API."
    assert re.search(r"\bOpen\s*\(", source), "The program must open the SQLite database."
    assert re.search(r"\bSUM\s*\(", source, re.I), "The SQL query must aggregate incoming weights with SUM."
    assert re.search(r"\bRANK\s*\(", source, re.I), "The SQL query must calculate rank with a window function."
    assert re.search(r"\bOVER\b", source, re.I), "The ranking expression must use SQL OVER."
    assert re.search(r"\bPARTITION\s+BY\b", source, re.I), "The SQL window must partition rankings by category."


def test_program_runs_on_original_input():
    run_etl()


def test_output_json_exists():
    assert os.path.isfile(OUTPUT), "/home/user/output.json does not exist. Did the Go program run successfully?"


def test_output_json_content():
    with open(OUTPUT, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail("/home/user/output.json is not a valid JSON file.")

    assert "top_nodes" in data, "The JSON must contain a 'top_nodes' key at the root level."
    top_nodes = data["top_nodes"]
    assert isinstance(top_nodes, list), "'top_nodes' must be a list."

    expected_nodes = [
        {"id": "N8", "category": "auth", "in_weight": 1000, "rank": 1},
        {"id": "N7", "category": "auth", "in_weight": 500, "rank": 2},
        {"id": "N6", "category": "backend", "in_weight": 200, "rank": 1},
        {"id": "N5", "category": "backend", "in_weight": 120, "rank": 2},
        {"id": "N3", "category": "frontend", "in_weight": 50, "rank": 1},
        {"id": "N1", "category": "frontend", "in_weight": 25, "rank": 2}
    ]

    assert len(top_nodes) == len(expected_nodes), f"Expected {len(expected_nodes)} nodes in 'top_nodes', but found {len(top_nodes)}."

    for i, expected in enumerate(expected_nodes):
        actual = top_nodes[i]
        assert actual.get("id") == expected["id"], f"Expected node id '{expected['id']}' at index {i}, got '{actual.get('id')}'."
        assert actual.get("category") == expected["category"], f"Expected category '{expected['category']}' at index {i}, got '{actual.get('category')}'."
        assert actual.get("in_weight") == expected["in_weight"], f"Expected in_weight {expected['in_weight']} at index {i}, got {actual.get('in_weight')}."
        assert actual.get("rank") == expected["rank"], f"Expected rank {expected['rank']} at index {i}, got {actual.get('rank')}."


def test_randomized_csv_ingestion_aggregation_ranking_and_filtering():
    rng = random.Random(secrets.randbits(128))
    token = "".join(secrets.choice(string.ascii_lowercase) for _ in range(10))
    categories = [f"a_{token}", f"m_{token}", f"z_{token}"]
    node_rows = []
    edge_rows = []
    expected = []

    for category_index, category in enumerate(categories):
        destinations = [f"dst_{token}_{category_index}_{i}" for i in range(4)]
        sources = [f"src_{token}_{category_index}_{i}" for i in range(8)]
        node_rows.extend((node_id, category) for node_id in destinations + sources)

        # Unique totals in deliberately non-ID order; each total is split over
        # two rows so the implementation must aggregate before ranking.
        totals = rng.sample(range(1000, 9000), 4)
        totals.sort(reverse=True)
        assignment = list(totals)
        rng.shuffle(assignment)
        category_results = []
        for i, (dst, total) in enumerate(zip(destinations, assignment)):
            first = rng.randint(1, total - 1)
            edge_rows.append((sources[2 * i], dst, first))
            edge_rows.append((sources[2 * i + 1], dst, total - first))
            category_results.append((total, dst))

        category_results.sort(reverse=True)
        for rank, (total, dst) in enumerate(category_results[:2], 1):
            expected.append({
                "id": dst,
                "category": category,
                "in_weight": total,
                "rank": rank,
            })

    rng.shuffle(node_rows)
    rng.shuffle(edge_rows)
    write_csv(NODES, ["id", "category"], node_rows)
    write_csv(EDGES, ["src", "dst", "weight"], edge_rows)

    run_etl()
    actual = load_output_strict()["top_nodes"]
    expected.sort(key=lambda row: (row["category"], row["rank"]))
    assert actual == expected, "The program failed on verifier-generated CSV data."


if __name__ == "__main__":
    raise SystemExit(pytest.main([__file__, "-x", "--tb=short"]))
TEST_EOF

