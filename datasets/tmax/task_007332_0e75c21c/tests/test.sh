#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import secrets
import subprocess
import tempfile
import pytest

EXPECTED_SOURCE = b'''#include <stdio.h>
#include <string.h>
#include <math.h>

int main(int argc, char **argv) {
    if (argc < 2) return 1;
    double val = sqrt(256.0); // Intentional math dependency
    char buf[16];
    // Buffer overflow vulnerability
    strcpy(buf, argv[1]);
    printf("Status: OK, Val: %f, Input: %s\\n", val, buf);
    return 0;
}
'''

RECOVERED = "/home/user/recovered.c"
APP = "/home/user/app.bin"
PAYLOAD_FILE = "/home/user/crash_payload.txt"


def run_program(path, argument=None):
    command = [path] if argument is None else [path, argument]
    try:
        return subprocess.run(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=3,
            check=False,
        )
    except subprocess.TimeoutExpired:
        pytest.fail(f"{path} hung while processing a verifier input")


def is_segfault(result):
    return result.returncode in (-11, 139)


def test_recovered_c_exists_and_content():
    assert os.path.isfile(RECOVERED), f"File {RECOVERED} is missing."
    with open(RECOVERED, "rb") as source_file:
        content = source_file.read()
    assert b"sqrt(256.0);" in content, f"File {RECOVERED} does not contain the expected recovered source code."
    assert content == EXPECTED_SOURCE, f"File {RECOVERED} is not the exact deleted source code."


def test_app_bin_exists_and_executable():
    assert os.path.isfile(APP), f"File {APP} is missing."
    assert os.access(APP, os.X_OK), f"File {APP} is not executable."
    with open(APP, "rb") as executable:
        assert executable.read(4) == b"\x7fELF", f"File {APP} is not an ELF executable."


def test_app_bin_linked_correctly():
    try:
        output = subprocess.check_output(["ldd", APP], stderr=subprocess.STDOUT).decode("utf-8", "replace")
    except subprocess.CalledProcessError as error:
        pytest.fail(f"Failed to run ldd on {APP}: {error.output.decode('utf-8', 'replace')}")
    assert "libm.so" in output, f"File {APP} does not link to libm (math library)."


def test_app_matches_recovered_program():
    with tempfile.TemporaryDirectory() as directory:
        reference_source = os.path.join(directory, "reference.c")
        reference_binary = os.path.join(directory, "reference.bin")
        with open(reference_source, "wb") as source_file:
            source_file.write(EXPECTED_SOURCE)

        compile_result = subprocess.run(
            ["gcc", reference_source, "-o", reference_binary,
             "-fno-stack-protector", "-Wl,--no-as-needed", "-lm"],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
        assert compile_result.returncode == 0, compile_result.stderr.decode("utf-8", "replace")

        # Exercise answers generated by an independently compiled copy. Random
        # inputs prevent a fixed unrelated executable from satisfying this test.
        inputs = ["", "A", "hello", "monitor", "123456789012345"]
        inputs.extend(secrets.token_hex(6) for _ in range(12))

        for value in inputs:
            expected = run_program(reference_binary, value)
            actual = run_program(APP, value)
            assert actual.returncode == expected.returncode, f"app.bin returned the wrong status for input {value!r}"
            assert actual.stdout == expected.stdout, f"app.bin produced the wrong output for input {value!r}"
            assert actual.stderr == expected.stderr, f"app.bin produced unexpected diagnostics for input {value!r}"

        expected_no_arg = run_program(reference_binary)
        actual_no_arg = run_program(APP)
        assert actual_no_arg.returncode == expected_no_arg.returncode
        assert actual_no_arg.stdout == expected_no_arg.stdout


def test_crash_payload_is_genuinely_minimal():
    assert os.path.isfile(PAYLOAD_FILE), f"File {PAYLOAD_FILE} is missing."
    with open(PAYLOAD_FILE, "r") as payload_file:
        payload = payload_file.read().strip("\n")

    assert len(payload) > 0, "Payload is empty."
    assert all(character == "A" for character in payload), "Payload contains characters other than 'A'."
    assert len(payload) <= 4096, "Payload is unreasonably large."

    crashing_result = run_program(APP, payload)
    assert is_segfault(crashing_result), f"Payload did not cause a segfault. Exit code: {crashing_result.returncode}"

    # Check every shorter nonempty all-A string, rather than only payload[:-1].
    for length in range(1, len(payload)):
        shorter_result = run_program(APP, "A" * length)
        assert not is_segfault(shorter_result), f"A shorter all-A payload of length {length} also caused a segfault."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
