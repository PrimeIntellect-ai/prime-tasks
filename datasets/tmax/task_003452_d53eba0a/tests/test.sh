#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import signal
import stat
import subprocess
import time


def matching_pids(text):
    result = []
    needle = text.encode()
    for entry in os.listdir('/proc'):
        if not entry.isdigit() or int(entry) == os.getpid():
            continue
        try:
            with open(f'/proc/{entry}/cmdline', 'rb') as f:
                cmdline = f.read()
            if needle in cmdline:
                result.append(int(entry))
        except (FileNotFoundError, PermissionError, ProcessLookupError):
            pass
    return result


def stop_old_deployment():
    targets = ['/home/user/storage_monitor.sh', '/home/user/backend/server.sh']
    pids = set()
    for target in targets:
        pids.update(matching_pids(target))
    for sig in (signal.SIGTERM, signal.SIGKILL):
        for pid in list(pids):
            try:
                os.kill(pid, sig)
            except ProcessLookupError:
                pass
        time.sleep(0.3)
    try:
        os.unlink('/home/user/run/backend_v2.sock')
    except FileNotFoundError:
        pass


def socket_owner_pids(path):
    inode = os.stat(path).st_ino
    wanted = f'socket:[{inode}]'
    owners = []
    for entry in os.listdir('/proc'):
        if not entry.isdigit():
            continue
        fd_dir = f'/proc/{entry}/fd'
        try:
            for fd in os.listdir(fd_dir):
                try:
                    if os.readlink(f'{fd_dir}/{fd}') == wanted:
                        owners.append(int(entry))
                        break
                except (FileNotFoundError, PermissionError):
                    pass
        except (FileNotFoundError, PermissionError, ProcessLookupError):
            pass
    return owners


def parent_pid(pid):
    try:
        with open(f'/proc/{pid}/status') as f:
            for line in f:
                if line.startswith('PPid:'):
                    return int(line.split()[1])
    except (FileNotFoundError, PermissionError, ProcessLookupError):
        pass
    return 0


def has_ancestor(pid, ancestors):
    seen = set()
    while pid > 1 and pid not in seen:
        if pid in ancestors:
            return True
        seen.add(pid)
        pid = parent_pid(pid)
    return pid in ancestors


def test_complete_deployment_behavior():
    config_path = '/home/user/proxy/config.env'
    monitor_script = '/home/user/storage_monitor.sh'
    deploy_script = '/home/user/deploy.sh'
    log_path = '/home/user/logs/backend.log'
    result_path = '/home/user/deployment_result.log'
    sock_path = '/home/user/run/backend_v2.sock'

    # Preserve the original configuration and executable assertions.
    assert os.path.isfile(config_path), f'{config_path} is missing.'
    with open(config_path) as f:
        config = f.read()
    assert 'UPSTREAM_SOCKET=/home/user/run/backend_v2.sock' in config, \
        'The UPSTREAM_SOCKET in config.env was not updated to backend_v2.sock.'

    assert os.path.isfile(monitor_script), f'{monitor_script} is missing.'
    assert os.path.isfile(deploy_script), f'{deploy_script} is missing.'
    assert os.stat(monitor_script).st_mode & stat.S_IXUSR, f'{monitor_script} is not executable.'
    assert os.stat(deploy_script).st_mode & stat.S_IXUSR, f'{deploy_script} is not executable.'

    # Remove processes that could make a no-op deploy script appear successful, then
    # execute the submitted deployment artifact itself.
    stop_old_deployment()
    with open(result_path, 'w') as f:
        f.write('STALE RESULT\n')

    started = time.monotonic()
    try:
        completed = subprocess.run(
            [deploy_script],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=15,
            check=False,
        )
    except subprocess.TimeoutExpired:
        assert False, 'deploy.sh did not finish after starting its background services.'
    elapsed = time.monotonic() - started
    assert completed.returncode == 0, f'deploy.sh exited with status {completed.returncode}.'
    assert elapsed >= 4.5, 'deploy.sh did not wait approximately 5 seconds before its health check.'

    # Preserve the original deployment-result assertion, while requiring fresh,
    # exact output generated by the executed health check.
    assert os.path.isfile(result_path), f'{result_path} is missing. Did you run deploy.sh?'
    with open(result_path) as f:
        result = f.read()
    assert '200 OK: Backend Healthy' in result, \
        f'Expected successful health check message in {result_path}, got: {result}'
    assert result == '200 OK: Backend Healthy\n', \
        f'deployment_result.log was not strictly redirected health-check output: {result!r}'

    monitor_pids = matching_pids(monitor_script)
    server_pids = matching_pids('/home/user/backend/server.sh')
    assert monitor_pids, 'storage_monitor.sh is not running in the background.'
    assert server_pids, 'server.sh is not running in the background.'

    # Preserve the socket assertions and prove it is a live backend socket, not just
    # an arbitrary Unix socket.
    assert os.path.exists(sock_path), f'Unix socket {sock_path} does not exist.'
    assert stat.S_ISSOCK(os.stat(sock_path).st_mode), f'{sock_path} is not a socket.'
    owners = socket_owner_pids(sock_path)
    assert owners, 'No live process owns the backend Unix socket.'
    assert any(has_ancestor(pid, set(server_pids)) for pid in owners), \
        'The backend socket is not served by the server.sh deployment process.'

    response = subprocess.run(
        ['python3', '-c',
         "import socket; s=socket.socket(socket.AF_UNIX); "
         "s.settimeout(2); s.connect('/home/user/run/backend_v2.sock'); "
         "s.sendall(b'GET / HTTP/1.1\\r\\n\\r\\n'); "
         "print(s.recv(1024).decode(), end='')"],
        capture_output=True,
        text=True,
        timeout=4,
    )
    assert response.returncode == 0, f'Could not communicate with backend socket: {response.stderr}'
    assert '200 OK' in response.stdout and 'Backend V2' in response.stdout, \
        f'Unexpected backend response: {response.stdout!r}'

    health = subprocess.run(
        ['/home/user/proxy/health_check.sh'], capture_output=True, text=True, timeout=5
    )
    assert health.returncode == 0, f'health_check.sh failed: {health.stdout}{health.stderr}'
    assert health.stdout == '200 OK: Backend Healthy\n', \
        f'Unexpected health-check output: {health.stdout!r}'

    assert os.path.isfile(log_path), \
        f'{log_path} is missing. The backend server might not be running.'

    # Pause the aggressive logger and exercise the submitted monitor at both the
    # exact boundary and just above it. Truncation must retain the same file inode.
    for pid in server_pids:
        os.kill(pid, signal.SIGSTOP)
    try:
        with open(log_path, 'wb') as f:
            f.write(b'x' * 50000)
        inode_before = os.stat(log_path).st_ino
        time.sleep(2.5)
        assert os.path.getsize(log_path) == 50000, \
            'storage_monitor.sh truncated the log at 50000 bytes; it should act only above 50000.'

        with open(log_path, 'ab') as f:
            f.write(b'x')
        deadline = time.monotonic() + 4.5
        while time.monotonic() < deadline and os.path.getsize(log_path) != 0:
            time.sleep(0.1)
        assert os.path.getsize(log_path) == 0, \
            'storage_monitor.sh did not truncate a log larger than 50000 bytes.'
        assert os.stat(log_path).st_ino == inode_before, \
            'The monitor replaced or deleted backend.log instead of truncating it.'
    finally:
        for pid in server_pids:
            try:
                os.kill(pid, signal.SIGCONT)
            except ProcessLookupError:
                pass

    # Preserve the original live-process and bounded-log checks in the final state.
    time.sleep(2.5)
    size = os.path.getsize(log_path)
    assert size < 200000, \
        f'Log file size is {size} bytes, which exceeds the expected threshold. The storage monitor is not working correctly.'

    ps_output = subprocess.check_output(['ps', '-ef']).decode('utf-8')
    assert 'storage_monitor.sh' in ps_output, 'storage_monitor.sh is not running in the background.'
    assert 'server.sh' in ps_output, 'server.sh is not running in the background.'
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
