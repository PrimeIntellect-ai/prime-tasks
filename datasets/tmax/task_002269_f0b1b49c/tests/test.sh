#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import csv
import heapq
import json
import os
import random
import secrets
import subprocess

import pytest

SCRIPT_PATH = "/home/user/lineage.py"
CSV_PATH = "/home/user/dependencies.csv"
REPORT_PATH = "/home/user/report.json"


def run_script():
    if os.path.exists(REPORT_PATH):
        os.remove(REPORT_PATH)
    result = subprocess.run(
        ["python3", SCRIPT_PATH],
        cwd="/home/user",
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert result.returncode == 0, (
        f"lineage.py exited with status {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


def load_report():
    assert os.path.isfile(REPORT_PATH), f"The output file {REPORT_PATH} was not created."
    with open(REPORT_PATH, "r") as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as exc:
            pytest.fail(f"The file {REPORT_PATH} does not contain valid JSON: {exc}")


def derive_expected(rows):
    graph = {}
    for child, parent, processing_time in rows:
        graph.setdefault(child, []).append((parent, int(processing_time)))

    ancestors = set()
    stack = ["Omega"]
    while stack:
        node = stack.pop()
        for parent, _ in graph.get(node, []):
            if parent not in ancestors:
                ancestors.add(parent)
                stack.append(parent)

    distances = {"Omega": 0}
    queue = [(0, "Omega")]
    while queue:
        distance, node = heapq.heappop(queue)
        if distance != distances[node]:
            continue
        if node == "Alpha":
            return distance, sorted(ancestors)
        for parent, weight in graph.get(node, []):
            candidate = distance + weight
            if candidate < distances.get(parent, float("inf")):
                distances[parent] = candidate
                heapq.heappush(queue, (candidate, parent))
    pytest.fail("Verifier-generated graph unexpectedly has no path from Omega to Alpha")


def assert_strict_report(data, expected_time, expected_ancestors):
    assert isinstance(data, dict), "report.json must contain a JSON object."
    assert set(data.keys()) == {"shortest_time", "ancestors"}, \
        "report.json must contain exactly 'shortest_time' and 'ancestors'."
    assert type(data["shortest_time"]) is int, "The 'shortest_time' value should be an integer."
    assert data["shortest_time"] == expected_time, \
        f"Expected shortest_time to be {expected_time}, but got {data['shortest_time']}."
    assert isinstance(data["ancestors"], list), "The 'ancestors' value should be a list."
    assert data["ancestors"] == expected_ancestors, \
        f"Expected sorted ancestors {expected_ancestors}, but got {data['ancestors']}."
    assert all(isinstance(item, str) for item in data["ancestors"]), \
        "Every ancestor must be a string."


def test_lineage_script_exists():
    """Verify that the lineage.py script was created."""
    assert os.path.isfile(SCRIPT_PATH), f"The script {SCRIPT_PATH} does not exist."


@pytest.fixture(scope="module")
def original_execution():
    run_script()


def test_report_json_exists(original_execution):
    """Verify that the report.json file was generated by executing the script."""
    assert os.path.isfile(REPORT_PATH), f"The output file {REPORT_PATH} was not created."


def test_report_json_content(original_execution):
    """Verify the content generated for the supplied dependency data."""
    data = load_report()

    assert "shortest_time" in data, "The key 'shortest_time' is missing from report.json."
    assert "ancestors" in data, "The key 'ancestors' is missing from report.json."

    expected_shortest_time = 27
    expected_ancestors = ["Alpha", "Beta", "Delta", "Epsilon", "Gamma"]

    assert data["shortest_time"] == expected_shortest_time, \
        f"Expected shortest_time to be {expected_shortest_time}, but got {data['shortest_time']}."
    assert isinstance(data["ancestors"], list), "The 'ancestors' value should be a list."
    assert sorted(data["ancestors"]) == expected_ancestors, \
        f"Expected ancestors to be {expected_ancestors}, but got {sorted(data['ancestors'])}."

    assert_strict_report(data, expected_shortest_time, expected_ancestors)


def test_script_processes_changed_dependency_graphs():
    original_csv = open(CSV_PATH, "rb").read()
    rng = random.Random(int.from_bytes(secrets.token_bytes(16), "big"))

    try:
        for _ in range(2):
            suffix = secrets.token_hex(5)
            p, q, r, s, t, u = [f"{name}_{suffix}" for name in "PQRSTU"]
            weights = [rng.randint(1, 40) for _ in range(9)]
            rows = [
                ("Omega", p, weights[0]),
                ("Omega", q, weights[1]),
                (p, r, weights[2]),
                (r, "Alpha", weights[3]),
                (q, s, weights[4]),
                (s, "Alpha", weights[5]),
                (q, r, weights[6]),
                (p, t, weights[7]),
                (t, u, weights[8]),
            ]
            expected_time, expected_ancestors = derive_expected(rows)

            with open(CSV_PATH, "w", newline="") as f:
                writer = csv.writer(f)
                writer.writerow(["Child", "Parent", "Processing_Time"])
                writer.writerows(rows)

            run_script()
            assert_strict_report(load_report(), expected_time, expected_ancestors)
    finally:
        with open(CSV_PATH, "wb") as f:
            f.write(original_csv)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
