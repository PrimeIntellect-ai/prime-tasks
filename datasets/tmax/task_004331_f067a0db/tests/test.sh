import configparser
import http.server
import os
import random
import re
import signal
import socketserver
import string
import subprocess
import threading
import time
import uuid
from pathlib import Path

import pytest

APP = Path('/home/user/app')
LOG = APP / 'logs/access.log'
METRICS = APP / 'metrics.txt'
PROJECT = APP / 'rust_monitor'
BINARY = PROJECT / 'target/release/rust_monitor'


def wait_until(predicate, timeout=10.0, interval=0.02):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return True
        time.sleep(interval)
    return False


def stop_process(proc):
    if proc is None or proc.poll() is not None:
        return
    proc.terminate()
    try:
        proc.wait(timeout=2)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait(timeout=2)


def test_01_release_build_and_real_backlog_benchmark():
    main_rs = PROJECT / 'src/main.rs'
    cargo_toml = PROJECT / 'Cargo.toml'
    assert main_rs.is_file(), 'Rust source src/main.rs is missing'
    assert cargo_toml.is_file(), 'Cargo.toml is missing'

    cargo = '/root/.cargo/bin/cargo'
    subprocess.run([cargo, 'build', '--release'], cwd=PROJECT, check=True, timeout=300)
    assert BINARY.is_file() and os.access(BINARY, os.X_OK), 'Release binary was not produced'
    file_out = subprocess.check_output(['file', str(BINARY)], text=True)
    assert 'ELF' in file_out, f'Release artifact is not a native executable: {file_out}'

    # Construct a fresh, verifier-randomized 500,000-line backlog. Each error has
    # a secret token, so a fixed-output process cannot satisfy the behavioral test.
    rng = random.SystemRandom()
    error_positions = set(rng.sample(range(500000), 500))
    tokens = [f'BACKLOG-{uuid.uuid4().hex}' for _ in range(500)]
    token_iter = iter(tokens)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open('w', buffering=1024 * 1024) as f:
        for i in range(500000):
            if i in error_positions:
                f.write(f'ERROR: Critical failure {next(token_iter)}\n')
            else:
                f.write(f'INFO: Request processed smoothly {rng.randrange(1 << 30):08x}\n')

    received = []
    lock = threading.Lock()

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_POST(self):
            length = int(self.headers.get('Content-Length', '0'))
            body = self.rfile.read(length).decode('utf-8', errors='replace')
            with lock:
                received.append(body)
            self.send_response(200)
            self.end_headers()

        def log_message(self, fmt, *args):
            pass

    class Server(socketserver.ThreadingMixIn, http.server.HTTPServer):
        daemon_threads = True
        allow_reuse_address = True

    server = Server(('127.0.0.1', 8080), Handler)
    server_thread = threading.Thread(target=server.serve_forever, daemon=True)
    server_thread.start()

    METRICS.unlink(missing_ok=True)
    start_wall_ns = time.time_ns()
    proc = subprocess.Popen([str(BINARY)], cwd=PROJECT,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        assert wait_until(lambda: METRICS.is_file(), timeout=3), \
            'The compiled monitor did not create metrics.txt while processing the backlog'
        metric_mtime_ns = METRICS.stat().st_mtime_ns
        observed_ms = (metric_mtime_ns - start_wall_ns) / 1_000_000
        assert observed_ms >= 0, 'metrics.txt was not freshly generated by this execution'
        assert observed_ms <= 150, \
            f'Externally observed backlog parsing completion took {observed_ms:.2f}ms'

        content = METRICS.read_text()
        assert re.fullmatch(r'[0-9]+\n?', content), \
            f'metrics.txt must contain only an integer number of milliseconds, got {content!r}'
        claimed_ms = int(content.strip())
        assert claimed_ms <= 150, f'Reported parsing time was {claimed_ms}ms'

        # Destroy the input immediately after the monitor says parsing is complete.
        # It must therefore already have parsed and retained all randomized errors.
        LOG.write_text('INFO: benchmark input retired\n')

        def all_seen():
            with lock:
                combined = '\n'.join(received)
            return all(token in combined for token in tokens)

        assert wait_until(all_seen, timeout=25, interval=0.05), \
            f'Monitor did not emit alerts for all randomized backlog errors (received {len(received)} POSTs)'
    finally:
        stop_process(proc)
        server.shutdown()
        server.server_close()
        server_thread.join(timeout=2)


def test_02_logrotate_configuration_is_semantic_and_valid():
    path = APP / 'logrotate.conf'
    assert path.is_file(), 'logrotate.conf is missing'
    subprocess.run(['logrotate', '--debug', str(path)], check=True,
                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)

    lines = []
    for raw in path.read_text().splitlines():
        line = raw.split('#', 1)[0].strip()
        if line:
            lines.append(line)

    start = None
    depth = 0
    body = []
    for line in lines:
        if start is None and line.startswith('/home/user/app/logs/access.log') and '{' in line:
            start = True
            depth = line.count('{') - line.count('}')
            continue
        if start:
            depth += line.count('{') - line.count('}')
            if depth <= 0:
                break
            body.append(line)

    assert start is not None, 'No logrotate block for /home/user/app/logs/access.log'
    assert any(re.fullmatch(r'daily', x) for x in body), 'daily rotation is not configured'
    assert any(re.fullmatch(r'rotate\s+7', x) for x in body), 'exactly 7 backups are not configured'
    assert any(re.fullmatch(r'compress', x) for x in body), 'compression is not enabled'
    assert any(re.fullmatch(r'create\s+0?644(?:\s+\S+\s+\S+)?', x) for x in body), \
        'new log creation with mode 0644 is not configured'


def test_03_supervisor_configuration_and_random_end_to_end_alerts():
    conf_path = APP / 'supervisord.conf'
    assert conf_path.is_file(), 'supervisord.conf is missing'

    parser = configparser.RawConfigParser()
    parser.read(conf_path)
    programs = [s for s in parser.sections() if s.lower().startswith('program:')]
    assert len(programs) >= 3, 'supervisord.conf must define all three managed programs'

    required = {
        'web_server.py': False,
        'git_auditor.py': False,
        '/home/user/app/rust_monitor/target/release/rust_monitor': False,
    }
    for section in programs:
        command = parser.get(section, 'command', fallback='')
        for needle in required:
            if needle in command:
                required[needle] = True
                value = parser.get(section, 'autorestart', fallback='unexpected').strip().lower()
                assert value in ('true', 'unexpected'), f'{section} does not restart on failure'
    assert all(required.values()), f'Supervisor does not manage the required commands: {required}'

    LOG.write_text('INFO: supervisor startup marker\n')
    before_size = LOG.stat().st_size
    supervisor = subprocess.Popen(['supervisord', '-c', str(conf_path)],
                                  stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        assert wait_until(lambda: LOG.exists() and LOG.stat().st_size > before_size,
                          timeout=8, interval=0.1), 'Managed web_server.py did not write to the access log'

        tokens = [f'LIVE-{uuid.uuid4().hex}' for _ in range(3)]
        with LOG.open('a') as f:
            for token in tokens:
                f.write(f'ERROR: Dynamic verifier failure {token}\n')
            f.flush()
            os.fsync(f.fileno())

        git_dir = '/home/user/git/alerts.git'

        def committed_all():
            result = subprocess.run(
                ['git', '--git-dir', git_dir, 'log', '--all', '--pretty=%B'],
                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
            return result.returncode == 0 and all(t in result.stdout for t in tokens)

        assert wait_until(committed_all, timeout=15, interval=0.2), \
            'Random live errors were not delivered through the monitor and committed by git_auditor'
    finally:
        stop_process(supervisor)
TEST_EOF

