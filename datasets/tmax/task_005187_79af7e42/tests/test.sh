#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import secrets
import sqlite3
import stat
import subprocess

import pytest

DB_PATH = "/home/user/audit.db"
JSON_PATH = "/home/user/violations.json"
SOURCE_PATH = "/home/user/audit.c"
TOOL_PATH = "/home/user/audit_tool"
VERIFIED_TOOL_PATH = "/tmp/audit_tool_from_source"

QUERY = """
WITH paths AS (
  SELECT u1.id AS source_user, u2.id AS target_user,
         (u1.risk_weight + r1.risk_weight + r2.risk_weight + u2.risk_weight) AS path_risk,
         ROW_NUMBER() OVER (
           PARTITION BY u2.id
           ORDER BY (u1.risk_weight + r1.risk_weight + r2.risk_weight + u2.risk_weight) DESC,
                    u1.id ASC
         ) AS rn
  FROM nodes u1
  JOIN edges e1 ON u1.id = e1.src AND e1.rel_type = 'ASSUMES'
  JOIN nodes r1 ON e1.dst = r1.id AND r1.type = 'ROLE'
  JOIN edges e2 ON r1.id = e2.src AND e2.rel_type = 'INHERITS'
  JOIN nodes r2 ON e2.dst = r2.id AND r2.type = 'ROLE'
  JOIN edges e3 ON r2.id = e3.src AND e3.rel_type = 'CAN_MODIFY'
  JOIN nodes u2 ON e3.dst = u2.id AND u2.type = 'USER'
  WHERE u1.type = 'USER' AND u1.id != u2.id
)
SELECT target_user, source_user, path_risk
FROM paths
WHERE rn = 1
ORDER BY target_user ASC;
"""


def expected_from_database():
    assert os.path.isfile(DB_PATH), f"Database {DB_PATH} is missing, cannot compute expected results."
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    try:
        rows = conn.execute(QUERY).fetchall()
    except sqlite3.Error as exc:
        pytest.fail(f"Failed to query database for expected results: {exc}")
    finally:
        conn.close()
    return [
        {
            "target_user": row["target_user"],
            "source_user": row["source_user"],
            "path_risk": row["path_risk"],
        }
        for row in rows
    ]


def execute_and_read(tool):
    if os.path.exists(JSON_PATH):
        os.unlink(JSON_PATH)
    result = subprocess.run(
        [tool], cwd="/home/user", stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True, timeout=15
    )
    assert result.returncode == 0, (
        f"{tool} exited with status {result.returncode}. "
        f"stdout: {result.stdout!r}; stderr: {result.stderr!r}"
    )
    assert os.path.isfile(JSON_PATH), f"Running {tool} did not create {JSON_PATH}."
    try:
        with open(JSON_PATH, "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except json.JSONDecodeError as exc:
        pytest.fail(f"The file {JSON_PATH} does not contain valid JSON: {exc}")
    assert isinstance(data, list), "The JSON output must be a top-level array."
    return data


def test_c_source_and_executable_exist():
    assert os.path.isfile(SOURCE_PATH), "The C source file /home/user/audit.c is missing."
    assert os.path.isfile(TOOL_PATH), "The compiled executable /home/user/audit_tool is missing."
    assert os.access(TOOL_PATH, os.X_OK), "The file /home/user/audit_tool is not executable."
    with open(TOOL_PATH, "rb") as handle:
        assert handle.read(4) == b"\x7fELF", "/home/user/audit_tool must be a compiled native executable."


def test_source_compiles_and_uses_sqlite_c_api():
    compile_result = subprocess.run(
        ["gcc", "-std=c11", "-O2", SOURCE_PATH, "-o", VERIFIED_TOOL_PATH, "-lsqlite3", "-lm"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=30
    )
    assert compile_result.returncode == 0, (
        f"/home/user/audit.c did not compile with the SQLite C library: {compile_result.stderr}"
    )

    symbols = subprocess.run(
        ["nm", "-D", VERIFIED_TOOL_PATH], stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, text=True, timeout=10, check=True
    ).stdout
    assert "sqlite3_open" in symbols, "The C program does not call sqlite3_open/sqlite3_open_v2."
    assert any(name in symbols for name in ("sqlite3_prepare_v2", "sqlite3_exec", "sqlite3_get_table")), (
        "The C program does not use a SQLite C API query function."
    )
    if "sqlite3_prepare_v2" in symbols:
        assert "sqlite3_step" in symbols, "A prepared SQLite query must be executed with sqlite3_step."


def test_tool_generates_current_violations_json():
    expected = expected_from_database()
    actual = execute_and_read(TOOL_PATH)
    assert actual == expected, (
        f"The content generated by {TOOL_PATH} does not match the expected output. "
        f"Expected: {expected}, Actual: {actual}"
    )


def test_violations_json_exists_and_valid():
    assert os.path.isfile(JSON_PATH), f"The output file {JSON_PATH} is missing."
    with open(JSON_PATH, "r", encoding="utf-8") as handle:
        try:
            data = json.load(handle)
        except json.JSONDecodeError:
            pytest.fail(f"The file {JSON_PATH} does not contain valid JSON.")
    assert isinstance(data, list), "The JSON output must be a top-level array."


def test_violations_json_content():
    expected = expected_from_database()
    with open(JSON_PATH, "r", encoding="utf-8") as handle:
        try:
            actual = json.load(handle)
        except json.JSONDecodeError:
            pytest.fail(f"The file {JSON_PATH} does not contain valid JSON.")
    assert actual == expected, (
        f"The content of {JSON_PATH} does not match the expected output. "
        f"Expected: {expected}, Actual: {actual}"
    )


def create_unseen_database(path):
    token = secrets.token_hex(8)
    ids = {name: f"{name}_{token}" for name in
           ("UA", "UB", "UC", "UD", "R1", "R2", "R3", "R4", "R5", "DECOY")}
    conn = sqlite3.connect(path)
    try:
        conn.executescript("""
            CREATE TABLE nodes (id VARCHAR, type VARCHAR, risk_weight INTEGER);
            CREATE TABLE edges (src VARCHAR, dst VARCHAR, rel_type VARCHAR);
        """)
        conn.executemany("INSERT INTO nodes VALUES (?, ?, ?)", [
            (ids["UA"], "USER", 10), (ids["UB"], "USER", 20),
            (ids["UC"], "USER", 15), (ids["UD"], "USER", 25),
            (ids["R1"], "ROLE", 50), (ids["R2"], "ROLE", 30),
            (ids["R3"], "ROLE", 40), (ids["R4"], "ROLE", 60),
            (ids["R5"], "ROLE", 45), (ids["DECOY"], "SERVICE", 9999),
        ])
        conn.executemany("INSERT INTO edges VALUES (?, ?, ?)", [
            (ids["UA"], ids["R1"], "ASSUMES"),
            (ids["R1"], ids["R2"], "INHERITS"),
            (ids["R2"], ids["UB"], "CAN_MODIFY"),
            (ids["UC"], ids["R3"], "ASSUMES"),
            (ids["R3"], ids["R2"], "INHERITS"),
            (ids["UC"], ids["R1"], "ASSUMES"),
            (ids["R1"], ids["R4"], "INHERITS"),
            (ids["R4"], ids["UD"], "CAN_MODIFY"),
            (ids["UD"], ids["R3"], "ASSUMES"),
            (ids["R3"], ids["R4"], "INHERITS"),
            (ids["R4"], ids["UA"], "CAN_MODIFY"),
            (ids["UB"], ids["R5"], "ASSUMES"),
            (ids["R5"], ids["R4"], "INHERITS"),
            # Self-path that must be excluded.
            (ids["UB"], ids["R1"], "ASSUMES"),
            # Wrong relationship/type decoys.
            (ids["DECOY"], ids["R1"], "ASSUMES"),
            (ids["UA"], ids["R3"], "CAN_MODIFY"),
        ])
        conn.commit()
    finally:
        conn.close()


def test_both_artifacts_query_an_unseen_database():
    original_bytes = open(DB_PATH, "rb").read()
    original_stat = os.stat(DB_PATH)
    temp_db = DB_PATH + ".verifier-new"
    if os.path.exists(temp_db):
        os.unlink(temp_db)
    try:
        create_unseen_database(temp_db)
        os.replace(temp_db, DB_PATH)
        expected = expected_from_database()
        assert expected, "Verifier's generated test database unexpectedly produced no paths."

        for tool in (TOOL_PATH, VERIFIED_TOOL_PATH):
            actual = execute_and_read(tool)
            assert actual == expected, (
                f"{tool} did not query the unseen SQLite database correctly. "
                f"Expected: {expected}, Actual: {actual}"
            )
    finally:
        if os.path.exists(temp_db):
            os.unlink(temp_db)
        with open(DB_PATH, "wb") as handle:
            handle.write(original_bytes)
        os.chmod(DB_PATH, stat.S_IMODE(original_stat.st_mode))
        os.chown(DB_PATH, original_stat.st_uid, original_stat.st_gid)
        try:
            execute_and_read(TOOL_PATH)
        except Exception:
            pass
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
