#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import secrets
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

SCRIPT_PATH = Path("/home/user/config_tracker.py")
CONFIG_DIR = Path("/home/user/configs")
SUMMARY_PATH = Path("/home/user/summary.md")
LOG_PATH = Path("/home/user/pipeline.log")


def run_tracker():
    result = subprocess.run(
        [sys.executable, str(SCRIPT_PATH)],
        cwd="/home/user",
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
    )
    assert result.returncode == 0, (
        f"config_tracker.py failed with exit code {result.returncode}\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


def expected_report(configs):
    all_keys = sorted({key for values in configs.values() for key in values})
    divergent = []
    for key in all_keys:
        present = {env: values[key] for env, values in configs.items() if key in values}
        distinct = {json.dumps(value, sort_keys=True) for value in present.values()}
        if len(distinct) > 1:
            divergent.append((key, present))

    lines = [
        "# Configuration Divergence Report",
        f"Total Keys: {len(all_keys)}",
        f"Divergent Keys: {len(divergent)}",
        "",
        "## Divergent Details",
    ]
    for key, present in divergent:
        pairs = ", ".join(f"{env}: {present[env]}" for env in sorted(present))
        lines.append(f"- Key: {key} | Values: {pairs}")
    return lines, len(all_keys), len(divergent)


def test_script_executes_and_tracks_runtime_configurations():
    assert SCRIPT_PATH.exists(), f"{SCRIPT_PATH} is missing"
    assert SCRIPT_PATH.is_file(), f"{SCRIPT_PATH} is not a file"
    assert stat.S_ISREG(SCRIPT_PATH.stat().st_mode), f"{SCRIPT_PATH} is not a regular file"

    token = secrets.token_hex(5)
    environments = [f"alpha_{token}", f"beta_{token}", f"gamma_{token}"]
    keys = {
        "same": f"a_same_{token}",
        "divergent": f"b_divergent_{token}",
        "number": f"c_number_{token}",
        "partial": f"d_partial_{token}",
        "single": f"e_single_{token}",
    }
    configs = {
        environments[0]: {
            keys["same"]: f"stable_{token}",
            keys["divergent"]: f"first_{token}",
            keys["number"]: 11,
            keys["partial"]: f"left_{token}",
            keys["single"]: f"only_{token}",
        },
        environments[1]: {
            keys["same"]: f"stable_{token}",
            keys["divergent"]: f"second_{token}",
            keys["number"]: 11,
            keys["partial"]: f"right_{token}",
        },
        environments[2]: {
            keys["same"]: f"stable_{token}",
            keys["divergent"]: f"third_{token}",
            keys["number"]: 29,
        },
    }

    backup_root = Path(tempfile.mkdtemp(prefix="config_tracker_backup_"))
    backup_configs = backup_root / "configs"
    shutil.copytree(CONFIG_DIR, backup_configs)

    try:
        shutil.rmtree(CONFIG_DIR)
        CONFIG_DIR.mkdir(parents=True)
        for environment, values in configs.items():
            with open(CONFIG_DIR / f"{environment}.json", "w", encoding="utf-8") as handle:
                json.dump(values, handle)

        for output in (SUMMARY_PATH, LOG_PATH):
            if output.exists() or output.is_symlink():
                output.unlink()

        run_tracker()

        assert SUMMARY_PATH.is_file(), f"{SUMMARY_PATH} was not generated by the script"
        assert LOG_PATH.is_file(), f"{LOG_PATH} was not generated by the script"

        expected_lines, total_keys, divergent_count = expected_report(configs)
        actual_lines = SUMMARY_PATH.read_text(encoding="utf-8").strip().splitlines()
        assert actual_lines == expected_lines, (
            "Generated report did not match the runtime configuration data.\n"
            f"Expected:\n{chr(10).join(expected_lines)}\n"
            f"Actual:\n{chr(10).join(actual_lines)}"
        )

        log_content = LOG_PATH.read_text(encoding="utf-8")
        for environment in environments:
            assert f"INFO: Loaded environment: {environment}" in log_content
        assert (
            f"INFO: Analyzed {total_keys} total keys. Found {divergent_count} divergent keys."
            in log_content
        )
        assert "INFO: Report generated at /home/user/summary.md" in log_content
    finally:
        if CONFIG_DIR.exists():
            shutil.rmtree(CONFIG_DIR)
        shutil.copytree(backup_configs, CONFIG_DIR)
        shutil.rmtree(backup_root)
        for output in (SUMMARY_PATH, LOG_PATH):
            if output.exists() or output.is_symlink():
                output.unlink()
        run_tracker()


def test_summary_md_exists_and_content():
    summary_path = "/home/user/summary.md"
    assert os.path.isfile(summary_path), f"{summary_path} is missing. Did the script run successfully?"

    with open(summary_path, 'r') as f:
        content = f.read()

    expected_content = """# Configuration Divergence Report
Total Keys: 5
Divergent Keys: 4

## Divergent Details
- Key: api_url | Values: dev: http://dev.api, prod: https://api.domain.com, staging: http://staging.api
- Key: db_host | Values: dev: localhost, prod: prod-db, staging: staging-db
- Key: debug | Values: dev: true, prod: false, staging: true
- Key: retry_count | Values: dev: 3, prod: 5, staging: 3"""

    # We check if the expected lines are present to allow minor trailing whitespace differences
    for expected_line in expected_content.strip().split("\n"):
        assert expected_line in content, f"Expected line not found in {summary_path}:\n{expected_line}"


def test_pipeline_log_exists_and_content():
    log_path = "/home/user/pipeline.log"
    assert os.path.isfile(log_path), f"{log_path} is missing. Did the script log its progress?"

    with open(log_path, 'r') as f:
        log_content = f.read()

    expected_lines = [
        "INFO: Loaded environment: dev",
        "INFO: Loaded environment: staging",
        "INFO: Loaded environment: prod",
        "INFO: Analyzed 5 total keys. Found 4 divergent keys.",
        "INFO: Report generated at /home/user/summary.md"
    ]

    for line in expected_lines:
        assert line in log_content, f"Expected log line not found in {log_path}:\n{line}"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
