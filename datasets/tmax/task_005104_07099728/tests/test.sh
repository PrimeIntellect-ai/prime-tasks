#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import cmath
import json
import math
import os
import random
import re
import subprocess
from pathlib import Path

import pytest


def test_extractor_executable_exists():
    path = "/home/user/bin/extractor"
    assert os.path.isfile(path), f"Expected executable {path} to exist."
    assert os.access(path, os.X_OK), f"Expected {path} to be executable."


def test_signal_csv_exists_and_valid():
    path = "/home/user/data/signal.csv"
    assert os.path.isfile(path), f"Expected file {path} to exist."

    with open(path, 'r') as f:
        lines = f.read().strip().split('\n')

    assert len(lines) == 1024, f"Expected {path} to contain exactly 1024 lines, found {len(lines)}."

    try:
        float(lines[0])
    except ValueError:
        pytest.fail(f"First line of {path} is not a valid float: {lines[0]}")


def test_rust_project_exists():
    cargo_path = "/home/user/processor/Cargo.toml"
    assert os.path.isfile(cargo_path), f"Expected Rust project Cargo.toml at {cargo_path}."


def test_processed_csv_exists_and_valid():
    path = "/home/user/data/processed.csv"
    assert os.path.isfile(path), f"Expected file {path} to exist."

    with open(path, 'r') as f:
        lines = f.read().strip().split('\n')

    assert len(lines) == 1024, f"Expected {path} to contain exactly 1024 lines, found {len(lines)}."

    for i, line in enumerate(lines):
        if '.' in line:
            decimals = len(line.split('.')[1])
            assert decimals == 4, f"Expected exactly 4 decimal places at index {i}, got {decimals} in '{line}'."
        else:
            pytest.fail(f"Expected floating point number with 4 decimal places at index {i}, got '{line}'.")

        t = i / 1024.0
        expected = math.sin(2 * math.pi * 10 * t)

        try:
            actual = float(line)
        except ValueError:
            pytest.fail(f"Invalid float at index {i}: {line}")

        assert abs(expected - actual) <= 1e-3, f"Mismatch at index {i}: expected {expected}, got {actual}"


def test_extractor_is_real_and_generated_signal():
    executable = Path('/home/user/bin/extractor')
    signal = Path('/home/user/data/signal.csv')

    assert executable.read_bytes()[:4] == b'\x7fELF', "extractor must be a compiled ELF executable"

    generated = subprocess.run(
        [str(executable), '1024'],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
    ).stdout
    assert generated == signal.read_bytes(), "signal.csv was not generated by extractor with argument 1024"

    probe_n = random.SystemRandom().randint(33, 97)
    probe = subprocess.run(
        [str(executable), str(probe_n)],
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
    ).stdout.strip().splitlines()
    assert len(probe) == probe_n
    for i, text in enumerate(probe):
        actual = float(text)
        expected = math.sin(2 * math.pi * 10 * i / probe_n) + 0.5 * math.sin(2 * math.pi * 100 * i / probe_n)
        assert abs(actual - expected) <= 1e-6, f"extractor produced an incorrect value at index {i}"


def test_processor_executes_rustfft_pipeline_on_unseen_input():
    project = Path('/home/user/processor')
    manifest = project / 'Cargo.toml'
    signal_path = Path('/home/user/data/signal.csv')
    processed_path = Path('/home/user/data/processed.csv')

    metadata_result = subprocess.run(
        ['cargo', 'metadata', '--format-version', '1', '--no-deps'],
        cwd=project,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=60,
    )
    metadata = json.loads(metadata_result.stdout)
    package = next(
        (p for p in metadata['packages'] if Path(p['manifest_path']).resolve() == manifest.resolve()),
        None,
    )
    assert package is not None, "Cargo.toml is not a valid Cargo package"
    rustfft_deps = [d for d in package['dependencies'] if d['name'] == 'rustfft']
    assert rustfft_deps, "processor must declare the rustfft crate as a dependency"

    aliases = {d.get('rename') or d['name'] for d in rustfft_deps}
    sources = []
    for source_path in project.rglob('*.rs'):
        if 'target' not in source_path.parts:
            text = source_path.read_text(errors='replace')
            text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
            text = re.sub(r'//.*', '', text)
            sources.append(text)
    source_text = '\n'.join(sources)
    assert sources, "processor must contain Rust source files"
    assert any(re.search(r'\b' + re.escape(alias) + r'\b', source_text) for alias in aliases), \
        "Rust source must use the declared rustfft crate"

    original_signal = signal_path.read_bytes()
    original_processed = processed_path.read_bytes() if processed_path.exists() else None

    rng = random.SystemRandom()
    values = [rng.uniform(-2.0, 2.0) for _ in range(1024)]
    serialized = ''.join(f'{value:.9f}\n' for value in values)
    values = [float(x) for x in serialized.splitlines()]

    try:
        signal_path.write_text(serialized)
        if processed_path.exists():
            processed_path.unlink()

        result = subprocess.run(
            ['cargo', 'run', '--quiet'],
            cwd=project,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=180,
        )
        assert result.returncode == 0, f"cargo run failed:\n{result.stderr}"
        assert processed_path.is_file(), "Running the Rust project did not create processed.csv"

        lines = processed_path.read_text().splitlines()
        assert len(lines) == 1024, f"Expected processed.csv to contain 1024 lines, found {len(lines)}"
        pattern = re.compile(r'^-?(?:\d+)\.\d{4}$')
        assert all(pattern.fullmatch(line) for line in lines), "Every output must have exactly four decimal places"
        actual = [float(line) for line in lines]
        assert all(math.isfinite(x) for x in actual), "Output contains a non-finite value"

        n = 1024
        kept_bins = list(range(32)) + list(range(993, 1024))
        spectrum = {}
        for k in kept_bins:
            spectrum[k] = sum(
                value * cmath.exp(-2j * math.pi * k * index / n)
                for index, value in enumerate(values)
            )

        for index, got in enumerate(actual):
            expected = sum(
                spectrum[k] * cmath.exp(2j * math.pi * k * index / n)
                for k in kept_bins
            ).real / n
            assert abs(got - expected) <= 6e-4, \
                f"Incorrect dynamically tested output at index {index}: expected {expected:.4f}, got {got:.4f}"
    finally:
        signal_path.write_bytes(original_signal)
        if original_processed is None:
            if processed_path.exists():
                processed_path.unlink()
        else:
            processed_path.write_bytes(original_processed)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
