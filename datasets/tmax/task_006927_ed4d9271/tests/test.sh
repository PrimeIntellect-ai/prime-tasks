#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import builtins
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd
import pytest
from sklearn.model_selection import KFold
from sklearn.neighbors import NearestNeighbors

SCRIPT_PATH = '/home/user/pipeline.py'
RAW_PATH = '/home/user/raw_ratings.csv'
RESULTS_PATH = '/home/user/experiment_results.json'

RUNNER = r'''
import builtins
import os
import runpy
import sys

real_import = builtins.__import__

def checked_import(name, globals=None, locals=None, fromlist=(), level=0):
    top = name.split('.', 1)[0]
    if top in {'numpy', 'pandas', 'scipy', 'sklearn'}:
        if os.environ.get('OMP_NUM_THREADS') != '1':
            raise RuntimeError(
                'OMP_NUM_THREADS must be set to 1 before importing numerical libraries; '
                f"found {os.environ.get('OMP_NUM_THREADS')!r} while importing {name}"
            )
    return real_import(name, globals, locals, fromlist, level)

builtins.__import__ = checked_import
runpy.run_path(sys.argv[1], run_name='__main__')

required_modules = ['pandas', 'sklearn.neighbors', 'sklearn.model_selection']
missing = [name for name in required_modules if name not in sys.modules]
if missing:
    raise RuntimeError('Pipeline did not use required modules: ' + ', '.join(missing))
'''


def expected_results(csv_bytes):
    from io import BytesIO

    frame = pd.read_csv(BytesIO(csv_bytes))
    frame = frame.dropna()
    counts = frame.groupby('user_id')['user_id'].transform('size')
    frame = frame[counts >= 3]
    matrix = frame.pivot(index='user_id', columns='item_id', values='rating').fillna(0.0)

    scores = {}
    splitter = KFold(n_splits=3, shuffle=True, random_state=42)
    for k in [2, 3, 4]:
        fold_means = []
        for train_idx, validation_idx in splitter.split(matrix):
            train = matrix.iloc[train_idx]
            validation = matrix.iloc[validation_idx]
            model = NearestNeighbors(metric='cosine', n_neighbors=k)
            model.fit(train)
            distances, _ = model.kneighbors(validation)
            fold_means.append(float(distances.mean()))
        scores[k] = float(np.mean(fold_means))

    best_k = min(scores, key=scores.get)
    return {
        'best_k': best_k,
        'best_mean_distance': round(scores[best_k], 4),
    }


def run_pipeline(csv_bytes):
    original = open(RAW_PATH, 'rb').read()
    try:
        with open(RAW_PATH, 'wb') as handle:
            handle.write(csv_bytes)
        if os.path.exists(RESULTS_PATH):
            os.remove(RESULTS_PATH)

        env = os.environ.copy()
        env['OMP_NUM_THREADS'] = '9'
        completed = subprocess.run(
            [sys.executable, '-c', RUNNER, SCRIPT_PATH],
            cwd='/home/user',
            env=env,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=60,
        )
        assert completed.returncode == 0, (
            'pipeline.py failed when executed.\n'
            f'stdout:\n{completed.stdout}\n'
            f'stderr:\n{completed.stderr}'
        )
        assert os.path.exists(RESULTS_PATH), (
            f'{RESULTS_PATH} was not generated by executing pipeline.py.'
        )
        try:
            with open(RESULTS_PATH, 'r') as handle:
                return json.load(handle)
        except json.JSONDecodeError as exc:
            pytest.fail(f'{RESULTS_PATH} is not valid JSON: {exc}')
    finally:
        with open(RAW_PATH, 'wb') as handle:
            handle.write(original)


def assert_result(result, expected):
    assert 'best_k' in result, "Missing 'best_k' in results JSON."
    assert 'best_mean_distance' in result, "Missing 'best_mean_distance' in results JSON."
    assert result['best_k'] == expected['best_k'], (
        f"Expected best_k to be {expected['best_k']}, got {result['best_k']}"
    )
    assert result['best_mean_distance'] == expected['best_mean_distance'], (
        'Expected best_mean_distance to be '
        f"{expected['best_mean_distance']}, got {result['best_mean_distance']}"
    )


def test_pipeline_script_exists():
    assert os.path.exists(SCRIPT_PATH), f'{SCRIPT_PATH} does not exist.'
    assert os.path.isfile(SCRIPT_PATH), f'{SCRIPT_PATH} is not a regular file.'
    with open(SCRIPT_PATH, 'r') as handle:
        content = handle.read()
    assert 'OMP_NUM_THREADS' in content, (
        'The script does not seem to configure OMP_NUM_THREADS.'
    )


def test_experiment_results():
    assert os.path.exists(RAW_PATH), 'raw_ratings.csv is missing.'
    original_csv = open(RAW_PATH, 'rb').read()
    result = run_pipeline(original_csv)
    assert_result(result, expected_results(original_csv))


