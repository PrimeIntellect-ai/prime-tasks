#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import secrets
import struct
import subprocess

VM = "/home/user/vm"
SOURCE = "/home/user/vm.c"
TEST_BIN = "/home/user/test.bin"
RESULT_LOG = "/home/user/test_result.log"


def make_sum_program(values):
    program = bytearray()
    for value in values:
        program.append(0x01)
        program.extend(struct.pack("<i", value))
    program.extend(b"\x02" * (len(values) - 1))
    program.append(0x03)
    return bytes(program)


REQUIRED_VALUES = [10, 20, 30, 40, 50, 60]
REQUIRED_PROGRAM = make_sum_program(REQUIRED_VALUES)

# These programs are generated only after the agent has finished. Each forces
# the stack to resize, and the expected result is independently derived here.
HIDDEN_CASES = [list(range(1, 33))]
for _ in range(4):
    count = 9 + secrets.randbelow(40)
    HIDDEN_CASES.append([secrets.randbelow(2001) - 1000 for _ in range(count)])


def run_vm(executable, program, path):
    with open(path, "wb") as f:
        f.write(program)
    proc = subprocess.run(
        [executable, path],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=10,
        env={**os.environ, "ASAN_OPTIONS": "detect_leaks=0:abort_on_error=1"},
    )
    assert proc.returncode == 0, (
        f"{executable} exited with {proc.returncode}; stderr: "
        f"{proc.stderr.decode(errors='replace')}"
    )
    return proc.stdout.decode(errors="strict")


def test_vm_executable_exists():
    """Check if the compiled VM executable exists."""
    file_path = VM
    assert os.path.isfile(file_path), f"The executable {file_path} does not exist. Did you compile vm.c?"
    assert os.access(file_path, os.X_OK), f"The file {file_path} is not executable."
    with open(file_path, "rb") as f:
        assert f.read(4) == b"\x7fELF", f"The executable {file_path} is not a compiled ELF binary."


def test_test_bin_exists():
    """Check if the generated bytecode test file exists."""
    file_path = TEST_BIN
    assert os.path.isfile(file_path), f"The bytecode file {file_path} does not exist."
    with open(file_path, "rb") as f:
        actual = f.read()
    assert actual == REQUIRED_PROGRAM, "test.bin does not contain the required PUSH/ADD/PRINT sequence."


def test_test_result_log():
    """Check if the test result log exists and contains the correct sum."""
    file_path = RESULT_LOG
    assert os.path.isfile(file_path), f"The log file {file_path} does not exist. Did you run the VM and redirect output?"
    with open(file_path, "r") as f:
        content = f.read()
    assert content.strip() == "210", f"Expected the log file to contain '210', but got '{content.strip()}'."


def test_submitted_vm_executes_required_bytecode():
    output = run_vm(VM, REQUIRED_PROGRAM, "/tmp/verifier_required.bin")
    assert output == "210\n", f"VM produced {output!r} instead of '210\\n' for the required program."


def test_submitted_vm_on_verifier_generated_programs():
    for index, values in enumerate(HIDDEN_CASES):
        output = run_vm(VM, make_sum_program(values), f"/tmp/verifier_hidden_{index}.bin")
        expected = f"{sum(values)}\n"
        assert output == expected, f"VM produced {output!r}; expected {expected!r}."


def test_source_has_safe_stack_resize():
    assert os.path.isfile(SOURCE), f"The source file {SOURCE} does not exist."
    checked_vm = "/tmp/verifier_vm_from_source"
    compile_proc = subprocess.run(
        [
            "gcc", "-std=c11", "-O0", "-g", "-fno-omit-frame-pointer",
            "-fsanitize=address,undefined", "-o", checked_vm, SOURCE,
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
    )
    assert compile_proc.returncode == 0, (
        "vm.c did not compile with gcc: " + compile_proc.stderr.decode(errors="replace")
    )

    # The original realloc bug is reliably exposed by ASan once more than four
    # values are pushed. Run several independently generated resize cases.
    for index, values in enumerate(HIDDEN_CASES):
        output = run_vm(checked_vm, make_sum_program(values), f"/tmp/verifier_source_{index}.bin")
        expected = f"{sum(values)}\n"
        assert output == expected, (
            f"The VM compiled from vm.c produced {output!r}; expected {expected!r}."
        )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
