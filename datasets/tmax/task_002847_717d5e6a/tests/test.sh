#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import math
import os
import re
import subprocess

import numpy as np
from scipy import stats

SIM_DIR = "/home/user/sim"
CPP = os.path.join(SIM_DIR, "simulation.cpp")
EXE = os.path.join(SIM_DIR, "simulation")
SIGNAL = os.path.join(SIM_DIR, "signal.txt")
SUM = os.path.join(SIM_DIR, "sum.txt")
ANALYZE = os.path.join(SIM_DIR, "analyze.py")
RESULTS = os.path.join(SIM_DIR, "results.json")


def run(cmd, env=None, timeout=60):
    completed = subprocess.run(
        cmd,
        cwd=SIM_DIR,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=timeout,
    )
    assert completed.returncode == 0, (
        f"Command failed: {' '.join(cmd)}\n"
        f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    )
    return completed


def cpp_int32(value):
    return ((value + (1 << 31)) % (1 << 32)) - (1 << 31)


def cpp_remainder(value, divisor):
    quotient = abs(value) // divisor
    if value < 0:
        quotient = -quotient
    return value - quotient * divisor


def expected_signal():
    values = []
    for i in range(10000):
        raw = cpp_int32(i * 1103515245 + 12345)
        noise = cpp_remainder(raw, 10000) / 10000.0 - 0.5
        t = i / 1000.0
        values.append(
            math.sin(2.0 * math.pi * 50.0 * t)
            + 0.5 * math.sin(2.0 * math.pi * 120.0 * t)
            + noise
        )
    return np.asarray(values, dtype=float)


def read_outputs():
    assert os.path.isfile(SIGNAL), "signal.txt was not generated."
    assert os.path.isfile(SUM), "sum.txt was not generated."
    signal = np.loadtxt(SIGNAL, dtype=float)
    assert signal.shape == (10000,), f"signal.txt must contain 10000 values, got {signal.shape}."
    assert np.all(np.isfinite(signal)), "signal.txt contains non-finite values."
    with open(SUM, "r") as handle:
        total = float(handle.read().strip())
    assert math.isfinite(total), "sum.txt contains a non-finite value."
    return signal, total


def test_complete_workflow():
    assert os.path.isfile(CPP), f"File {CPP} does not exist."
    assert os.path.isfile(ANALYZE), "analyze.py does not exist."
    assert os.path.getsize(ANALYZE) > 0, "analyze.py is empty."

    # Inspect active preprocessed code, so a comment or disabled #if block cannot
    # satisfy the required OpenMP reduction assertion.
    preprocessed = run(["g++", "-E", "-fopenmp", CPP]).stdout
    reduction = re.compile(
        r"#\s*pragma\s+omp\s+parallel\s+for[^\n]*"
        r"reduction\s*\(\s*\+\s*:\s*global_sum\s*\)",
        re.IGNORECASE,
    )
    assert reduction.search(preprocessed), (
        "The active OpenMP parallel-for must use reduction(+:global_sum)."
    )

    # Compile the submitted source with the command required by the task.
    if os.path.exists(EXE):
        os.remove(EXE)
    run(["g++", "-O2", "-fopenmp", "simulation.cpp", "-o", "simulation"])
    assert os.path.isfile(EXE), "The simulation executable was not generated."
    assert os.access(EXE, os.X_OK), "simulation is not executable."

    expected = expected_signal()
    expected_sum = float(np.sum(expected))
    observed_runs = []

    # Execute the artifact repeatedly and with different thread counts. This
    # verifies that the sum is no longer a raced, pre-written result.
    for threads in (1, 4, 4):
        for path in (SIGNAL, SUM):
            if os.path.exists(path):
                os.remove(path)
        env = os.environ.copy()
        env["OMP_NUM_THREADS"] = str(threads)
        env["OMP_DYNAMIC"] = "FALSE"
        run([EXE], env=env)
        signal, total = read_outputs()
        assert np.allclose(signal, expected, rtol=0.0, atol=1.1e-6), (
            "The generated signal does not match the supplied simulation parameters."
        )
        assert math.isclose(total, expected_sum, rel_tol=0.0, abs_tol=2e-5), (
            f"global_sum is incorrect: expected {expected_sum}, got {total}."
        )
        observed_runs.append(total)

    assert max(observed_runs) - min(observed_runs) <= 1e-6, (
        f"global_sum is not reproducible across runs/thread counts: {observed_runs}"
    )

    # Force analyze.py to create a fresh result from the freshly generated files.
    if os.path.exists(RESULTS):
        os.remove(RESULTS)
    run(["python3", ANALYZE])
    assert os.path.isfile(RESULTS), "results.json was not generated by analyze.py."

    with open(RESULTS, "r") as handle:
        results = json.load(handle)

    expected_keys = {"global_sum", "dominant_freq", "ks_statistic", "p_value"}
    assert set(results.keys()) == expected_keys, (
        f"results.json keys do not match expected keys. Found: {list(results.keys())}"
    )
    for key in expected_keys:
        assert isinstance(results[key], (int, float)), f"Value for {key} must be a float."
        assert math.isfinite(float(results[key])), f"Value for {key} must be finite."

    final_signal, final_sum = read_outputs()
    assert math.isclose(float(results["global_sum"]), final_sum, rel_tol=0.0, abs_tol=1e-9), (
        "results.json global_sum does not match sum.txt."
    )

    # Independently recompute the FFT, dominant component, residuals, and KS test.
    n = final_signal.size
    spectrum = np.fft.rfft(final_signal)
    frequencies = np.fft.rfftfreq(n, d=1.0 / 1000.0)
    dominant_index = int(np.argmax(np.abs(spectrum[1:])) + 1)
    dominant_freq = float(frequencies[dominant_index])
    amplitude = 2.0 * abs(spectrum[dominant_index]) / n
    phase = float(np.angle(spectrum[dominant_index]))
    times = np.arange(n, dtype=float) / 1000.0
    ideal = amplitude * np.cos(2.0 * math.pi * dominant_freq * times + phase)
    residuals = final_signal - ideal
    ks_statistic, p_value = stats.kstest(residuals, "norm")

    # Retain the original dominant-frequency and range assertions, and add
    # comparisons against independently derived analysis values.
    assert math.isclose(float(results["dominant_freq"]), 50.0, abs_tol=1.0), (
        f"Dominant frequency should be 50 Hz, got {results['dominant_freq']}"
    )
    assert math.isclose(float(results["dominant_freq"]), dominant_freq, rel_tol=0.0, abs_tol=1e-9)
    assert 0.0 <= float(results["ks_statistic"]) <= 1.0, "KS statistic must be between 0 and 1."
    assert 0.0 <= float(results["p_value"]) <= 1.0, "p-value must be between 0 and 1."
    assert math.isclose(float(results["ks_statistic"]), float(ks_statistic), rel_tol=0.0, abs_tol=1e-6), (
        "ks_statistic does not match the KS test on the FFT-derived residuals."
    )
    assert math.isclose(float(results["p_value"]), float(p_value), rel_tol=0.0, abs_tol=1e-6), (
        "p_value does not match the KS test on the FFT-derived residuals."
    )
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
