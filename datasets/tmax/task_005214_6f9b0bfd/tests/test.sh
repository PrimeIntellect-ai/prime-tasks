#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import secrets
import signal
import subprocess

import pytest

BILLING_DIR = "/home/user/billing"
RUN_SH = os.path.join(BILLING_DIR, "run.sh")
PROCESSOR_PY = os.path.join(BILLING_DIR, "processor.py")
TRANSACTIONS_LOG = os.path.join(BILLING_DIR, "transactions.log")
RATES_JSON = os.path.join(BILLING_DIR, "rates.json")
SUMMARY_TXT = "/home/user/billing_summary.txt"


def test_rates_json_recovered():
    assert os.path.isfile(RATES_JSON), f"Expected {RATES_JSON} to be recovered and exist."
    with open(RATES_JSON, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"{RATES_JSON} is not valid JSON.")
    assert "multiplier" in data, f"{RATES_JSON} must contain a 'multiplier' key."
    assert isinstance(data["multiplier"], (int, float)), "The multiplier must be a number."
    assert not isinstance(data["multiplier"], bool), "The multiplier must be a number, not a boolean."
    assert float(data["multiplier"]) == 1.5, "The recovered multiplier must be 1.5."


def test_run_sh_timezone_fixed():
    assert os.path.isfile(RUN_SH), f"{RUN_SH} must exist."
    with open(RUN_SH, "r") as f:
        content = f.read()
    assert "America/Los_Angles" not in content, (
        f"{RUN_SH} still contains the misspelled timezone 'America/Los_Angles'."
    )


def test_processor_py_fixed():
    assert os.path.isfile(PROCESSOR_PY), f"{PROCESSOR_PY} must exist."
    try:
        with open(PROCESSOR_PY, "r") as f:
            compile(f.read(), PROCESSOR_PY, "exec")
    except SyntaxError as e:
        pytest.fail(f"{PROCESSOR_PY} has a syntax error: {e}")


def run_billing():
    try:
        os.unlink(SUMMARY_TXT)
    except FileNotFoundError:
        pass

    try:
        proc = subprocess.Popen(
            [RUN_SH],
            cwd=BILLING_DIR,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            start_new_session=True,
        )
    except OSError as e:
        pytest.fail(f"Could not execute {RUN_SH}: {e}")

    try:
        stdout, stderr = proc.communicate(timeout=8)
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL)
        proc.communicate()
        pytest.fail(f"{RUN_SH} did not finish within 8 seconds; processing still hangs.")

    assert proc.returncode == 0, (
        f"{RUN_SH} exited with status {proc.returncode}. "
        f"stdout={stdout!r}, stderr={stderr!r}"
    )
    assert os.path.isfile(SUMMARY_TXT), (
        f"The expected output file {SUMMARY_TXT} was not generated by run.sh."
    )
    with open(SUMMARY_TXT, "r") as f:
        return f.read()


def test_summary_txt_exists_and_correct():
    with open(RATES_JSON, "rb") as f:
        original_rates = f.read()
    with open(TRANSACTIONS_LOG, "rb") as f:
        original_transactions = f.read()

    # Exercise the real entry point with verifier-selected values and an injected
    # null byte, so a stale or fabricated summary cannot pass.
    multiplier = secrets.randbelow(7) + 2
    cents_a = secrets.randbelow(90000) + 100
    cents_b = secrets.randbelow(90000) + 100
    amount_a = cents_a / 100.0
    amount_b = cents_b / 100.0

    try:
        with open(RATES_JSON, "w") as f:
            json.dump({"multiplier": multiplier}, f)
        with open(TRANSACTIONS_LOG, "wb") as f:
            f.write(f"2024-01-15T08:00:00,{amount_a:.2f}\n".encode("ascii"))
            f.write(f"2024-01-15T09:00:00\x00,{amount_b:.2f}\n".encode("ascii"))

        expected_probe = (amount_a + amount_b) * multiplier
        probe_output = run_billing()
        assert probe_output == f"Total: {expected_probe:.2f}\n", (
            "run.sh did not produce the exact required one-line summary for "
            f"corrupted input. Found: {probe_output!r}"
        )
    finally:
        with open(RATES_JSON, "wb") as f:
            f.write(original_rates)
        with open(TRANSACTIONS_LOG, "wb") as f:
            f.write(original_transactions)

    # Execute again on the restored nightly data and leave the requested final
    # summary in place.
    rates = json.loads(original_rates.decode("utf-8"))
    restored_multiplier = float(rates.get("multiplier", 1.0))
    expected_total = 0.0
    for line in original_transactions.splitlines():
        clean_line = line.replace(b"\x00", b"").decode("utf-8").strip()
        if not clean_line:
            continue
        parts = clean_line.split(",")
        if len(parts) >= 2:
            expected_total += float(parts[1]) * restored_multiplier

    final_output = run_billing()
    assert final_output == f"Total: {expected_total:.2f}\n", (
        f"{SUMMARY_TXT} must contain exactly one correctly formatted line. "
        f"Found: {final_output!r}"
    )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
