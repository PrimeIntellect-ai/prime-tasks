#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
# test_final_state.py

import os
import re
import stat
import subprocess
import pytest

PROJECT = "/home/user/operator_project"
SCRIPT = os.path.join(PROJECT, "ci_cd.sh")
SOURCE = os.path.join(PROJECT, "operator.c")
BINARY = os.path.join(PROJECT, "operator.bin")
LOG = os.path.join(PROJECT, "deploy.log")
EXPECTED_LOG = "DEPLOY_SUCCESS: Read config successfully.\n"

def test_env_profile_exists_and_correct():
    """Ensure .env_profile exists and exports NETWORK_CONFIG_PATH correctly."""
    env_path = "/home/user/operator_project/.env_profile"
    assert os.path.isfile(env_path), f"File {env_path} does not exist."

    with open(env_path, "r") as f:
        content = f.read()

    # Allow for spaces around equals sign or quotes
    pattern = r"export\s+NETWORK_CONFIG_PATH\s*=\s*[\"']?/home/user/operator_project/network_config\.json[\"']?"
    assert re.search(pattern, content), f"{env_path} does not correctly export NETWORK_CONFIG_PATH."

def test_ci_cd_script_exists_and_executable():
    """Ensure ci_cd.sh exists, is executable, and contains required elements."""
    script_path = "/home/user/operator_project/ci_cd.sh"
    assert os.path.isfile(script_path), f"Script {script_path} does not exist."

    # Check if executable
    st = os.stat(script_path)
    assert bool(st.st_mode & stat.S_IXUSR), f"Script {script_path} is not executable."

    with open(script_path, "r") as f:
        content = f.read()

    assert "gcc" in content, f"Script {script_path} does not contain 'gcc'."
    assert re.search(r"\b(source|\.)\s+", content), f"Script {script_path} does not source the .env_profile."
    assert re.search(r"\b(for|while|until)\b", content), f"Script {script_path} does not contain a loop mechanism."

def test_operator_bin_exists_and_executable():
    """Ensure operator.bin was compiled and is executable."""
    bin_path = "/home/user/operator_project/operator.bin"
    assert os.path.isfile(bin_path), f"Executable {bin_path} does not exist."

    st = os.stat(bin_path)
    assert bool(st.st_mode & stat.S_IXUSR), f"Binary {bin_path} is not executable."

def test_deploy_log_exists_and_correct():
    """Ensure deploy.log was generated by the operator and contains the success message."""
    log_path = "/home/user/operator_project/deploy.log"
    assert os.path.isfile(log_path), f"Log file {log_path} does not exist. Did the operator run successfully?"

    with open(log_path, "r") as f:
        content = f.read()

    expected_content = "DEPLOY_SUCCESS: Read config successfully.\n"
    assert content == expected_content, f"Content of {log_path} is incorrect. Expected: {expected_content!r}, got: {content!r}"

def _remove(path):
    try:
        os.remove(path)
    except FileNotFoundError:
        pass

def _run_script(extra_env=None):
    env = os.environ.copy()
    # The script itself must load this variable from .env_profile.
    env.pop("NETWORK_CONFIG_PATH", None)
    if extra_env:
        env.update(extra_env)
    return subprocess.run(
        ["/bin/bash", SCRIPT],
        cwd=PROJECT,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20,
    )

def _assert_elf_binary():
    assert os.path.isfile(BINARY), "ci_cd.sh did not produce operator.bin"
    assert os.access(BINARY, os.X_OK), "operator.bin is not executable"
    with open(BINARY, "rb") as f:
        assert f.read(4) == b"\x7fELF", "operator.bin is not a compiled ELF executable"

def _fixture_source(fail_until):
    return r'''#include <stdio.h>
#include <stdlib.h>

int main(void) {
    const char *path = getenv("ATTEMPT_FILE");
    if (path == NULL) return 90;
    int attempts = 0;
    FILE *f = fopen(path, "r");
    if (f != NULL) {
        (void)fscanf(f, "%d", &attempts);
        fclose(f);
    }
    attempts++;
    f = fopen(path, "w");
    if (f == NULL) return 91;
    fprintf(f, "%d\n", attempts);
    fclose(f);
    return attempts <= %d ? 1 : 0;
}
''' % fail_until

def _run_fixture(fail_until, counter_path):
    _remove(counter_path)
    _remove(BINARY)
    with open(SOURCE, "w") as f:
        f.write(_fixture_source(fail_until))
    result = _run_script({"ATTEMPT_FILE": counter_path})
    _assert_elf_binary()
    assert os.path.isfile(counter_path), "The compiled operator was not executed"
    with open(counter_path, "r") as f:
        attempts = int(f.read().strip())
    return result, attempts

def test_supervisor_executes_compiles_and_retries_correctly():
    """Execute the submitted pipeline and exercise immediate success and retry limits."""
    with open(SOURCE, "rb") as f:
        original_source = f.read()

    counters = ["/tmp/operator_attempt_success", "/tmp/operator_attempt_retry", "/tmp/operator_attempt_fail"]
    try:
        # Prove that the real source is compiled and run with the sourced profile.
        _remove(BINARY)
        _remove(LOG)
        result = _run_script()
        assert result.returncode == 0, f"ci_cd.sh failed on the real operator:\n{result.stdout}\n{result.stderr}"
        _assert_elf_binary()
        assert os.path.isfile(LOG), "Running ci_cd.sh did not generate deploy.log"
        with open(LOG, "r") as f:
            assert f.read() == EXPECTED_LOG

        # A successful process must terminate the loop after its first run.
        result, attempts = _run_fixture(0, counters[0])
        assert result.returncode == 0, "ci_cd.sh did not finish successfully after an immediate success"
        assert attempts == 1, f"Successful operator was run {attempts} times instead of once"

        # Two failures followed by success must produce exactly three executions.
        result, attempts = _run_fixture(2, counters[1])
        assert result.returncode == 0, "ci_cd.sh did not succeed when the third attempt succeeded"
        assert attempts == 3, f"Expected three attempts after two failures, got {attempts}"

        # A permanently failing process must stop after the maximum of three runs.
        result, attempts = _run_fixture(99, counters[2])
        assert attempts == 3, f"Permanently failing operator must be attempted exactly three times, got {attempts}"
    finally:
        with open(SOURCE, "wb") as f:
            f.write(original_source)
        for counter in counters:
            _remove(counter)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
