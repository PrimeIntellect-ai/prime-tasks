#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import datetime
import ipaddress
import os
import random
import stat
import subprocess
import uuid

from scapy.all import IP, TCP, Raw, wrpcap

SCRIPT = "/home/user/analyze.sh"
PCAP = "/home/user/traffic.pcap"
LOGS = "/home/user/service_logs.txt"
TIMELINE = "/home/user/malware_timeline.log"


def run_script():
    if os.path.exists(TIMELINE):
        os.remove(TIMELINE)
    result = subprocess.run(
        ["/bin/bash", SCRIPT],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, (
        f"{SCRIPT} failed with exit code {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


def read_nonempty_lines(path):
    with open(path, "r") as f:
        return [line.rstrip("\n") for line in f if line.strip()]


def syslog_key(line):
    return datetime.datetime.strptime(line[:15], "%b %d %H:%M:%S")


def test_script_exists_and_handles_unseen_inputs():
    assert os.path.isfile(SCRIPT), f"The required Bash script {SCRIPT} does not exist."
    assert not os.path.islink(SCRIPT), f"{SCRIPT} must be a regular script, not a symlink."
    mode = os.stat(SCRIPT).st_mode
    assert mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH), f"{SCRIPT} is not executable."
    with open(SCRIPT, "rb") as f:
        first_line = f.readline().decode("utf-8", errors="replace").strip()
    assert first_line.startswith("#!") and "bash" in first_line, f"{SCRIPT} must be a Bash script."

    public_pool = ["8.8.8.8", "1.1.1.1", "9.9.9.9", "208.67.222.222", "64.6.64.6"]
    selected = random.SystemRandom().sample(public_pool, 3)
    nonce = uuid.uuid4().hex

    destinations = selected + ["10.23.4.5", "127.0.0.1", "192.168.77.9", "203.0.113.77"]
    packets = [
        IP(src="10.0.0.5", dst=dst)/TCP(sport=12000+i, dport=80)/Raw((nonce + str(i)).encode())
        for i, dst in enumerate(destinations)
    ]
    wrpcap(PCAP, packets)

    candidate_lines = [
        f"Nov  2 08:11:22 testhost challenge[{nonce}]: contacted {selected[0]}",
        f"Sep 30 23:59:59 testhost challenge[{nonce}]: contacted {selected[1]}",
        f"Oct  9 09:12:00 testhost challenge[{nonce}]: contacted {selected[2]}",
        f"Oct 10 10:00:00 testhost challenge[{nonce}]: internal 10.23.4.5",
        f"Oct 11 10:00:00 testhost challenge[{nonce}]: loopback 127.0.0.1",
        f"Oct 12 10:00:00 testhost challenge[{nonce}]: private 192.168.77.9",
        f"Oct 13 10:00:00 testhost challenge[{nonce}]: documentation 203.0.113.77",
        f"Oct 14 10:00:00 testhost challenge[{nonce}]: absent destination 8.8.4.4",
    ]
    random.SystemRandom().shuffle(candidate_lines)
    with open(LOGS, "w") as f:
        f.write("\n".join(candidate_lines) + "\n")

    public_destinations = {ip for ip in destinations if ipaddress.ip_address(ip).is_global}
    expected = sorted(
        [line for line in candidate_lines if any(ip in line for ip in public_destinations)],
        key=syslog_key,
    )

    run_script()
    assert os.path.isfile(TIMELINE), f"The file {TIMELINE} was not generated by {SCRIPT}."
    actual = read_nonempty_lines(TIMELINE)
    assert actual == expected, f"Script failed the unseen-input behavioral test.\nExpected: {expected}\nActual: {actual}"

    # Install a deterministic, genuinely public equivalent of the original fixture
    # for the original final-state assertions below.
    baseline_packets = [
        IP(src="10.0.0.5", dst="8.8.8.8")/TCP(sport=1024, dport=80)/Raw(b"external one"),
        IP(src="10.0.0.5", dst="10.0.0.8")/TCP(sport=1025, dport=443)/Raw(b"internal"),
        IP(src="10.0.0.5", dst="1.1.1.1")/TCP(sport=1026, dport=53)/Raw(b"external two"),
        IP(src="127.0.0.1", dst="127.0.0.1")/TCP(sport=5000, dport=5000)/Raw(b"loopback"),
    ]
    wrpcap(PCAP, baseline_packets)
    with open(LOGS, "w") as f:
        f.write(
            "Nov  2 08:11:22 testhost systemd[1]: Started suspicious.\n"
            "Oct 12 10:01:22 testhost suspicious_bin[1234]: Connection to 8.8.8.8 established.\n"
            "Oct 12 10:01:25 testhost kernel: DROP SRC=1.1.1.1 DST=10.0.0.5\n"
            "Oct  9 09:12:00 testhost systemd[1]: Installed suspicious_bin.\n"
            "Dec  1 12:00:00 testhost network: Connection to 10.0.0.8 closed.\n"
            "Sep 30 23:59:59 testhost root: Initialized system.\n"
        )
    run_script()


def test_malware_timeline_exists():
    path = "/home/user/malware_timeline.log"
    assert os.path.isfile(path), f"The file {path} does not exist. Did you run the script?"


def test_malware_timeline_contents():
    path = "/home/user/malware_timeline.log"
    with open(path, "r") as f:
        lines = [line.strip() for line in f if line.strip()]

    expected_lines = [
        "Oct 12 10:01:22 testhost suspicious_bin[1234]: Connection to 8.8.8.8 established.",
        "Oct 12 10:01:25 testhost kernel: DROP SRC=1.1.1.1 DST=10.0.0.5"
    ]

    assert len(lines) == len(expected_lines), f"Expected {len(expected_lines)} lines in {path}, but found {len(lines)}."

    for i, (actual, expected) in enumerate(zip(lines, expected_lines)):
        assert actual == expected, f"Line {i+1} mismatch.\nExpected: {expected}\nActual:   {actual}"


def test_internal_ips_excluded():
    path = "/home/user/malware_timeline.log"
    with open(path, "r") as f:
        content = f.read()

    assert "Connection to 10.0.0.8 closed." not in content, "Internal IPs (e.g. 10.0.0.8) should be excluded from the timeline."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
