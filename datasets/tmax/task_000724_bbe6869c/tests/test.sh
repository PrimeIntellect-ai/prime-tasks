import pytest


def test_ca_coords_extracted_correctly():
    pdb_path = "/home/user/data/protein.pdb"
    ca_coords_path = "/home/user/ca_coords.txt"

    assert os.path.exists(ca_coords_path), f"File {ca_coords_path} is missing."

    expected_coords = []
    if os.path.exists(pdb_path):
        with open(pdb_path, "r") as f:
            for line in f:
                parts = line.split()
                if len(parts) >= 8 and parts[0] == "ATOM" and parts[2] == "CA":
                    expected_coords.append(f"{parts[5]} {parts[6]} {parts[7]}")

    with open(ca_coords_path, "r") as f:
        actual_coords = [line.strip() for line in f if line.strip()]

    assert actual_coords == expected_coords, f"Contents of {ca_coords_path} do not match the expected CA coordinates."


def test_reduce_script_fixed():
    reduce_path = "/home/user/reduce.sh"
    assert os.path.exists(reduce_path), f"File {reduce_path} is missing."
    assert stat.S_ISREG(os.stat(reduce_path, follow_symlinks=False).st_mode), "reduce.sh must be a regular file."
    assert os.access(reduce_path, os.X_OK), "reduce.sh is not executable."

    with open(reduce_path, "r") as f:
        content = f.read()

    assert "sort" in content and "-n" in content, "reduce.sh does not appear to sort the values numerically (missing 'sort -n' or equivalent)."
    assert "awk" in content, "reduce.sh is missing 'awk' for summation."


def _expected_simulation_score(i):
    program = '''BEGIN {
        srand(i * 123);
        val = (rand() - 0.2) * (10 ^ (rand() * 5));
        printf "%.15f\\n", val;
    }'''
    proc = subprocess.run(
        ["awk", "-v", f"i={i}", program],
        text=True,
        capture_output=True,
        check=True,
    )
    return proc.stdout


def test_mc_simulation_produced_all_expected_outputs():
    results_dir = "/home/user/results"
    assert os.path.isdir(results_dir) and not os.path.islink(results_dir), "/home/user/results must be a real directory."

    score_files = glob.glob(os.path.join(results_dir, "*.score"))
    expected_names = {f"run_{i}.score" for i in range(1, 101)}
    actual_names = {os.path.basename(path) for path in score_files}
    assert len(score_files) == 100, f"Expected exactly 100 .score files, found {len(score_files)}."
    assert actual_names == expected_names, "The simulation output filenames are incomplete or unexpected."

    for i in range(1, 101):
        path = os.path.join(results_dir, f"run_{i}.score")
        assert stat.S_ISREG(os.stat(path, follow_symlinks=False).st_mode), f"{path} must be a regular file."
        with open(path, "r") as f:
            content = f.read()
        assert content == _expected_simulation_score(i), f"{path} does not contain the score generated by mc_sim.sh."
        lines = content.splitlines()
        assert len(lines) == 1, f"{path} must contain exactly one score."
        assert math.isfinite(float(lines[0])), f"{path} does not contain a finite floating-point score."


def test_final_sum_correct():
    results_dir = "/home/user/results"
    final_sum_path = "/home/user/final_sum.txt"

    assert os.path.exists(final_sum_path), f"File {final_sum_path} is missing."

    score_files = glob.glob(os.path.join(results_dir, "*.score"))
    assert len(score_files) > 0, "No .score files found in /home/user/results."

    scores = []
    for sf in score_files:
        with open(sf, "r") as f:
            val = f.read().strip()
            if val:
                scores.append(float(val))

    # Replicate the required sorting and reduction logic
    scores.sort()
    expected_sum = 0.0
    for s in scores:
        expected_sum += s

    expected_sum_str = f"{expected_sum:.15f}"

    with open(final_sum_path, "r") as f:
        actual_sum_str = f.read().strip()

    assert actual_sum_str == expected_sum_str, f"Final sum in {final_sum_path} ({actual_sum_str}) does not match expected sorted sum ({expected_sum_str})."


def test_histogram_correct():
    results_dir = "/home/user/results"
    histogram_path = "/home/user/histogram.txt"

    assert os.path.exists(histogram_path), f"File {histogram_path} is missing."

    score_files = glob.glob(os.path.join(results_dir, "*.score"))

    scores = []
    for sf in score_files:
        with open(sf, "r") as f:
            val = f.read().strip()
            if val:
                scores.append(float(val))

    bin1 = sum(1 for x in scores if x < 0.0)
    bin2 = sum(1 for x in scores if 0.0 <= x < 10.0)
    bin3 = sum(1 for x in scores if 10.0 <= x < 100.0)
    bin4 = sum(1 for x in scores if x >= 100.0)

    expected_histogram = {
        "bin1_lt_0": bin1,
        "bin2_0_10": bin2,
        "bin3_10_100": bin3,
        "bin4_ge_100": bin4
    }

    actual_histogram = {}
    with open(histogram_path, "r") as f:
        for line in f:
            if ":" in line:
                key, val = line.split(":", 1)
                actual_histogram[key.strip()] = int(val.strip())

    for key, expected_count in expected_histogram.items():
        assert key in actual_histogram, f"Missing key {key} in {histogram_path}."
        assert actual_histogram[key] == expected_count, f"Count for {key} in {histogram_path} is {actual_histogram[key]}, expected {expected_count}."


def _trusted_reduction(values):
    data = "".join(value + "\n" for value in values)
    sorted_proc = subprocess.run(
        ["sort", "-n"], input=data, text=True, capture_output=True, check=True
    )
    awk_proc = subprocess.run(
        ["awk", '{sum+=$1} END {printf "%.15f\\n", sum}'],
        input=sorted_proc.stdout,
        text=True,
        capture_output=True,
        check=True,
    )
    return awk_proc.stdout


def test_reduce_script_executes_a_numeric_sorted_reduction():
    results_dir = "/home/user/results"
    reduce_path = "/home/user/reduce.sh"
    backup_dir = f"/home/user/results.verifier-backup-{uuid.uuid4().hex}"

    # Runtime-generated values prevent a script from passing by printing the
    # known simulation total. Large and small magnitudes exercise reduction order.
    rng = random.SystemRandom()
    values = []
    for _ in range(25):
        large = 10**15 + rng.randrange(1, 10**12)
        small_whole = rng.randrange(-5000, 5001)
        small_fraction = rng.randrange(1, 1000000)
        values.extend([
            str(large),
            f"{small_whole}.{small_fraction:06d}",
            str(-large),
            f"{rng.randrange(-99, 100)}.{rng.randrange(0, 1000000):06d}",
        ])

    creation_values = list(values)
    rng.shuffle(creation_values)

    os.rename(results_dir, backup_dir)
    try:
        os.mkdir(results_dir)
        for index, value in enumerate(creation_values):
            name = f"case_{index:03d}_{uuid.uuid4().hex}.score"
            with open(os.path.join(results_dir, name), "w") as f:
                f.write(value + "\n")

        expected = _trusted_reduction(values)
        proc = subprocess.run(
            [reduce_path],
            cwd="/home/user",
            text=True,
            capture_output=True,
            timeout=10,
        )
        assert proc.returncode == 0, f"reduce.sh failed when executed: {proc.stderr}"
        assert re.fullmatch(r"-?[0-9]+\.[0-9]{15}\n", proc.stdout), "reduce.sh output is not formatted as %.15f followed by a newline."
        assert proc.stdout == expected, f"reduce.sh did not numerically sort and then sum its input values: got {proc.stdout!r}, expected {expected!r}."
    finally:
        if os.path.lexists(results_dir):
            if os.path.isdir(results_dir) and not os.path.islink(results_dir):
                shutil.rmtree(results_dir)
            else:
                os.unlink(results_dir)
        os.rename(backup_dir, results_dir)
TEST_EOF

