#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import stat
import subprocess
import numpy as np
import pytest

SCRIPT = '/home/user/run_model.sh'
TRAJECTORY = '/home/user/trajectory.tsv'
FREQ_FILE = '/tmp/freq.txt'


def test_trajectory_mse():
    assert os.path.isfile(SCRIPT), f"Missing pipeline script at {SCRIPT}"
    assert stat.S_ISREG(os.stat(SCRIPT).st_mode), f"Expected {SCRIPT} to be a regular file"
    assert os.access(SCRIPT, os.X_OK), f"Expected {SCRIPT} to be executable"

    script_text = open(SCRIPT, encoding='utf-8').read()
    assert '/app/signal.mp4' in script_text, 'run_model.sh must process the supplied video'
    assert '/home/user/fft.py' in script_text, 'run_model.sh must use the supplied FFT script'

    for path in (TRAJECTORY, FREQ_FILE):
        try:
            os.remove(path)
        except FileNotFoundError:
            pass

    result = subprocess.run(
        [SCRIPT], cwd='/home/user', text=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60
    )
    assert result.returncode == 0, (
        f"run_model.sh failed with exit code {result.returncode}\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )

    assert os.path.isfile(FREQ_FILE), 'Pipeline did not produce /tmp/freq.txt'
    try:
        frequency = float(open(FREQ_FILE, encoding='utf-8').read().strip())
    except Exception as e:
        pytest.fail(f"Could not read the extracted frequency: {e}")
    assert np.isfinite(frequency) and abs(frequency - 2.5) <= 1e-6, (
        f"Expected video frequency 2.5 Hz, got {frequency}"
    )

    file_path = TRAJECTORY
    assert os.path.isfile(file_path), f"Missing trajectory file at {file_path}"

    with open(file_path, encoding='utf-8') as f:
        header = f.readline().rstrip('\n').split('\t')
    assert len(header) >= 2 and header[0] == 'Time' and header[1] == 'Position', (
        'trajectory.tsv must have tab-separated Time and Position columns'
    )

    try:
        data = np.loadtxt(file_path, skiprows=1, ndmin=2)
    except Exception as e:
        pytest.fail(f"Failed to load {file_path} with numpy: {e}")

    assert data.shape[1] >= 2, f"Expected at least 2 columns in {file_path}, but got {data.shape[1]}"

    t = data[:, 0]
    y_agent = data[:, 1]
    assert len(t) >= 101, 'Trajectory has too few samples to cover 0 through 2 seconds with a small step'
    assert np.all(np.isfinite(t)) and np.all(np.isfinite(y_agent)), 'Trajectory contains non-finite values'
    assert abs(t[0]) <= 1e-9, f"Trajectory must start at t=0, got {t[0]}"
    assert abs(t[-1] - 2.0) <= 1e-9, f"Trajectory must end at t=2.0, got {t[-1]}"

    steps = np.diff(t)
    assert np.all(steps > 0), 'Timestamps must be strictly increasing and distinct'
    assert np.max(steps) <= 0.0200001, f"Time step is too large: maximum step is {np.max(steps)}"

    # Verify that the emitted samples are generated by semi-implicit Euler:
    # update velocity first, then use the new velocity to update position.
    omega = 2 * np.pi * frequency
    y_expected = 1.0
    v_expected = 0.0
    assert abs(y_agent[0] - y_expected) <= 1e-6, f"Expected y(0)=1, got {y_agent[0]}"
    for i, dt in enumerate(steps):
        v_expected = v_expected - omega**2 * y_expected * dt
        y_expected = y_expected + v_expected * dt
        assert abs(y_agent[i + 1] - y_expected) <= 2e-4, (
            f"Sample {i + 1} does not follow the semi-implicit Euler update: "
            f"got {y_agent[i + 1]}, expected {y_expected}"
        )

    # Expected analytical solution (retain the original accuracy assertion).
    f_expected = 2.5
    omega = 2 * np.pi * f_expected
    y_true = np.cos(omega * t)
    mse = np.mean((y_agent - y_true)**2)
    assert mse <= 0.05, f"MSE between agent trajectory and analytical solution is {mse}, which is > threshold 0.05"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
