#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import re
import sys
import json
import subprocess
import hashlib
import pytest

SCRIPT_PATH = "/home/user/generate_report.py"
REPORT_PATH = "/home/user/incident_report.json"
LOG_PATH = "/home/user/process_dump.log"


def test_generate_report_script_exists():
    assert os.path.isfile(SCRIPT_PATH), f"The script {SCRIPT_PATH} does not exist."


def test_incident_report_json():
    assert os.path.isfile(SCRIPT_PATH), f"The script {SCRIPT_PATH} does not exist."

    # Ensure the report being checked was actually produced by the submitted script.
    if os.path.lexists(REPORT_PATH):
        if os.path.isfile(REPORT_PATH) or os.path.islink(REPORT_PATH):
            os.remove(REPORT_PATH)
        else:
            pytest.fail(f"{REPORT_PATH} exists but is not a file.")

    try:
        subprocess.run(
            [sys.executable, SCRIPT_PATH],
            cwd="/home/user",
            check=True,
            timeout=30,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as e:
        pytest.fail(f"Executing {SCRIPT_PATH} failed: {e}")

    assert os.path.isfile(REPORT_PATH), f"The incident report {REPORT_PATH} was not generated by the script."

    with open(REPORT_PATH, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"The file {REPORT_PATH} does not contain valid JSON.")

    # Derive the token and target from the monitored command line.
    with open(LOG_PATH, "r") as f:
        process_log = f.read()

    matching_lines = [
        line for line in process_log.splitlines()
        if "--auth-token=" in line and "--target=" in line
    ]
    assert len(matching_lines) == 1, "Expected exactly one process containing both auth-token and target arguments."

    token_match = re.search(r"(?:^|\s)--auth-token=([^\s]+)", matching_lines[0])
    path_match = re.search(r"(?:^|\s)--target=([^\s]+)", matching_lines[0])
    assert token_match is not None, "Could not extract the authentication token from the process log."
    assert path_match is not None, "Could not extract the payload path from the process log."

    expected_token = token_match.group(1)
    expected_path = path_match.group(1)

    # Preserve the expected artifact assertions from the original verifier.
    assert expected_token == "sec_t0k3n_99f2a1"
    assert expected_path == "/home/user/drop/payload.elf"

    with open(expected_path, "rb") as f:
        expected_hash = hashlib.sha256(f.read()).hexdigest()

    try:
        out_arch = subprocess.check_output(["readelf", "-h", expected_path]).decode("utf-8")
        expected_arch = [
            line.split("Machine:", 1)[1].strip()
            for line in out_arch.splitlines()
            if "Machine:" in line
        ][0]
    except Exception as e:
        pytest.fail(f"Could not read ELF architecture from {expected_path}: {e}")

    assert data.get("leaked_token") == expected_token, f"Expected leaked_token to be '{expected_token}', got '{data.get('leaked_token')}'."
    assert data.get("payload_path") == expected_path, f"Expected payload_path to be '{expected_path}', got '{data.get('payload_path')}'."
    assert data.get("payload_sha256") == expected_hash, f"Expected payload_sha256 to be '{expected_hash}', got '{data.get('payload_sha256')}'."

    actual_arch = data.get("elf_architecture", "")
    assert isinstance(actual_arch, str) and actual_arch.strip(), "elf_architecture must be a non-empty string."
    assert expected_arch.lower() in actual_arch.lower() or actual_arch.lower() in expected_arch.lower(), \
        f"Expected elf_architecture to match '{expected_arch}', got '{actual_arch}'."
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
