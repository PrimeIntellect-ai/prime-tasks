#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import json
import sqlite3
import base64
import statistics
import subprocess
import secrets
import math
from pathlib import Path

AGGREGATOR = Path('/home/user/aggregator.py')
DB_PATH = Path('/home/user/metrics.db')
OUTPUT_PATH = Path('/home/user/hidden_output_dir/metrics_out.json')


def read_temperatures():
    conn = sqlite3.connect(str(DB_PATH))
    try:
        rows = conn.execute('SELECT payload FROM sensor_data').fetchall()
    finally:
        conn.close()

    temps = []
    for row in rows:
        try:
            json_str = base64.b64decode(row[0]).decode('utf-8')
            data = json.loads(json_str)
            temps.append(data['temperature'])
        except Exception:
            pass
    return temps


def run_and_check_output(expected_temps):
    if OUTPUT_PATH.exists() or OUTPUT_PATH.is_symlink():
        OUTPUT_PATH.unlink()

    result = subprocess.run(
        ['python3', str(AGGREGATOR)],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert result.returncode == 0, (
        f'Executing {AGGREGATOR} failed with exit code {result.returncode}. '
        f'stdout={result.stdout!r}, stderr={result.stderr!r}'
    )
    assert OUTPUT_PATH.exists(), f'{AGGREGATOR} did not create {OUTPUT_PATH}.'
    assert OUTPUT_PATH.is_file(), f'{OUTPUT_PATH} is not a file.'

    with OUTPUT_PATH.open('r') as f:
        data = json.load(f)
    assert 'temperature_variance' in data, (
        f"'temperature_variance' key missing from {OUTPUT_PATH}."
    )

    actual = data['temperature_variance']
    assert isinstance(actual, (int, float)) and not isinstance(actual, bool), (
        'temperature_variance must be numeric.'
    )
    assert math.isfinite(actual), 'temperature_variance must be finite.'

    expected_values = [
        statistics.pvariance(expected_temps),
        statistics.variance(expected_temps),
    ]
    assert any(math.isclose(actual, expected, rel_tol=1e-8, abs_tol=5e-5)
               for expected in expected_values), (
        f'Incorrect temperature_variance: got {actual!r}, expected one of '
        f'{expected_values!r}.'
    )


def test_aggregator_executes_and_computes_database_values():
    assert AGGREGATOR.exists(), f'{AGGREGATOR} does not exist.'
    assert AGGREGATOR.is_file(), f'{AGGREGATOR} is not a regular file.'
    assert not AGGREGATOR.is_symlink(), f'{AGGREGATOR} must be modified in place, not be a symlink.'
    assert DB_PATH.exists(), f'Database {DB_PATH} is missing.'

    original_temps = read_temperatures()
    assert len(original_temps) > 1, 'Could not extract temperatures from the database.'

    # Remove any pre-created output and verify the submitted artifact produces the
    # correct value from the original database.
    run_and_check_output(original_temps)

    # Exercise the artifact against fresh encoded inputs so a dummy or hard-coded
    # output cannot pass. Restore the incident database and final output afterward.
    original_db = DB_PATH.read_bytes()
    baseline = 10_000_000_000 + secrets.randbelow(1_000_000)
    scale = 0.25 * (1 + secrets.randbelow(8))
    generated_temps = [baseline + scale * x for x in (-3, -1, 0, 2, 5)]

    try:
        conn = sqlite3.connect(str(DB_PATH))
        try:
            conn.execute('DELETE FROM sensor_data')
            for temp in generated_temps:
                payload = json.dumps({'sensor': 'temp_test', 'temperature': temp})
                encoded = base64.b64encode(payload.encode('utf-8')).decode('ascii')
                conn.execute('INSERT INTO sensor_data (payload) VALUES (?)', (encoded,))
            conn.commit()
        finally:
            conn.close()

        run_and_check_output(generated_temps)
    finally:
        DB_PATH.write_bytes(original_db)

    # Leave the required output in the final state, generated by the repaired script
    # from the original database.
    run_and_check_output(original_temps)


def test_hidden_output_dir_exists():
    dir_path = '/home/user/hidden_output_dir'
    assert os.path.exists(dir_path), f'Directory {dir_path} does not exist.'
    assert os.path.isdir(dir_path), f'{dir_path} is not a directory.'


def test_metrics_out_json_exists():
    file_path = '/home/user/hidden_output_dir/metrics_out.json'
    assert os.path.exists(file_path), f'File {file_path} does not exist. The script probably did not run successfully or write the output.'
    assert os.path.isfile(file_path), f'{file_path} is not a file.'

    with open(file_path, 'r') as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            assert False, f'{file_path} does not contain valid JSON.'

    assert 'temperature_variance' in data, f"'temperature_variance' key missing from {file_path}."

    temps = read_temperatures()
    assert len(temps) > 0, 'Could not extract temperatures from the database.'
    actual = data['temperature_variance']
    expected_values = [statistics.pvariance(temps), statistics.variance(temps)]
    assert isinstance(actual, (int, float)) and not isinstance(actual, bool)
    assert any(math.isclose(actual, expected, rel_tol=1e-8, abs_tol=5e-5)
               for expected in expected_values), (
        f'Incorrect temperature_variance: got {actual!r}, expected one of {expected_values!r}.'
    )


def test_final_answer_txt_correct():
    file_path = '/home/user/final_answer.txt'
    assert os.path.exists(file_path), f'File {file_path} does not exist.'
    assert os.path.isfile(file_path), f'{file_path} is not a file.'

    with open(file_path, 'r') as f:
        content = f.read().strip()

    assert DB_PATH.exists(), f'Database {DB_PATH} is missing.'
    temps = read_temperatures()
    assert len(temps) > 0, 'Could not extract temperatures from the database.'

    expected_pvariance = statistics.pvariance(temps)
    expected_variance = statistics.variance(temps)
    expected_pvar_str = f'{expected_pvariance:.4f}'
    expected_var_str = f'{expected_variance:.4f}'

    assert content in [expected_pvar_str, expected_var_str], \
        f"Expected {file_path} to contain {expected_pvar_str} or {expected_var_str}, but got '{content}'."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
