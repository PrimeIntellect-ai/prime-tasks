#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import re
import secrets
import subprocess
import tempfile
import pytest

SOURCE_PATH = "/home/user/net_monitor.cpp"
EXECUTABLE_PATH = "/home/user/net_monitor"
TARGET_LOG = "/home/user/logs/net_monitor.log"


def run_monitor(hosts):
    env = os.environ.copy()
    if hosts is None:
        env.pop("TARGET_HOSTS", None)
    else:
        env["TARGET_HOSTS"] = hosts
    return subprocess.run(
        [EXECUTABLE_PATH],
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=5,
    )


def test_source_compiles_and_executable_runs_correctly():
    assert os.path.isfile(SOURCE_PATH), f"Source file {SOURCE_PATH} does not exist."
    assert os.path.isfile(EXECUTABLE_PATH), f"Executable {EXECUTABLE_PATH} does not exist."
    assert os.access(EXECUTABLE_PATH, os.X_OK), f"File {EXECUTABLE_PATH} is not executable."

    with open(EXECUTABLE_PATH, "rb") as f:
        assert f.read(4) == b"\x7fELF", "net_monitor must be a compiled ELF executable, not a script."

    with tempfile.TemporaryDirectory() as tmpdir:
        rebuilt = os.path.join(tmpdir, "net_monitor")
        compile_result = subprocess.run(
            ["g++", "-std=c++17", "-Wall", "-Wextra", "-pedantic", SOURCE_PATH, "-o", rebuilt],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=20,
        )
        assert compile_result.returncode == 0, (
            "The repaired C++ source does not compile: " + compile_result.stderr.decode(errors="replace")
        )

    # Preserve the original fixed-input execution assertion.
    result = run_monitor("test_host")
    assert result.returncode == 0, (
        f"Executable returned non-zero exit code: {result.returncode}. "
        f"Stderr: {result.stderr.decode(errors='replace')}"
    )
    assert result.stdout == b"Monitoring hosts: test_host\n"

    # Exercise values generated by the verifier so a fixed-output executable cannot pass.
    for hosts in [secrets.token_hex(18), f"host-{secrets.token_hex(8)} other_{secrets.token_hex(8)}"]:
        result = run_monitor(hosts)
        assert result.returncode == 0, result.stderr.decode(errors="replace")
        assert result.stdout == f"Monitoring hosts: {hosts}\n".encode()

    result = run_monitor(None)
    assert result.returncode != 0, "The program must fail when TARGET_HOSTS is absent."
    assert b"TARGET_HOSTS not set" in result.stderr


def test_bashrc_contains_export():
    bashrc_path = "/home/user/.bashrc"
    assert os.path.isfile(bashrc_path), f"File {bashrc_path} is missing."

    with open(bashrc_path, "r") as f:
        content = f.read()

    # Preserve the original content assertion.
    pattern = r"TARGET_HOSTS=[\"']?127\.0\.0\.1 1\.1\.1\.1[\"']?"
    assert re.search(pattern, content), f"Could not find the correct TARGET_HOSTS export in {bashrc_path}."

    # Require an active export statement rather than a comment or plain shell variable.
    export_pattern = re.compile(
        r'^\s*export\s+TARGET_HOSTS\s*=\s*([\"\'])127\.0\.0\.1 1\.1\.1\.1\1\s*(?:#.*)?$',
        re.MULTILINE,
    )
    assert export_pattern.search(content), (
        f"{bashrc_path} must contain an active export of TARGET_HOSTS with the required value."
    )

    result = subprocess.run(
        [
            "bash", "--noprofile", "--norc", "-c",
            'unset TARGET_HOSTS; source "$1" || exit $?; /usr/bin/env -0',
            "bash", bashrc_path,
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=5,
    )
    assert result.returncode == 0, f"Failed to source {bashrc_path}: {result.stderr.decode(errors='replace')}"
    environment = dict(
        entry.split(b"=", 1) for entry in result.stdout.split(b"\0") if b"=" in entry
    )
    assert environment.get(b"TARGET_HOSTS") == b"127.0.0.1 1.1.1.1"


def test_logrotate_config():
    logrotate_path = "/home/user/logrotate.conf"
    assert os.path.isfile(logrotate_path), f"File {logrotate_path} is missing."

    with open(logrotate_path, "r") as f:
        content = f.read()

    # Preserve the original assertions.
    assert TARGET_LOG in content, "Logrotate config missing target log file path."
    directives = ["daily", "rotate 3", "compress", "missingok"]
    for directive in directives:
        pattern = r"\b" + directive.replace(" ", r"\s+") + r"\b"
        assert re.search(pattern, content), f"Logrotate config is missing the '{directive}' directive."

    # Parse the requested minimal configuration after removing comments and blanks.
    active = []
    for line in content.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            active.append(line)

    assert active, "Logrotate configuration is empty."
    quoted_path = rf'(?:{re.escape(TARGET_LOG)}|"{re.escape(TARGET_LOG)}"|\'{re.escape(TARGET_LOG)}\')'

    if re.fullmatch(quoted_path + r"\s*\{", active[0]):
        body = active[1:]
    elif re.fullmatch(quoted_path, active[0]) and len(active) > 1 and active[1] == "{":
        body = active[2:]
    else:
        pytest.fail("Logrotate configuration must begin with the requested log path and an opening brace.")

    assert body and body[-1] == "}", "Logrotate configuration is missing its closing brace."
    assert "}" not in body[:-1], "Logrotate configuration has an unexpected closing brace."
    body = body[:-1]

    # The task requests this complete minimal block; requiring directive-shaped active
    # lines prevents comments and malformed free text from satisfying the checks.
    allowed = {
        "daily": re.compile(r"^daily$"),
        "rotate": re.compile(r"^rotate\s+3$"),
        "compress": re.compile(r"^compress$"),
        "missingok": re.compile(r"^missingok$"),
    }
    found = set()
    for line in body:
        matches = [name for name, pattern in allowed.items() if pattern.fullmatch(line)]
        assert matches, f"Invalid or unexpected logrotate syntax in requested block: {line!r}"
        found.add(matches[0])

    assert found == set(allowed), "The logrotate block does not contain all required active directives."
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
