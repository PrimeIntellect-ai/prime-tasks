#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import ctypes
import importlib.util
import os
import re
import subprocess
import sys
import pytest

PROJECT = "/home/user/math_polyglot/rust_math"
LIB_PATH = PROJECT + "/target/release/librust_math.so"
SCRIPT_PATH = "/home/user/math_polyglot/python_e2e/test_fib.py"
LOG_PATH = "/home/user/e2e_success.log"
CARGO = "/root/.cargo/bin/cargo"


def fib(n):
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def test_cargo_configuration_and_clean_release_build():
    cargo_toml = os.path.join(PROJECT, "Cargo.toml")
    with open(cargo_toml, "r") as f:
        config = f.read()
    assert re.search(r'crate-type\s*=\s*\[[^\]]*["\']cdylib["\']', config), (
        "Cargo.toml must configure the library as a cdylib."
    )

    subprocess.run([CARGO, "clean"], cwd=PROJECT, check=True)
    build = subprocess.run(
        [CARGO, "build", "--release"],
        cwd=PROJECT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    assert build.returncode == 0, build.stdout
    assert os.path.isfile(LIB_PATH), "A clean release build did not produce librust_math.so"
    with open(LIB_PATH, "rb") as f:
        assert f.read(4) == b"\x7fELF", "librust_math.so is not an ELF shared library"


def test_exported_fast_fib_behavior():
    lib = ctypes.CDLL(LIB_PATH)
    try:
        fast_fib = lib.fast_fib
    except AttributeError as exc:
        pytest.fail(f"The shared library does not export an unmangled fast_fib symbol: {exc}")
    fast_fib.argtypes = [ctypes.c_uint32]
    fast_fib.restype = ctypes.c_uint64
    for n in (0, 1, 2, 3, 10, 47, 92, 93):
        assert fast_fib(n) == fib(n), f"fast_fib({n}) returned an incorrect result"


def test_python_e2e_uses_correct_abi():
    spec = importlib.util.spec_from_file_location("submitted_test_fib", SCRIPT_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    class FakeFunction:
        def __init__(self):
            self.argtypes = None
            self.restype = None
            self.calls = []

        def __call__(self, n):
            self.calls.append(n)
            return fib(n)

    class FakeLibrary:
        def __init__(self):
            self.fast_fib = FakeFunction()

    fake_lib = FakeLibrary()
    original_cdll = module.ctypes.CDLL
    module.ctypes.CDLL = lambda path: fake_lib
    try:
        module.run_test()
    finally:
        module.ctypes.CDLL = original_cdll

    assert fake_lib.fast_fib.argtypes == [ctypes.c_uint32], (
        "The Python E2E script must declare the fast_fib uint32 argument."
    )
    assert fake_lib.fast_fib.restype is ctypes.c_uint64, (
        "The Python E2E script must declare fast_fib's return type as ctypes.c_uint64."
    )
    assert fake_lib.fast_fib.calls == [93], "The E2E script did not call fast_fib(93)."


def test_run_python_e2e_fresh():
    if os.path.exists(LOG_PATH):
        os.remove(LOG_PATH)
    result = subprocess.run(
        [sys.executable, SCRIPT_PATH],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    assert result.returncode == 0, result.stdout
    assert "E2E Test Passed" in result.stdout, result.stdout


def test_success_log_exists():
    """Verify that the success log file was generated by the Python E2E test."""
    log_path = "/home/user/e2e_success.log"
    assert os.path.isfile(log_path), (
        f"The file {log_path} does not exist. "
        "This means the Python E2E test was either not run, or it failed to complete successfully."
    )


def test_success_log_content():
    """Verify that the success log contains the exact expected success message."""
    log_path = "/home/user/e2e_success.log"
    if not os.path.exists(log_path):
        pytest.fail(f"Cannot check content because {log_path} is missing.")

    with open(log_path, "r") as f:
        content = f.read().strip()

    expected_content = "SUCCESS: 12200160415121876738"
    assert content == expected_content, (
        f"The content of {log_path} is incorrect. "
        f"Expected '{expected_content}', but got '{content}'."
    )


def test_rust_shared_library_exists():
    """Verify that the Rust shared library was compiled successfully."""
    lib_path = "/home/user/math_polyglot/rust_math/target/release/librust_math.so"
    assert os.path.isfile(lib_path), (
        f"The shared library {lib_path} does not exist. "
        "This means the Rust project was not compiled correctly with 'cargo build --release' "
        "or the Cargo.toml is missing the cdylib crate-type."
    )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
