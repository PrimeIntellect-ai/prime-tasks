#!/bin/bash
set +e
mkdir -p /logs/verifier
echo "0" > /logs/verifier/reward.txt

# Require the requested source and a compiled native executable.
if ! python3 - <<'PY'
import os
src = "/home/user/organizer.c"
bin_path = "/home/user/organizer"
assert os.path.isfile(src) and os.path.getsize(src) > 0
assert os.path.isfile(bin_path) and os.access(bin_path, os.X_OK)
with open(bin_path, "rb") as f:
    assert f.read(4) == b"\x7fELF"
PY
then
    exit 0
fi

# Stop any agent-started instance, clear fixed artifacts, and execute the submitted binary ourselves.
pkill -x organizer 2>/dev/null || true
mkdir -p /home/user/spool/manifests /home/user/spool/chunks /home/user/project_root /home/user/logs
find /home/user/spool/manifests -mindepth 1 -delete 2>/dev/null
find /home/user/spool/chunks -mindepth 1 -delete 2>/dev/null
find /home/user/project_root -mindepth 1 -delete 2>/dev/null
find /home/user/logs -mindepth 1 -delete 2>/dev/null
rm -f /home/user/user/evil.txt /home/user/evil.txt

/home/user/organizer >/tmp/organizer-verifier.log 2>&1 &
ORGANIZER_PID=$!
cleanup() {
    kill "$ORGANIZER_PID" 2>/dev/null || true
    wait "$ORGANIZER_PID" 2>/dev/null || true
}
trap cleanup EXIT
sleep 1
kill -0 "$ORGANIZER_PID" 2>/dev/null || exit 0

# Generate fresh chunks and manifests after the daemon starts. Checksums are derived
# from the generated bytes rather than copied from the defective fixture.
if ! python3 - <<'PY'
import base64
import json
import os
import secrets

chunks = "/home/user/spool/chunks"
manifests = "/home/user/spool/manifests"
os.makedirs(chunks, exist_ok=True)
os.makedirs(manifests, exist_ok=True)

def put_chunk(name, data):
    path = os.path.join(chunks, name)
    with open(path, "wb") as f:
        f.write(data)
    return path

def put_manifest(name, dest, paths, checksum):
    path = os.path.join(manifests, name)
    text = "DEST:" + dest + "\nCHUNKS:" + str(len(paths)) + "\n"
    text += "".join(p + "\n" for p in paths)
    text += "CHECKSUM:" + str(checksum) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)

# Original behavioral cases, with the valid checksum corrected to sum(data) % 256.
hello = b"Hello World!"
h1 = put_chunk("file1.part1", b"Hello ")
h2 = put_chunk("file1.part2", b"World!")
put_manifest("doc.manifest", "docs/hello.txt", [h1, h2], sum(hello) % 256)

e1 = put_chunk("file2.part1", b"Secret ")
e2 = put_chunk("file2.part2", b"Data")
put_manifest("evil.manifest", "../user/evil.txt", [e1, e2], sum(b"Secret Data") % 256)

b1 = put_chunk("file3.part1", b"Bad ")
b2 = put_chunk("file3.part2", b"Checksum")
put_manifest("bad.manifest", "docs/bad.txt", [b1, b2], 99)

# Unpredictable merge, checksum-error, and traversal cases.
token = secrets.token_hex(10)
payload = os.urandom(311)
parts = [payload[:37], payload[37:203], payload[203:]]
paths = [put_chunk(f"fresh_{token}_{i}.part", part) for i, part in enumerate(parts)]
fresh_dest = f"generated/{token}/ordered.bin"
put_manifest(f"fresh_{token}.manifest", fresh_dest, paths, sum(payload) % 256)

bad_payload = os.urandom(73)
bad_chunk = put_chunk(f"bad_{token}.part", bad_payload)
fresh_bad_dest = f"generated/{token}/bad.bin"
put_manifest(f"fresh_bad_{token}.manifest", fresh_bad_dest, [bad_chunk], (sum(bad_payload) + 1) % 256)

escape_dest = f"../../../tmp/organizer_escape_{token}"
escape_path = f"/tmp/organizer_escape_{token}"
try:
    os.unlink(escape_path)
except FileNotFoundError:
    pass
escape_chunk = put_chunk(f"escape_{token}.part", b"must not escape")
put_manifest(f"escape_{token}.manifest", escape_dest, [escape_chunk], sum(b"must not escape") % 256)

with open("/tmp/organizer_expect.json", "w", encoding="utf-8") as f:
    json.dump({
        "fresh_dest": fresh_dest,
        "fresh_payload": base64.b64encode(payload).decode("ascii"),
        "fresh_bad_dest": fresh_bad_dest,
        "escape_dest": escape_dest,
        "escape_path": escape_path,
    }, f)
PY
then
    exit 0
fi

# Allow asynchronous inotify processing, returning early once all expected effects appear.
python3 - <<'PY'
import json
import os
import time
with open("/tmp/organizer_expect.json", encoding="utf-8") as f:
    e = json.load(f)
required = [
    "/home/user/project_root/docs/hello.txt",
    "/home/user/project_root/" + e["fresh_dest"],
    "/home/user/logs/security.log",
]
for _ in range(100):
    if all(os.path.exists(p) for p in required):
        try:
            log = open("/home/user/logs/security.log", encoding="utf-8").read()
            if ("VIOLATION: ../user/evil.txt" in log and
                "CHECKSUM_ERROR: docs/bad.txt" in log and
                "VIOLATION: " + e["escape_dest"] in log and
                "CHECKSUM_ERROR: " + e["fresh_bad_dest"] in log):
                break
        except OSError:
            pass
    time.sleep(0.1)
PY

# A continuously running watcher must still be alive after processing the events.
kill -0 "$ORGANIZER_PID" 2>/dev/null || exit 0

cat <<'TEST_EOF' > /tmp/test_final_state.py
import base64
import json
import os

with open("/tmp/organizer_expect.json", encoding="utf-8") as f:
    EXPECT = json.load(f)

def test_hello_txt_merged_correctly():
    target_path = "/home/user/project_root/docs/hello.txt"
    assert os.path.isfile(target_path), f"Expected merged file was not created at {target_path}."

    with open(target_path, "rb") as f:
        content = f.read()

    expected_content = b"Hello World!"
    assert content == expected_content, f"Content of {target_path} is incorrect. Expected {expected_content}, but got {content}."

def test_security_log_contents():
    log_path = "/home/user/logs/security.log"
    assert os.path.isfile(log_path), f"Security log file was not created at {log_path}."

    with open(log_path, "r") as f:
        lines = [line.strip() for line in f.readlines() if line.strip()]

    expected_violation = "VIOLATION: ../user/evil.txt"
    expected_checksum_error = "CHECKSUM_ERROR: docs/bad.txt"

    assert expected_violation in lines, f"Security log is missing the expected path traversal violation. Expected to find: '{expected_violation}'"
    assert expected_checksum_error in lines, f"Security log is missing the expected checksum error. Expected to find: '{expected_checksum_error}'"
    assert "VIOLATION: " + EXPECT["escape_dest"] in lines
    assert "CHECKSUM_ERROR: " + EXPECT["fresh_bad_dest"] in lines

def test_invalid_files_not_written():
    evil_path_1 = "/home/user/project_root/../user/evil.txt"
    evil_path_2 = "/home/user/evil.txt"
    bad_path = "/home/user/project_root/docs/bad.txt"

    assert not os.path.exists(evil_path_1) and not os.path.exists(evil_path_2), "Path traversal vulnerability detected! The file evil.txt was written outside the project root."
    assert not os.path.exists(bad_path), f"File with invalid checksum was written to {bad_path}. It should have been rejected."
    assert not os.path.exists("/home/user/project_root/" + EXPECT["fresh_bad_dest"])
    assert not os.path.exists(EXPECT["escape_path"])

def test_fresh_generated_file_is_merged_in_order():
    target = "/home/user/project_root/" + EXPECT["fresh_dest"]
    assert os.path.isfile(target)
    with open(target, "rb") as f:
        actual = f.read()
    assert actual == base64.b64decode(EXPECT["fresh_payload"])
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
fi
