#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import ast
import json
import os
import re
import secrets
import shutil
import sqlite3
import subprocess
import tempfile
import pytest

DB_PATH = '/home/user/research.db'
SCRIPT_PATH = '/home/user/export_graph.py'
JSON_PATH = '/home/user/coauthorship_graph.json'


def derive_expected(min_citations):
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    cursor.execute("SELECT id, citations FROM papers WHERE citations >= ?", (min_citations,))
    valid_papers = {row[0]: row[1] for row in cursor.fetchall()}

    paper_authors = {}
    for pid in valid_papers:
        cursor.execute("SELECT author_id FROM paper_authors WHERE paper_id = ?", (pid,))
        paper_authors[pid] = [row[0] for row in cursor.fetchall()]

    edges_dict = {}
    valid_author_ids = set()
    for pid, authors in paper_authors.items():
        citations = valid_papers[pid]
        for i in range(len(authors)):
            for j in range(i + 1, len(authors)):
                a1, a2 = sorted([authors[i], authors[j]])
                valid_author_ids.add(a1)
                valid_author_ids.add(a2)
                pair = (a1, a2)
                edges_dict[pair] = edges_dict.get(pair, 0) + citations

    expected_nodes = []
    if valid_author_ids:
        placeholders = ','.join('?' * len(valid_author_ids))
        cursor.execute(
            f"SELECT id, name FROM authors WHERE id IN ({placeholders}) ORDER BY id ASC",
            tuple(valid_author_ids),
        )
        expected_nodes = [{"id": row[0], "name": row[1]} for row in cursor.fetchall()]

    conn.close()
    expected_edges = [
        {"source": source, "target": target, "weight": weight}
        for (source, target), weight in sorted(edges_dict.items())
    ]
    return expected_nodes, expected_edges


def run_export(threshold):
    if os.path.exists(JSON_PATH):
        os.remove(JSON_PATH)
    result = subprocess.run(
        ['python3', SCRIPT_PATH, '--min-citations', str(threshold)],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert result.returncode == 0, (
        f"export_graph.py failed for threshold {threshold}: {result.stderr}"
    )
    assert os.path.isfile(JSON_PATH), "Script did not create the required JSON output"
    with open(JSON_PATH, 'r') as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as exc:
            pytest.fail(f"Script produced invalid JSON for threshold {threshold}: {exc}")


def assert_graph(data, threshold):
    expected_nodes, expected_edges = derive_expected(threshold)
    assert set(data.keys()) == {'nodes', 'edges'}, "JSON must contain exactly nodes and edges"
    assert data['nodes'] == expected_nodes
    assert data['edges'] == expected_edges

    node_ids = [node.get('id') for node in data['nodes']]
    assert node_ids == sorted(node_ids)
    edge_pairs = [(edge.get('source'), edge.get('target')) for edge in data['edges']]
    assert edge_pairs == sorted(edge_pairs)
    assert all(edge.get('source') < edge.get('target') for edge in data['edges'])


def test_script_exists():
    """Test that the export_graph.py script exists."""
    assert os.path.isfile(SCRIPT_PATH), f"Script not found at {SCRIPT_PATH}"


def test_json_output_exists():
    """Test that the requested threshold-50 output was generated by the agent."""
    assert os.path.isfile(JSON_PATH), f"Output JSON not found at {JSON_PATH}"


def test_script_uses_parameterized_sql():
    """Check that SQL execution supplies parameters rather than interpolating the threshold."""
    source = open(SCRIPT_PATH, 'r').read()
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        pytest.fail(f"export_graph.py is not valid Python: {exc}")

    parameterized_execute = any(
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == 'execute'
        and len(node.args) >= 2
        for node in ast.walk(tree)
    )
    has_sql_placeholder = bool(re.search(r'\?|[:@$][A-Za-z_]\w*', source))
    assert parameterized_execute and has_sql_placeholder, (
        "The citation filter must be executed as a parameterized SQL query"
    )


def test_script_executes_for_dynamic_data_and_thresholds():
    """Execute the submitted artifact against data and thresholds not known in advance."""
    fd, backup_path = tempfile.mkstemp(prefix='research-backup-', suffix='.db')
    os.close(fd)
    shutil.copy2(DB_PATH, backup_path)

    threshold = 20 + secrets.randbelow(80)
    token = secrets.token_hex(8)

    try:
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute('SELECT COALESCE(MAX(id), 0) FROM authors')
        first_author = cursor.fetchone()[0] + 1
        author_ids = [first_author, first_author + 1, first_author + 2]
        cursor.executemany(
            'INSERT INTO authors(id, name, institution) VALUES (?, ?, ?)',
            [(aid, f'Dynamic {token} {i}', 'Test') for i, aid in enumerate(author_ids)],
        )

        cursor.execute('SELECT COALESCE(MAX(id), 0) FROM papers')
        first_paper = cursor.fetchone()[0] + 1
        papers = [
            (first_paper, f'Dynamic exact {token}', 2025, threshold),
            (first_paper + 1, f'Dynamic low {token}', 2025, threshold - 1),
            (first_paper + 2, f'Dynamic high {token}', 2025, threshold + 7),
        ]
        cursor.executemany('INSERT INTO papers VALUES (?, ?, ?, ?)', papers)
        cursor.executemany(
            'INSERT INTO paper_authors(paper_id, author_id) VALUES (?, ?)',
            [
                (first_paper, author_ids[0]), (first_paper, author_ids[1]),
                (first_paper + 1, author_ids[0]), (first_paper + 1, author_ids[2]),
                (first_paper + 2, author_ids[0]), (first_paper + 2, author_ids[1]),
                (first_paper + 2, author_ids[2]),
            ],
        )
        conn.commit()
        conn.close()

        for value in (threshold - 1, threshold, threshold + 1, threshold + 8):
            assert_graph(run_export(value), value)
    finally:
        for suffix in ('-wal', '-shm', '-journal'):
            try:
                os.remove(DB_PATH + suffix)
            except FileNotFoundError:
                pass
        shutil.copy2(backup_path, DB_PATH)
        os.remove(backup_path)
        # Leave the required final artifact generated from the original database.
        subprocess.run(
            ['python3', SCRIPT_PATH, '--min-citations', '50'],
            cwd='/home/user', stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, timeout=15,
        )


def test_json_content_and_structure():
    """Test that the threshold-50 output has the correct structure and derived data."""
    min_citations = 50
    expected_nodes, expected_edges = derive_expected(min_citations)

    with open(JSON_PATH, 'r') as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"File {JSON_PATH} is not valid JSON.")

    assert "nodes" in data, "JSON missing 'nodes' key."
    assert "edges" in data, "JSON missing 'edges' key."

    nodes = data["nodes"]
    edges = data["edges"]

    node_ids = [n.get("id") for n in nodes]
    assert node_ids == sorted(node_ids), "Nodes are not sorted by id ascending."

    edge_pairs = [(e.get("source"), e.get("target")) for e in edges]
    assert edge_pairs == sorted(edge_pairs), "Edges are not sorted by source ascending, then target ascending."

    for e in edges:
        assert e.get("source") < e.get("target"), f"Edge source must be strictly less than target: {e}"

    assert nodes == expected_nodes, f"Nodes mismatch. Expected {expected_nodes}, got {nodes}"
    assert edges == expected_edges, f"Edges mismatch. Expected {expected_edges}, got {edges}"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
