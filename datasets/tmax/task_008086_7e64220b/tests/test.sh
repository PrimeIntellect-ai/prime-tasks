#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import subprocess
import tempfile
import uuid


def run(cmd, **kwargs):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kwargs)


def test_setup_config_idempotent():
    """Verify that setup_config.sh is idempotent and creates the required files/directories."""
    script_path = "/home/user/setup_config.sh"
    assert os.path.exists(script_path), f"{script_path} does not exist."

    subprocess.run(["bash", script_path], check=True)
    subprocess.run(["bash", script_path], check=True)

    assert os.path.isdir("/home/user/backup_mnt"), "/home/user/backup_mnt directory was not created."
    assert os.path.exists("/home/user/local_fstab"), "/home/user/local_fstab was not created."

    expected_line = "/dev/disk/by-label/BACKUP /home/user/backup_mnt ext4 rw,nosuid,nodev,noexec,auto,nouser,async 0 2"

    with open("/home/user/local_fstab", "r") as f:
        content = f.read()

    count = content.count(expected_line)
    assert count == 1, f"Expected exactly 1 occurrence of the fstab line, found {count}. The script might not be idempotent."


def test_git_repo_and_hook():
    """Verify the bare repository, source, and compiled post-receive hook."""
    repo_path = "/home/user/config.git"
    assert os.path.isdir(repo_path), f"{repo_path} does not exist."

    result = subprocess.run(
        ["git", "-C", repo_path, "rev-parse", "--is-bare-repository"],
        capture_output=True,
        text=True,
    )
    assert result.stdout.strip() == "true", f"{repo_path} is not a bare git repository."

    hook_path = os.path.join(repo_path, "hooks", "post-receive")
    assert os.path.exists(hook_path), f"Hook {hook_path} does not exist."
    assert os.access(hook_path, os.X_OK), f"Hook {hook_path} is not executable."

    source_path = "/home/user/hook.go"
    assert os.path.isfile(source_path), f"{source_path} does not exist."

    with tempfile.TemporaryDirectory(prefix="verify-go-build-") as td:
        rebuilt_hook = os.path.join(td, "post-receive")
        result = subprocess.run(
            ["go", "build", "-o", rebuilt_hook, source_path],
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, f"hook.go does not compile:\n{result.stderr}"
        with open(hook_path, "rb") as installed, open(rebuilt_hook, "rb") as rebuilt:
            assert installed.read() == rebuilt.read(), \
                "Installed post-receive hook is not the program compiled from /home/user/hook.go."


def test_alerts_log():
    """Verify that alerts.log contains the correct JSON logs for the required initial push."""
    repo_path = "/home/user/config.git"
    log_path = "/home/user/alerts.log"

    assert os.path.exists(log_path), f"{log_path} does not exist."

    result = subprocess.run(
        ["git", "-C", repo_path, "rev-parse", "refs/heads/master"],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, "Failed to get the latest revision from refs/heads/master."
    newrev = result.stdout.strip()

    with open(log_path, "r") as f:
        lines = [line.strip() for line in f if line.strip()]

    parsed_logs = []
    for line in lines:
        try:
            parsed_logs.append(json.loads(line))
        except json.JSONDecodeError:
            pass

    fstab_found = any(
        log.get("event") == "alert"
        and log.get("reason") == "critical_config_change"
        and log.get("file") == "local_fstab"
        and log.get("revision") == newrev
        for log in parsed_logs
    )
    backup_found = any(
        log.get("event") == "alert"
        and log.get("reason") == "critical_config_change"
        and log.get("file") == "backup.sh"
        and log.get("revision") == newrev
        for log in parsed_logs
    )

    assert fstab_found, f"alerts.log does not contain the expected alert for local_fstab with revision {newrev}."
    assert backup_found, f"alerts.log does not contain the expected alert for backup.sh with revision {newrev}."


def test_fresh_push_exercises_hook():
    """Perform a fresh push and verify alerts are generated by the installed hook."""
    repo_path = "/home/user/config.git"
    log_path = "/home/user/alerts.log"
    branch = "verifier-" + uuid.uuid4().hex

    with open(log_path, "rb") as f:
        f.seek(0, os.SEEK_END)
        original_size = f.tell()

    with tempfile.TemporaryDirectory(prefix="verify-push-") as td:
        workspace = os.path.join(td, "workspace")
        run(["git", "clone", repo_path, workspace])
        run(["git", "-C", workspace, "config", "user.name", "Verifier"])
        run(["git", "-C", workspace, "config", "user.email", "verifier@example.invalid"])
        run(["git", "-C", workspace, "checkout", "-b", branch])

        marker = uuid.uuid4().hex
        with open(os.path.join(workspace, "local_fstab"), "a") as f:
            f.write(f"\n# verifier change {marker}\n")
        with open(os.path.join(workspace, "backup.sh"), "a") as f:
            f.write(f"\necho verifier-{marker}\n")
        with open(os.path.join(workspace, "noncritical.txt"), "w") as f:
            f.write(marker + "\n")

        run(["git", "-C", workspace, "add", "local_fstab", "backup.sh", "noncritical.txt"])
        run(["git", "-C", workspace, "commit", "-m", "Verifier hook test"])
        revision = run(["git", "-C", workspace, "rev-parse", "HEAD"]).stdout.strip()
        run(["git", "-C", workspace, "push", "origin", f"HEAD:refs/heads/{branch}"])

    with open(log_path, "rb") as f:
        f.seek(original_size)
        appended = f.read().decode("utf-8")

    raw_lines = [line.strip() for line in appended.splitlines() if line.strip()]
    parsed = []
    for line in raw_lines:
        try:
            parsed.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise AssertionError(f"Hook appended a non-JSON alert line: {line}") from exc

    expected = [
        {
            "event": "alert",
            "reason": "critical_config_change",
            "file": "local_fstab",
            "revision": revision,
        },
        {
            "event": "alert",
            "reason": "critical_config_change",
            "file": "backup.sh",
            "revision": revision,
        },
    ]

    assert len(parsed) == 2, f"Fresh push should append exactly two alerts, but appended {len(parsed)}: {parsed}"
    for record in expected:
        assert parsed.count(record) == 1, f"Fresh push did not generate exactly one expected alert: {record}"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
