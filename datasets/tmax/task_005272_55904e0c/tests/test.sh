#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import re
import subprocess
import time
from pathlib import Path

import pytest

ROOT = Path('/home/user/model_eval')
CV_PATH = ROOT / 'cv_results.csv'
INFERENCE_PATH = ROOT / 'inference_data.csv'
REPORT_PATH = ROOT / 'report.json'


def rust_sources():
    return [p for p in ROOT.rglob('*.rs') if 'target' not in p.parts]


def submission_command():
    manifest = ROOT / 'Cargo.toml'
    if manifest.is_file():
        return ['cargo', 'run', '--quiet', '--manifest-path', str(manifest)]

    sources = rust_sources()
    assert len(sources) == 1, 'Expected a Cargo project or exactly one standalone Rust source file.'
    binary = Path('/tmp/model_eval_submission')
    result = subprocess.run(
        ['rustc', '--edition=2021', '-O', str(sources[0]), '-o', str(binary)],
        cwd=ROOT, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        timeout=120,
    )
    assert result.returncode == 0, f'Rust compilation failed:\n{result.stdout}\n{result.stderr}'
    return [str(binary)]


def run_submission(command, expect_success=True):
    if REPORT_PATH.exists():
        REPORT_PATH.unlink()
    started = time.time_ns()
    result = subprocess.run(
        command, cwd=ROOT, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, timeout=180,
    )
    if expect_success:
        assert result.returncode == 0, f'Rust program failed:\n{result.stdout}\n{result.stderr}'
        assert REPORT_PATH.is_file(), f'Expected report file at {REPORT_PATH} does not exist.'
        assert REPORT_PATH.stat().st_mtime_ns >= started, 'report.json was not generated by this execution.'
    else:
        assert result.returncode != 0, 'Program must exit non-zero when no k reaches 0.80 accuracy.'
    return result


def load_report():
    with open(REPORT_PATH, 'r') as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as e:
            pytest.fail(f'Could not parse {REPORT_PATH} as JSON: {e}')


def test_rust_implementation_and_behavior():
    sources = rust_sources()
    assert sources, 'No Rust source code was found in /home/user/model_eval.'
    source = '\n'.join(p.read_text(errors='replace') for p in sources)
    compact = re.sub(r'\s+', '', source)

    assert 'cv_results.csv' in source, 'Rust code does not reference cv_results.csv.'
    assert 'inference_data.csv' in source, 'Rust code does not reference inference_data.csv.'
    assert 'report.json' in source, 'Rust code does not reference report.json.'
    assert re.search(r'Instant\s*::\s*now\s*\(', source), 'Rust code does not measure benchmark time with Instant.'
    assert ('as_micros' in source), 'Rust code does not report benchmark duration in microseconds.'
    assert re.search(r'(0\.\.1000|1\.\.=1000|0\.\.=999)', compact), 'Rust code does not contain a 1,000-iteration benchmark loop.'
    assert re.search(r'>\s*[A-Za-z_][A-Za-z0-9_]*', source), 'Rust code does not contain the required threshold comparison.'
    assert re.search(r'if[^\n\{]*>[^\n\{]*\{\s*1\s*\}\s*else\s*\{\s*0\s*\}', source), 'Rust code does not implement prediction = 1 above the threshold and 0 otherwise.'

    original_cv = CV_PATH.read_bytes()
    original_inference = INFERENCE_PATH.read_bytes()
    original_report = REPORT_PATH.read_bytes() if REPORT_PATH.exists() else None

    try:
        command = submission_command()

        # Execute against the supplied data, rather than trusting a prewritten report.
        run_submission(command)
        data = load_report()

        assert 'best_k' in data, "JSON is missing 'best_k' key."
        assert 'cv_accuracy' in data, "JSON is missing 'cv_accuracy' key."
        assert 'benchmark_time_us' in data, "JSON is missing 'benchmark_time_us' key."
        assert set(data) == {'best_k', 'cv_accuracy', 'benchmark_time_us'}, 'report.json must have exactly the required structure.'

        assert float(data['best_k']) == 5.0, f"Expected best_k to be 5.0, got {data['best_k']}."
        cv_acc = float(data['cv_accuracy'])
        assert 0.83 <= cv_acc <= 0.84, f'Expected cv_accuracy to be between 0.83 and 0.84, got {cv_acc}.'
        bench_time = data['benchmark_time_us']
        assert isinstance(bench_time, (int, float)), 'benchmark_time_us must be a number.'
        assert bench_time > 0, f'Expected benchmark_time_us to be > 0, got {bench_time}.'
        assert isinstance(bench_time, int) and not isinstance(bench_time, bool), 'benchmark_time_us must be an integer number of microseconds.'

        # Unequal fold sizes distinguish mean fold accuracy from aggregate row accuracy.
        CV_PATH.write_text(
            'fold_id,k,y_true,y_pred\n'
            '1,9.0,1,1\n'
            '2,9.0,1,1\n2,9.0,1,1\n2,9.0,1,1\n2,9.0,1,1\n2,9.0,0,1\n'
            '1,2.0,1,1\n1,2.0,1,1\n1,2.0,1,1\n1,2.0,1,1\n1,2.0,0,1\n'
            '2,2.0,1,1\n2,2.0,1,1\n2,2.0,1,1\n2,2.0,1,1\n2,2.0,0,1\n'
        )
        INFERENCE_PATH.write_text(
            'id,feature_val\n1,0.0\n2,8.9\n3,9.0\n4,9.1\n5,20.0\n'
        )
        run_submission(command)
        changed = load_report()
        assert set(changed) == {'best_k', 'cv_accuracy', 'benchmark_time_us'}
        assert float(changed['best_k']) == pytest.approx(9.0), 'Program did not recompute best_k from changed CV data.'
        assert float(changed['cv_accuracy']) == pytest.approx(0.9), 'Program must average per-fold accuracies.'
        assert isinstance(changed['benchmark_time_us'], int) and not isinstance(changed['benchmark_time_us'], bool)

        # Verify the required graceful failure path.
        CV_PATH.write_text(
            'fold_id,k,y_true,y_pred\n'
            '1,4.0,1,0\n1,4.0,0,1\n2,4.0,1,0\n2,4.0,0,1\n'
            '1,6.0,1,0\n1,6.0,0,1\n2,6.0,1,0\n2,6.0,0,1\n'
        )
        run_submission(command, expect_success=False)
    finally:
        CV_PATH.write_bytes(original_cv)
        INFERENCE_PATH.write_bytes(original_inference)
        if original_report is None:
            if REPORT_PATH.exists():
                REPORT_PATH.unlink()
        else:
            REPORT_PATH.write_bytes(original_report)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
