#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import subprocess
import sys

PIPELINE_DIR = "/home/user/log_pipeline"
SCRIPT_PATH = os.path.join(PIPELINE_DIR, "process_logs.py")
LOG_PATH = os.path.join(PIPELINE_DIR, "logs.txt")
OUTPUT_PATH = os.path.join(PIPELINE_DIR, "parsed_logs.json")
RESULTS_PATH = os.path.join(PIPELINE_DIR, "debug_results.txt")


def load_expected_fields(path):
    expected = []
    with open(path, "r") as f:
        for line_number, line in enumerate(f, 1):
            parts = line.strip().split(" ", 3)
            if len(parts) >= 4:
                expected.append({
                    "timestamp": parts[0],
                    "ip": parts[1],
                    "status": parts[2],
                    "line_number": line_number,
                })
    return expected


def run_parser(input_path):
    assert os.path.isfile(SCRIPT_PATH), f"File {SCRIPT_PATH} does not exist."
    if os.path.exists(OUTPUT_PATH):
        os.remove(OUTPUT_PATH)

    try:
        completed = subprocess.run(
            [sys.executable, SCRIPT_PATH, input_path],
            cwd=PIPELINE_DIR,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=10,
        )
    except subprocess.TimeoutExpired:
        assert False, "process_logs.py hung while processing an input containing malformed brackets."

    assert completed.returncode == 0, (
        f"process_logs.py exited with status {completed.returncode}. "
        f"stdout: {completed.stdout}\nstderr: {completed.stderr}"
    )
    assert os.path.isfile(OUTPUT_PATH), (
        f"File {OUTPUT_PATH} was not generated by process_logs.py."
    )

    try:
        with open(OUTPUT_PATH, "r") as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        assert False, f"{OUTPUT_PATH} is not valid JSON after running the parser: {e}"


def assert_matches_input(data, input_path):
    expected = load_expected_fields(input_path)
    assert isinstance(data, list), f"Expected the parsed JSON to be a list, but got {type(data).__name__}."
    assert len(data) > 0, "The parsed JSON list is empty, but it should contain log entries."
    assert len(data) == len(expected), (
        f"Expected {len(expected)} parsed records, but found {len(data)}."
    )

    for index, (record, source) in enumerate(zip(data, expected), 1):
        assert isinstance(record, dict), f"Parsed record {index} is not an object."
        for key in ("timestamp", "ip", "status", "modules"):
            assert key in record, f"Parsed record {index} is missing key {key!r}."
        assert record["timestamp"] == source["timestamp"], f"Wrong timestamp in parsed record {index}."
        assert record["ip"] == source["ip"], f"Wrong IP in parsed record {index}."
        assert str(record["status"]) == source["status"], f"Wrong status in parsed record {index}."
        assert isinstance(record["modules"], list), f"modules in parsed record {index} is not a list."
        assert record["modules"], f"modules in parsed record {index} is empty."
        assert all(isinstance(value, str) for value in record["modules"]), (
            f"modules in parsed record {index} must contain strings."
        )


def test_debug_results_exists_and_correct():
    """Check if debug_results.txt exists and contains the correct findings."""
    assert os.path.isfile(RESULTS_PATH), f"File {RESULTS_PATH} does not exist."

    with open(RESULTS_PATH, "r") as f:
        content = f.read().strip()

    lines = [line.strip() for line in content.split("\n") if line.strip()]

    expected_hang_line = "HANG_LINE=3142"
    expected_ip = "ANOMALOUS_IP=10.0.0.99"

    assert expected_hang_line in lines, f"Could not find '{expected_hang_line}' in {RESULTS_PATH}. Content was: {content}"
    assert expected_ip in lines, f"Could not find '{expected_ip}' in {RESULTS_PATH}. Content was: {content}"

    malformed_lines = []
    counts = {}
    with open(LOG_PATH, "r") as f:
        for line_number, line in enumerate(f, 1):
            parts = line.strip().split(" ", 3)
            if len(parts) < 4:
                continue
            timestamp, ip, status, rest = parts
            if "[" in rest and "]" not in rest:
                malformed_lines.append(line_number)
            if "2023-10-12T10:15:00Z" <= timestamp <= "2023-10-12T10:19:59Z" and status == "500":
                counts[ip] = counts.get(ip, 0) + 1

    assert malformed_lines == [3142], f"Unexpected malformed-bracket lines: {malformed_lines}"
    derived_ip = max(counts, key=counts.get)
    assert derived_ip == "10.0.0.99", f"Unexpected independently derived anomalous IP: {derived_ip}"


def test_parser_executes_and_handles_malformed_brackets():
    probe_path = "/tmp/parser_probe_logs.txt"
    with open(probe_path, "w") as f:
        f.write("2024-01-01T00:00:00Z 203.0.113.1 200 [auth] normal entry\n")
        f.write("2024-01-01T00:00:01Z 203.0.113.2 500 [broken missing close\n")
        f.write("2024-01-01T00:00:02Z 203.0.113.3 404 text with ] stray close\n")
        f.write("2024-01-01T00:00:03Z 203.0.113.4 200 plain text\n")

    probe_data = run_parser(probe_path)
    assert_matches_input(probe_data, probe_path)


def test_parsed_logs_json_exists_and_valid():
    """Run the repaired parser on logs.txt and validate its complete output."""
    data = run_parser(LOG_PATH)
    assert_matches_input(data, LOG_PATH)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
