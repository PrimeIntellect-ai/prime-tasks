#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import stat
import subprocess
import uuid
import pytest

RUN_TASK = "/home/user/run_task.sh"
MONITOR = "/home/user/supervisor/monitor.py"
SSH_MANAGER = "/home/user/supervisor/ssh_manager.sh"
ALERT = "/home/user/supervisor/alert.rb"
SSH_LOG = "/home/user/logs/ssh_cmd.log"
ERROR_LOG = "/home/user/logs/monitor_error.log"
WRONG_ERROR_LOG = "/home/user/error.log"
ALERT_FILE = "/home/user/mail/alert.eml"
EXPECTED_CMD = "ssh -f -N -L 8080:localhost:80 mockuser@remotehost"
EXPECTED_EMAIL = (
    "To: admin@example.com\n"
    "Subject: Tunnel Restored\n"
    "\n"
    "Tunnel is active.\n"
)


def remove_if_present(path):
    try:
        os.remove(path)
    except FileNotFoundError:
        pass


def run_checked(command, timeout=15):
    result = subprocess.run(
        command,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=timeout,
    )
    assert result.returncode == 0, (
        f"Command {command!r} failed with status {result.returncode}. "
        f"stdout={result.stdout!r}, stderr={result.stderr!r}"
    )
    return result


def assert_regular(path, executable=False):
    assert os.path.isfile(path), f"File {path} is missing."
    assert not os.path.islink(path), f"{path} must be a regular file, not a symlink."
    assert stat.S_ISREG(os.stat(path).st_mode), f"{path} is not a regular file."
    if executable:
        assert os.access(path, os.X_OK), f"Script {path} is not executable."


def assert_outputs():
    assert os.path.isfile(SSH_LOG), "ssh_cmd.log was not generated by execution."
    with open(SSH_LOG, "r") as f:
        assert f.read() == EXPECTED_CMD + "\n"

    assert os.path.isfile(ALERT_FILE), "alert.eml was not generated by execution."
    with open(ALERT_FILE, "r") as f:
        assert f.read() == EXPECTED_EMAIL

    assert not os.path.exists(ERROR_LOG), "Successful execution wrote a monitor error."
    assert not os.path.exists(WRONG_ERROR_LOG), "Successful execution wrote error.log in /home/user."


@pytest.fixture(scope="session", autouse=True)
def exercise_artifacts():
    for path, executable in [
        (RUN_TASK, True),
        (MONITOR, False),
        (SSH_MANAGER, True),
        (ALERT, True),
    ]:
        assert_regular(path, executable)

    # Exercise each subordinate artifact directly and derive outputs from a clean state.
    remove_if_present(SSH_LOG)
    run_checked([SSH_MANAGER])
    with open(SSH_LOG, "r") as f:
        assert f.read() == EXPECTED_CMD + "\n"

    remove_if_present(ALERT_FILE)
    run_checked([ALERT])
    with open(ALERT_FILE, "r") as f:
        assert f.read() == EXPECTED_EMAIL

    token = uuid.uuid4().hex
    ssh_backup = SSH_MANAGER + ".verifier_backup_" + token
    alert_backup = ALERT + ".verifier_backup_" + token
    ssh_marker = "/tmp/ssh_invoked_" + token
    alert_marker = "/tmp/alert_invoked_" + token

    # Wrap the real scripts so invocation through monitor.py and run_task.sh is observable.
    os.replace(SSH_MANAGER, ssh_backup)
    os.replace(ALERT, alert_backup)
    try:
        with open(SSH_MANAGER, "w") as f:
            f.write(
                "#!/bin/bash\n"
                f"echo invoked >> {ssh_marker}\n"
                f"exec {ssh_backup} \"$@\"\n"
            )
        os.chmod(SSH_MANAGER, 0o755)

        with open(ALERT, "w") as f:
            f.write(
                "#!/usr/bin/ruby\n"
                f"File.open({alert_marker!r}, 'a') {{ |m| m.puts 'invoked' }}\n"
                f"exec({alert_backup!r}, *ARGV)\n"
            )
        os.chmod(ALERT, 0o755)

        for path in [SSH_LOG, ALERT_FILE, ERROR_LOG, WRONG_ERROR_LOG]:
            remove_if_present(path)

        # Directly exercise monitor.py in the same stripped environment as cron.
        run_checked([
            "/usr/bin/env", "-i", "/bin/bash", "-c",
            "cd /home/user && python3 supervisor/monitor.py",
        ])
        assert_outputs()
        with open(ssh_marker, "r") as f:
            assert len(f.readlines()) == 1, "monitor.py did not execute ssh_manager.sh."
        with open(alert_marker, "r") as f:
            assert len(f.readlines()) == 1, "monitor.py did not execute alert.rb after success."

        for path in [SSH_LOG, ALERT_FILE, ERROR_LOG, WRONG_ERROR_LOG]:
            remove_if_present(path)

        # Exercise the required top-level scheduler script and require the whole chain again.
        run_checked([RUN_TASK])
        assert_outputs()
        with open(ssh_marker, "r") as f:
            assert len(f.readlines()) == 2, "run_task.sh did not reach ssh_manager.sh through monitoring."
        with open(alert_marker, "r") as f:
            assert len(f.readlines()) == 2, "run_task.sh did not reach alert.rb through monitoring."
    finally:
        remove_if_present(SSH_MANAGER)
        remove_if_present(ALERT)
        if os.path.exists(ssh_backup):
            os.replace(ssh_backup, SSH_MANAGER)
        if os.path.exists(alert_backup):
            os.replace(alert_backup, ALERT)
        remove_if_present(ssh_marker)
        remove_if_present(alert_marker)

    # Force the SSH manager to fail and verify monitor.py uses the absolute error log
    # and does not send a success alert.
    fail_backup = SSH_MANAGER + ".verifier_failure_backup_" + token
    os.replace(SSH_MANAGER, fail_backup)
    try:
        with open(SSH_MANAGER, "w") as f:
            f.write("#!/bin/bash\nexit 23\n")
        os.chmod(SSH_MANAGER, 0o755)
        for path in [ERROR_LOG, WRONG_ERROR_LOG, ALERT_FILE, SSH_LOG]:
            remove_if_present(path)

        run_checked([RUN_TASK])
        assert os.path.isfile(ERROR_LOG), "monitor.py did not write the absolute monitor error log."
        assert os.path.getsize(ERROR_LOG) > 0, "monitor_error.log is empty."
        assert not os.path.exists(WRONG_ERROR_LOG), "monitor.py wrote error.log in the working directory."
        assert not os.path.exists(ALERT_FILE), "monitor.py executed alert.rb after SSH manager failure."
    finally:
        remove_if_present(SSH_MANAGER)
        if os.path.exists(fail_backup):
            os.replace(fail_backup, SSH_MANAGER)

    # Leave final artifacts produced by an authentic successful top-level run.
    for path in [SSH_LOG, ALERT_FILE, ERROR_LOG, WRONG_ERROR_LOG]:
        remove_if_present(path)
    run_checked([RUN_TASK])
    assert_outputs()


def test_success_file():
    path = "/home/user/success.txt"
    assert os.path.isfile(path), f"File {path} is missing. Did you complete the verification step?"
    with open(path, "r") as f:
        content = f.read().strip()
    assert "DONE" in content, f"File {path} does not contain 'DONE'."


def test_ssh_cmd_log():
    path = "/home/user/logs/ssh_cmd.log"
    assert os.path.isfile(path), f"File {path} is missing. Did the ssh_manager.sh script run successfully?"
    with open(path, "r") as f:
        content = f.read()
    expected_cmd = "ssh -f -N -L 8080:localhost:80 mockuser@remotehost"
    assert expected_cmd in content, f"File {path} does not contain the exact expected SSH command."


def test_alert_eml():
    path = "/home/user/mail/alert.eml"
    assert os.path.isfile(path), f"File {path} is missing. Did alert.rb run and create the email?"
    with open(path, "r") as f:
        content = f.read()

    expected_content = (
        "To: admin@example.com\n"
        "Subject: Tunnel Restored\n"
        "\n"
        "Tunnel is active.\n"
    )
    assert content.strip() == expected_content.strip(), f"File {path} does not have the exact expected content."


def test_monitor_py_updates():
    path = "/home/user/supervisor/monitor.py"
    assert os.path.isfile(path), f"File {path} is missing."
    with open(path, "r") as f:
        content = f.read()

    assert "/home/user/supervisor/ssh_manager.sh" in content, "monitor.py does not use the absolute path to ssh_manager.sh"
    assert "/home/user/logs/monitor_error.log" in content, "monitor.py does not use the absolute path for the error log"
    assert "/home/user/supervisor/alert.rb" in content, "monitor.py does not execute alert.rb on success"


def test_alert_rb_exists_and_executable():
    path = "/home/user/supervisor/alert.rb"
    assert os.path.isfile(path), f"Script {path} is missing."
    assert os.access(path, os.X_OK), f"Script {path} is not executable."
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
