#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import base64
import hashlib
import io
import json
import os
import random
import secrets
import shutil
import subprocess
import tarfile
import tempfile

import pytest

ANALYZER = "/home/user/analyzer.go"
SUMMARY = "/home/user/summary.json"
BACKUPS = "/home/user/config_backups"
BASELINE_EXPECTED = {"Alice": 3, "Bob": 1, "Charlie": 2}


def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as e:
            pytest.fail(f"Failed to parse {path} as JSON: {e}")


def assert_baseline_summary():
    assert os.path.isfile(SUMMARY), f"File {SUMMARY} is missing. Did you run the Go program to generate the output?"
    data = load_json(SUMMARY)
    assert isinstance(data, dict), f"Expected the JSON root to be an object, but got {type(data).__name__}."
    assert data.get("Alice") == 3, f"Expected Alice to have 3 changes, got {data.get('Alice')}."
    assert data.get("Bob") == 1, f"Expected Bob to have 1 change, got {data.get('Bob')}."
    assert data.get("Charlie") == 2, f"Expected Charlie to have 2 changes, got {data.get('Charlie')}."
    assert "Eve" not in data, "Found 'Eve' in the summary, but her backup had an invalid checksum and should have been skipped."
    assert data == BASELINE_EXPECTED, f"Summary JSON does not match expected output. Expected {BASELINE_EXPECTED}, got {data}."


def run_analyzer():
    result = subprocess.run(
        ["go", "run", ANALYZER],
        cwd="/home/user",
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=90,
    )
    assert result.returncode == 0, (
        f"go run {ANALYZER} failed with exit code {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    assert os.path.isfile(SUMMARY), f"File {SUMMARY} was not generated by the Go program."


def make_log(authors, decoy):
    parts = [f"unrelated text\nAuthor: {decoy}\n\n"]
    for index, author in enumerate(authors, 1):
        parts.append(
            "START_CHANGE\n"
            f"Author: {author}\n"
            f"Date: 2025-04-{index:02d}\n"
            f"Files: {index}\n"
            "Details:\n"
            "A detail line\n"
            f"Author: {decoy}\n"
            "Another detail line\n"
            "END_CHANGE\n\n"
        )
        if index % 2:
            parts.append("random text between records\n\n")
    return "".join(parts).encode("utf-8")


def make_tar(log_bytes):
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode="w:gz") as tf:
        info = tarfile.TarInfo("changes.log")
        info.size = len(log_bytes)
        info.mode = 0o644
        tf.addfile(info, io.BytesIO(log_bytes))
    return output.getvalue()


def write_dynamic_fixtures():
    token = secrets.token_hex(6)
    alice = f"Atlas_{token}"
    bob = f"Birch_{token}"
    charlie = f"Cedar_{token}"
    poison = f"Poison_{token}"

    a_count = random.randint(2, 5)
    b_tar_count = random.randint(1, 3)
    b_clog_count = random.randint(1, 3)
    c_count = random.randint(2, 5)

    tar_authors = [alice] * a_count + [bob] * b_tar_count
    clog_authors = [bob] * b_clog_count + [charlie] * c_count
    random.shuffle(tar_authors)
    random.shuffle(clog_authors)

    valid_tar = make_tar(make_log(tar_authors, poison))
    decoded_clog = make_tar(make_log(clog_authors, poison))
    encoded = base64.b64encode(decoded_clog).decode("ascii")
    valid_clog = ("\n".join(encoded[i:i + 76] for i in range(0, len(encoded), 76)) + "\n").encode("ascii")
    invalid_tar = make_tar(make_log([poison] * random.randint(2, 5), poison))
    unsigned_tar = make_tar(make_log([poison] * random.randint(1, 4), poison))

    tar_name = f"valid_{secrets.token_hex(4)}.tar.gz"
    clog_name = f"encoded_{secrets.token_hex(4)}.clog"
    invalid_name = f"corrupt_{secrets.token_hex(4)}.tar.gz"
    unsigned_name = f"unsigned_{secrets.token_hex(4)}.tar.gz"

    files = {
        tar_name: valid_tar,
        clog_name: valid_clog,
        invalid_name: invalid_tar,
        unsigned_name: unsigned_tar,
    }
    for name, content in files.items():
        with open(os.path.join(BACKUPS, name), "wb") as f:
            f.write(content)

    wrong_hash = secrets.token_hex(32)
    actual_invalid_hash = hashlib.sha256(invalid_tar).hexdigest()
    while wrong_hash == actual_invalid_hash:
        wrong_hash = secrets.token_hex(32)

    with open(os.path.join(BACKUPS, "checksums.txt"), "w", encoding="ascii") as f:
        f.write(f"{hashlib.sha256(valid_tar).hexdigest()}  {tar_name}\n")
        f.write(f"{hashlib.sha256(valid_clog).hexdigest()}  {clog_name}\n")
        f.write(f"{wrong_hash}  {invalid_name}\n")

    expected = {
        alice: a_count,
        bob: b_tar_count + b_clog_count,
        charlie: c_count,
    }
    return expected, poison


def test_complete_analyzer_behavior():
    assert os.path.isfile(ANALYZER), f"File {ANALYZER} is missing. Did you write the Go program?"
    assert os.path.getsize(ANALYZER) > 0, f"File {ANALYZER} is empty."

    # Preserve the original verifier's checks on the agent-generated output.
    assert_baseline_summary()

    snapshot_root = tempfile.mkdtemp(prefix="analyzer-verifier-")
    snapshot = os.path.join(snapshot_root, "config_backups")
    shutil.copytree(BACKUPS, snapshot)
    baseline_summary = None

    try:
        # Execute the submitted artifact on the supplied data, then retain all
        # original exact-content assertions against the newly generated output.
        run_analyzer()
        assert_baseline_summary()
        with open(SUMMARY, "rb") as f:
            baseline_summary = f.read()

        # Replace the data with unpredictable archives so a fixed JSON writer or
        # filename-specific solution cannot pass.
        shutil.rmtree(BACKUPS)
        os.makedirs(BACKUPS)
        expected, poison = write_dynamic_fixtures()
        if os.path.exists(SUMMARY):
            os.remove(SUMMARY)

        run_analyzer()
        data = load_json(SUMMARY)
        assert isinstance(data, dict), f"Expected the JSON root to be an object, but got {type(data).__name__}."
        assert data == expected, f"Dynamic archive aggregation was incorrect. Expected {expected}, got {data}."
        assert poison not in data, "Records from bad/unsigned archives or decoy Author lines were incorrectly counted."
        assert all(type(value) is int for value in data.values()), "All summary counts must be JSON integers."
    finally:
        if os.path.exists(BACKUPS):
            shutil.rmtree(BACKUPS)
        shutil.copytree(snapshot, BACKUPS)
        if baseline_summary is not None:
            with open(SUMMARY, "wb") as f:
                f.write(baseline_summary)
        shutil.rmtree(snapshot_root, ignore_errors=True)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
