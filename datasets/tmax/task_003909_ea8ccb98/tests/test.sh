#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import csv
import fcntl
import json
import os
import random
import signal
import subprocess
import time

import pytest


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8", newline="") as f:
        return list(csv.reader(f))


def test_run_script_and_evaluate_accuracy():
    script_path = "/home/user/run_test.sh"
    archive_path = "/home/user/archive.csv"

    assert os.path.exists(script_path), f"Script {script_path} does not exist."

    # The result must be generated by this invocation, not left in the image.
    if os.path.exists(archive_path):
        os.unlink(archive_path)

    try:
        subprocess.run(["bash", script_path], timeout=20, check=True)
    except subprocess.TimeoutExpired:
        pytest.fail(f"The script {script_path} timed out after 20 seconds.")
    except subprocess.CalledProcessError as e:
        pytest.fail(f"The script {script_path} failed with exit code {e.returncode}.")

    assert os.path.exists(archive_path), f"Output file {archive_path} does not exist."
    assert os.path.getsize(archive_path) < 10_000_000, "archive.csv is unreasonably large."

    rows = read_csv(archive_path)

    # Preserve the original shape/count assertion.
    original_valid_count = sum(
        1 for row in rows if len(row) == 2 and row[0].isdigit()
    )
    total_expected = 5000
    accuracy = original_valid_count / float(total_expected)
    assert accuracy >= 0.95, (
        f"Accuracy {accuracy:.4f} is below threshold 0.95. "
        f"Valid lines: {original_valid_count}/{total_expected}"
    )

    # Every archived row must be one distinct record actually emitted by log_writer.
    seen = set()
    for line_number, row in enumerate(rows, 1):
        assert len(row) == 2, f"Malformed CSV row {line_number}: {row!r}"
        seq_text, text = row
        assert seq_text.isdigit(), f"Non-numeric sequence at row {line_number}: {seq_text!r}"
        seq = int(seq_text)
        assert 0 <= seq < total_expected, f"Sequence out of range at row {line_number}: {seq}"
        assert seq not in seen, f"Duplicate sequence in archive: {seq}"
        assert text == f"Log entry {seq}", (
            f"Incorrect UTF-8 text for sequence {seq}: {text!r}"
        )
        seen.add(seq)

    assert len(seen) >= 4750, f"Only {len(seen)}/5000 distinct correct records were archived."


def test_executable_exists():
    archiver_path = "/home/user/archiver"
    assert os.path.exists(archiver_path), f"Archiver executable {archiver_path} does not exist."
    assert os.access(archiver_path, os.X_OK), f"Archiver {archiver_path} is not executable."
    assert os.path.isfile(archiver_path), f"Archiver {archiver_path} is not a regular file."
    with open(archiver_path, "rb") as f:
        assert f.read(4) == b"\x7fELF", "Archiver is not a compiled ELF executable."


def test_archiver_parses_converts_and_locks_controlled_logs(tmp_path):
    archiver_path = "/home/user/archiver"
    assert os.path.exists(archiver_path)
    assert os.access(archiver_path, os.X_OK)

    log_dir = tmp_path / "logs"
    log_dir.mkdir()
    archive_path = tmp_path / "archive.csv"
    marker_path = tmp_path / "shared-lock-used"

    # Interpose flock so the test observes an actual LOCK_SH call by the submitted
    # executable rather than trusting source text or comments.
    shim_source = tmp_path / "flock_shim.c"
    shim_library = tmp_path / "flock_shim.so"
    shim_source.write_text(r'''
#define _GNU_SOURCE
#include <dlfcn.h>
#include <fcntl.h>
#include <sys/file.h>
#include <sys/syscall.h>
#include <unistd.h>
#include <stdlib.h>

typedef int (*flock_fn)(int, int);
int flock(int fd, int operation) {
    static flock_fn real_flock = 0;
    if (!real_flock) real_flock = (flock_fn)dlsym(RTLD_NEXT, "flock");
    if ((operation & LOCK_SH) == LOCK_SH) {
        const char *p = getenv("ARCHIVER_LOCK_MARKER");
        if (p) {
            int m = (int)syscall(SYS_openat, AT_FDCWD, p,
                                 O_WRONLY | O_CREAT | O_APPEND, 0600);
            if (m >= 0) {
                syscall(SYS_write, m, "1\n", 2);
                syscall(SYS_close, m);
            }
        }
    }
    return real_flock(fd, operation);
}
''', encoding="utf-8")
    subprocess.run(
        ["gcc", "-shared", "-fPIC", str(shim_source), "-ldl", "-o", str(shim_library)],
        check=True,
    )

    rng = random.SystemRandom()
    seqs = rng.sample(range(100000, 900000), 32)
    samples = [
        "Grüße", "Καλημέρα", "日本語", "Привет", "مرحبا", "שלום",
        "naïve café", "snowman ☃", "music ♫", "emoji 😀", "rocket 🚀",
        "हिन्दी", "한국어", "Español", "Português", "中文",
    ]
    expected = {}
    records = []
    for i, seq in enumerate(seqs):
        text = f"{samples[i % len(samples)]} {rng.randrange(10**8, 10**9)}"
        expected[seq] = text
        data = text.encode("utf-16le").hex()
        # Vary JSON member order and include an irrelevant member.
        if i % 2:
            obj = {"data": data, "ignored": i, "seq": seq}
        else:
            obj = {"seq": seq, "ignored": i, "data": data}
        records.append(json.dumps(obj, ensure_ascii=True, separators=(",", ":")))

    decoy_seq = rng.randrange(900001, 999999)
    malformed = [
        "not json at all",
        '{"seq":%d,"data":"4100",}' % decoy_seq,
        '{"seq":"wrong type","data":"4100"}',
        '{"seq":%d,"data":"not-hex"}' % (decoy_seq + 1),
    ]

    rotated_lines = records[:16] + malformed[:2]
    active_lines = malformed[2:] + records[16:31]
    (log_dir / "rotated.log").write_text("\n".join(rotated_lines) + "\n", encoding="utf-8")
    (log_dir / "active.log").write_text("\n".join(active_lines) + "\n", encoding="utf-8")

    # Hold an exclusive lock while appending the final complete record. A correct
    # archiver must not read any active.log records until this lock is released.
    final_line = records[31]
    active_fd = os.open(log_dir / "active.log", os.O_WRONLY | os.O_APPEND)
    fcntl.flock(active_fd, fcntl.LOCK_EX)
    os.write(active_fd, (final_line + "\n").encode("utf-8"))
    os.fsync(active_fd)

    env = os.environ.copy()
    env["LD_PRELOAD"] = str(shim_library)
    env["ARCHIVER_LOCK_MARKER"] = str(marker_path)
    proc = subprocess.Popen(
        [archiver_path, str(log_dir), str(archive_path)],
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )

    try:
        deadline = time.time() + 2.0
        while time.time() < deadline and not marker_path.exists():
            if proc.poll() is not None:
                break
            time.sleep(0.02)
        assert marker_path.exists(), "Archiver never called flock with LOCK_SH."

        # active.log was exclusively locked before the process started.
        time.sleep(0.4)
        active_seqs = set(seqs[16:])
        for row in read_csv(archive_path):
            if len(row) == 2 and row[0].isdigit():
                assert int(row[0]) not in active_seqs, (
                    "Archiver read active.log while another process held LOCK_EX."
                )

        fcntl.flock(active_fd, fcntl.LOCK_UN)
        os.close(active_fd)
        active_fd = -1

        deadline = time.time() + 6.0
        while time.time() < deadline:
            rows = read_csv(archive_path)
            found = {
                int(row[0]): row[1]
                for row in rows
                if len(row) == 2 and row[0].isdigit()
            }
            if all(found.get(seq) == text for seq, text in expected.items()):
                break
            if proc.poll() is not None:
                break
            time.sleep(0.05)

        rows = read_csv(archive_path)
        assert rows, "Controlled run produced no CSV records."
        found = {}
        for row in rows:
            assert len(row) == 2, f"Malformed controlled CSV row: {row!r}"
            assert row[0].isdigit(), f"Invalid controlled sequence: {row!r}"
            seq = int(row[0])
            assert seq in expected, f"Malformed JSON or an unknown record was archived: {seq}"
            assert seq not in found, f"Controlled record was duplicated: {seq}"
            assert row[1] == expected[seq], f"Incorrect UTF-16LE to UTF-8 conversion for {seq}"
            found[seq] = row[1]
        assert found == expected, (
            f"Controlled run archived {len(found)}/{len(expected)} expected records."
        )
    finally:
        if active_fd >= 0:
            fcntl.flock(active_fd, fcntl.LOCK_UN)
            os.close(active_fd)
        if proc.poll() is None:
            try:
                os.killpg(proc.pid, signal.SIGINT)
                proc.wait(timeout=2)
            except (ProcessLookupError, subprocess.TimeoutExpired):
                try:
                    os.killpg(proc.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
                proc.wait(timeout=2)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
