#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import base64
import os
from pathlib import Path
import re
import secrets
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request

import pytest

APP = Path("/home/user/app_stack")
CONF = APP / "nginx/nginx.conf"
HTPASSWD = APP / "nginx/.htpasswd"
MANAGE_AUTH = APP / "manage_auth.sh"
CONNECTION_SCRIPT = APP / "test_connection.sh"
RESULT_LOG = APP / "final_result.log"
URL = "http://127.0.0.1:8080/"
EXPECTED_LOG = "HTTP_STATUS: 200, BODY: Backend operational!"


def authenticated_get(username, password):
    req = urllib.request.Request(URL)
    token = base64.b64encode(f"{username}:{password}".encode()).decode("ascii")
    req.add_header("Authorization", f"Basic {token}")
    with urllib.request.urlopen(req, timeout=5) as response:
        return response.getcode(), response.read().decode("utf-8")


def run_as_user(command, timeout=15):
    return subprocess.run(
        ["runuser", "-u", "user", "--", *command],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=timeout,
    )


def run_connection_script():
    if RESULT_LOG.exists():
        RESULT_LOG.unlink()
    result = run_as_user(["bash", str(CONNECTION_SCRIPT)])
    assert result.returncode == 0, (
        f"test_connection.sh failed with exit code {result.returncode}. "
        f"stdout={result.stdout!r}, stderr={result.stderr!r}"
    )
    assert RESULT_LOG.is_file(), "test_connection.sh did not create final_result.log."
    lines = RESULT_LOG.read_text().splitlines()
    assert len(lines) == 1, f"final_result.log must contain exactly one line; found {lines!r}"
    return lines[0]


def reload_nginx():
    result = subprocess.run(
        ["nginx", "-c", str(CONF), "-p", str(APP / "nginx") + "/", "-s", "reload"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=10,
    )
    assert result.returncode == 0, (
        f"Could not reload Nginx. stdout={result.stdout!r}, stderr={result.stderr!r}"
    )
    time.sleep(0.5)


def test_nginx_conf_fixed_and_secured():
    conf_path = str(CONF)
    assert os.path.isfile(conf_path), f"{conf_path} does not exist."

    content = CONF.read_text()
    assert "proxy_pass http://127.0.0.1:9091;" in content, "Nginx config proxy_pass port was not fixed to 9091."
    assert 'auth_basic "Restricted Area";' in content, "Nginx config does not contain the required auth_basic directive."
    assert "auth_basic_user_file" in content and ".htpasswd" in content, "Nginx config does not contain the auth_basic_user_file directive pointing to .htpasswd."


def test_htpasswd_file_exists_and_contains_sysadmin():
    assert HTPASSWD.is_file(), f"{HTPASSWD} was not created."
    content = HTPASSWD.read_text()
    assert "sysadmin:" in content, "The .htpasswd file does not contain an entry for 'sysadmin'."


def test_manage_auth_script():
    script_path = str(MANAGE_AUTH)
    assert os.path.isfile(script_path), f"{script_path} does not exist."
    assert os.access(script_path, os.X_OK), f"{script_path} is not executable."

    username = "verify_" + secrets.token_hex(6)
    password = "Pw-" + secrets.token_urlsafe(12)
    before = HTPASSWD.read_text() if HTPASSWD.exists() else ""
    assert not re.search(rf"^{re.escape(username)}:", before, re.MULTILINE)

    result = run_as_user([script_path, username, password])
    assert result.returncode == 0, (
        f"manage_auth.sh failed with exit code {result.returncode}. "
        f"stdout={result.stdout!r}, stderr={result.stderr!r}"
    )

    after = HTPASSWD.read_text()
    entries = re.findall(rf"^{re.escape(username)}:(.+)$", after, re.MULTILINE)
    assert len(entries) == 1, "manage_auth.sh did not append exactly one entry for the supplied username."
    assert entries[0].strip(), "manage_auth.sh appended an empty password hash."
    assert password not in entries[0], "manage_auth.sh stored the supplied plaintext password."

    status, body = authenticated_get(username, password)
    assert status == 200, f"The account generated by manage_auth.sh could not authenticate; got HTTP {status}."
    assert "Backend operational!" in body, "Generated credentials did not reach the backend through Nginx."


def test_test_connection_script_exists():
    script_path = str(CONNECTION_SCRIPT)
    assert os.path.isfile(script_path), f"{script_path} does not exist."


def test_final_result_log():
    line = run_connection_script()
    assert EXPECTED_LOG in line, f"Log file does not contain the expected string. Found: {line}"
    assert line == EXPECTED_LOG, f"Log file has the wrong format or content. Found: {line!r}"


def test_connection_script_performs_live_diagnostic():
    original_conf = CONF.read_text()
    nonce_body = "diagnostic-" + secrets.token_hex(12)

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]

    server_code = r'''
from http.server import BaseHTTPRequestHandler, HTTPServer
import sys
body = sys.argv[1].encode()
class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def log_message(self, *args):
        pass
HTTPServer(("127.0.0.1", int(sys.argv[2])), Handler).serve_forever()
'''
    server = subprocess.Popen(
        [sys.executable, "-c", server_code, nonce_body, str(port)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    try:
        deadline = time.time() + 5
        while time.time() < deadline:
            try:
                with socket.create_connection(("127.0.0.1", port), timeout=0.2):
                    break
            except OSError:
                time.sleep(0.05)
        else:
            pytest.fail("Could not start the verifier's temporary backend.")

        assert "proxy_pass http://127.0.0.1:9091;" in original_conf
        CONF.write_text(original_conf.replace(
            "proxy_pass http://127.0.0.1:9091;",
            f"proxy_pass http://127.0.0.1:{port};",
            1,
        ))
        reload_nginx()

        line = run_connection_script()
        expected = f"HTTP_STATUS: 200, BODY: {nonce_body}"
        assert line == expected, (
            "test_connection.sh did not report the live authenticated response in the required format. "
            f"Expected {expected!r}, found {line!r}."
        )
    finally:
        CONF.write_text(original_conf)
        try:
            reload_nginx()
        finally:
            server.terminate()
            try:
                server.wait(timeout=3)
            except subprocess.TimeoutExpired:
                server.kill()
                server.wait(timeout=3)

    # Leave the required final artifact representing the real backend, not the temporary challenge server.
    line = run_connection_script()
    assert line == EXPECTED_LOG, f"Final diagnostic after restoring the backend was incorrect: {line!r}"


def test_live_service_authentication():
    req_unauth = urllib.request.Request(URL)
    try:
        urllib.request.urlopen(req_unauth, timeout=5)
        pytest.fail("Service is accessible without authentication, but it should be protected.")
    except urllib.error.HTTPError as e:
        assert e.code == 401, f"Expected HTTP 401 Unauthorized without credentials, got {e.code}."
    except urllib.error.URLError as e:
        pytest.fail(f"Could not connect to Nginx on port 8080: {e.reason}")

    try:
        status, body = authenticated_get("sysadmin", "supersecurepass")
        assert status == 200, f"Expected HTTP 200 with valid credentials, got {status}."
        assert "Backend operational!" in body, "Response body did not contain expected backend text."
    except urllib.error.HTTPError as e:
        pytest.fail(f"Authentication failed or backend error. HTTP {e.code}: {e.reason}")
    except urllib.error.URLError as e:
        pytest.fail(f"Could not connect to Nginx on port 8080: {e.reason}")
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
