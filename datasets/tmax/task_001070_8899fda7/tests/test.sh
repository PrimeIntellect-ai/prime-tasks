#!/bin/bash
mkdir -p /logs/verifier

ok=1
ORIGINAL_DATA=$(mktemp)
cp /home/user/data/observations.csv "$ORIGINAL_DATA" || ok=0
restore_data() {
    cp "$ORIGINAL_DATA" /home/user/data/observations.csv 2>/dev/null || true
}
trap restore_data EXIT

# Execute the notebook from a clean output state so pre-fabricated artifacts cannot pass.
rm -f /home/user/output/distances.json /home/user/output/best_pair.txt
if [ "$ok" -eq 1 ]; then
    jupyter nbconvert --to notebook --execute /home/user/workflow.ipynb \
        --output executed_workflow.ipynb --output-dir /tmp \
        --ExecutePreprocessor.timeout=300 >/tmp/notebook.log 2>&1 || ok=0
fi
if [ "$ok" -eq 1 ]; then
    test -f /home/user/output/distances.json && test -f /home/user/output/best_pair.txt || ok=0
fi
if [ "$ok" -eq 1 ]; then
    cp /home/user/output/distances.json /tmp/notebook_distances.json || ok=0
    cp /home/user/output/best_pair.txt /tmp/notebook_best_pair.txt || ok=0
fi
# The workflow must not replace its input data.
if [ "$ok" -eq 1 ]; then
    cmp -s "$ORIGINAL_DATA" /home/user/data/observations.csv || ok=0
fi
restore_data
cp "$ORIGINAL_DATA" /tmp/original_observations.csv 2>/dev/null || ok=0

# Independently execute the submitted Rust artifact on the real data.
if [ "$ok" -eq 1 ]; then
    rm -f /home/user/output/distances.json
    cargo run --release --quiet --manifest-path /home/user/rust_dist/Cargo.toml \
        >/tmp/rust_original.log 2>&1 || ok=0
fi
if [ "$ok" -eq 1 ]; then
    test -f /home/user/output/distances.json || ok=0
    cp /home/user/output/distances.json /tmp/rust_original_distances.json || ok=0
fi

# Exercise the Rust program on a second valid dataset, including bin boundaries,
# empty bins, and value 1.0, to reject hard-coded output.
if [ "$ok" -eq 1 ]; then
    python3 - <<'PY' || ok=0
import csv
rows = {
    'A-17': [0.0, 0.0999, 0.1, 0.2, 0.31, 0.44, 0.55, 0.66, 0.77, 0.88, 0.99, 1.0],
    'B-03': [0.01, 0.08, 0.12, 0.21, 0.35, 0.42, 0.59, 0.61, 0.79, 0.81, 0.95, 1.0],
    'C-99': [0.0, 0.01, 0.02, 0.03, 0.04, 0.1, 0.11, 0.12, 0.2, 0.21, 0.22],
    'D-42': [0.72, 0.75, 0.79, 0.8, 0.82, 0.85, 0.9, 0.91, 0.95, 0.99, 1.0],
    'E-5':  [0.05, 0.15, 0.25, 0.35, 0.45, 0.55, 0.65, 0.75, 0.85, 0.95],
}
path = '/tmp/challenge_observations.csv'
with open(path, 'w', newline='') as f:
    w = csv.writer(f)
    w.writerow(['timestamp', 'sensor_id', 'value'])
    n = 0
    for sensor, values in rows.items():
        for value in values:
            w.writerow([f'challenge-{n}', sensor, value])
            n += 1
with open(path, 'rb') as src, open('/home/user/data/observations.csv', 'wb') as dst:
    dst.write(src.read())
PY
fi
if [ "$ok" -eq 1 ]; then
    rm -f /home/user/output/distances.json
    cargo run --release --quiet --manifest-path /home/user/rust_dist/Cargo.toml \
        >/tmp/rust_challenge.log 2>&1 || ok=0
fi
if [ "$ok" -eq 1 ]; then
    test -f /home/user/output/distances.json || ok=0
    cp /home/user/output/distances.json /tmp/rust_challenge_distances.json || ok=0
fi

# Restore the specified input and leave outputs generated by the program for the
# original data, preserving the original verifier's final-state assertions.
restore_data
if [ "$ok" -eq 1 ]; then
    rm -f /home/user/output/distances.json
    cargo run --release --quiet --manifest-path /home/user/rust_dist/Cargo.toml \
        >/tmp/rust_final.log 2>&1 || ok=0
fi

cat <<'TEST_EOF' > /tmp/test_final_state.py
import csv
import itertools
import json
import math
import os
import re
import pytest


def expected_from_csv(path):
    counts = {}
    with open(path, newline='') as f:
        reader = csv.DictReader(f)
        assert reader.fieldnames == ['timestamp', 'sensor_id', 'value']
        for row in reader:
            sensor = row['sensor_id']
            value = float(row['value'])
            assert 0.0 <= value <= 1.0
            bins = counts.setdefault(sensor, [0] * 10)
            index = 9 if value == 1.0 else int(value * 10.0)
            bins[index] += 1

    distributions = {}
    for sensor, bins in counts.items():
        smoothed = [count + 1e-9 for count in bins]
        total = sum(smoothed)
        distributions[sensor] = [value / total for value in smoothed]

    expected = {}
    for a, b in itertools.combinations(sorted(distributions), 2):
        p, q = distributions[a], distributions[b]
        m = [(x + y) / 2.0 for x, y in zip(p, q)]
        jsd = 0.5 * sum(x * math.log(x / z) for x, z in zip(p, m))
        jsd += 0.5 * sum(y * math.log(y / z) for y, z in zip(q, m))
        expected[(a, b)] = jsd
    return expected


def load_and_validate_distances(json_path, csv_path):
    with open(json_path) as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f'The file {json_path} is not valid JSON.')

    assert isinstance(data, list), 'The JSON output must be an array.'
    expected = expected_from_csv(csv_path)
    assert len(data) == len(expected), (
        f'{json_path} has {len(data)} pairs; expected {len(expected)}.'
    )

    actual = {}
    for item in data:
        assert isinstance(item, dict), 'Each result must be a JSON object.'
        assert 'sensor_a' in item, "Missing 'sensor_a' in JSON output."
        assert 'sensor_b' in item, "Missing 'sensor_b' in JSON output."
        assert 'jsd' in item, "Missing 'jsd' in JSON output."
        a, b, value = item['sensor_a'], item['sensor_b'], item['jsd']
        assert isinstance(a, str) and isinstance(b, str)
        assert a < b, f'Pair must be lexicographically ordered, got {a},{b}.'
        assert (a, b) not in actual, f'Duplicate pair {a},{b}.'
        assert isinstance(value, (int, float)) and not isinstance(value, bool)
        assert math.isfinite(value) and value >= -1e-12
        actual[(a, b)] = float(value)

    assert set(actual) == set(expected), 'The output does not contain exactly all unique sensor pairs.'
    for pair, wanted in expected.items():
        assert math.isclose(actual[pair], wanted, rel_tol=1e-8, abs_tol=1e-10), (
            f'Incorrect JSD for {pair}: got {actual[pair]}, expected {wanted}.'
        )
    return expected


def expected_best(csv_path):
    values = expected_from_csv(csv_path)
    return min(values.items(), key=lambda item: item[1])[0]


def test_output_directory_exists():
    assert os.path.isdir('/home/user/output'), 'The output directory /home/user/output does not exist.'


def test_distances_json_exists_and_valid():
    json_path = '/home/user/output/distances.json'
    assert os.path.isfile(json_path), f'The file {json_path} does not exist.'
    load_and_validate_distances(json_path, '/tmp/original_observations.csv')


def test_notebook_generated_correct_distances():
    load_and_validate_distances('/tmp/notebook_distances.json', '/tmp/original_observations.csv')


def test_independent_rust_runs_are_correct():
    load_and_validate_distances('/tmp/rust_original_distances.json', '/tmp/original_observations.csv')
    load_and_validate_distances('/tmp/rust_challenge_distances.json', '/tmp/challenge_observations.csv')


def test_best_pair_txt():
    txt_path = '/home/user/output/best_pair.txt'
    assert os.path.isfile(txt_path), f'The file {txt_path} does not exist.'
    with open(txt_path) as f:
        content = f.read().strip()
    assert content == 'S1,S2', f"Expected 'S1,S2' in {txt_path}, but got '{content}'."
    assert tuple(content.split(',')) == expected_best('/tmp/original_observations.csv')


def test_notebook_generated_best_pair():
    with open('/tmp/notebook_best_pair.txt') as f:
        content = f.read().strip()
    assert content == 'S1,S2'
    assert tuple(content.split(',')) == expected_best('/tmp/original_observations.csv')


def test_rust_project_structure_and_rayon():
    cargo_toml_path = '/home/user/rust_dist/Cargo.toml'
    main_rs_path = '/home/user/rust_dist/src/main.rs'
    assert os.path.isfile(cargo_toml_path), f'The file {cargo_toml_path} does not exist.'
    assert os.path.isfile(main_rs_path), f'The file {main_rs_path} does not exist.'
    with open(cargo_toml_path) as f:
        cargo_content = f.read()
        assert 'rayon' in cargo_content, "The 'rayon' crate is missing from Cargo.toml."
    with open(main_rs_path) as f:
        main_content = f.read()
        assert 'par_iter' in main_content or 'par_bridge' in main_content or 'rayon::' in main_content, \
            'Could not find evidence of rayon parallelism (e.g., par_iter) in main.rs.'


def test_workflow_notebook_exists_and_valid():
    ipynb_path = '/home/user/workflow.ipynb'
    assert os.path.isfile(ipynb_path), f'The file {ipynb_path} does not exist.'
    with open(ipynb_path) as f:
        try:
            notebook = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f'The file {ipynb_path} is not valid JSON (Jupyter notebook).')
    assert 'cells' in notebook, "The notebook does not have a 'cells' property."
    kernel = notebook.get('metadata', {}).get('kernelspec', {})
    assert kernel.get('name') == 'python3' or 'python' in kernel.get('display_name', '').lower(), \
        'The notebook must use a Python 3 kernel.'
    cells_source = []
    for cell in notebook.get('cells', []):
        source = cell.get('source', [])
        if isinstance(source, list):
            cells_source.extend(source)
        else:
            cells_source.append(source)
    full_source = ''.join(cells_source)
    assert 'cargo build --release' in full_source or '!cargo build --release' in full_source, \
        'The notebook does not contain a command to compile the Rust project in release mode.'
    assert 'distances.json' in full_source, 'The notebook does not contain code to read distances.json.'
    assert re.search(r'cargo\s+run|target/release', full_source), \
        'The notebook does not contain a command that executes the compiled Rust application.'
TEST_EOF

if [ "$ok" -eq 1 ] && python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
