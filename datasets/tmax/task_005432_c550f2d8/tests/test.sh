#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import math
import os
import secrets
import shutil
import tempfile
from datetime import date, timedelta

import pandas as pd
import pytest
import requests

URL = "http://127.0.0.1:5000/rolling_stats"
TOKEN = "SECRET-99X-2024"
PARQUET_PATH = "/home/user/processed_data.parquet"
DATA_DIR = "/app/data"


def assert_parquet_contents(expected_records):
    assert os.path.isfile(PARQUET_PATH), f"Parquet file {PARQUET_PATH} was not generated by the API."

    # Retain the original magic-byte assertion.
    with open(PARQUET_PATH, "rb") as f:
        header = f.read(4)
    assert header == b"PAR1", (
        f"File {PARQUET_PATH} does not appear to be a valid Parquet file "
        "(missing PAR1 magic bytes)."
    )

    try:
        frame = pd.read_parquet(PARQUET_PATH)
    except Exception as exc:
        pytest.fail(f"Could not read generated file as Parquet: {exc}")

    assert "date" in frame.columns, "Generated Parquet is missing the date column"
    assert "amount" in frame.columns, "Generated Parquet is missing the amount column"
    assert len(frame) == len(expected_records), (
        f"Expected {len(expected_records)} rows in Parquet, got {len(frame)}"
    )

    actual_dates = pd.to_datetime(frame["date"], errors="raise").dt.strftime("%Y-%m-%d").tolist()
    expected_dates = [d for d, _ in expected_records]
    assert actual_dates == expected_dates, (
        f"Parquet rows were not combined and chronologically sorted: {actual_dates}"
    )

    actual_amounts = pd.to_numeric(frame["amount"], errors="raise").astype(float).tolist()
    expected_amounts = [float(a) for _, a in expected_records]
    assert all(math.isclose(a, e, rel_tol=1e-9, abs_tol=1e-9)
               for a, e in zip(actual_amounts, expected_amounts)), (
        f"Parquet amounts do not match all CSV records: {actual_amounts}"
    )

    expected_rolling = [
        sum(expected_amounts[max(0, i - 2):i + 1]) / len(expected_amounts[max(0, i - 2):i + 1])
        for i in range(len(expected_amounts))
    ]
    candidate_columns = [c for c in frame.columns if c not in ("date", "amount")]
    matching_columns = []
    for column in candidate_columns:
        try:
            values = pd.to_numeric(frame[column], errors="raise").astype(float).tolist()
        except Exception:
            continue
        if len(values) == len(expected_rolling) and all(
            math.isclose(a, e, rel_tol=1e-7, abs_tol=1e-7)
            for a, e in zip(values, expected_rolling)
        ):
            matching_columns.append(column)
    assert matching_columns, (
        "Generated Parquet does not contain a column with the computed 3-day rolling averages"
    )


def test_cron_schedule():
    path = "/home/user/cron_schedule.txt"
    assert os.path.isfile(path), f"Cron schedule file {path} is missing."
    with open(path, "r") as f:
        raw = f.read()
    content = raw.strip()
    expected = "30 4 * * 2 /bin/bash /home/user/backup.sh"
    # Retain the original assertion and additionally require exactly one line.
    assert expected in content, f"Expected '{expected}' in cron schedule file, got '{content}'"
    assert raw in (expected, expected + "\n"), (
        f"Cron schedule must contain exactly one crontab line, got {raw!r}"
    )


def test_api_unauthorized():
    try:
        response = requests.get(URL, timeout=5)
    except requests.exceptions.RequestException as exc:
        pytest.fail(f"Failed to connect to the API at {URL}: {exc}")
    assert response.status_code == 401, (
        f"Expected 401 Unauthorized for missing token, got {response.status_code}"
    )

    response = requests.get(
        URL, headers={"Authorization": "Bearer definitely-not-the-token"}, timeout=5
    )
    assert response.status_code == 401, (
        f"Expected 401 Unauthorized for incorrect token, got {response.status_code}"
    )


def test_api_authorized_and_dynamic_processing():
    headers = {"Authorization": f"Bearer {TOKEN}"}
    original_records = [
        ("2024-01-01", 10.0),
        ("2024-01-02", 20.0),
        ("2024-01-03", 30.0),
        ("2024-01-04", 40.0),
        ("2024-01-05", 50.0),
    ]

    if os.path.exists(PARQUET_PATH):
        os.remove(PARQUET_PATH)
    try:
        response = requests.get(URL, headers=headers, timeout=10)
    except requests.exceptions.RequestException as exc:
        pytest.fail(f"Failed to connect to the API at {URL}: {exc}")

    assert response.status_code == 200, (
        f"Expected 200 OK, got {response.status_code}. Response: {response.text}"
    )
    try:
        data = response.json()
    except ValueError:
        pytest.fail(f"Expected JSON response, but could not parse it. Response: {response.text}")
    assert "latest_date" in data, "Response missing 'latest_date'"
    assert "rolling_avg_3d" in data, "Response missing 'rolling_avg_3d'"
    assert data["latest_date"] == "2024-01-05", (
        f"Expected latest_date '2024-01-05', got {data['latest_date']}"
    )
    assert math.isclose(float(data["rolling_avg_3d"]), 40.0, rel_tol=1e-5), (
        f"Expected rolling_avg_3d 40.0, got {data['rolling_avg_3d']}"
    )
    assert_parquet_contents(original_records)

    # Replace the fixed inputs with unpredictable records and mixed encodings. This
    # proves the live endpoint rereads, decodes, combines, sorts, and computes data.
    backup_dir = tempfile.mkdtemp(prefix="verifier_csv_backup_")
    original_files = []
    try:
        for name in os.listdir(DATA_DIR):
            path = os.path.join(DATA_DIR, name)
            if os.path.isfile(path):
                shutil.copy2(path, os.path.join(backup_dir, name))
                original_files.append(name)
                os.remove(path)

        start = date(2028, 1, 1) + timedelta(days=secrets.randbelow(1200))
        amounts = [float(secrets.randbelow(9000) + 101) / 10.0 for _ in range(7)]
        records = [((start + timedelta(days=i)).isoformat(), amounts[i]) for i in range(7)]

        # Deliberately distribute records out of chronological order.
        fixtures = [
            ("dynamic_utf8.csv", "utf-8", [records[5], records[0], records[3]]),
            ("dynamic_utf16.csv", "utf-16", [records[6], records[2]]),
            ("dynamic_shiftjis.csv", "shift_jis", [records[4], records[1]]),
        ]
        for filename, encoding, rows in fixtures:
            with open(os.path.join(DATA_DIR, filename), "w", encoding=encoding, newline="") as f:
                f.write("date,amount\n")
                for row_date, amount in rows:
                    f.write(f"{row_date},{amount:.10f}\n")

        if os.path.exists(PARQUET_PATH):
            os.remove(PARQUET_PATH)
        response = requests.get(URL, headers=headers, timeout=10)
        assert response.status_code == 200, (
            f"Dynamic request returned {response.status_code}: {response.text}"
        )
        try:
            dynamic_data = response.json()
        except ValueError:
            pytest.fail(f"Dynamic request did not return JSON: {response.text}")

        expected_latest_avg = sum(amounts[-3:]) / 3.0
        assert dynamic_data.get("latest_date") == records[-1][0], (
            f"API did not dynamically determine latest date: {dynamic_data}"
        )
        assert "rolling_avg_3d" in dynamic_data, "Dynamic response missing rolling_avg_3d"
        assert math.isclose(
            float(dynamic_data["rolling_avg_3d"]), expected_latest_avg,
            rel_tol=1e-7, abs_tol=1e-7
        ), f"Dynamic rolling average is incorrect: {dynamic_data}"
        assert_parquet_contents(records)
    finally:
        for name in os.listdir(DATA_DIR):
            path = os.path.join(DATA_DIR, name)
            if os.path.isfile(path):
                os.remove(path)
        for name in original_files:
            shutil.copy2(os.path.join(backup_dir, name), os.path.join(DATA_DIR, name))
        shutil.rmtree(backup_dir, ignore_errors=True)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
