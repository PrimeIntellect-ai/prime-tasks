#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import subprocess

REFERENCE_C = r'''#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include <gsl/gsl_rng.h>

int main(void) {
    FILE *f = fopen("/home/user/data.txt", "r");
    if (!f) return 1;
    double data[100];
    for (int i = 0; i < 100; i++) {
        if (fscanf(f, "%lf", &data[i]) != 1) {
            fclose(f);
            return 2;
        }
    }
    fclose(f);

    gsl_rng *r = gsl_rng_alloc(gsl_rng_mt19937);
    if (!r) return 3;
    gsl_rng_set(r, 42);

    const int B = 1000;
    const int N = 100;
    double means[1000];
    double sum_of_means = 0.0;

    for (int i = 0; i < B; i++) {
        double sample_sum = 0.0;
        for (int j = 0; j < N; j++) {
            int idx = gsl_rng_uniform_int(r, N);
            sample_sum += data[idx];
        }
        means[i] = sample_sum / N;
        sum_of_means += means[i];
    }

    double overall_mean = sum_of_means / B;
    double sum_sq_diff = 0.0;
    for (int i = 0; i < B; i++) {
        double d = means[i] - overall_mean;
        sum_sq_diff += d * d;
    }
    double stddev = sqrt(sum_sq_diff / (B - 1));

    printf("Overall Mean: %.6f\n", overall_mean);
    printf("StdDev: %.6f\n", stddev);
    gsl_rng_free(r);
    return 0;
}
'''

def compile_program(source, output):
    result = subprocess.run(
        ["gcc", "-o", output, source, "-lgsl", "-lgslcblas", "-lm"],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, f"Failed to compile {source}:\n{result.stderr}"


def run_program(path):
    result = subprocess.run([path], capture_output=True, text=True, timeout=15)
    assert result.returncode == 0, (
        f"{path} exited with status {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    return result.stdout.strip()


def ensure_reference():
    if not os.path.exists("/tmp/reference"):
        with open("/tmp/reference.c", "w") as f:
            f.write(REFERENCE_C)
        compile_program("/tmp/reference.c", "/tmp/reference")


def assert_gsl_executable(path):
    with open(path, "rb") as f:
        assert f.read(4) == b"\x7fELF", f"{path} is not a compiled ELF executable."
    linked = subprocess.run(["ldd", path], capture_output=True, text=True, timeout=10)
    assert linked.returncode == 0, f"Could not inspect linked libraries for {path}."
    assert "libgsl.so" in linked.stdout, f"{path} is not linked to GSL."


def write_dataset(values):
    with open("/home/user/data.txt", "w") as f:
        for value in values:
            f.write(f"{value:.17g}\n")


def test_gsl_installed():
    """Verify that libgsl-dev is installed."""
    assert os.path.exists("/usr/include/gsl/gsl_rng.h"), "libgsl-dev does not appear to be installed (/usr/include/gsl/gsl_rng.h missing)."


def test_files_exist():
    """Verify that the required source, executable, and result files exist."""
    assert os.path.exists("/home/user/bootstrap.c"), "/home/user/bootstrap.c is missing."
    assert os.path.exists("/home/user/bootstrap"), "/home/user/bootstrap is missing."
    assert os.access("/home/user/bootstrap", os.X_OK), "/home/user/bootstrap is not executable."
    assert os.path.exists("/home/user/result.txt"), "/home/user/result.txt is missing."


def test_result_correct():
    """Verify that result.txt matches the expected output generated by the reference implementation."""
    ensure_reference()
    expected_output = run_program("/tmp/reference")
    with open("/home/user/result.txt", "r") as f:
        actual_output = f.read().strip()
    assert actual_output == expected_output, f"Expected result.txt to be:\n{expected_output}\n\nBut got:\n{actual_output}"


def test_source_compiles_and_uses_gsl():
    """Compile the submitted source and verify that both artifacts are GSL-linked C executables."""
    with open("/home/user/bootstrap.c", "r", errors="replace") as f:
        source = f.read()
    for required in ("gsl_rng_alloc", "gsl_rng_mt19937", "gsl_rng_set", "gsl_rng_uniform_int"):
        assert required in source, f"bootstrap.c does not use required GSL API {required}."

    compile_program("/home/user/bootstrap.c", "/tmp/bootstrap_from_source")
    assert_gsl_executable("/tmp/bootstrap_from_source")
    assert_gsl_executable("/home/user/bootstrap")


def test_executables_on_derived_inputs():
    """Run both the submitted executable and freshly compiled source on multiple datasets."""
    ensure_reference()
    if not os.path.exists("/tmp/bootstrap_from_source"):
        compile_program("/home/user/bootstrap.c", "/tmp/bootstrap_from_source")

    with open("/home/user/data.txt", "rb") as f:
        original_data = f.read()
    with open("/home/user/result.txt", "r") as f:
        saved_result = f.read().strip()

    datasets = [
        [float(i) for i in range(1, 101)],
        [7.25 for _ in range(100)],
        [((i * 37) % 113) / 3.0 - 12.5 for i in range(100)],
    ]

    try:
        for values in datasets:
            write_dataset(values)
            expected = run_program("/tmp/reference")
            for artifact in ("/home/user/bootstrap", "/tmp/bootstrap_from_source"):
                write_dataset(values)
                actual = run_program(artifact)
                assert actual == expected, (
                    f"{artifact} produced incorrect output for a verifier-supplied dataset.\n"
                    f"Expected:\n{expected}\nGot:\n{actual}"
                )

        write_dataset(datasets[0])
        executable_output = run_program("/home/user/bootstrap")
        assert executable_output == saved_result, (
            "result.txt is not the output produced by /home/user/bootstrap on the original dataset."
        )
    finally:
        with open("/home/user/data.txt", "wb") as f:
            f.write(original_data)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
