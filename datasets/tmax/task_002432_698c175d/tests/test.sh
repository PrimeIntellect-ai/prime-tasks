    assert nodes == [(i,) for i in range(1, 10001)], "The nodes fixture in graph.db is incorrect"
    assert edges == EXPECTED_EDGES, "The edges fixture in graph.db was modified or was not regenerated correctly"


def test_fixture_integrity():
    assert_fixture_integrity()


def test_indexes_created():
    db_path = "/home/user/graph.db"
    assert os.path.exists(db_path), "graph.db not found. Did you re-run db_setup.py?"

    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    cur.execute("SELECT name FROM sqlite_master WHERE type='index' AND tbl_name='edges'")
    indexes = [row[0] for row in cur.fetchall()]

    indexed_columns = set()
    for index_name in indexes:
        quoted_name = index_name.replace('"', '""')
        columns = tuple(row[2] for row in conn.execute(f'PRAGMA index_info("{quoted_name}")'))
        indexed_columns.add(columns)
    conn.close()

    assert len(indexes) >= 2, "Indexes on 'edges' table were not created. Did you fix the bug in sqlite-utils and re-run db_setup.py?"
    assert ("source",) in indexed_columns, "A real index on edges(source) was not created"
    assert ("target",) in indexed_columns, "A real index on edges(target) was not created"


