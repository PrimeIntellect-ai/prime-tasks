def expected_fixtures():
    rng = random.Random(42)
    edges = []
    for _ in range(50000):
        edges.append((
            rng.randint(1, 10000),
            rng.randint(1, 10000),
            rng.randint(1, 100),
        ))
    pairs = [[rng.randint(1, 10000), rng.randint(1, 10000)] for _ in range(50)]
    return edges, pairs


EXPECTED_EDGES, EXPECTED_PAIRS = expected_fixtures()


def assert_fixture_integrity():
    assert os.path.exists(DB_PATH), "graph.db not found. Did you re-run db_setup.py?"
    assert os.path.exists(PAIRS_PATH), "pairs.json not found."

    with open(PAIRS_PATH, "r") as f:
        pairs = json.load(f)
    assert pairs == EXPECTED_PAIRS, "pairs.json was modified or was not generated by the provided db_setup.py"

