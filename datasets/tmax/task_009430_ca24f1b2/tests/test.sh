#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import ast
import math
import os
import shutil
import stat
import subprocess

OPT_DIR = "/home/user/optimization"
HELPER_PATH = os.path.join(OPT_DIR, "helper.py")
FIND_ROOT_PATH = os.path.join(OPT_DIR, "find_root.py")
RESULT_PATH = os.path.join(OPT_DIR, "root_result.txt")

EXPECTED_HELPER = '''
def log_result(val):
    with open("/home/user/optimization/root_result.txt", "w") as f:
        f.write(f"{val:.5f}\\n")
'''

EXPECTED_FIND_ROOT = '''
import sys
from helper import log_result

def f(x):
    return x**3 - 2*x + 2

def df(x):
    return 3*x**2 - 2

def newton_raphson(initial_guess, max_iter=1000):
    x = initial_guess
    for _ in range(max_iter):
        fx = f(x)
        dfx = df(x)
        if abs(fx) < 1e-7:
            return x
        if dfx == 0:
            raise ValueError("Zero derivative")
        x = x - fx / dfx
    raise RuntimeError("Failed to converge")

if __name__ == "__main__":
    x0 = -2.0
    root = newton_raphson(x0)
    log_result(root)
'''


def ast_dump(source):
    return ast.dump(ast.parse(source), include_attributes=False)


def re_search_x0(content):
    # Preserve the original check that the known-bad initial guess is gone.
    for line in content.splitlines():
        if line.strip() == "x0 = 0.0":
            return False
    return True


def test_helper_py_fixed():
    assert os.path.isfile(HELPER_PATH), "helper.py is missing."

    with open(HELPER_PATH, "r") as f:
        lines = f.readlines()
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("import obsolete_math_lib_v1"):
            assert False, "The broken import 'import obsolete_math_lib_v1' is still present and uncommented in helper.py."

    content = "".join(lines)
    assert ast_dump(content) == ast_dump(EXPECTED_HELPER), (
        "helper.py must only have the broken import removed or commented; "
        "log_result must remain unchanged."
    )


def test_find_root_py_fixed():
    assert os.path.isfile(FIND_ROOT_PATH), "find_root.py is missing."

    with open(FIND_ROOT_PATH, "r") as f:
        content = f.read()

    assert re_search_x0(content), "The initial guess x0 = 0.0 was not changed in find_root.py."
    assert ast_dump(content) == ast_dump(EXPECTED_FIND_ROOT), (
        "find_root.py must retain the supplied polynomial and Newton-Raphson logic "
        "and set x0 to -2.0."
    )


def test_script_generates_correct_root():
    # Remove any answer prepared in advance and stale bytecode, then execute the
    # requested artifact in a clean Python process.
    try:
        os.unlink(RESULT_PATH)
    except FileNotFoundError:
        pass

    shutil.rmtree(os.path.join(OPT_DIR, "__pycache__"), ignore_errors=True)
    for name in os.listdir(OPT_DIR):
        if name.endswith(".pyc"):
            os.unlink(os.path.join(OPT_DIR, name))

    completed = subprocess.run(
        ["/usr/bin/python3", "-E", "-s", "-S", "-B", FIND_ROOT_PATH],
        cwd=OPT_DIR,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=10,
    )
    assert completed.returncode == 0, (
        f"find_root.py failed with exit code {completed.returncode}.\n"
        f"stdout: {completed.stdout}\nstderr: {completed.stderr}"
    )

    assert os.path.isfile(RESULT_PATH), "root_result.txt was not generated."
    assert stat.S_ISREG(os.lstat(RESULT_PATH).st_mode), (
        "root_result.txt must be a regular file generated by the script."
    )

    with open(RESULT_PATH, "r") as f:
        content = f.read().strip()

    # Preserve the original exact-result assertion.
    assert content == "-1.76929", f"Expected root to be '-1.76929', but got '{content}'."

    value = float(content)
    assert math.isfinite(value), "The generated root is not finite."
    assert abs(value**3 - 2 * value + 2) < 5e-5, (
        "The generated value does not satisfy x^3 - 2x + 2 = 0."
    )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
