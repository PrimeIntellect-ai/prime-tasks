#!/bin/bash
set -u
mkdir -p /logs/verifier

cat <<'PYTEST_EOF' > /tmp/test_final_state.py
import os
import re
import stat
import subprocess
from pathlib import Path

WORKSPACE = Path('/home/user/workspace')
PROJECT = WORKSPACE / 'rs_app'
OUTPUT = WORKSPACE / 'output.bin'
CHECKSUM = WORKSPACE / 'checksum.c'
PROTO = WORKSPACE / 'message.proto'
BUILD_RS = PROJECT / 'build.rs'
MAIN_RS = PROJECT / 'src/main.rs'
PAYLOAD = b'INTEGRATION_TEST_DATA'


def run(cmd, cwd=PROJECT, timeout=300):
    result = subprocess.run(
        cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        text=True, timeout=timeout
    )
    assert result.returncode == 0, f"Command failed: {' '.join(cmd)}\n{result.stdout}"
    return result


def varint(value):
    result = bytearray()
    while True:
        byte = value & 0x7f
        value >>= 7
        if value:
            result.append(byte | 0x80)
        else:
            result.append(byte)
            return bytes(result)


def protobuf_bytes(payload_tag, fec_tag, fec):
    return (
        varint((payload_tag << 3) | 2)
        + varint(len(PAYLOAD))
        + PAYLOAD
        + varint(fec_tag << 3)
        + varint(fec)
    )


def original_fec(data):
    fec = 0x12345678
    for byte in data:
        fec ^= byte
        fec = ((fec << 5) | (fec >> 27)) & 0xffffffff
    return fec


def alternate_fec(data):
    fec = 0xCAFEBABE
    for byte in data:
        fec = ((fec * 16777619) ^ byte) & 0xffffffff
    return fec


def assert_regular_file(path):
    assert path.exists(), f'Missing required file: {path}'
    assert stat.S_ISREG(path.stat().st_mode), f'Not a regular file: {path}'


def build_and_execute():
    run(['cargo', 'clean'])
    run(['cargo', 'build', '--quiet'])

    binary = PROJECT / 'target/debug/rs_app'
    assert_regular_file(binary)
    assert os.access(binary, os.X_OK), f'Built application is not executable: {binary}'

    archives = list((PROJECT / 'target/debug/build').glob('*/out/libchecksum.a'))
    assert archives, 'The build did not produce the required libchecksum.a static library'
    for archive in archives:
        assert archive.stat().st_size > 0, f'Empty checksum archive: {archive}'

    generated = list((PROJECT / 'target/debug/build').glob('*/out/polyglot.rs'))
    assert generated, 'prost-build did not produce polyglot.rs'
    assert any('MessageRecord' in path.read_text(errors='replace') for path in generated), \
        'Generated protobuf source does not define MessageRecord'

    if OUTPUT.exists():
        OUTPUT.unlink()
    run([str(binary)], cwd=PROJECT)
    assert_regular_file(OUTPUT)
    return OUTPUT.read_bytes()


def test_polyglot_build_and_application():
    assert_regular_file(BUILD_RS)
    assert_regular_file(MAIN_RS)

    build_source = BUILD_RS.read_text()
    main_source = MAIN_RS.read_text()

    # Keep structural checks for each explicitly requested mechanism.
    assert 'prost_build' in build_source and 'compile_protos' in build_source, \
        'build.rs must compile message.proto using prost-build'
    assert 'message.proto' in build_source, 'build.rs does not reference message.proto'
    assert re.search(r'cc\s*::\s*Build', build_source), \
        'build.rs must use cc::Build to compile the C source'
    assert 'checksum.c' in build_source, 'build.rs does not reference checksum.c'
    assert re.search(r'compile\s*\([^)]*["\']checksum["\']', build_source, re.S), \
        'The C library must be compiled with the name checksum'

    assert 'include!' in main_source and 'OUT_DIR' in main_source and 'polyglot.rs' in main_source, \
        'main.rs must include the protobuf code generated by build.rs'
    assert re.search(r'extern\s*["\']C["\']', main_source) and 'compute_fec' in main_source, \
        'main.rs must declare compute_fec through C FFI'
    assert 'prost::Message' in main_source, 'main.rs must use the Prost Message API'
    assert 'encode' in main_source, 'main.rs must serialize the MessageRecord with Prost'
    assert 'INTEGRATION_TEST_DATA' in main_source, 'main.rs must use the required payload'

    old_checksum = CHECKSUM.read_bytes()
    old_proto = PROTO.read_bytes()
    original_output = None
    try:
        # Build first, then delete output.bin and execute the compiled binary directly.
        # This prevents build.rs or a precomputed file from satisfying the output check.
        actual = build_and_execute()
        expected = protobuf_bytes(1, 2, original_fec(PAYLOAD))
        assert actual == expected, \
            f'Original output.bin is incorrect: expected {expected.hex()}, got {actual.hex()}'
        original_output = actual

        # Change both independent build inputs. A real prost-build/cc/FFI pipeline must
        # regenerate the field tags and obtain the new checksum from the C function.
        CHECKSUM.write_text(r'''#include <stdint.h>
#include <stddef.h>
uint32_t compute_fec(const uint8_t* data, size_t len) {
    uint32_t fec = 0xCAFEBABEu;
    for (size_t i = 0; i < len; i++) {
        fec = (fec * 16777619u) ^ data[i];
    }
    return fec;
}
''')
        PROTO.write_text('''syntax = "proto3";
package polyglot;
message MessageRecord {
    bytes payload = 3;
    uint32 fec = 5;
}
''')

        actual = build_and_execute()
        expected = protobuf_bytes(3, 5, alternate_fec(PAYLOAD))
        assert actual == expected, \
            f'Rebuilt application did not use regenerated Prost code and C FFI: expected {expected.hex()}, got {actual.hex()}'
    finally:
        CHECKSUM.write_bytes(old_checksum)
        PROTO.write_bytes(old_proto)
        if original_output is not None:
            OUTPUT.write_bytes(original_output)
        try:
            subprocess.run(['cargo', 'clean'], cwd=PROJECT, stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, timeout=60)
        except Exception:
            pass
PYTEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
