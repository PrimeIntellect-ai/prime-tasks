#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import secrets
import subprocess

import pytest

PROJECT = "/home/user/ms_analyzer"
RESULT = "/home/user/result.json"
FASTA = "/home/user/data/sequences.fasta"
PEAKS = "/home/user/data/ms_peaks.csv"


def run_application():
    if os.path.exists(RESULT):
        os.remove(RESULT)
    completed = subprocess.run(
        ["cargo", "run", "--quiet", "--manifest-path", f"{PROJECT}/Cargo.toml"],
        cwd=PROJECT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=120,
    )
    assert completed.returncode == 0, (
        "The Rust application failed to build or run.\n"
        f"stdout:\n{completed.stdout}\n"
        f"stderr:\n{completed.stderr}"
    )
    assert os.path.isfile(RESULT), f"Result file {RESULT} was not generated by the Rust application."


def load_result():
    with open(RESULT, "r") as f:
        try:
            return json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"File {RESULT} is not valid JSON.")


def test_rust_project_exists():
    assert os.path.isdir("/home/user/ms_analyzer"), "Rust project directory /home/user/ms_analyzer does not exist."
    assert os.path.isfile("/home/user/ms_analyzer/Cargo.toml"), "Cargo.toml not found in the Rust project directory."
    assert os.path.isfile("/home/user/ms_analyzer/src/main.rs"), "src/main.rs not found in the Rust project directory."


def test_result_json_exists_and_correct():
    # Remove any pre-created result, then actually build and execute the submitted project.
    run_application()
    data = load_result()

    assert "KR_count" in data, "Key 'KR_count' missing from JSON output."
    assert "LLR" in data, "Key 'LLR' missing from JSON output."
    assert "Best_H" in data, "Key 'Best_H' missing from JSON output."

    assert data["KR_count"] == 4, f"Expected KR_count to be 4, but got {data['KR_count']}."

    # N = 4, mu0 = 20.0, mu1 = 32.0, sigma = 15.0
    # x = [21.5, 19.8, 22.1, 18.5]
    expected_llr = 1.179
    assert isinstance(data["LLR"], (int, float)), "LLR must be a number."
    assert abs(data["LLR"] - expected_llr) <= 0.001, f"Expected LLR to be approximately {expected_llr}, but got {data['LLR']}."
    assert data["Best_H"] == "H0", f"Expected Best_H to be 'H0', but got '{data['Best_H']}'."

    # Exercise the executable on verifier-generated inputs so hardcoded output cannot pass.
    with open(FASTA, "rb") as f:
        original_fasta = f.read()
    with open(PEAKS, "rb") as f:
        original_peaks = f.read()

    rng = secrets.SystemRandom()
    n = rng.randint(5, 12)
    kr_sequence = "".join(rng.choice("KR") for _ in range(n))
    target_h = rng.choice(("H0", "H1"))
    target_mu = n * (5.0 if target_h == "H0" else 8.0)
    values = [target_mu + rng.randint(-25, 25) / 10.0 for _ in range(rng.randint(4, 8))]

    try:
        with open(FASTA, "w") as f:
            # K and R in the header must be ignored.
            f.write(">verifier_KR_header_must_be_ignored\n")
            f.write("AC" + kr_sequence + "DE\n")
            f.write(">second_record_RK_header\n")
            f.write("ACDEFGHILMNPQSTVWY\n")
        with open(PEAKS, "w") as f:
            f.write("peak_intensity\n")
            for value in values:
                f.write(f"{value:.1f}\n")

        mu0 = n * 5.0
        mu1 = n * 8.0
        llr = sum((x - mu1) ** 2 - (x - mu0) ** 2 for x in values) / (2.0 * 15.0 ** 2)
        expected_dynamic_llr = float(f"{llr:.3f}")
        expected_dynamic_h = "H0" if llr > 0 else "H1"

        run_application()
        dynamic = load_result()
        assert "KR_count" in dynamic, "Key 'KR_count' missing from JSON output on generated input."
        assert "LLR" in dynamic, "Key 'LLR' missing from JSON output on generated input."
        assert "Best_H" in dynamic, "Key 'Best_H' missing from JSON output on generated input."
        assert dynamic["KR_count"] == n, (
            f"Expected generated-input KR_count {n}, got {dynamic['KR_count']}."
        )
        assert isinstance(dynamic["LLR"], (int, float)), "LLR must be a number."
        assert abs(dynamic["LLR"] - expected_dynamic_llr) <= 0.001, (
            f"Expected generated-input LLR approximately {expected_dynamic_llr}, got {dynamic['LLR']}."
        )
        assert dynamic["Best_H"] == expected_dynamic_h, (
            f"Expected generated-input Best_H '{expected_dynamic_h}', got '{dynamic['Best_H']}'."
        )
    finally:
        with open(FASTA, "wb") as f:
            f.write(original_fasta)
        with open(PEAKS, "wb") as f:
            f.write(original_peaks)
        # Restore result.json for the original supplied datasets.
        run_application()
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
