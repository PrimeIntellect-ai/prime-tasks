import json
import os

_log_path = os.environ.get("PIPELINE_AUDIT_LOG")
if _log_path:
    try:
        from sklearn.pipeline import Pipeline
        from sklearn.preprocessing import StandardScaler
        from sklearn.linear_model import LinearRegression

        _original_fit = Pipeline.fit
        _original_predict = Pipeline.predict

        def _write(event):
            with open(_log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(event) + "\n")

        def _describe_x(X):
            return {
                "rows": len(X),
                "index": [int(v) for v in list(X.index)],
                "columns": [str(v) for v in list(X.columns)],
                "dtypes": [str(v) for v in list(X.dtypes)],
            }

        def audited_fit(self, X, y=None, **fit_params):
            event = {"event": "fit", "valid_steps": False}
            try:
                event.update(_describe_x(X))
                event["valid_steps"] = (
                    len(self.steps) == 2
                    and isinstance(self.steps[0][1], StandardScaler)
                    and isinstance(self.steps[1][1], LinearRegression)
                )
            except Exception as exc:
                event["audit_error"] = repr(exc)
            _write(event)
            return _original_fit(self, X, y, **fit_params)

        def audited_predict(self, X, *args, **kwargs):
            event = {"event": "predict"}
            try:
                event.update(_describe_x(X))
            except Exception as exc:
                event["audit_error"] = repr(exc)
            _write(event)
            return _original_predict(self, X, *args, **kwargs)

        Pipeline.fit = audited_fit
        Pipeline.predict = audited_predict
    except Exception as exc:
        with open(_log_path, "a", encoding="utf-8") as f:
            f.write(json.dumps({"event": "sitecustomize_error", "error": repr(exc)}) + "\n")
