import json
import math
import os
import subprocess
import time

import numpy as np
import pandas as pd
import pytest
from sklearn.linear_model import LinearRegression
from sklearn.metrics import r2_score
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

SCRIPT_PATH = "/home/user/pipeline/train_and_benchmark.py"
DATA_PATH = "/home/user/pipeline/data.csv"
RESULTS_PATH = "/home/user/pipeline/results.json"
FEATURES = ["f1", "f2", "f3", "f4"]


def expected_for(path):
    df = pd.read_csv(path)
    df = df.dropna()
    df[FEATURES] = df[FEATURES].astype("float64")
    np.random.seed(42)
    train_df = df.sample(frac=1.0, replace=True, random_state=42)
    oob_df = df.drop(train_df.index)
    pipeline = Pipeline([
        ("scaler", StandardScaler()),
        ("model", LinearRegression()),
    ])
    pipeline.fit(train_df[FEATURES], train_df["target"])
    expected_r2 = r2_score(oob_df["target"], pipeline.predict(oob_df[FEATURES]))
    return expected_r2, train_df, oob_df


def run_agent(log_path):
    if os.path.exists(RESULTS_PATH):
        os.remove(RESULTS_PATH)
    if os.path.exists(log_path):
        os.remove(log_path)

    started = time.time_ns()
    env = os.environ.copy()
    env["PYTHONPATH"] = "/tmp" + (":" + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
    env["PIPELINE_AUDIT_LOG"] = log_path
    result = subprocess.run(
        ["python3", SCRIPT_PATH],
        cwd="/home/user/pipeline",
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert result.returncode == 0, f"Script execution failed:\n{result.stdout}\n{result.stderr}"
    assert os.path.isfile(RESULTS_PATH), f"Verification Failed: {RESULTS_PATH} not found after execution."
    assert os.stat(RESULTS_PATH).st_mtime_ns >= started, "results.json was not freshly generated by the script."

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        results = json.load(f)
    events = []
    if os.path.exists(log_path):
        with open(log_path, "r", encoding="utf-8") as f:
            events = [json.loads(line) for line in f if line.strip()]
    return results, events


def assert_run(results, events, expected_r2, train_df, oob_df):
    assert set(results.keys()) == {"oob_r2", "avg_inference_ms"}, \
        "results.json must have exactly the two required keys."
    assert isinstance(results["oob_r2"], float), "oob_r2 must be a float."
    assert abs(results["oob_r2"] - expected_r2) <= 1e-4, \
        f"Verification Failed: Expected oob_r2 near {expected_r2}, got {results['oob_r2']}"
    assert isinstance(results["avg_inference_ms"], float), \
        "Verification Failed: avg_inference_ms must be a float."
    assert math.isfinite(results["avg_inference_ms"]) and results["avg_inference_ms"] > 0, \
        "Verification Failed: avg_inference_ms must be a positive finite float."

    fits = [e for e in events if e.get("event") == "fit"]
    predicts = [e for e in events if e.get("event") == "predict"]
    assert len(fits) == 1, "The required sklearn Pipeline must be fitted exactly once."
    fit = fits[0]
    assert fit.get("valid_steps") is True, \
        "Pipeline must consist of StandardScaler followed by LinearRegression."
    assert fit.get("columns") == FEATURES
    assert fit.get("dtypes") == ["float64"] * 4, "Training features must be explicitly float64."
    assert fit.get("index") == [int(v) for v in train_df.index], \
        "Pipeline was not fitted on the required bootstrap sample."

    assert len(predicts) == 101, \
        "Pipeline.predict must be used once for evaluation and 100 times for benchmarking."
    expected_oob_index = [int(v) for v in oob_df.index]
    for event in predicts:
        assert event.get("columns") == FEATURES
        assert event.get("dtypes") == ["float64"] * 4
        assert event.get("index") == expected_oob_index, \
            "Every prediction pass must use the complete OOB feature set."


@pytest.fixture(scope="session", autouse=True)
def execute_and_audit_workflow():
    assert os.path.isfile(SCRIPT_PATH), f"Verification Failed: {SCRIPT_PATH} not found."
    assert os.path.getsize(SCRIPT_PATH) > 0, f"Verification Failed: {SCRIPT_PATH} is empty."

    with open(DATA_PATH, "rb") as f:
        original_data = f.read()

