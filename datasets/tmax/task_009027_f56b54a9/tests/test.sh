def expected_condition(status, elapsed, var, op, value):
    actual = status if var == 'STATUS' else elapsed
    if op == '==':
        return actual == value
    if op == '<':
        return actual < value
    return actual > value


def test_c_source_compiles_and_evaluator_handles_general_dsl(tmp_path):
    source = HOME / 'api_evaluator.c'
    independently_compiled = tmp_path / 'api_evaluator_from_source'
    compiled = run([
        'gcc', '-std=c11', '-Wall', '-Wextra', str(source), '-o', str(independently_compiled)
    ])
    assert compiled.returncode == 0, f'api_evaluator.c did not compile:\n{compiled.stderr}'

    make_binary = HOME / 'api_evaluator'
    assert make_binary.read_bytes()[:4] == b'\x7fELF', 'make test did not produce a native compiled executable.'

    rng = random.SystemRandom()
    cases = []
    # Generate fresh values each verification run, while ensuring every operator and variable is covered.
    for var in ('STATUS', 'TIME'):
        for op in ('==', '<', '>'):
            for _ in range(5):
                status = rng.randint(-50, 650)
                elapsed = rng.randint(-50, 500)
                value = rng.randint(-75, 700)
                cases.append((status, elapsed, [(var, op, value)]))
    for _ in range(40):
        status = rng.randint(-50, 650)
        elapsed = rng.randint(-50, 500)
        conditions = []
        for _ in range(2):
            conditions.append((rng.choice(('STATUS', 'TIME')), rng.choice(('==', '<', '>')), rng.randint(-75, 700)))
        cases.append((status, elapsed, conditions))

    for binary in (make_binary, independently_compiled):
        for status, elapsed, conditions in cases:
            state = f'STATUS={status},TIME={elapsed}'
            rule = ' AND '.join(f'{var} {op} {value}' for var, op, value in conditions)
            passed = all(expected_condition(status, elapsed, *condition) for condition in conditions)
            expected = 'PASS' if passed else 'FAIL'
            result = run([str(binary), state, rule])
            assert result.returncode == 0, f'{binary} rejected valid input {state!r}, {rule!r}'
            assert result.stdout == expected + '\n', (
                f'{binary} produced {result.stdout!r} for {state!r}, {rule!r}; expected {expected!r}'
            )

        assert run([str(binary)]).returncode != 0, f'{binary} accepted zero arguments'
        assert run([str(binary), 'STATUS=1,TIME=2', 'STATUS == 1', 'extra']).returncode != 0, (
            f'{binary} accepted more than two arguments'
        )


def wait_for_port(process, timeout=5):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if process.poll() is not None:
            raise AssertionError('server exited before listening on port 8080')
        try:
            with socket.create_connection(('127.0.0.1', 8080), timeout=0.1):
                return
        except OSError:
            time.sleep(0.03)
    raise AssertionError('server did not listen on 127.0.0.1:8080')


def stop_process(process):
    if process.poll() is None:
        process.terminate()
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=3)


def curl_endpoint(endpoint):
    started = time.monotonic()
    result = run([
        'curl', '-sS', '-o', '/dev/null', '-w', '%{http_code}',
        f'http://127.0.0.1:8080{endpoint}'
    ], timeout=3)
    elapsed = time.monotonic() - started
    assert result.returncode == 0, f'curl failed for {endpoint}: {result.stderr}'
    return int(result.stdout), elapsed


def test_mock_server_endpoints_status_and_timing():
    server = subprocess.Popen(
        ['python3', str(HOME / 'mock_server.py')],
        cwd=HOME, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
    )
    try:
        wait_for_port(server)
        observations = {'/success': [], '/timeout': [], '/error': []}
        statuses = {}
        for _ in range(3):
            for endpoint in observations:
                status, elapsed = curl_endpoint(endpoint)
                statuses[endpoint] = status
                observations[endpoint].append(elapsed)

        assert statuses == {'/success': 200, '/timeout': 200, '/error': 500}
        short_success = statistics.median(observations['/success'])
        timeout_time = statistics.median(observations['/timeout'])
        short_error = statistics.median(observations['/error'])
        assert short_success >= 0.006 and short_error >= 0.006, 'short endpoints did not perform their required delay'
        assert timeout_time >= 0.120, f'/timeout returned too quickly ({timeout_time:.3f}s)'
        assert timeout_time - max(short_success, short_error) >= 0.075, 'timeout endpoint is not substantially slower'
        assert short_success < 0.100 and short_error < 0.100, '10ms endpoints are too slow for the stated rules'
    finally:
        stop_process(server)


def test_runner_really_fetches_endpoints_and_invokes_evaluator(tmp_path):
    runner_text = (HOME / 'test_runner.sh').read_text()
    assert 'curl' in runner_text, 'test_runner.sh does not use curl'

    control_source = tmp_path / 'control_server.py'
    request_log = tmp_path / 'requests.log'
    control_source.write_text(f'''\
from http.server import BaseHTTPRequestHandler, HTTPServer
import time
LOG = {str(request_log)!r}
class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        with open(LOG, 'a') as f:
            f.write(self.path + "\\n")
        if self.path == '/timeout':
            time.sleep(0.150)
            code = 200
        elif self.path == '/success':
            time.sleep(0.010)
            code = 200
        elif self.path == '/error':
            time.sleep(0.010)
            code = 500
        else:
            code = 404
        self.send_response(code)
        self.end_headers()
    def log_message(self, *args):
        pass
HTTPServer(('127.0.0.1', 8080), Handler).serve_forever()
''')

    evaluator = HOME / 'api_evaluator'
    real_evaluator = HOME / 'api_evaluator.verifier-real'
    eval_log = tmp_path / 'evaluator.log'
    report = HOME / 'test_report.txt'
    server = subprocess.Popen(['python3', str(control_source)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        wait_for_port(server)
        evaluator.rename(real_evaluator)
        evaluator.write_text(
            '#!/bin/bash\n'
            f'printf "%s\\t%s\\n" "$1" "$2" >> {str(eval_log)!r}\n'
            f'exec {str(real_evaluator)!r} "$@"\n'
        )
        evaluator.chmod(0o755)
        report.unlink(missing_ok=True)

        result = run([str(HOME / 'test_runner.sh')], cwd=HOME, timeout=15)
        assert result.returncode == 0, f'test_runner.sh failed:\n{result.stdout}\n{result.stderr}'
        assert report.read_text().strip() == '/success -> PASS\n/timeout -> PASS\n/error -> PASS'

        requests = request_log.read_text().splitlines()
        for endpoint in ('/success', '/timeout', '/error'):
            assert endpoint in requests, f'test_runner.sh did not fetch {endpoint}'

        calls = [line.split('\t', 1) for line in eval_log.read_text().splitlines()]
        expected_rules = {
            'STATUS == 200 AND TIME < 100': (200, lambda t: t < 100),
            'STATUS == 200 AND TIME > 100': (200, lambda t: t > 100),
            'STATUS == 500 AND TIME < 100': (500, lambda t: t < 100),
        }
        for rule, (wanted_status, time_check) in expected_rules.items():
            matching = [state for state, actual_rule in calls if actual_rule == rule]
            assert matching, f'test_runner.sh never invoked the evaluator with rule {rule!r}'
            match = re.fullmatch(r'STATUS=(-?\d+),TIME=(-?\d+)', matching[0])
            assert match, f'invalid state string passed to evaluator: {matching[0]!r}'
            status, elapsed = map(int, match.groups())
            assert status == wanted_status and time_check(elapsed), (
                f'test_runner.sh passed incorrect measured state {matching[0]!r} for {rule!r}'
            )
    finally:
        stop_process(server)
        if evaluator.exists():
            evaluator.unlink()
        if real_evaluator.exists():
            real_evaluator.rename(evaluator)


def test_makefile_invokes_server_and_runner(tmp_path):
    server = HOME / 'mock_server.py'
    runner = HOME / 'test_runner.sh'
    saved_server = HOME / 'mock_server.verifier-original.py'
    saved_runner = HOME / 'test_runner.verifier-original.sh'
    server_marker = tmp_path / 'server.started'
    runner_marker = tmp_path / 'runner.started'

    server.rename(saved_server)
    runner.rename(saved_runner)
    server.write_text(
        'import pathlib, runpy\n'
        f'pathlib.Path({str(server_marker)!r}).write_text("started")\n'
        f'runpy.run_path({str(saved_server)!r}, run_name="__main__")\n'
    )
    runner.write_text(
        '#!/bin/bash\n'
        f'printf started > {str(runner_marker)!r}\n'
        f'exec {str(saved_runner)!r} "$@"\n'
    )
    runner.chmod(0o755)

    try:
        result = run(['make', 'test'], cwd=HOME, timeout=30)
        assert result.returncode == 0, f'make test failed during orchestration check:\n{result.stdout}\n{result.stderr}'
        assert server_marker.exists(), 'Makefile test target did not start mock_server.py'
        assert runner_marker.exists(), 'Makefile test target did not execute test_runner.sh'
    finally:
        server.unlink(missing_ok=True)
        runner.unlink(missing_ok=True)
        saved_server.rename(server)
        saved_runner.rename(runner)

    time.sleep(0.1)
    result = run(['pgrep', '-f', 'mock_server.py'])
    assert result.returncode != 0, 'mock_server.py is still running after the orchestration check'
