#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import csv
import json
import os
import random
import secrets
import subprocess
import pytest

GO_FILE = "/home/user/pipeline.go"
REVIEWS_FILE = "/home/user/data/reviews.txt"
PRODUCTS_FILE = "/home/user/data/products.csv"
OUT_FILE = "/home/user/output.jsonl"


def run_pipeline():
    if os.path.exists(OUT_FILE):
        os.remove(OUT_FILE)
    completed = subprocess.run(
        ["go", "run", GO_FILE],
        cwd="/home/user",
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=60,
    )
    assert completed.returncode == 0, (
        f"Go program failed with exit code {completed.returncode}.\n"
        f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    )
    assert os.path.isfile(OUT_FILE), f"File {OUT_FILE} was not generated by the Go program."


def read_results():
    results = []
    with open(OUT_FILE, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                results.append(json.loads(line))
            except json.JSONDecodeError:
                pytest.fail(f"Invalid JSON line in output: {line}")
    return results


def assert_results(results, expected):
    assert len(results) == len(expected), (
        f"Expected {len(expected)} categories in output, got {len(results)}."
    )
    categories = [r.get("category") for r in results]
    assert categories == sorted(categories), (
        "The output JSONL file must be sorted alphabetically by category."
    )
    assert set(categories) == set(expected), (
        f"Expected categories {sorted(expected)}, got {categories}."
    )
    for r in results:
        cat = r.get("category")
        try:
            rating = float(r.get("average_rating"))
        except (TypeError, ValueError):
            pytest.fail(f"Invalid average_rating for {cat}: {r.get('average_rating')!r}")
        assert abs(rating - expected[cat]) < 1e-9, (
            f"Expected average rating for {cat} to be {expected[cat]}, got {rating}."
        )


def test_pipeline_go_exists_and_concurrent():
    assert os.path.isfile(GO_FILE), f"File {GO_FILE} does not exist."

    with open(GO_FILE, "r", encoding="utf-8") as f:
        content = f.read()

    has_sync = '"sync"' in content or "sync." in content
    has_chan = "chan " in content or "chan<-" in content or "<-chan" in content or "make(chan" in content
    assert has_sync or has_chan, "The Go program must use concurrency primitives (sync or channels)."


def test_output_jsonl():
    run_pipeline()
    results = read_results()

    assert len(results) == 3, f"Expected 3 categories in output, got {len(results)}."

    categories = [r.get("category") for r in results]
    assert categories == sorted(categories), "The output JSONL file must be sorted alphabetically by category."

    expected = {
        "Electronics": 4.0,
        "Home": 2.0,
        "Outdoors": 5.0,
    }

    for r in results:
        cat = r.get("category")
        assert cat in expected, f"Unexpected category {cat} in output."
        rating = float(r.get("average_rating"))
        assert rating == expected[cat], f"Expected average rating for {cat} to be {expected[cat]}, got {rating}."


def test_pipeline_processes_supplied_inputs():
    original_reviews = open(REVIEWS_FILE, "rb").read()
    original_products = open(PRODUCTS_FILE, "rb").read()
    original_output = open(OUT_FILE, "rb").read() if os.path.exists(OUT_FILE) else None

    rng = random.SystemRandom()
    suffix = secrets.token_hex(5)
    categories = [f"Alpha_{suffix}", f"Beta_{suffix}", f"Gamma_{suffix}"]
    product_ids = [f"PRD-{n}" for n in range(701, 707)]
    assignments = [category for category in categories for _ in range(2)]
    rng.shuffle(assignments)

    expected_totals = {category: 0 for category in categories}
    expected_counts = {category: 0 for category in categories}
    review_lines = []

    for category in categories:
        ids = [pid for pid, assigned in zip(product_ids, assignments) if assigned == category]
        review_products = [ids[0], ids[0], ids[1]]
        for index, pid in enumerate(review_products):
            rating = rng.randint(1, 5)
            expected_totals[category] += rating
            expected_counts[category] += 1
            text = ["Excelente compra", "品質レビュー", "Useful product"][index]
            review_lines.append(f"{text} [{pid}] {'⭐' * rating}")

    rng.shuffle(review_lines)
    expected = {
        category: round(expected_totals[category] / expected_counts[category], 2)
        for category in categories
    }

    try:
        with open(PRODUCTS_FILE, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f, lineterminator="\n")
            writer.writerow(["ProductID", "Category", "Price"])
            for index, (pid, category) in enumerate(zip(product_ids, assignments)):
                writer.writerow([pid, category, f"{10 + index}.25"])

        with open(REVIEWS_FILE, "w", encoding="utf-8") as f:
            f.write("\n".join(review_lines) + "\n")

        run_pipeline()
        assert_results(read_results(), expected)
    finally:
        with open(REVIEWS_FILE, "wb") as f:
            f.write(original_reviews)
        with open(PRODUCTS_FILE, "wb") as f:
            f.write(original_products)
        if original_output is None:
            if os.path.exists(OUT_FILE):
                os.remove(OUT_FILE)
        else:
            with open(OUT_FILE, "wb") as f:
                f.write(original_output)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
