#!/bin/bash
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import random
import re
import stat
import subprocess
import tempfile

import pytest

DEPLOY_TRACE = ""


@pytest.fixture(scope="session", autouse=True)
def execute_deployment():
    """Run deploy.sh against fresh, verifier-generated sensor data."""
    global DEPLOY_TRACE

    deploy_path = "/home/user/deploy.sh"
    assert os.path.isfile(deploy_path), f"Missing {deploy_path}"

    rng = random.SystemRandom()
    critical_temps = [rng.randint(20, 99) for _ in range(rng.randint(3, 6))]
    records = [
        f"[2026-09-11 12:{i:02d}:00] [CRITICAL] Sensor: {100+i} Temp: {temp}C Humidity: {rng.randint(30, 95)}%"
        for i, temp in enumerate(critical_temps)
    ]
    records.extend([
        f"[2026-09-11 13:00:00] [INFO] Sensor: 301 Temp: {rng.randint(20, 99)}C Humidity: 50%",
        f"[2026-09-11 13:05:00] [WARNING] Sensor: 302 Temp: {rng.randint(20, 99)}C Humidity: 60%",
        f"[2026-09-11 13:10:00] [ERROR] Sensor: 303 Temp: {rng.randint(20, 99)}C Humidity: 70%",
    ])
    rng.shuffle(records)

    with open("/home/user/raw_sensors.log", "w") as f:
        f.write("\n".join(records) + "\n")

    # Ensure all final artifacts must be regenerated by deploy.sh.
    for path in (
        "/home/user/filtered_logs.txt",
        "/home/user/config.json",
        "/home/user/edge_bin",
        "/home/user/metrics.out",
    ):
        try:
            os.remove(path)
        except FileNotFoundError:
            pass

    result = subprocess.run(
        ["bash", "-x", deploy_path],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=90,
    )
    DEPLOY_TRACE = result.stderr
    assert result.returncode == 0, (
        f"deploy.sh failed with exit code {result.returncode}\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )


def test_files_exist():
    """Test that all required files exist."""
    required_files = [
        "/home/user/edge_parser.go",
        "/home/user/deploy.sh",
        "/home/user/filtered_logs.txt",
        "/home/user/config.json",
        "/home/user/edge_bin",
        "/home/user/metrics.out"
    ]
    for filepath in required_files:
        assert os.path.isfile(filepath), f"Required file missing: {filepath}"


def test_filtered_logs_content():
    """Test that filtered_logs.txt contains the correct extracted temperatures."""
    log_path = "/home/user/raw_sensors.log"
    filtered_path = "/home/user/filtered_logs.txt"

    assert os.path.isfile(log_path), f"Missing {log_path}"
    assert os.path.isfile(filtered_path), f"Missing {filtered_path}"

    expected_temps = []
    with open(log_path, 'r') as f:
        for line in f:
            if "CRITICAL" in line:
                # Extract temperature e.g., "Temp: 90C" -> 90
                parts = line.split()
                for part in parts:
                    if part.endswith("C") and part[:-1].isdigit():
                        expected_temps.append(part[:-1])
                        break

    with open(filtered_path, 'r') as f:
        actual_temps = [line.strip() for line in f if line.strip()]

    assert actual_temps == expected_temps, "filtered_logs.txt does not contain the correct extracted temperatures."


def test_config_json_validity():
    """Test that config.json is valid and contains correct paths."""
    config_path = "/home/user/config.json"
    assert os.path.isfile(config_path), f"Missing {config_path}"

    with open(config_path, 'r') as f:
        try:
            config = json.load(f)
        except json.JSONDecodeError:
            pytest.fail("config.json is not a valid JSON file.")

    assert config.get("input_file") == "/home/user/filtered_logs.txt", "config.json input_file path is incorrect."
    assert config.get("output_file") == "/home/user/metrics.out", "config.json output_file path is incorrect."


def test_permissions():
    """Test the permissions of edge_bin and metrics.out."""
    bin_path = "/home/user/edge_bin"
    out_path = "/home/user/metrics.out"

    assert os.path.isfile(bin_path), f"Missing {bin_path}"
    assert os.path.isfile(out_path), f"Missing {out_path}"

    bin_mode = stat.S_IMODE(os.stat(bin_path).st_mode)
    out_mode = stat.S_IMODE(os.stat(out_path).st_mode)

    assert bin_mode == 0o500, f"edge_bin permissions should be 0500, but got {oct(bin_mode)}"
    assert out_mode == 0o400, f"metrics.out permissions should be 0400, but got {oct(out_mode)}"


def test_metrics_out_content():
    """Test that metrics.out contains the correct average temperature."""
    filtered_path = "/home/user/filtered_logs.txt"
    out_path = "/home/user/metrics.out"

    assert os.path.isfile(filtered_path), f"Missing {filtered_path}"
    assert os.path.isfile(out_path), f"Missing {out_path}"

    with open(filtered_path, 'r') as f:
        temps = [int(line.strip()) for line in f if line.strip().isdigit()]

    assert len(temps) > 0, "No valid temperatures found in filtered_logs.txt to calculate average."

    expected_avg = sum(temps) / len(temps)
    expected_output = f"Average_Temp: {expected_avg:.2f}"

    with open(out_path, 'r') as f:
        actual_output = f.read().strip()

    assert actual_output == expected_output, f"metrics.out content is incorrect. Expected '{expected_output}', got '{actual_output}'"


def test_deploy_compiles_and_executes_parser():
    """Confirm the traced deployment compiled the source and invoked edge_bin."""
    commands = [line[2:].strip() for line in DEPLOY_TRACE.splitlines() if line.startswith("+ ")]

    build_seen = any(
        re.search(r"(?:^|\s)(?:\S*/)?go\s+build(?:\s|$)", command)
        and "edge_parser.go" in command
        and "edge_bin" in command
        for command in commands
    )
    assert build_seen, "deploy.sh did not compile edge_parser.go into edge_bin"

    run_seen = any(
        re.match(r"^(?:(?:exec|command)\s+)?(?:/home/user/edge_bin|\./edge_bin)(?:\s|$)", command)
        for command in commands
    )
    assert run_seen, "deploy.sh did not execute the compiled edge_bin"

    version = subprocess.run(
        ["go", "version", "/home/user/edge_bin"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
    )
    assert version.returncode == 0 and "go version go" in version.stdout, (
        "edge_bin is not a compiled Go executable"
    )


def test_go_source_and_deployed_binary_on_independent_inputs():
    """Compile the submitted source and exercise both it and the deployed binary."""
    config_path = "/home/user/config.json"
    with open(config_path, "rb") as f:
        original_config = f.read()
    original_mode = stat.S_IMODE(os.stat(config_path).st_mode)

    rng = random.SystemRandom()

    def exercise(binary, values, directory, output_name):
        input_path = os.path.join(directory, output_name + ".in")
        output_path = os.path.join(directory, output_name + ".out")
        with open(input_path, "w") as f:
            f.write("\n".join(str(value) for value in values) + "\n")
        with open(config_path, "w") as f:
            json.dump({"input_file": input_path, "output_file": output_path}, f)

        result = subprocess.run(
            [binary],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=30,
        )
        assert result.returncode == 0, (
            f"{binary} failed on independent input: {result.stderr}"
        )
        assert os.path.isfile(output_path), f"{binary} did not create its configured output"
        with open(output_path, "r") as f:
            actual = f.read().strip()
        expected = f"Average_Temp: {sum(values) / len(values):.2f}"
        assert actual == expected, f"Expected '{expected}', got '{actual}' from {binary}"

    try:
        with tempfile.TemporaryDirectory(prefix="edge_parser_test_") as directory:
            exercise(
                "/home/user/edge_bin",
                [rng.randint(1, 150) for _ in range(5)],
                directory,
                "deployed",
            )

            rebuilt = os.path.join(directory, "rebuilt_edge_parser")
            build = subprocess.run(
                ["go", "build", "-o", rebuilt, "/home/user/edge_parser.go"],
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=90,
            )
            assert build.returncode == 0, f"edge_parser.go does not compile: {build.stderr}"
            exercise(
                rebuilt,
                [rng.randint(1, 150) for _ in range(7)],
                directory,
                "rebuilt",
            )
    finally:
        with open(config_path, "wb") as f:
            f.write(original_config)
        os.chmod(config_path, original_mode)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
