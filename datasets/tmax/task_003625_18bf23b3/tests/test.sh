cat << 'TEST_EOF' > /tmp/test_final_state.py
import importlib.util
import math
import os
import random
import secrets
import subprocess
import sys

import pytest

MONITOR = '/home/user/monitor.py'
METRICS = '/home/user/metrics.py'
RESULT = '/home/user/result.log'


def get_expected_stddev():
    """Derive the expected standard deviation based on the data loader logic."""
    data = [100000.0 + (i % 10) * 1e-5 for i in range(10000)]
    n = len(data)
    if n == 0:
        return 0.0
    mean = sum(data) / n
    variance = sum((x - mean) ** 2 for x in data) / n
    return math.sqrt(variance)


def stable_variance(data):
    if not data:
        return 0.0
    mean = math.fsum(data) / len(data)
    return math.fsum((x - mean) ** 2 for x in data) / len(data)


@pytest.fixture(scope='session', autouse=True)
def run_monitor():
    assert os.path.isfile(MONITOR), (
        f"{MONITOR} is missing. Resolve the project structure so the requested script exists there."
    )
    assert os.path.isfile(METRICS), f"{METRICS} is missing."

    if os.path.exists(RESULT):
        os.remove(RESULT)

    completed = subprocess.run(
        [sys.executable, MONITOR],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert completed.returncode == 0, (
        f"monitor.py failed with exit code {completed.returncode}.\n"
        f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    )


def test_data_loader_is_unchanged():
    spec = importlib.util.spec_from_file_location(
        'submitted_loader', '/home/user/data_loader/loader.py'
    )
    loader = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loader)
    expected = [100000.0 + (i % 10) * 1e-5 for i in range(10000)]
    assert loader.load_data() == expected, "The data generated by the data loader was modified."


def test_calculate_variance_on_unpredictable_precision_sensitive_data():
    spec = importlib.util.spec_from_file_location('submitted_metrics', METRICS)
    metrics = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(metrics)
    assert callable(getattr(metrics, 'calculate_variance', None)), (
        'metrics.py must define calculate_variance(data).'
    )

    rng = random.Random(secrets.randbits(128))
    for _ in range(4):
        values = [100000.0 + rng.randint(-30, 30) * 1e-5 for _ in range(2001)]
        rng.shuffle(values)
        expected = stable_variance(values)
        actual = metrics.calculate_variance(values)
        assert isinstance(actual, (int, float)), 'calculate_variance must return a number.'
        assert math.isfinite(actual) and actual >= 0.0, (
            f'calculate_variance returned invalid variance {actual!r}.'
        )
        assert math.isclose(actual, expected, rel_tol=5e-4, abs_tol=1e-20), (
            f'calculate_variance returned {actual!r}; expected {expected!r} on '
            'precision-sensitive input. Implement a numerically stable algorithm.'
        )

    assert metrics.calculate_variance([]) == 0.0
    assert metrics.calculate_variance([42.0] * 25) == 0.0


def test_result_log_exists():
    """Verify that the script successfully ran and produced the result file."""
    assert os.path.isfile(RESULT), (
        "The file /home/user/result.log was not found. "
        "Ensure that the monitor.py script executes successfully and writes the result."
    )


def test_result_log_value():
    """Verify that the calculated standard deviation is correct."""
    with open(RESULT, 'r') as f:
        content = f.read().strip()

    assert content, "The file /home/user/result.log is empty."
    try:
        actual_stddev = float(content)
    except ValueError:
        pytest.fail(f"The content of /home/user/result.log is not a valid float: '{content}'")

    expected_stddev = get_expected_stddev()
    assert math.isfinite(actual_stddev) and actual_stddev > 0.0, (
        'The standard deviation must be a positive finite float.'
    )
    assert math.isclose(actual_stddev, expected_stddev, rel_tol=1e-5), (
        f"The standard deviation in result.log ({actual_stddev}) does not match the expected value "
        f"({expected_stddev}). Ensure you implemented a numerically stable variance algorithm."
    )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
