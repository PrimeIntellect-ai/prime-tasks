#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import csv
import os
import secrets
import stat
import struct
import subprocess
import sys

BASE_DIR = "/home/user/uptime_pipeline"
CONFIG_FILE = "/home/user/.sre_monitor_conf"
REPORT_FILE = os.path.join(BASE_DIR, "report.txt")
METRICS_BIN = os.path.join(BASE_DIR, "data", "raw_metrics.bin")
METRICS_CSV = os.path.join(BASE_DIR, "metrics_output.csv")
PROCESS_SCRIPT = os.path.join(BASE_DIR, "process_metrics.py")
LOGS_DIR = os.path.join(BASE_DIR, "logs")


def test_config_file_exists_and_correct():
    assert os.path.isfile(CONFIG_FILE), f"The config file {CONFIG_FILE} was not created."
    with open(CONFIG_FILE, "r") as f:
        content = f.read().strip()
    assert content == "STRICT_MODE", f"Expected config file to contain 'STRICT_MODE', but got '{content}'."


def test_metrics_output_correct():
    assert os.path.isfile(METRICS_CSV), f"The output file {METRICS_CSV} was not generated."

    # Derive expected values from the binary file
    assert os.path.isfile(METRICS_BIN), f"The raw metrics file {METRICS_BIN} is missing."
    with open(METRICS_BIN, "rb") as f:
        data = f.read()

    expected_values = []
    for i in range(len(data) // 8):
        chunk = data[i*8:(i+1)*8]
        val = struct.unpack('d', chunk)[0]
        expected_values.append(f"{val:.5f}")

    # Read the generated CSV
    actual_values = []
    with open(METRICS_CSV, "r") as f:
        reader = csv.reader(f)
        header = next(reader, None)
        assert header == ['MetricID', 'Uptime'], "CSV header is incorrect or missing."
        for row in reader:
            if len(row) == 2:
                actual_values.append(row[1])

    assert actual_values == expected_values, (
        f"Metrics output values do not match expected 64-bit double precision values. "
        f"Expected {expected_values}, got {actual_values}."
    )


def _run_process_script():
    result = subprocess.run(
        [sys.executable, PROCESS_SCRIPT],
        cwd=BASE_DIR,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert result.returncode == 0, (
        f"process_metrics.py failed with exit code {result.returncode}. "
        f"stdout={result.stdout!r}, stderr={result.stderr!r}"
    )
    assert os.path.isfile(METRICS_CSV), "process_metrics.py did not generate metrics_output.csv."


def _assert_exact_csv(values):
    with open(METRICS_CSV, newline="") as f:
        rows = list(csv.reader(f))
    expected_rows = [['MetricID', 'Uptime']] + [
        [str(i), f"{value:.5f}"] for i, value in enumerate(values)
    ]
    assert rows == expected_rows, (
        "CSV generated by process_metrics.py is incorrect for verifier-supplied "
        f"64-bit input. Expected {expected_rows}, got {rows}."
    )


def test_process_metrics_script_is_fixed_and_generates_output():
    assert os.path.exists(PROCESS_SCRIPT), f"The required script {PROCESS_SCRIPT} is missing."
    assert not os.path.islink(PROCESS_SCRIPT), "process_metrics.py must be a regular Python source file."
    assert stat.S_ISREG(os.stat(PROCESS_SCRIPT).st_mode), "process_metrics.py is not a regular file."

    compile_result = subprocess.run(
        [sys.executable, "-m", "py_compile", PROCESS_SCRIPT],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert compile_result.returncode == 0, f"process_metrics.py is not valid Python: {compile_result.stderr}"

    assert os.path.isfile(CONFIG_FILE), "The required configuration file is missing."
    with open(CONFIG_FILE) as f:
        assert f.read().strip() == "STRICT_MODE"

    with open(METRICS_BIN, "rb") as f:
        original_data = f.read()

    # Use unpredictable values so a prewritten CSV cannot satisfy this check.
    probe_values = [
        90.0 + secrets.randbelow(10_000_000_000) / 1_000_000_000
        for _ in range(7)
    ]

    try:
        with open(METRICS_BIN, "wb") as f:
            f.write(struct.pack(f"{len(probe_values)}d", *probe_values))
        if os.path.lexists(METRICS_CSV):
            os.unlink(METRICS_CSV)
        _run_process_script()
        _assert_exact_csv(probe_values)
    finally:
        with open(METRICS_BIN, "wb") as f:
            f.write(original_data)

    # Restore the required final output using the repaired script and original data.
    if os.path.lexists(METRICS_CSV):
        os.unlink(METRICS_CSV)
    _run_process_script()
    original_values = [
        struct.unpack('d', original_data[i:i+8])[0]
        for i in range(0, len(original_data), 8)
    ]
    _assert_exact_csv(original_values)


def test_report_file_correct():
    assert os.path.isfile(REPORT_FILE), f"The report file {REPORT_FILE} was not created."

    # Derive the earliest TIMEOUT timestamp from logs
    min_timestamp = None
    for log_file in os.listdir(LOGS_DIR):
        if log_file.endswith(".log"):
            with open(os.path.join(LOGS_DIR, log_file), "r") as f:
                for line in f:
                    if "TIMEOUT" in line:
                        parts = line.split()
                        if parts and parts[0].isdigit():
                            ts = int(parts[0])
                            if min_timestamp is None or ts < min_timestamp:
                                min_timestamp = ts

    assert min_timestamp is not None, "Could not find any TIMEOUT events in logs to derive expected answer."

    with open(REPORT_FILE, "r") as f:
        lines = [line.strip() for line in f.readlines() if line.strip()]

    assert len(lines) == 2, f"Expected exactly 2 lines in {REPORT_FILE}, but got {len(lines)}."
    assert lines[0] == CONFIG_FILE, f"Line 1 of report.txt should be '{CONFIG_FILE}', got '{lines[0]}'."
    assert lines[1] == str(min_timestamp), f"Line 2 of report.txt should be the earliest TIMEOUT timestamp '{min_timestamp}', got '{lines[1]}'."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
