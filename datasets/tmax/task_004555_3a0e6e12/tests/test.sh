#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import re
import secrets
import shutil
import subprocess
import tempfile
from collections import Counter

import h5py
import numpy as np


def test_hostfile_exists_and_correct():
    """Verify that the hostfile exists and defines 4 workers with 8 slots each."""
    hostfile_path = "/home/user/hostfile"
    assert os.path.isfile(hostfile_path), f"Hostfile {hostfile_path} is missing."

    with open(hostfile_path, "r") as f:
        content = f.read()

    for i in range(4):
        worker = f"worker-{i}"
        pattern = rf"{worker}\b.*(?:slots|cpu)s?\s*=?\s*8\b"
        assert re.search(pattern, content, re.IGNORECASE), (
            f"Could not find valid configuration for {worker} with 8 slots in {hostfile_path}. "
            f"Ensure it follows the format '{worker} slots=8'."
        )


def test_analyze_script_exists_and_executable():
    """Verify that analyze.sh exists, is executable, and is a Bash script."""
    script_path = "/home/user/analyze.sh"
    assert os.path.isfile(script_path), f"Script {script_path} is missing."
    assert os.access(script_path, os.X_OK), f"Script {script_path} is not executable."
    with open(script_path, "rb") as f:
        first_line = f.readline().strip()
    assert first_line.startswith(b"#!") and re.search(rb"(?:^|[/ ])bash(?:\s|$)", first_line), (
        f"Script {script_path} must have a Bash shebang."
    )


def test_max_degree_output():
    """Verify the output generated by the agent for the provided graph."""
    output_path = "/home/user/max_degree.txt"
    assert os.path.isfile(output_path), f"Output file {output_path} is missing."

    with open(output_path, "r") as f:
        content = f.read().strip()

    expected = "Node ID: 4, Degree: 7"
    assert content == expected, (
        f"Incorrect output in {output_path}.\n"
        f"Expected: '{expected}'\n"
        f"Got: '{content}'"
    )


def _write_graph(path, source, target):
    assert len(source) == len(target)
    with h5py.File(path, "w") as f:
        f.create_dataset("/links/source", data=np.asarray(source, dtype=np.int64))
        f.create_dataset("/links/target", data=np.asarray(target, dtype=np.int64))


def _expected(source, target):
    counts = Counter(source)
    counts.update(target)
    max_degree = max(counts.values())
    node = min(node for node, degree in counts.items() if degree == max_degree)
    return f"Node ID: {node}, Degree: {max_degree}"


def _run_and_check(source, target):
    network_path = "/home/user/network.h5"
    output_path = "/home/user/max_degree.txt"
    script_path = "/home/user/analyze.sh"
    _write_graph(network_path, source, target)
    if os.path.lexists(output_path):
        os.remove(output_path)

    result = subprocess.run(
        [script_path],
        cwd="/home/user",
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20,
    )
    assert result.returncode == 0, (
        f"analyze.sh exited with status {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    assert os.path.isfile(output_path), "analyze.sh did not generate /home/user/max_degree.txt"
    with open(output_path, "r") as f:
        actual = f.read().strip()
    expected = _expected(source, target)
    assert actual == expected, f"Expected '{expected}' for the test graph, got '{actual}'"


def test_analyze_script_reads_hdf5_and_computes_degrees():
    """Execute the submitted script against independently generated graph inputs."""
    network_path = "/home/user/network.h5"
    output_path = "/home/user/max_degree.txt"

    with tempfile.TemporaryDirectory() as tmpdir:
        network_backup = os.path.join(tmpdir, "network.h5")
        output_backup = os.path.join(tmpdir, "max_degree.txt")
        shutil.copy2(network_path, network_backup)
        had_output = os.path.isfile(output_path)
        if had_output:
            shutil.copy2(output_path, output_backup)

        try:
            # Re-run on the provided graph so a pre-created output alone cannot pass.
            original_source = [1, 1, 1, 2, 3, 4, 4, 4, 4, 5]
            original_target = [2, 3, 4, 4, 4, 5, 6, 7, 8, 8]
            _run_and_check(original_source, original_target)

            # Generate a graph with a randomized pair of tied maximum-degree nodes.
            rng = secrets.SystemRandom()
            nodes = sorted(rng.sample(range(100, 10000), 6))
            degree_counts = {
                nodes[0]: 4,
                nodes[1]: 6,
                nodes[2]: 2,
                nodes[3]: 4,
                nodes[4]: 6,
                nodes[5]: 2,
            }
            occurrences = [node for node, count in degree_counts.items() for _ in range(count)]
            rng.shuffle(occurrences)
            source = occurrences[::2]
            target = occurrences[1::2]
            _run_and_check(source, target)
        finally:
            shutil.copy2(network_backup, network_path)
            if had_output:
                shutil.copy2(output_backup, output_path)
            elif os.path.lexists(output_path):
                os.remove(output_path)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
