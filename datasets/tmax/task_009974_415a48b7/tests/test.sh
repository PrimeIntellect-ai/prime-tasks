import ast
import ctypes
import json
import math
import os
import subprocess

import numpy as np
import pytest

PROJECT_DIR = "/home/user/sim_project"
SO_FILE = os.path.join(PROJECT_DIR, "libintegrator.so")
PY_FILE = os.path.join(PROJECT_DIR, "run_sim.py")
RESULTS_FILE = os.path.join(PROJECT_DIR, "results.json")
EXPECTED_KEYS = {"error_dt_0.1", "error_dt_0.01", "error_dt_0.001"}


def rk4_reference(dt):
    """Independently compute the requested RK4 error."""
    A = np.array([[-100.0, 1.0], [0.0, -1.0]], dtype=float)
    x = np.array([1.0, 1.0], dtype=float)
    t = 0.0
    while t < 1.0 - 1e-9:
        h = min(dt, 1.0 - t)
        k1 = A @ x
        k2 = A @ (x + 0.5 * h * k1)
        k3 = A @ (x + 0.5 * h * k2)
        k4 = A @ (x + h * k3)
        x = x + (h / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        t += h

    # Exact solution for this upper-triangular system at t=1.
    e1 = math.exp(-1.0)
    e100 = math.exp(-100.0)
    exact = np.array([e100 + (e1 - e100) / 99.0, e1], dtype=float)
    return float(np.linalg.norm(x - exact))


@pytest.fixture(scope="session", autouse=True)
def execute_submission():
    assert os.path.isfile(SO_FILE), f"Shared library {SO_FILE} does not exist."
    assert os.path.isfile(PY_FILE), f"Python script {PY_FILE} does not exist."
    assert os.access(PY_FILE, os.X_OK), f"Python script {PY_FILE} is not executable."

    # Ensure the checked output is freshly generated by the submitted script.
    if os.path.lexists(RESULTS_FILE):
        os.unlink(RESULTS_FILE)
    completed = subprocess.run(
        [PY_FILE], cwd=PROJECT_DIR, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, text=True, timeout=30
    )
    assert completed.returncode == 0, (
        f"run_sim.py failed with exit code {completed.returncode}.\n"
        f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    )


def test_shared_library_exists():
    """Test that the C code was compiled into a loadable shared library."""
    assert os.path.exists(SO_FILE), f"Shared library {SO_FILE} does not exist."
    assert os.path.isfile(SO_FILE), f"Path {SO_FILE} is not a file."
    with open(SO_FILE, "rb") as f:
        assert f.read(4) == b"\x7fELF", "libintegrator.so is not an ELF library."
    lib = ctypes.CDLL(SO_FILE)
    assert hasattr(lib, "integrate"), "Shared library does not export integrate."


def test_library_integrate_function():
    """Exercise integrate through ctypes on an independently checked input."""
    lib = ctypes.CDLL(SO_FILE)
    callback_type = ctypes.CFUNCTYPE(
        None, ctypes.c_double, ctypes.POINTER(ctypes.c_double),
        ctypes.POINTER(ctypes.c_double)
    )

    @callback_type
    def deriv(t, x, dx):
        dx[0] = -2.5 * x[0]

    lib.integrate.argtypes = [
        callback_type, ctypes.c_double, ctypes.c_double,
        ctypes.POINTER(ctypes.c_double), ctypes.c_int, ctypes.c_double
    ]
    lib.integrate.restype = None
    state = (ctypes.c_double * 1)(1.25)
    lib.integrate(deriv, 0.0, 0.37, state, 1, 0.06)

    expected = 1.25
    t = 0.0
    while t < 0.37 - 1e-9:
        h = min(0.06, 0.37 - t)
        z = -2.5 * h
        expected *= 1.0 + z + z*z/2.0 + z*z*z/6.0 + z*z*z*z/24.0
        t += h
    assert math.isclose(state[0], expected, rel_tol=1e-12, abs_tol=1e-12)


def test_python_script_exists_and_uses_ctypes():
    """Test that the executable Python script loads a library through ctypes."""
    assert os.path.exists(PY_FILE), f"Python script {PY_FILE} does not exist."
    assert os.path.isfile(PY_FILE), f"Path {PY_FILE} is not a file."
    with open(PY_FILE, "r", encoding="utf-8") as f:
        tree = ast.parse(f.read(), filename=PY_FILE)
    imports_ctypes = any(
        (isinstance(n, ast.Import) and any(a.name == "ctypes" for a in n.names)) or
        (isinstance(n, ast.ImportFrom) and n.module == "ctypes")
        for n in ast.walk(tree)
    )
    loader_call = any(
        isinstance(n, ast.Call) and (
            (isinstance(n.func, ast.Name) and n.func.id in {"CDLL", "LoadLibrary"}) or
            (isinstance(n.func, ast.Attribute) and n.func.attr in {"CDLL", "LoadLibrary"})
        )
        for n in ast.walk(tree)
    )
    assert imports_ctypes and loader_call, "run_sim.py must load the shared library using ctypes."


def test_results_json_exists_and_valid():
    """Test that results.json exists, is valid JSON, and has the correct keys."""
    assert os.path.exists(RESULTS_FILE), f"Results file {RESULTS_FILE} does not exist."
    with open(RESULTS_FILE, "r") as f:
        try:
            results = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"{RESULTS_FILE} does not contain valid JSON.")

    assert set(results.keys()) == EXPECTED_KEYS, \
        f"JSON keys do not match expected keys. Found: {list(results.keys())}"
    for key in EXPECTED_KEYS:
        assert isinstance(results[key], (int, float)) and not isinstance(results[key], bool), \
            f"Value for {key} is not a number."


def test_results_values():
    """Compare freshly generated errors with independently derived RK4 errors."""
    with open(RESULTS_FILE, "r") as f:
        results = json.load(f)

    err_01 = results["error_dt_0.1"]
    err_001 = results["error_dt_0.01"]
    err_0001 = results["error_dt_0.001"]

    # Preserve the valid original stability and upper-bound assertions.
    assert math.isnan(err_01) or math.isinf(err_01) or err_01 > 1000.0, \
        f"Expected large error for dt=0.1 due to instability, got {err_01}"
    assert err_001 < 1e-4, f"Unexpectedly large error for dt=0.01: {err_001}"
    assert err_0001 < 1e-7, f"Unexpectedly large error for dt=0.001: {err_0001}"

    expected = {
        "error_dt_0.1": rk4_reference(0.1),
        "error_dt_0.01": rk4_reference(0.01),
        "error_dt_0.001": rk4_reference(0.001),
    }
    for key, actual in results.items():
        assert math.isfinite(actual), f"{key} must be a finite computed error."
        target = expected[key]
        tolerance = max(2e-13, abs(target) * 1e-9)
        assert math.isclose(actual, target, rel_tol=1e-9, abs_tol=tolerance), \
            f"{key} is {actual}, but the independently computed RK4 error is {target}."
TEST_EOF

