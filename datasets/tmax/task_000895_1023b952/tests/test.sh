#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import base64
import json
import os
import random
import subprocess
import tempfile

import pytest

BUILDER = "/home/user/artifact-builder"
EXTRACTOR = os.path.join(BUILDER, "extractor")
RAW_EVENTS = "/home/user/raw_events.json"
MIGRATION_SOURCE = "/home/user/migrate/main.go"
MIGRATION_BINARY = "/home/user/migrate/run_migration"


def run_checked(command, **kwargs):
    result = subprocess.run(command, capture_output=True, text=True, timeout=30, **kwargs)
    assert result.returncode == 0, (
        f"Command failed: {command}\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    return result


def test_extractor_built():
    go_mod = os.path.join(BUILDER, "go.mod")
    build_script = os.path.join(BUILDER, "build.sh")
    assert os.path.isfile(go_mod), "go.mod was not created."
    assert os.path.isfile(build_script), "build.sh is missing."
    assert os.access(build_script, os.X_OK), "build.sh is not executable."

    module = run_checked(["go", "list", "-m"], cwd=BUILDER).stdout.strip()
    assert module == "artifact-builder", f"Expected module artifact-builder, got {module!r}."

    if os.path.exists(EXTRACTOR):
        os.remove(EXTRACTOR)
    run_checked([build_script], cwd=BUILDER)

    assert os.path.exists(EXTRACTOR), "The extractor binary was not built."
    assert os.access(EXTRACTOR, os.X_OK), "The extractor is not executable."
    run_checked(["go", "version", "-m", EXTRACTOR])


def test_c_header_copy_is_memory_safe_and_complete():
    source = os.path.join(BUILDER, "libextractor.c")
    assert os.path.isfile(source), "libextractor.c is missing."

    harness = r'''#include <stdint.h>
#include <string.h>

void parse_header(const char* src, int len, char* buffer);

struct guarded_buffer {
    uint64_t before;
    char data[8];
    uint64_t after;
};

int main(void) {
    const char src[9] = {1,2,3,4,5,6,7,8,99};
    struct guarded_buffer out;
    out.before = UINT64_C(0x1122334455667788);
    memset(out.data, 0, sizeof(out.data));
    out.after = UINT64_C(0x8877665544332211);

    parse_header(src, 8, out.data);

    if (out.before != UINT64_C(0x1122334455667788)) return 10;
    if (out.after != UINT64_C(0x8877665544332211)) return 11;
    if (memcmp(out.data, src, sizeof(out.data)) != 0) return 12;
    return 0;
}
'''
    with tempfile.TemporaryDirectory() as tmpdir:
        harness_path = os.path.join(tmpdir, "harness.c")
        binary_path = os.path.join(tmpdir, "check_header")
        with open(harness_path, "w") as f:
            f.write(harness)
        run_checked([
            "gcc", "-std=c11", "-O0", "-fsanitize=address",
            "-fno-omit-frame-pointer", source, harness_path, "-o", binary_path
        ])
        run_checked([binary_path])


def test_raw_events_generated():
    if os.path.exists(RAW_EVENTS):
        os.remove(RAW_EVENTS)

    run_checked([EXTRACTOR, "/app/security_feed.mp4"], cwd=BUILDER)
    assert os.path.exists(RAW_EVENTS), f"{RAW_EVENTS} was not generated by the extractor."

    with open(RAW_EVENTS, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"{RAW_EVENTS} does not contain valid JSON.")

    assert isinstance(data, list), f"{RAW_EVENTS} should contain a JSON array."
    for index, event in enumerate(data):
        assert isinstance(event, dict), f"Raw event {index} is not an object."
        assert set(event) == {"frame_id", "raw_data", "timestamp"}, (
            f"Raw event {index} does not use the Schema V1 fields."
        )
        assert isinstance(event["frame_id"], int) and not isinstance(event["frame_id"], bool)
        assert isinstance(event["raw_data"], str)
        assert isinstance(event["timestamp"], (int, float)) and not isinstance(event["timestamp"], bool)
        try:
            base64.b64decode(event["raw_data"], validate=True)
        except Exception as exc:
            pytest.fail(f"Raw event {index} has invalid base64 data: {exc}")


def generate_random_base64(length):
    raw_bytes = bytes(random.choices(range(256), k=length))
    return base64.b64encode(raw_bytes).decode("utf-8")


def generate_v1_array(num_elements):
    arr = []
    for _ in range(num_elements):
        arr.append({
            "frame_id": random.randint(0, 10000),
            "raw_data": generate_random_base64(random.randint(10, 50)),
            "timestamp": random.uniform(0.0, 3600.0),
        })
    return arr


def expected_v2(data):
    events = []
    for item in data:
        events.append({
            "id": f"evt_{item['frame_id']}",
            "decoded_hex": base64.b64decode(item["raw_data"], validate=True).hex(),
            "ts_ms": int(item["timestamp"] * 1000),
        })
    events.sort(key=lambda event: (event["ts_ms"], event["id"]))
    return {"events": events, "total": len(events)}


def assert_migration(binary, data, label):
    with tempfile.NamedTemporaryFile(mode="w", delete=False, suffix=".json") as tmp:
        json.dump(data, tmp)
        tmp_path = tmp.name

    try:
        proc = subprocess.run(
            [binary, tmp_path], capture_output=True, text=True, timeout=10
        )
        assert proc.returncode == 0, (
            f"{label} failed for input {data}.\n"
            f"stdout: {proc.stdout}\nstderr: {proc.stderr}"
        )
        try:
            actual = json.loads(proc.stdout)
        except json.JSONDecodeError as exc:
            pytest.fail(f"{label} did not emit valid JSON for input {data}: {exc}\n{proc.stdout}")

        expected = expected_v2(data)
        assert actual == expected, (
            f"{label} produced the wrong migration.\n"
            f"Input: {data}\nExpected: {expected}\nGot: {actual}"
        )
        assert isinstance(actual, dict) and set(actual) == {"events", "total"}
        assert isinstance(actual["events"], list)
        for event in actual["events"]:
            assert isinstance(event, dict)
            assert set(event) == {"id", "decoded_hex", "ts_ms"}
    finally:
        os.remove(tmp_path)


def test_fuzz_equivalence_migration():
    assert os.path.isfile(MIGRATION_SOURCE), f"Go source {MIGRATION_SOURCE} not found."
    assert os.path.exists(MIGRATION_BINARY), f"Agent binary {MIGRATION_BINARY} not found."
    assert os.access(MIGRATION_BINARY, os.X_OK), f"Agent binary {MIGRATION_BINARY} is not executable."

    rebuilt = "/tmp/run_migration_rebuilt"
    if os.path.exists(rebuilt):
        os.remove(rebuilt)
    run_checked(["go", "build", "-o", rebuilt, MIGRATION_SOURCE], cwd="/home/user/migrate")

    cases = [
        [],
        [
            {"frame_id": 20, "raw_data": base64.b64encode(b"\x00\xffA").decode(), "timestamp": 1.9999},
            {"frame_id": 3, "raw_data": base64.b64encode(b"abc").decode(), "timestamp": 1.5},
            {"frame_id": 10, "raw_data": base64.b64encode(b"").decode(), "timestamp": 1.5},
        ],
        [
            {"frame_id": 2, "raw_data": "AQI=", "timestamp": 0.0009},
            {"frame_id": 1, "raw_data": "AwQ=", "timestamp": 0.0001},
        ],
    ]

    random.seed(42)
    for i in range(50):
        data = generate_v1_array(random.randint(0, 20))
        if i % 10 == 0 and len(data) >= 2:
            data[0]["timestamp"] = 12.345
            data[1]["timestamp"] = 12.345
        cases.append(data)

    for index, data in enumerate(cases):
        assert_migration(MIGRATION_BINARY, data, f"run_migration case {index}")
        assert_migration(rebuilt, data, f"rebuilt main.go case {index}")
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
