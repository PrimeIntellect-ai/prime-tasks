#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import math
import os
import random
import re
import subprocess

PROJECT = "/home/user/MathRouter"
ROUTER = os.path.join(PROJECT, "src/router.cpp")
TEST_ROUTER = os.path.join(PROJECT, "tests/test_router.cpp")
CI_SCRIPT = os.path.join(PROJECT, "ci.sh")
OUTPUT_FILE = "/home/user/ci_output.txt"


def run(cmd, **kwargs):
    return subprocess.run(cmd, text=True, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, timeout=30, **kwargs)


def test_router_cpp_fixes():
    assert os.path.isfile(ROUTER), f"{ROUTER} is missing"
    with open(ROUTER, "r") as f:
        content = f.read()

    # Preserve the original source assertions.
    assert "std::stoi" not in content, "The std::stoi bug is still present in router.cpp. It should be std::stod."
    assert "std::stod" in content or "stod" in content, "Expected to find stod in router.cpp for parsing doubles."

    # If vals is moved, it must not subsequently be used as a value.
    code = re.sub(r"//.*?$|/\*.*?\*/", "", content, flags=re.M | re.S)
    move = re.search(r"std::move\s*\(\s*vals\s*\)", code)
    if move:
        tail = code[move.end():]
        assert not re.search(r"\bvals\b", tail), "router.cpp still uses vals after moving from it"


def test_test_router_cpp_fixes():
    assert os.path.isfile(TEST_ROUTER), f"{TEST_ROUTER} is missing"
    with open(TEST_ROUTER, "r") as f:
        content = f.read()

    # Preserve the original fixture assertions.
    assert '{"result": 4.000000}' in content, "The expected output format in test_router.cpp is incorrect. It should expect 'result' instead of 'answer'."
    assert "fixture.initialized = true" in content or "initialized = true" in content or "setup()" in content, "The fixture is not properly initialized in test_router.cpp."

    code = re.sub(r"//.*?$|/\*.*?\*/", "", content, flags=re.M | re.S)
    direct_init = re.search(r"fixture\s*\.\s*initialized\s*=\s*true\s*;", code)
    setup_body = re.search(r"void\s+setup\s*\([^)]*\)\s*\{(.*?)\}", code, flags=re.S)
    setup_initializes = setup_body and re.search(r"\binitialized\s*=\s*true\s*;", setup_body.group(1))
    setup_called = re.search(r"fixture\s*\.\s*setup\s*\(\s*\)\s*;", code)
    assert direct_init or (setup_initializes and setup_called), "The mock must actually be initialized before it is used"


def test_independent_router_behavior():
    assert os.path.isfile(ROUTER), f"{ROUTER} is missing"

    # Inputs are generated by the verifier, and expected answers are derived here.
    rng = random.SystemRandom()
    cases = []
    for _ in range(10):
        count = rng.randint(2, 6)
        vals = [rng.randint(11, 950) / 10.0 for _ in range(count)]
        expected = math.exp(sum(math.log(v) for v in vals) / len(vals))
        request = "GET /api/geom_mean?vals=" + ",".join(f"{v:.1f}" for v in vals) + " HTTP/1.1"
        cases.append((request, expected))

    lines = [
        '#include <cmath>',
        '#include <cstdlib>',
        '#include <iostream>',
        '#include <string>',
        'std::string handle_request(const std::string&);',
        'int main() {'
    ]
    for request, expected in cases:
        lines.extend([
            '  {',
            f'    std::string response = handle_request({json.dumps(request)});',
            '    const std::string prefix = "{\\\"result\\\": ";',
            '    if (response.rfind(prefix, 0) != 0 || response.empty() || response.back() != \'}\') return 10;',
            '    char* end = nullptr;',
            '    double actual = std::strtod(response.c_str() + prefix.size(), &end);',
            '    if (!end || end != response.c_str() + response.size() - 1 || !std::isfinite(actual)) return 11;',
            f'    double expected = {expected:.17g};',
            '    if (std::fabs(actual - expected) > 0.00001 * std::max(1.0, std::fabs(expected))) return 12;',
            '  }'
        ])
    lines.extend(['  return 0;', '}'])
    with open('/tmp/router_behavior.cpp', 'w') as f:
        f.write('\n'.join(lines) + '\n')

    compiled = run(['g++', '-std=c++17', '-O2', ROUTER, '/tmp/router_behavior.cpp', '-o', '/tmp/router_behavior'])
    assert compiled.returncode == 0, f"router.cpp failed independent compilation:\n{compiled.stdout}"
    executed = run(['/tmp/router_behavior'])
    assert executed.returncode == 0, f"router failed independent geometric-mean tests (code {executed.returncode}):\n{executed.stdout}"


def test_project_fixture_really_runs():
    # Compile and execute the submitted fixture directly instead of trusting ci.sh.
    compiled = run(['g++', '-std=c++17', ROUTER, TEST_ROUTER, '-o', '/tmp/submitted_test_runner'])
    assert compiled.returncode == 0, f"Project test fixture failed compilation:\n{compiled.stdout}"
    executed = run(['/tmp/submitted_test_runner'])
    assert executed.returncode == 0, f"Project test fixture failed when executed:\n{executed.stdout}"
    assert "CI SUCCESS: All tests passed." in executed.stdout, "Project test fixture did not report success"


def test_ci_script_passes_and_output_is_exact():
    assert os.path.isfile(CI_SCRIPT), f"{CI_SCRIPT} is missing"
    result = run(['bash', CI_SCRIPT], cwd=PROJECT)
    assert result.returncode == 0, f"ci.sh failed with return code {result.returncode}.\nOUTPUT: {result.stdout}"
    assert "CI SUCCESS: All tests passed." in result.stdout, "ci.sh did not output the success message."

    assert os.path.isfile(OUTPUT_FILE), f"Expected output file {OUTPUT_FILE} does not exist."
    with open(OUTPUT_FILE, "r") as f:
        content = f.read()
    assert "CI SUCCESS: All tests passed." in content, f"Output file does not contain the success message. Content: {content}"
    assert content == result.stdout, "ci_output.txt is not the exact console output of the successful ci.sh run"
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
