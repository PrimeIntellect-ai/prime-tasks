import importlib.util
import json
import os
import random
import re
import subprocess
import sys
import time

import pytest

EVIL_CORPUS_DIR = "/app/corpus/evil/"
CLEAN_CORPUS_DIR = "/app/corpus/clean/"
SANITIZER_MODULE_PATH = "/home/user/pipeline/sanitizer.py"
ETL_PATH = "/home/user/pipeline/etl.py"
OUTPUT_JSON_PATH = "/home/user/pipeline/output.json"
LOG_PATH = "/home/user/pipeline/etl.log"
REQUIRED_KEYS = {
    "timestamp",
    "speaker_id",
    "original_length",
    "sanitized_text",
    "rolling_redaction_avg",
}


def load_sanitizer():
    assert os.path.isfile(SANITIZER_MODULE_PATH), f"Sanitizer module not found at {SANITIZER_MODULE_PATH}"
    spec = importlib.util.spec_from_file_location("sanitizer", SANITIZER_MODULE_PATH)
    sanitizer = importlib.util.module_from_spec(spec)
    sys.modules["sanitizer"] = sanitizer
    try:
        spec.loader.exec_module(sanitizer)
    except Exception as exc:
        pytest.fail(f"Failed to load sanitizer module: {exc}")
    assert hasattr(sanitizer, "sanitize_text"), "sanitizer.py is missing 'sanitize_text' function."
    assert callable(sanitizer.sanitize_text), "sanitize_text must be callable."
    return sanitizer.sanitize_text


@pytest.fixture(scope="module", autouse=True)
def run_etl_from_scratch():
    assert os.path.isfile(ETL_PATH), f"ETL script not found at {ETL_PATH}"
    assert os.path.isfile("/app/input_stream.wav"), "Audio fixture is missing."
    assert os.path.isfile("/app/speaker_metadata.csv"), "Speaker metadata is missing."

    for path in (OUTPUT_JSON_PATH, LOG_PATH):
        try:
            os.remove(path)
        except FileNotFoundError:
            pass

    started = time.time()
    try:
        result = subprocess.run(
            [sys.executable, ETL_PATH],
            cwd="/home/user/pipeline",
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=180,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        pytest.fail(f"ETL script timed out: {exc}")

    assert result.returncode == 0, f"ETL script failed with exit code {result.returncode}:\n{result.stdout}"
    assert os.path.isfile(OUTPUT_JSON_PATH), "ETL did not create output.json when executed."
    assert os.path.getmtime(OUTPUT_JSON_PATH) >= started - 1.0, "output.json was not regenerated by this ETL run."


def test_sanitizer_clean_corpus():
    sanitize_text = load_sanitizer()
    clean_files = [f for f in os.listdir(CLEAN_CORPUS_DIR) if f.endswith(".txt")]
    assert len(clean_files) > 0, "Clean corpus is empty."

    modified_clean = []
    for filename in clean_files:
        filepath = os.path.join(CLEAN_CORPUS_DIR, filename)
        with open(filepath, "r", encoding="utf-8") as handle:
            content = handle.read()
        output = sanitize_text(content)
        if output != content:
            modified_clean.append(filename)

    if modified_clean:
        pytest.fail(
            f"{len(modified_clean)} of {len(clean_files)} clean files modified. "
            f"Offending files: {', '.join(modified_clean[:5])}"
        )


def test_sanitizer_evil_corpus():
    sanitize_text = load_sanitizer()
    evil_files = [f for f in os.listdir(EVIL_CORPUS_DIR) if f.endswith(".txt")]
    assert len(evil_files) > 0, "Evil corpus is empty."

    bypassed_evil = []
    for filename in evil_files:
        filepath = os.path.join(EVIL_CORPUS_DIR, filename)
        with open(filepath, "r", encoding="utf-8") as handle:
            content = handle.read()
        output = sanitize_text(content)
        if output == content or "[REDACTED]" not in output:
            bypassed_evil.append(filename)

    if bypassed_evil:
        pytest.fail(
            f"{len(bypassed_evil)} of {len(evil_files)} evil files bypassed. "
            f"Offending files: {', '.join(bypassed_evil[:5])}"
        )


def test_sanitizer_adversarial_generated_inputs():
    sanitize_text = load_sanitizer()
    rng = random.SystemRandom()

    clean_samples = []
    for _ in range(50):
        year = rng.randint(1990, 2090)
        month = rng.randint(1, 12)
        day = rng.randint(1, 28)
        hour = rng.randint(0, 23)
        minute = rng.randint(0, 59)
        quantity = rng.randint(0, 999)
        clean_samples.append(
            f"Meeting on {year:04d}-{month:02d}-{day:02d} at {hour:02d}:{minute:02d}; bring {quantity} units."
        )

    for text in clean_samples:
        output = sanitize_text(text)
        assert isinstance(output, str), "sanitize_text must return a string."
        assert output == text, f"Benign dates, times, or quantities were modified: {text!r} -> {output!r}"

    secrets = []
    for _ in range(30):
        length = rng.randint(9, 18)
        secrets.append("".join(str(rng.randrange(10)) for _ in range(length)))

        ssn = f"{rng.randrange(100, 1000):03d}-{rng.randrange(10, 100):02d}-{rng.randrange(1000, 10000):04d}"
        secrets.append(ssn)

        groups = ["".join(str(rng.randrange(10)) for _ in range(4)) for _ in range(4)]
        secrets.append((" " if rng.randrange(2) else "-").join(groups))

    for index, secret in enumerate(secrets):
        text = f"Record {index}: sensitive identifier {secret}; do not disclose."
        output = sanitize_text(text)
        assert isinstance(output, str), "sanitize_text must return a string."
        assert output != text, f"Sensitive identifier was left unchanged: {secret}"
        assert "[REDACTED]" in output, f"Sensitive identifier was not replaced with [REDACTED]: {secret}"
        assert secret not in output, f"Sensitive identifier remains in sanitizer output: {secret}"
        assert output.startswith(f"Record {index}: sensitive identifier ")
        assert output.endswith("; do not disclose.")


def read_output():
    assert os.path.isfile(OUTPUT_JSON_PATH), f"Output JSON not found at {OUTPUT_JSON_PATH}"
    with open(OUTPUT_JSON_PATH, "r", encoding="utf-8") as handle:
        try:
            return json.load(handle)
        except json.JSONDecodeError as exc:
            pytest.fail(f"File {OUTPUT_JSON_PATH} is not valid JSON: {exc}")


def normalized(text):
    return re.sub(r"[^a-z0-9\[\]]+", " ", text.lower()).strip()


def test_output_json_structure_and_values():
    data = read_output()
    assert isinstance(data, list), "Output JSON must be a list of objects."
    assert len(data) >= 3, "Output JSON must contain at least 3 segments from the audio."

    first_item = data[0]
    expected_keys = REQUIRED_KEYS
    assert expected_keys.issubset(first_item.keys()), f"JSON objects missing required keys. Expected: {expected_keys}"

    for index, item in enumerate(data):
        assert isinstance(item, dict), f"Output item {index} must be an object."
        assert REQUIRED_KEYS.issubset(item.keys()), f"Output item {index} is missing required keys."
        assert isinstance(item["timestamp"], (int, float)) and not isinstance(item["timestamp"], bool)
        assert isinstance(item["speaker_id"], str) and item["speaker_id"]
        assert isinstance(item["original_length"], int) and not isinstance(item["original_length"], bool)
        assert item["original_length"] >= 0
        assert isinstance(item["sanitized_text"], str)
        assert isinstance(item["rolling_redaction_avg"], (int, float)) and not isinstance(item["rolling_redaction_avg"], bool)

    expected_speakers = ["ALPHA", "BETA", "ALPHA"]
    timestamp_ranges = [(0.0, 5.0), (5.0, 10.0), (10.0, 15.0)]
    for index, ((lower, upper), speaker) in enumerate(zip(timestamp_ranges, expected_speakers)):
        timestamp = float(data[index]["timestamp"])
        assert lower <= timestamp < upper, f"Chunk {index} timestamp {timestamp} does not fall in its audio segment."
        assert data[index]["speaker_id"] == speaker, f"Chunk {index} was joined to the wrong speaker."

    texts = [normalized(item["sanitized_text"]) for item in data[:3]]
    assert "fleet" in texts[0] and "moving" in texts[0] and "sector" in texts[0]
    assert "seven" in texts[0] or re.search(r"\b7\b", texts[0]), "First audio chunk was not transcribed."
    assert "authentication" in texts[1] and "code" in texts[1], "Second audio chunk was not transcribed."
    assert "confirming" in texts[2] and "receipt" in texts[2] and "units" in texts[2]
    assert ("two hundred" in texts[2] or re.search(r"\b200\b", texts[2])), "Third audio chunk was not transcribed."

    assert "[REDACTED]" in data[1].get("sanitized_text", ""), "Second segment should contain '[REDACTED]'."
    assert "[REDACTED]" not in data[0].get("sanitized_text", ""), "First segment should NOT contain '[REDACTED]'."
    assert "[REDACTED]" not in data[2].get("sanitized_text", ""), "Third segment should NOT contain '[REDACTED]'."
    assert data[1]["sanitized_text"].count("[REDACTED]") == 1

    assert data[0]["original_length"] == len(data[0]["sanitized_text"]), "First original_length is inconsistent."
    assert data[2]["original_length"] == len(data[2]["sanitized_text"]), "Third original_length is inconsistent."
    redacted_base_length = len(data[1]["sanitized_text"]) - len("[REDACTED]")
    assert redacted_base_length + 9 <= data[1]["original_length"] <= redacted_base_length + 50, \
        "Second original_length is inconsistent with the redacted spoken identifier."

    sanitize_text = load_sanitizer()
    for index, item in enumerate(data):
        assert sanitize_text(item["sanitized_text"]) == item["sanitized_text"], \
            f"Output item {index} still contains a sensitive numeric pattern."

    redaction_counts = [item["sanitized_text"].count("[REDACTED]") for item in data]
    expected_rolling = []
    for index in range(len(data)):
        window = redaction_counts[max(0, index - 2):index + 1]
        expected_rolling.append(sum(window) / len(window))

    for index, (item, expected) in enumerate(zip(data, expected_rolling)):
        actual = float(item["rolling_redaction_avg"])
        assert abs(actual - expected) < 0.01, \
            f"Chunk {index} rolling average should be {expected}, got {actual}."

    rolling_avgs = [item.get("rolling_redaction_avg", 0.0) for item in data[:3]]
    assert abs(rolling_avgs[0] - 0.0) < 0.01, f"Expected first rolling average to be 0.0, got {rolling_avgs[0]}"
    assert abs(rolling_avgs[1] - 0.5) < 0.01, f"Expected second rolling average to be 0.5, got {rolling_avgs[1]}"
    assert abs(rolling_avgs[2] - (1.0 / 3.0)) < 0.01, f"Expected third rolling average to be ~0.33, got {rolling_avgs[2]}"


def test_redaction_monitoring_log():
    data = read_output()
    redacted_chunks = sum("[REDACTED]" in item["sanitized_text"] for item in data)
    assert redacted_chunks > 0, "Fixture should produce at least one redaction."
    assert os.path.isfile(LOG_PATH), "ETL did not create etl.log."
    with open(LOG_PATH, "r", encoding="utf-8", errors="replace") as handle:
        log_text = handle.read()
    assert log_text.strip(), "etl.log is empty despite a redaction."
    redaction_lines = [line for line in log_text.splitlines() if "redact" in line.lower()]
    assert len(redaction_lines) >= redacted_chunks, "etl.log does not contain a monitoring entry for each redacted chunk."
