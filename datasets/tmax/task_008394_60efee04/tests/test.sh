#!/bin/bash
mkdir -p /logs/verifier
echo "0" > /logs/verifier/reward.txt

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import secrets
import shutil
import subprocess
from collections import defaultdict
from decimal import Decimal

SOURCE = "/home/user/aggregator.cpp"
BINARY = "/home/user/aggregator"
OUTPUT = "/home/user/fixed_timeline.csv"
LOG_PATHS = [
    "/home/user/logs/service_a.log",
    "/home/user/logs/service_b.log",
    "/home/user/logs/service_c.log",
]
ORIGINAL_LOGS = {
    LOG_PATHS[0]: "TXN001 1715000000.121\nTXN002 1715000005.402\nTXN003 1715000010.881\n",
    LOG_PATHS[1]: "TXN001 1715000000.125\nTXN002 1715000005.409\nTXN003 1715000010.884\n",
    LOG_PATHS[2]: "TXN001 1715000000.129\nTXN002 1715000005.415\nTXN003 1715000010.890\n",
}


def remove_output():
    if os.path.islink(OUTPUT) or os.path.isfile(OUTPUT):
        os.unlink(OUTPUT)
    elif os.path.isdir(OUTPUT):
        shutil.rmtree(OUTPUT)


def expected_csv(log_contents):
    events = defaultdict(list)
    for content in log_contents.values():
        for line in content.splitlines():
            parts = line.split()
            if len(parts) == 2:
                events[parts[0]].append(Decimal(parts[1]))

    lines = ["txn_id,duration"]
    for txn_id in sorted(events):
        timestamps = sorted(events[txn_id])
        duration = timestamps[-1] - timestamps[0]
        lines.append(f"{txn_id},{duration:.3f}")
    return "\n".join(lines)


def run_aggregator():
    remove_output()
    result = subprocess.run(
        [BINARY],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert result.returncode == 0, (
        f"Compiled aggregator exited with status {result.returncode}.\n"
        f"stdout:\n{result.stdout}\n"
        f"stderr:\n{result.stderr}"
    )
    assert os.path.isfile(OUTPUT), f"Running {BINARY} did not create {OUTPUT}."
    with open(OUTPUT, "r") as f:
        return f.read().strip()


def test_source_is_compiled_executed_and_output_is_correct():
    assert os.path.isfile(SOURCE), f"C++ source {SOURCE} is missing."

    # The supplied input logs are part of the task and must not be changed to
    # manufacture a matching result.
    for path, expected in ORIGINAL_LOGS.items():
        assert os.path.isfile(path), f"Log file {path} is missing."
        with open(path, "r") as f:
            assert f.read() == expected, f"Input log {path} was modified."

    if os.path.lexists(BINARY):
        if os.path.isdir(BINARY) and not os.path.islink(BINARY):
            shutil.rmtree(BINARY)
        else:
            os.unlink(BINARY)

    compile_result = subprocess.run(
        ["g++", "-std=c++17", SOURCE, "-o", BINARY],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=30,
    )
    assert compile_result.returncode == 0, (
        f"Failed to compile {SOURCE}.\n"
        f"stdout:\n{compile_result.stdout}\n"
        f"stderr:\n{compile_result.stderr}"
    )
    assert os.path.isfile(BINARY) and os.access(BINARY, os.X_OK), (
        f"Compilation did not produce executable {BINARY}."
    )

    # Exercise the newly compiled artifact on unpredictable transaction IDs
    # and large, closely spaced timestamps that expose float precision loss.
    token = secrets.token_hex(5).upper()
    txn_ids = [f"CHECK_{token}_{i}" for i in range(4)]
    bases = [1716000100, 1716000203, 1716000317, 1716000441]
    fractions = [
        (".111", ".115", ".119"),
        (".202", ".209", ".215"),
        (".331", ".342", ".352"),
        (".604", ".613", ".625"),
    ]
    generated = {path: "" for path in LOG_PATHS}
    for txn_id, base, values in zip(txn_ids, bases, fractions):
        for path, fraction in zip(LOG_PATHS, values):
            generated[path] += f"{txn_id} {base}{fraction}\n"

    try:
        for path, content in generated.items():
            with open(path, "w") as f:
                f.write(content)

        actual_generated = run_aggregator()
        assert actual_generated == expected_csv(generated), (
            "The compiled aggregator produced incorrect output for verifier-generated "
            "large, closely spaced timestamps.\n"
            f"Expected:\n{expected_csv(generated)}\n\n"
            f"Actual:\n{actual_generated}"
        )
    finally:
        for path, content in ORIGINAL_LOGS.items():
            with open(path, "w") as f:
                f.write(content)

    # Preserve the original final-state assertion, but require the output to be
    # regenerated by the compiled program after restoring the supplied logs.
    actual_content = run_aggregator()

    events = defaultdict(list)
    for log_path in LOG_PATHS:
        assert os.path.isfile(log_path), f"Log file {log_path} is missing."
        with open(log_path, "r") as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) == 2:
                    txn_id, ts = parts[0], float(parts[1])
                    events[txn_id].append(ts)

    expected_lines = ["txn_id,duration"]
    for txn_id in sorted(events.keys()):
        ts_list = sorted(events[txn_id])
        duration = ts_list[-1] - ts_list[0]
        expected_lines.append(f"{txn_id},{duration:.3f}")
    expected_content = "\n".join(expected_lines)

    assert actual_content == expected_content, (
        f"Content of {OUTPUT} does not match expected output.\n"
        f"Expected:\n{expected_content}\n\n"
        f"Actual:\n{actual_content}\n\n"
        "Ensure that the C++ program computes durations using sufficient precision."
    )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
