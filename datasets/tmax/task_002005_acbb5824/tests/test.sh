#!/bin/bash
set -e
mkdir -p /logs/verifier

cat <<'TEST_EOF' > /tmp/test_final_state.py
import csv
import json
import os
import re
import shutil
import sqlite3
import subprocess
import tempfile
import uuid

PROJECT = '/home/user/graph_analyzer'
MAIN_RS = os.path.join(PROJECT, 'src', 'main.rs')
CARGO_TOML = os.path.join(PROJECT, 'Cargo.toml')
DB_PATH = '/home/user/graph.db'
CSV_PATH = '/home/user/top_nodes.csv'

EXPECTED_CONTENT = (
    "type,name,total_weight\n"
    "Database,TransactionDB,25.0\n"
    "Queue,JobQueue,20.0\n"
    "Service,AuthService,16.0\n"
)


def run_cargo(threshold):
    if os.path.exists(CSV_PATH):
        os.remove(CSV_PATH)
    result = subprocess.run(
        ['cargo', 'run', '--release', '--quiet', '--', str(threshold)],
        cwd=PROJECT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=180,
    )
    assert result.returncode == 0, (
        f'Rust program failed with exit code {result.returncode}.\n'
        f'stdout:\n{result.stdout}\nstderr:\n{result.stderr}'
    )
    assert os.path.isfile(CSV_PATH), f'{CSV_PATH} was not generated by the Rust program.'


def read_csv_rows():
    with open(CSV_PATH, newline='') as f:
        rows = list(csv.reader(f))
    assert rows, 'CSV is empty.'
    assert rows[0] == ['type', 'name', 'total_weight'], 'CSV header is incorrect.'
    parsed = []
    for row in rows[1:]:
        assert len(row) == 3, f'Invalid CSV row: {row!r}'
        parsed.append((row[0], row[1], float(row[2])))
    assert [r[0] for r in parsed] == sorted(r[0] for r in parsed), 'Rows are not sorted by type.'
    return parsed


def create_hidden_database(seed):
    conn = sqlite3.connect(DB_PATH)
    try:
        conn.executescript('''
            CREATE TABLE nodes (id INTEGER PRIMARY KEY, type TEXT, name TEXT);
            CREATE TABLE edges (source INTEGER, target INTEGER, weight REAL);
            CREATE INDEX idx_edges_target ON edges(target);
        ''')
        base = 10 + seed
        suffix = uuid.uuid4().hex[:10]
        types = [f'Alpha_{suffix}', f'Middle_{suffix}', f'Zulu_{suffix}']
        totals = {}
        node_id = 1
        nodes = []
        edges = []

        desired = [
            [base + 10, base + 10, base + 2],
            [base + 20, base + 18, base + 1],
            [base + 30, base + 12, base + 3],
        ]
        for type_index, type_name in enumerate(types):
            for item_index, total in enumerate(desired[type_index]):
                name = f'Node_{type_index}_{item_index}_{suffix}'
                nodes.append((node_id, type_name, name))
                totals[(type_name, name)] = float(total)
                # Split each total over multiple incoming edges so SUM is required.
                edges.append((999, node_id, 4.5))
                edges.append((998, node_id, float(total) - 4.5))
                node_id += 1

        conn.executemany('INSERT INTO nodes(id,type,name) VALUES (?,?,?)', nodes)
        conn.executemany('INSERT INTO edges(source,target,weight) VALUES (?,?,?)', edges)
        conn.commit()
        return totals, float(base + 5), float(base + 25)
    finally:
        conn.close()


def expected_rows(totals, threshold):
    by_type = {}
    for (type_name, name), total in totals.items():
        by_type.setdefault(type_name, []).append((name, total))
    result = []
    for type_name, values in by_type.items():
        maximum = max(total for _, total in values)
        if maximum >= threshold:
            for name, total in values:
                if total == maximum:
                    result.append((type_name, name, total))
    return result


def assert_rows(actual, expected):
    assert len(actual) == len(expected), f'Expected {expected!r}, got {actual!r}'
    actual_map = {(t, n): w for t, n, w in actual}
    expected_map = {(t, n): w for t, n, w in expected}
    assert actual_map.keys() == expected_map.keys(), f'Expected {expected!r}, got {actual!r}'
    for key, value in expected_map.items():
        assert abs(actual_map[key] - value) < 1e-8, f'Wrong total for {key}: {actual_map[key]}'


def test_final_state_and_program():
    # Preserve the original existence assertions.
    assert os.path.isfile(MAIN_RS), f'{MAIN_RS} does not exist.'
    assert os.path.isfile(CARGO_TOML), f'{CARGO_TOML} does not exist.'
    assert os.path.isfile(DB_PATH), f'{DB_PATH} does not exist.'

    # Verify this is a buildable Cargo binary project that actually depends on rusqlite.
    metadata_result = subprocess.run(
        ['cargo', 'metadata', '--format-version=1', '--no-deps'],
        cwd=PROJECT, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60
    )
    assert metadata_result.returncode == 0, metadata_result.stderr
    metadata = json.loads(metadata_result.stdout)
    assert metadata['packages'], 'Cargo project has no package.'
    package = metadata['packages'][0]
    assert any(dep.get('name') == 'rusqlite' for dep in package.get('dependencies', [])), (
        'Cargo.toml must depend on the rusqlite crate.'
    )
    assert any('bin' in target.get('kind', []) for target in package.get('targets', [])), (
        'Cargo project does not define a binary target.'
    )

    with open(MAIN_RS, encoding='utf-8') as f:
        source = f.read()
    lowered = source.lower()
    assert re.search(r'\breindex\s+idx_edges_target\b', lowered), (
        'The submitted repair must execute REINDEX idx_edges_target.'
    )
    assert re.search(r'\brank\s*\(\s*\)', lowered), 'The analytics query must use RANK().'
    assert re.search(r'\bover\b', lowered) and re.search(r'\bpartition\s+by\b', lowered), (
        'The analytics query must use a window partition.'
    )
    assert re.search(r'\bsum\s*\(', lowered), 'The analytics query must sum incoming weights.'
    assert re.search(r'(\?[0-9]*|[:@$][a-z_][a-z0-9_]*)', lowered), (
        'The SQL must contain a bind parameter for the threshold.'
    )

    # Preserve and strengthen the original database integrity assertion.
    conn = sqlite3.connect(DB_PATH)
    try:
        result = conn.execute('PRAGMA integrity_check;').fetchone()
        assert result is not None, 'Failed to run integrity check.'
        assert result[0].lower() == 'ok', 'Database integrity check failed. Did you run REINDEX?'
        index = conn.execute(
            "SELECT name FROM sqlite_master WHERE type='index' AND name='idx_edges_target'"
        ).fetchone()
        assert index is not None, 'idx_edges_target is missing.'
        indexed = conn.execute(
            'SELECT rowid,target FROM edges INDEXED BY idx_edges_target ORDER BY rowid'
        ).fetchall()
        unindexed = conn.execute(
            'SELECT rowid,target FROM edges NOT INDEXED ORDER BY rowid'
        ).fetchall()
        assert indexed == unindexed, 'idx_edges_target contains stale or missing entries.'
    finally:
        conn.close()

    backup_dir = tempfile.mkdtemp(prefix='graph-verifier-')
    db_backup = os.path.join(backup_dir, 'graph.db')
    shutil.copy2(DB_PATH, db_backup)
    original_csv = None
    try:
        # Build and execute the artifact against the required database and threshold.
        run_cargo(15.0)
        with open(CSV_PATH, 'rb') as f:
            original_csv = f.read()
        content_lines = [line.strip() for line in original_csv.decode().strip().splitlines() if line.strip()]
        expected_lines = [line.strip() for line in EXPECTED_CONTENT.strip().splitlines() if line.strip()]
        assert content_lines == expected_lines, f'Content of {CSV_PATH} does not match expected output.'

        # Replace the database temporarily with unpredictable data and exercise SUM,
        # ranking (including a tie), partitioning, and two threshold arguments.
        os.remove(DB_PATH)
        seed = int.from_bytes(os.urandom(1), 'big') % 7
        totals, low_threshold, high_threshold = create_hidden_database(seed)

        run_cargo(low_threshold)
        assert_rows(read_csv_rows(), expected_rows(totals, low_threshold))

        run_cargo(high_threshold)
        assert_rows(read_csv_rows(), expected_rows(totals, high_threshold))
    finally:
        if os.path.exists(DB_PATH):
            os.remove(DB_PATH)
        shutil.copy2(db_backup, DB_PATH)
        if original_csv is not None:
            with open(CSV_PATH, 'wb') as f:
                f.write(original_csv)
        shutil.rmtree(backup_dir, ignore_errors=True)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
