import ast
import json
import os
import re
import secrets
import subprocess
import sys
import tempfile
import pytest

BASE_DIR = "/home/user/fast-token-parser"
OUTPUT_FILE = "/home/user/parsed_tokens.json"
LIBRARY = os.path.join(BASE_DIR, "libparser.so")
PARSER_SOURCE = os.path.join(BASE_DIR, "parser.c")
HELPER = "/tmp/exercise_parser.py"

@pytest.fixture(scope="session", autouse=True)
def run_submitted_test_suite():
    if os.path.exists(OUTPUT_FILE):
        os.remove(OUTPUT_FILE)
    env = os.environ.copy()
    env.pop("PARSER_INITIALIZED", None)
    proc = subprocess.run(
        [sys.executable, os.path.join(BASE_DIR, "test_suite.py")],
        cwd=BASE_DIR,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20,
    )
    assert proc.returncode == 0, (
        "The submitted test suite did not run successfully.\n"
        f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )
    assert os.path.isfile(OUTPUT_FILE), f"The output file {OUTPUT_FILE} was not generated by the test suite."


def make_cases():
    cases = []
    for length in (0, 1, 7, 63, 64):
        token_type = secrets.randbelow(256)
        payload = secrets.token_bytes(length)
        token = bytes([token_type, length >> 8, length & 0xff]) + payload
        cases.append({"token": token.hex(), "status": 0, "type": token_type, "data": payload.hex()})

    token_type = secrets.randbelow(256)
    short_payload = secrets.token_bytes(5)
    truncated = bytes([token_type, 0, 20]) + short_payload
    cases.append({"token": truncated.hex(), "status": -1})

    for length in (65, 69, 200):
        token_type = secrets.randbelow(256)
        payload = secrets.token_bytes(length)
        token = bytes([token_type, length >> 8, length & 0xff]) + payload
        cases.append({"token": token.hex(), "status": -1})
    return cases


def exercise_library(path, cases):
    proc = subprocess.run(
        [sys.executable, HELPER, "lib", path],
        input=json.dumps(cases),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20,
    )
    assert proc.returncode == 0, (
        f"Loading or exercising {path} failed (it may have crashed on malformed input).\n"
        f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )
    results = json.loads(proc.stdout)
    assert len(results) == len(cases)
    for case, result in zip(cases, results):
        assert result["result"] == case["status"], f"Incorrect parse status for token {case['token']}"
        if case["status"] == 0:
            assert result["type"] == case["type"]
            assert result["data"] == case["data"]


def test_parsed_tokens_json_exists_and_correct():
    assert os.path.isfile(OUTPUT_FILE), f"The output file {OUTPUT_FILE} was not generated."

    with open(OUTPUT_FILE, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"The file {OUTPUT_FILE} does not contain valid JSON.")

    expected_data = [
        {"type": 1, "data": "hello"},
        {"error": "Invalid token"},
        {"type": 3, "data": "test"}
    ]

    assert data == expected_data, f"The contents of {OUTPUT_FILE} do not match the expected output. Got: {data}"


def test_test_suite_import_order():
    test_suite_path = os.path.join(BASE_DIR, "test_suite.py")
    assert os.path.isfile(test_suite_path), f"File {test_suite_path} is missing."

    with open(test_suite_path, "r") as f:
        content = f.read()

    import_config_idx = content.find("import config")
    import_ffi_idx = content.find("import ffi_wrapper")

    assert import_config_idx != -1, "'import config' is missing from test_suite.py"
    assert import_ffi_idx != -1, "'import ffi_wrapper' is missing from test_suite.py"
    assert import_config_idx < import_ffi_idx, "The import order is still incorrect. 'import config' must come before 'import ffi_wrapper'."

    tree = ast.parse(content, filename=test_suite_path)
    imported_modules = []
    for node in tree.body:
        if isinstance(node, ast.Import):
            imported_modules.extend(alias.name for alias in node.names)
    assert "config" in imported_modules, "test_suite.py must actually import config"
    assert "ffi_wrapper" in imported_modules, "test_suite.py must actually import ffi_wrapper"
    assert imported_modules.index("config") < imported_modules.index("ffi_wrapper"), (
        "test_suite.py must execute the config import before the ffi_wrapper import"
    )


def test_parser_c_bounds_check():
    parser_path = os.path.join(BASE_DIR, "parser.c")
    assert os.path.isfile(parser_path), f"File {parser_path} is missing."

    with open(parser_path, "r") as f:
        content = f.read()

    has_check = re.search(r'data_len\s*>\s*64', content) or \
                re.search(r'64\s*<\s*data_len', content) or \
                re.search(r'data_len\s*>=\s*65', content) or \
                re.search(r'65\s*<=\s*data_len', content)

    assert has_check, "parser.c does not appear to contain a bounds check preventing data_len from exceeding 64 bytes."


def test_installed_and_rebuilt_parser_are_safe():
    assert os.path.isfile(LIBRARY), f"The rebuilt shared library {LIBRARY} is missing."
    with open(LIBRARY, "rb") as f:
        assert f.read(4) == b"\x7fELF", f"{LIBRARY} is not an ELF shared-library artifact"

    cases = make_cases()
    exercise_library(LIBRARY, cases)

    fd, rebuilt = tempfile.mkstemp(prefix="verifier_parser_", suffix=".so")
    os.close(fd)
    try:
        proc = subprocess.run(
            ["gcc", "-shared", "-o", rebuilt, "-fPIC", PARSER_SOURCE],
            cwd=BASE_DIR,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=20,
        )
        assert proc.returncode == 0, f"parser.c does not compile successfully:\n{proc.stderr}"
        exercise_library(rebuilt, cases)
    finally:
        if os.path.exists(rebuilt):
            os.remove(rebuilt)


def test_ffi_wrapper_uses_safe_parser_behavior():
    cases = make_cases()
    proc = subprocess.run(
        [sys.executable, HELPER, "wrapper"],
        input=json.dumps(cases),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20,
        env={k: v for k, v in os.environ.items() if k != "PARSER_INITIALIZED"},
    )
    assert proc.returncode == 0, (
        "ffi_wrapper failed or crashed while parsing generated tokens.\n"
        f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )
    results = json.loads(proc.stdout)
    assert len(results) == len(cases)
    for case, result in zip(cases, results):
        if case["status"] == -1:
            assert result == {"error": "Invalid token"}
        else:
            expected_text = bytes.fromhex(case["data"]).decode("utf-8", errors="ignore")
            assert result == {"type": case["type"], "data": expected_text}
