import ctypes
import json
import os
import sys

mode = sys.argv[1]
cases = json.load(sys.stdin)

if mode == "lib":
    lib = ctypes.CDLL(sys.argv[2])
    lib.parse_token.argtypes = [
        ctypes.POINTER(ctypes.c_ubyte),
        ctypes.c_int,
        ctypes.POINTER(ctypes.c_ubyte),
        ctypes.POINTER(ctypes.c_int),
    ]
    lib.parse_token.restype = ctypes.c_int
    results = []
    for case in cases:
        token = bytes.fromhex(case["token"])
        input_buf = (ctypes.c_ubyte * len(token)).from_buffer_copy(token)
        output_buf = (ctypes.c_ubyte * 256)()
        out_type = ctypes.c_int()
        result = lib.parse_token(input_buf, len(token), output_buf, ctypes.byref(out_type))
        item = {"result": result}
        if result == 0:
            length = (token[1] << 8) | token[2]
            item["type"] = out_type.value
            item["data"] = bytes(output_buf[:length]).hex()
        results.append(item)
    print(json.dumps(results))
elif mode == "wrapper":
    os.chdir("/home/user/fast-token-parser")
    os.environ.pop("PARSER_INITIALIZED", None)
    sys.path.insert(0, "/home/user/fast-token-parser")
    import config
    import ffi_wrapper
    results = []
    for case in cases:
        results.append(ffi_wrapper.parse(bytes.fromhex(case["token"])))
    print(json.dumps(results))
else:
    raise SystemExit("unknown mode")
HELPER_EOF

