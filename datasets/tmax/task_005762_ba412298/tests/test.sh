#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
# test_final_state.py

import os
import json
import stat
import time
import shutil
import datetime
import subprocess
import pytest

APP_DIR = "/home/user/app"
FINDINGS_JSON = "/home/user/findings.json"
GEN_CERT_SH = os.path.join(APP_DIR, "gen_cert.sh")
SERVER_CRT = os.path.join(APP_DIR, "server.crt")
SERVER_KEY = os.path.join(APP_DIR, "server.key")


def test_findings_json_exists_and_valid():
    assert os.path.isfile(FINDINGS_JSON), f"File {FINDINGS_JSON} does not exist."
    with open(FINDINGS_JSON, "r") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"File {FINDINGS_JSON} is not valid JSON.")

    assert "api.php" in data, "Key 'api.php' missing in findings.json"
    assert "auth.py_missing_flags" in data, "Key 'auth.py_missing_flags' missing in findings.json"


def test_findings_content():
    with open(FINDINGS_JSON, "r") as f:
        data = json.load(f)

    cwe = data.get("api.php", "")
    assert cwe.upper() == "CWE-78", f"Expected CWE-78 for api.php, got {cwe}"

    flags = data.get("auth.py_missing_flags", [])
    assert isinstance(flags, list), "auth.py_missing_flags should be a list"

    flags_lower = [str(f).lower() for f in flags]
    assert "httponly" in flags_lower, "Missing 'HttpOnly' flag in findings"
    assert "secure" in flags_lower, "Missing 'Secure' flag in findings"
    assert len(flags) == 2, f"Expected exactly 2 flags, got {len(flags)}"

    # Check if sorted alphabetically (case-insensitive check based on original strings)
    assert flags_lower == sorted(flags_lower), "Flags are not sorted alphabetically"


def test_gen_cert_sh_modified():
    assert os.path.isfile(GEN_CERT_SH), f"File {GEN_CERT_SH} does not exist."
    assert not os.path.islink(GEN_CERT_SH), "gen_cert.sh must be a regular script, not a symlink"
    assert stat.S_ISREG(os.lstat(GEN_CERT_SH).st_mode), "gen_cert.sh is not a regular file"
    assert os.access(GEN_CERT_SH, os.X_OK), "gen_cert.sh is not executable"

    with open(GEN_CERT_SH, "r") as f:
        content = f.read()

    assert "rsa:2048" in content, "gen_cert.sh does not use rsa:2048"
    assert "sha256" in content or "-sha256" in content, "gen_cert.sh does not use sha256"
    assert "rsa:1024" not in content, "gen_cert.sh still contains rsa:1024"
    assert "-md5" not in content, "gen_cert.sh still contains -md5"


def _remove_output(path):
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path)
    elif os.path.lexists(path):
        os.unlink(path)


def _cert_timestamp(label):
    result = subprocess.run(
        ["openssl", "x509", "-in", SERVER_CRT, "-noout", f"-{label}"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert result.returncode == 0, result.stderr
    value = result.stdout.strip().split("=", 1)[1]
    parsed = datetime.datetime.strptime(value, "%b %d %H:%M:%S %Y %Z")
    return parsed.replace(tzinfo=datetime.timezone.utc).timestamp()


def test_gen_cert_script_actually_generates_expected_certificate():
    # Existing artifacts cannot satisfy this test: the submitted script must recreate both.
    _remove_output(SERVER_CRT)
    _remove_output(SERVER_KEY)
    started = time.time()
    result = subprocess.run(
        [GEN_CERT_SH],
        cwd=APP_DIR,
        capture_output=True,
        text=True,
        timeout=30,
    )
    finished = time.time()
    assert result.returncode == 0, f"gen_cert.sh failed: {result.stderr}"

    for path in (SERVER_CRT, SERVER_KEY):
        assert os.path.lexists(path), f"gen_cert.sh did not create {path}"
        assert not os.path.islink(path), f"{path} must not be a symlink"
        assert stat.S_ISREG(os.lstat(path).st_mode), f"{path} is not a regular file"

    # Confirm the certificate was freshly produced by this execution and retained 365 days.
    not_before = _cert_timestamp("startdate")
    not_after = _cert_timestamp("enddate")
    assert started - 5 <= not_before <= finished + 5, "Certificate was not freshly generated by gen_cert.sh"
    assert not_after - not_before == 365 * 24 * 60 * 60, "Certificate validity must remain 365 days"

    subject = subprocess.run(
        ["openssl", "x509", "-in", SERVER_CRT, "-noout", "-subject", "-nameopt", "RFC2253"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert subject.returncode == 0, subject.stderr
    assert subject.stdout.strip().split("=", 1)[1] == "CN=localhost", "Certificate subject must remain /CN=localhost"

    issuer = subprocess.run(
        ["openssl", "x509", "-in", SERVER_CRT, "-noout", "-issuer", "-nameopt", "RFC2253"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert issuer.returncode == 0, issuer.stderr
    assert issuer.stdout.strip().split("=", 1)[1] == "CN=localhost", "Certificate must remain self-signed"

    verify = subprocess.run(
        ["openssl", "verify", "-CAfile", SERVER_CRT, SERVER_CRT],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert verify.returncode == 0, "Generated certificate is not a valid self-signed certificate"

    key_check = subprocess.run(
        ["openssl", "pkey", "-in", SERVER_KEY, "-noout", "-check"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert key_check.returncode == 0, "Generated server.key is invalid or encrypted"

    cert_modulus = subprocess.run(
        ["openssl", "x509", "-in", SERVER_CRT, "-noout", "-modulus"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    key_modulus = subprocess.run(
        ["openssl", "rsa", "-in", SERVER_KEY, "-noout", "-modulus"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert cert_modulus.returncode == 0 and key_modulus.returncode == 0, "Could not inspect generated key pair"
    assert cert_modulus.stdout.strip() == key_modulus.stdout.strip(), "server.key does not match server.crt"


def test_certificates_generated_and_valid():
    assert os.path.isfile(SERVER_CRT), f"Certificate {SERVER_CRT} was not generated."
    assert os.path.isfile(SERVER_KEY), f"Key {SERVER_KEY} was not generated."

    result = subprocess.run(
        ["openssl", "x509", "-text", "-noout", "-in", SERVER_CRT],
        capture_output=True,
        text=True
    )
    assert result.returncode == 0, "Failed to parse server.crt with openssl"

    output = result.stdout.lower()
    assert "sha256" in output, "Certificate signature algorithm does not use sha256"
    assert "2048 bit" in output or "rsa 2048" in output or "public-key: (2048 bit)" in output, "Certificate public key is not 2048 bit"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
