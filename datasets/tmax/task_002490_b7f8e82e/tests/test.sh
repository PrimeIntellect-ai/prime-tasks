#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import io
import os
import secrets
import subprocess

import pandas as pd
import pandas.testing as pdt

PROCESS_PATH = '/home/user/process.py'
RAW_PATH = '/home/user/data/raw_data.csv'
OUTPUT_PATH = '/home/user/processed.parquet'

EXPECTED_RAW = b'''user_id,group_id,score,name,session_id
1,100,95.5,alice,5050
2,,88.0,bob,
,102,76.2,charlie,5052
4,100,90.1,david,5053
'''


def run_process():
    result = subprocess.run(
        ['python3', PROCESS_PATH],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, (
        f'process.py failed with exit code {result.returncode}: '
        f'{result.stdout}\n{result.stderr}'
    )
    assert os.path.isfile(OUTPUT_PATH), f'{OUTPUT_PATH} was not generated by process.py'


def expected_processed(csv_source):
    df = pd.read_csv(csv_source)
    for col in df.columns:
        if col.endswith('_id'):
            df[col] = df[col].astype('Int64')
    return df


def test_process_script_and_generated_values():
    """Execute process.py on an unpredictable probe and then on the original input."""
    assert os.path.isfile(PROCESS_PATH), f'File {PROCESS_PATH} does not exist or is not a regular file.'
    assert os.path.isfile(RAW_PATH), f'File {RAW_PATH} does not exist or is not a regular file.'

    with open(RAW_PATH, 'rb') as f:
        original_raw = f.read()
    assert original_raw == EXPECTED_RAW, 'raw_data.csv was modified.'

    first_id = f'col_{secrets.token_hex(8)}_id'
    second_id = f'col_{secrets.token_hex(8)}_id'
    probe_csv = (
        f'{first_id},{second_id},metric,label\n'
        '1,,1.5,alpha\n'
        ',20,,beta\n'
        '-3,21,3.25,gamma\n'
    )
    probe_expected = expected_processed(io.StringIO(probe_csv))

    try:
        with open(RAW_PATH, 'w', newline='') as f:
            f.write(probe_csv)
        if os.path.lexists(OUTPUT_PATH):
            os.remove(OUTPUT_PATH)

        run_process()
        probe_actual = pd.read_parquet(OUTPUT_PATH)
        pdt.assert_frame_equal(probe_actual, probe_expected, check_dtype=True, check_like=False)
    finally:
        with open(RAW_PATH, 'wb') as f:
            f.write(original_raw)

    if os.path.lexists(OUTPUT_PATH):
        os.remove(OUTPUT_PATH)
    run_process()

    original_expected = expected_processed(io.BytesIO(original_raw))
    original_actual = pd.read_parquet(OUTPUT_PATH)
    pdt.assert_frame_equal(original_actual, original_expected, check_dtype=True, check_like=False)


def test_fixed_columns_file():
    """Verify that fixed_columns.txt exists and contains the correct sorted column names."""
    file_path = '/home/user/fixed_columns.txt'
    assert os.path.exists(file_path), f"File {file_path} does not exist."

    with open(file_path, 'r') as f:
        lines = [line.strip() for line in f.readlines() if line.strip()]

    expected_columns = ['group_id', 'session_id', 'user_id']
    assert lines == expected_columns, f"Expected {expected_columns}, but got {lines} in {file_path}"


def test_processed_parquet_exists_and_schema():
    """Verify that processed.parquet exists and has the correct Int64 schema for _id columns."""
    file_path = '/home/user/processed.parquet'
    assert os.path.exists(file_path), f"File {file_path} does not exist."

    check_script = f"""
import pandas as pd
import sys

try:
    df = pd.read_parquet('{file_path}')
    errors = []
    for col in ['user_id', 'group_id', 'session_id']:
        if col not in df.columns:
            errors.append(f"Missing column: {{col}}")
        elif str(df[col].dtype) != 'Int64':
            errors.append(f"Column {{col}} has dtype {{df[col].dtype}}, expected Int64")

    if errors:
        print("; ".join(errors))
        sys.exit(1)
    sys.exit(0)
except Exception as e:
    print(f"Error reading parquet file: {{e}}")
    sys.exit(1)
"""

    result = subprocess.run(['python3', '-c', check_script], capture_output=True, text=True)
    assert result.returncode == 0, f"Parquet schema verification failed: {result.stdout.strip()}"
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
