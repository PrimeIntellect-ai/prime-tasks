#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_tracker.py
import glob
import os
import re
import shutil
import subprocess
from pathlib import Path

HOME = Path('/home/user')
FILES = HOME / 'files'
TRACKER = HOME / 'tracker.py'


def reset_files():
    if FILES.exists():
        shutil.rmtree(FILES)
    FILES.mkdir(parents=True)
    for wal in (HOME / 'rename_log.wal', HOME / 'audit_random.wal'):
        if wal.exists():
            wal.unlink()


def run_tracker():
    assert TRACKER.is_file(), 'Expected /home/user/tracker.py to exist.'
    result = subprocess.run(
        ['python3', str(TRACKER)],
        cwd=str(HOME),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
    )
    assert result.returncode == 0, (
        f'tracker.py failed with exit code {result.returncode}\n'
        f'stdout:\n{result.stdout}\nstderr:\n{result.stderr}'
    )


def read_wal(path):
    assert path.is_file(), f'WAL log file {path} does not exist.'
    with path.open('r') as f:
        return [line.strip() for line in f if line.strip()]


def parse_wal(lines):
    parsed = []
    for line in lines:
        assert line.startswith('[RENAME] '), f"Log line does not start with '[RENAME] ': {line}"
        assert ' -> ' in line, f"Log line missing ' -> ' separator: {line}"
        match = re.fullmatch(r'\[RENAME\] ([^/\n]+) -> ([^/\n]+)', line)
        assert match, f'Log line is not strictly formatted: {line}'
        parsed.append(match.groups())
    return parsed


def test_tracker_executes_and_processes_inputs():
    # Recreate the original task inputs, then execute the submitted artifact.
    reset_files()
    (HOME / 'rules.ini').write_text(
        '[Naming]\n'
        'gcode_format = {material}_{time}s.gcode\n'
        'elf_format = firmware_{bitness}bit_{index}.elf\n\n'
        '[Log]\n'
        'wal_file = /home/user/rename_log.wal\n'
    )
    part1 = b'; Generated by Slicer\n; MATERIAL:PLA\n; TIME:4500\nG28 ; Home\nG1 Z15.0 F6000\n'
    part2 = b'; Generated by Slicer\n; MATERIAL:PETG\n; TIME:7200\nG28 ; Home\nG1 Z15.0 F6000\n'
    fw_a = b'\x7fELF\x01' + b'\x00' * 59
    fw_b = b'\x7fELF\x02' + b'\x00' * 59
    (FILES / 'part1.gcode').write_bytes(part1)
    (FILES / 'part2.gcode').write_bytes(part2)
    (FILES / 'fw_a.elf').write_bytes(fw_a)
    (FILES / 'fw_b.elf').write_bytes(fw_b)

    run_tracker()

    # Preserve the original verifier's assertions.
    pla_file = FILES / 'PLA_4500s.gcode'
    petg_file = FILES / 'PETG_7200s.gcode'
    assert pla_file.is_file(), f'Expected renamed file {pla_file} does not exist. Check gcode processing.'
    assert petg_file.is_file(), f'Expected renamed file {petg_file} does not exist. Check gcode processing.'

    elf_files = glob.glob(str(FILES / '*.elf'))
    bit32_files = [f for f in elf_files if '32bit' in os.path.basename(f)]
    bit64_files = [f for f in elf_files if '64bit' in os.path.basename(f)]
    assert len(bit32_files) == 1, 'Expected exactly one 32-bit ELF file renamed to firmware_32bit*.elf'
    assert len(bit64_files) == 1, 'Expected exactly one 64-bit ELF file renamed to firmware_64bit*.elf'

    lines = read_wal(HOME / 'rename_log.wal')
    assert len(lines) == 4, f'Expected exactly 4 rename log entries, found {len(lines)}.'
    parsed = parse_wal(lines)
    log_content = '\n'.join(lines)
    assert 'part1.gcode -> PLA_4500s.gcode' in log_content, 'Missing WAL entry for part1.gcode.'
    assert 'part2.gcode -> PETG_7200s.gcode' in log_content, 'Missing WAL entry for part2.gcode.'
    assert 'fw_a.elf -> firmware_32bit' in log_content, 'Missing WAL entry for fw_a.elf.'
    assert 'fw_b.elf -> firmware_64bit' in log_content, 'Missing WAL entry for fw_b.elf.'

    for original in ('part1.gcode', 'part2.gcode', 'fw_a.elf', 'fw_b.elf'):
        assert not (FILES / original).exists(), f'Original file {FILES / original} was not renamed/removed.'

    # Ensure these are genuine renames and the file data was preserved.
    assert pla_file.read_bytes() == part1
    assert petg_file.read_bytes() == part2
    assert Path(bit32_files[0]).read_bytes() == fw_a
    assert Path(bit64_files[0]).read_bytes() == fw_b
    wal_map = dict(parsed)
    assert wal_map['fw_a.elf'] == Path(bit32_files[0]).name
    assert wal_map['fw_b.elf'] == Path(bit64_files[0]).name
    assert set(FILES.iterdir()) == {pla_file, petg_file, Path(bit32_files[0]), Path(bit64_files[0])}

    # Exercise the script again with different metadata, configuration formats,
    # WAL path, source names, payloads, and ELF classes. Expected answers are
    # derived from these fresh inputs rather than fixed output names.
    reset_files()
    (HOME / 'rules.ini').write_text(
        '[Naming]\n'
        'gcode_format = audit-{time}-{material}.gcode\n'
        'elf_format = audit_{bitness}bit_{index}.elf\n\n'
        '[Log]\n'
        'wal_file = /home/user/audit_random.wal\n'
    )
    g1 = b'; header\n; MATERIAL :WRONG\n; MATERIAL:NYLONX\n; TIME:137\nG1 X11 Y22\n'
    g2 = b'; another header\n; TIME :999\n; MATERIAL:ABSCF\n; TIME:8642\nG1 X33 Y44\n'
    e1 = b'\x7fELF\x02' + b'64-bit-payload-A' + bytes(range(20))
    e2 = b'\x7fELF\x01' + b'32-bit-payload-B' + bytes(range(19, -1, -1))
    (FILES / 'job-red.gcode').write_bytes(g1)
    (FILES / 'job-blue.gcode').write_bytes(g2)
    (FILES / 'controller-z.elf').write_bytes(e1)
    (FILES / 'controller-q.elf').write_bytes(e2)

    run_tracker()

    expected_g1 = FILES / 'audit-137-NYLONX.gcode'
    expected_g2 = FILES / 'audit-8642-ABSCF.gcode'
    assert expected_g1.is_file() and expected_g1.read_bytes() == g1
    assert expected_g2.is_file() and expected_g2.read_bytes() == g2

    outputs = list(FILES.iterdir())
    elf_outputs = [p for p in outputs if p.suffix == '.elf']
    assert len(elf_outputs) == 2
    elf_info = {}
    indices = set()
    for path in elf_outputs:
        match = re.fullmatch(r'audit_(32|64)bit_(\d+)\.elf', path.name)
        assert match, f'ELF output does not use configured format: {path.name}'
        bitness, index = match.groups()
        assert index not in indices, 'ELF index values must distinguish the output files.'
        indices.add(index)
        elf_info[bitness] = (path, path.read_bytes())
    assert set(elf_info) == {'32', '64'}
    assert elf_info['32'][1] == e2
    assert elf_info['64'][1] == e1

    random_lines = read_wal(HOME / 'audit_random.wal')
    assert len(random_lines) == 4
    random_map = dict(parse_wal(random_lines))
    assert set(random_map) == {'job-red.gcode', 'job-blue.gcode', 'controller-z.elf', 'controller-q.elf'}
    assert random_map['job-red.gcode'] == expected_g1.name
    assert random_map['job-blue.gcode'] == expected_g2.name
    assert random_map['controller-z.elf'] == elf_info['64'][0].name
    assert random_map['controller-q.elf'] == elf_info['32'][0].name
    assert set(outputs) == {expected_g1, expected_g2, elf_info['32'][0], elf_info['64'][0]}
    assert not (HOME / 'rename_log.wal').exists(), 'Script ignored the configured WAL path.'
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_tracker.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
