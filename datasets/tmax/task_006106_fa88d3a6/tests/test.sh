#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import math
import os
import secrets
import shutil
import sqlite3
import stat
import subprocess
import tempfile
from pathlib import Path

import pytest

PROJECT = Path('/home/user/project')
BUILD_FILE = PROJECT / 'build.sh'
PROCESS_FILE = PROJECT / 'process_data.py'
VALIDATE_FILE = PROJECT / 'validate.py'
OUTPUT_FILE = PROJECT / 'output.json'


def run_build(env=None):
    result = subprocess.run(
        [str(BUILD_FILE)],
        cwd=PROJECT,
        env=env,
        text=True,
        capture_output=True,
        timeout=30,
    )
    assert result.returncode == 0, (
        f"build.sh failed with exit code {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    assert 'Build passed!' in result.stdout, (
        f"build.sh did not print 'Build passed!'. stdout was:\n{result.stdout}"
    )
    return result


def test_build_runs_pipeline_and_sets_reporting_environment():
    """Verify build.sh invokes both pipeline stages and supplies their required environment."""
    assert BUILD_FILE.is_file(), 'build.sh is missing'
    assert os.access(BUILD_FILE, os.X_OK), 'build.sh is not executable'
    assert PROCESS_FILE.is_file(), 'process_data.py is missing'
    assert VALIDATE_FILE.is_file(), 'validate.py is missing'

    original_process = PROCESS_FILE.read_bytes()
    original_validate = VALIDATE_FILE.read_bytes()
    process_mode = stat.S_IMODE(PROCESS_FILE.stat().st_mode)
    validate_mode = stat.S_IMODE(VALIDATE_FILE.stat().st_mode)

    with tempfile.TemporaryDirectory() as marker_dir:
        process_marker = Path(marker_dir) / 'process-ran.json'
        validate_marker = Path(marker_dir) / 'validate-ran'

        probe_process = f'''import json, os\nfrom pathlib import Path\nyear = int(os.environ.get("REPORT_YEAR", -1))\nmonth = int(os.environ.get("REPORT_MONTH", -1))\nPath({str(process_marker)!r}).write_text(json.dumps({{"year": year, "month": month}}))\nif year != 2023 or month != 10:\n    raise SystemExit("incorrect reporting environment")\nPath("output.json").write_text(json.dumps({{"year": year, "month": month, "total": 168.0}}))\n'''
        probe_validate = f'''import json\nfrom pathlib import Path\ndata = json.loads(Path("output.json").read_text())\nif data != {{"year": 2023, "month": 10, "total": 168.0}}:\n    raise SystemExit("invalid pipeline output")\nPath({str(validate_marker)!r}).write_text("ran")\nprint("Build passed!")\n'''

        try:
            PROCESS_FILE.write_text(probe_process)
            VALIDATE_FILE.write_text(probe_validate)
            os.chmod(PROCESS_FILE, process_mode)
            os.chmod(VALIDATE_FILE, validate_mode)
            OUTPUT_FILE.unlink(missing_ok=True)

            poisoned_env = os.environ.copy()
            poisoned_env['REPORT_YEAR'] = '1901'
            poisoned_env['REPORT_MONTH'] = '2'
            run_build(poisoned_env)

            assert process_marker.is_file(), 'build.sh did not execute process_data.py'
            assert validate_marker.is_file(), 'build.sh did not execute validate.py'
            observed = json.loads(process_marker.read_text())
            assert observed == {'year': 2023, 'month': 10}, (
                f"build.sh passed the wrong reporting environment: {observed}"
            )
        finally:
            PROCESS_FILE.write_bytes(original_process)
            VALIDATE_FILE.write_bytes(original_validate)
            os.chmod(PROCESS_FILE, process_mode)
            os.chmod(VALIDATE_FILE, validate_mode)
            OUTPUT_FILE.unlink(missing_ok=True)

    # Execute the real, restored pipeline so output.json must be generated by the submission.
    run_build(os.environ.copy())


def test_output_file_exists():
    """Verify that the output.json file was generated."""
    assert os.path.isfile(OUTPUT_FILE), f"Expected output file {OUTPUT_FILE} is missing. Did the build script run successfully?"


def test_output_file_contents():
    """Keep the original exact final-state assertions."""
    assert os.path.isfile(OUTPUT_FILE), 'Cannot check contents because output.json is missing.'

    with open(OUTPUT_FILE, 'r') as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f'{OUTPUT_FILE} is not a valid JSON file.')

    assert 'year' in data, "Key 'year' is missing from output.json"
    assert data['year'] == 2023, f"Expected year 2023, but got {data['year']}. The environment variable REPORT_YEAR might still be misconfigured in build.sh."

    assert 'month' in data, "Key 'month' is missing from output.json"
    assert data['month'] == 10, f"Expected month 10, but got {data['month']}."

    assert 'total' in data, "Key 'total' is missing from output.json"
    actual_total = data['total']
    expected_total = 168.0

    if actual_total < expected_total:
        pytest.fail(f'Expected total {expected_total}, but got {actual_total}. This indicates the SQL query boundary conditions (days 1 and 31) are still missing.')
    elif actual_total != expected_total:
        pytest.fail(f'Expected exact total {expected_total}, but got {actual_total}. Precision loss detected or incorrect row count. Ensure you use math.fsum or Decimal for aggregation.')


def test_process_data_on_derived_inputs():
    """Exercise the submitted processor on an independent database with hidden parameters."""
    with tempfile.TemporaryDirectory() as temp_dir:
        work = Path(temp_dir)
        shutil.copy2(PROCESS_FILE, work / 'process_data.py')

        year = 2030 + secrets.randbelow(500)
        month = 1 + secrets.randbelow(12)

        # Select a case where ordinary sequential addition differs from math.fsum.
        while True:
            count = 10 + secrets.randbelow(21)
            amount = secrets.choice([0.1, 0.2, 0.3])
            values = [amount] * count
            naive = 0.0
            for value in values:
                naive += value
            expected_total = math.fsum(values)
            if naive != expected_total:
                break

        db = sqlite3.connect(work / 'data.db')
        db.execute('CREATE TABLE transactions (id INTEGER PRIMARY KEY, year INTEGER, month INTEGER, day INTEGER, amount REAL)')

        # Include both required boundary days, with remaining selected rows inside them.
        days = [1, 31] + [2 + (i % 29) for i in range(count - 2)]
        for day, value in zip(days, values):
            db.execute(
                'INSERT INTO transactions (year, month, day, amount) VALUES (?, ?, ?, ?)',
                (year, month, day, value),
            )

        # These rows must be excluded by year, month, or day boundaries.
        decoys = [
            (year - 1, month, 1, 9000.0),
            (year, 1 + (month % 12), 31, 8000.0),
            (year, month, 0, 7000.0),
            (year, month, 32, 6000.0),
        ]
        db.executemany(
            'INSERT INTO transactions (year, month, day, amount) VALUES (?, ?, ?, ?)',
            decoys,
        )
        db.commit()
        db.close()

        env = os.environ.copy()
        env['REPORT_YEAR'] = str(year)
        env['REPORT_MONTH'] = str(month)
        result = subprocess.run(
            ['python3', 'process_data.py'],
            cwd=work,
            env=env,
            text=True,
            capture_output=True,
            timeout=30,
        )
        assert result.returncode == 0, (
            f"process_data.py failed on an independent database.\n"
            f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )

        generated = work / 'output.json'
        assert generated.is_file(), 'process_data.py did not generate output.json'
        try:
            data = json.loads(generated.read_text())
        except json.JSONDecodeError as exc:
            pytest.fail(f'Generated output.json is invalid JSON: {exc}')

        assert data.get('year') == year, 'process_data.py did not use REPORT_YEAR'
        assert data.get('month') == month, 'process_data.py did not use REPORT_MONTH'
        assert data.get('total') == expected_total, (
            f"Expected exact derived total {expected_total}, got {data.get('total')}. "
            'Check day 1/day 31 inclusion and precision-safe aggregation.'
        )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
