#!/bin/bash
mkdir -p /logs/verifier

cat <<'PYTEST_EOF' > /tmp/test_final_state.py
import difflib
import json
import os
import secrets
import signal
import subprocess
import textwrap
import time

import pytest

PROJECT = "/home/user/project_files"
SERVER = "/home/user/ws_server"
CLIENT = "/home/user/patch_client"


def run(cmd, cwd=None, timeout=180):
    return subprocess.run(
        cmd,
        cwd=cwd,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=timeout,
        check=True,
    )


def test_complete_implementation_and_pipeline():
    # Preserve the original final-state assertion.
    output_path = os.path.join(PROJECT, "config_fixed.json")
    assert os.path.isfile(output_path), (
        f"The output file was not created at {output_path}. Did the Rust client "
        "run successfully and save the output?"
    )
    try:
        with open(output_path, encoding="utf-8") as f:
            data = json.load(f)
    except json.JSONDecodeError:
        pytest.fail(f"The file {output_path} does not contain valid JSON.")

    expected_data = {
        "version": "1.0",
        "name": "organized_project",
        "files": ["new_file1.txt", "new_file2.txt"],
    }
    assert data == expected_data, (
        f"The patched content in {output_path} does not match the expected output. "
        "Make sure the Rust client applies the diff correctly."
    )

    assert os.path.isfile(os.path.join(SERVER, "main.go"))
    assert os.path.isfile(os.path.join(CLIENT, "src", "patcher.rs"))

    # Run the project's required property test.
    result = run(["cargo", "test", "--quiet"], cwd=CLIENT)
    assert "test result: ok" in result.stdout, result.stdout

    # Add an independent, verifier-generated test so editable in-source tests cannot
    # be deleted or weakened to conceal an unimplemented apply_diff.
    token = secrets.token_hex(8)
    tests_dir = os.path.join(CLIENT, "tests")
    os.makedirs(tests_dir, exist_ok=True)
    verifier_test = os.path.join(tests_dir, "verifier_apply_diff.rs")
    with open(verifier_test, "w", encoding="utf-8") as f:
        f.write(textwrap.dedent(f'''\
            #[path = "../src/patcher.rs"]
            mod patcher;

            #[test]
            fn applies_verifier_generated_diffs() {{
                let cases = [
                    ("alpha\\nbeta\\n", "alpha\\ngamma\\ndelta\\n"),
                    ("start-{token}\\nold value\\nend\\n",
                     "start-{token}\\nnew value\\nextra-{token}\\nend\\n"),
                    ("one line", "completely different"),
                ];
                for (original, modified) in cases {{
                    let patch = diffy::create_patch(original, modified).to_string();
                    assert_eq!(patcher::apply_diff(original, &patch), modified);
                }}
            }}
        '''))
    try:
        run(["cargo", "test", "--quiet", "--test", "verifier_apply_diff"], cwd=CLIENT)
    finally:
        try:
            os.remove(verifier_test)
        except FileNotFoundError:
            pass

    # Exercise the actual server and client on fresh content whose answer is
    # generated by the verifier rather than copied from the advertised example.
    original_obj = {
        "version": token,
        "name": "before_" + token,
        "files": ["old_" + token + ".txt"],
    }
    patched_obj = {
        "version": token,
        "name": "after_" + token,
        "files": ["new_a_" + token + ".txt", "new_b_" + token + ".txt"],
    }
    original = json.dumps(original_obj, indent=2) + "\n"
    expected = json.dumps(patched_obj, indent=2) + "\n"
    patch = "".join(difflib.unified_diff(
        original.splitlines(keepends=True),
        expected.splitlines(keepends=True),
        fromfile="config.json",
        tofile="config.json",
    ))

    with open(os.path.join(PROJECT, "config.json"), "w", encoding="utf-8") as f:
        f.write(original)
    with open(os.path.join(SERVER, "patch.diff"), "w", encoding="utf-8") as f:
        f.write(patch)
    try:
        os.remove(output_path)
    except FileNotFoundError:
        pass

    # This probe independently confirms that the Go program binds and sends the
    # exact patch over a WebSocket, rather than merely allowing a hardcoded client.
    probe_path = "/tmp/verifier_ws_probe.go"
    with open(probe_path, "w", encoding="utf-8") as f:
        f.write(r'''package main
import (
    "fmt"
    "os"
    "time"
    "github.com/gorilla/websocket"
)
func main() {
    want, err := os.ReadFile(os.Args[1])
    if err != nil { panic(err) }
    var conn *websocket.Conn
    for deadline := time.Now().Add(20*time.Second); time.Now().Before(deadline); {
        conn, _, err = websocket.DefaultDialer.Dial("ws://127.0.0.1:8080/", nil)
        if err == nil { break }
        time.Sleep(200*time.Millisecond)
    }
    if err != nil { panic(err) }
    defer conn.Close()
    conn.SetReadDeadline(time.Now().Add(10*time.Second))
    kind, got, err := conn.ReadMessage()
    if err != nil { panic(err) }
    if kind != websocket.TextMessage || string(got) != string(want) {
        panic(fmt.Sprintf("unexpected websocket message type/content"))
    }
}
''')

    server = subprocess.Popen(
        ["go", "run", "."],
        cwd=SERVER,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        start_new_session=True,
    )
    try:
        run(["go", "run", probe_path, os.path.join(SERVER, "patch.diff")], cwd=SERVER, timeout=90)
        run(["cargo", "run", "--quiet"], cwd=CLIENT, timeout=180)
    finally:
        try:
            os.killpg(server.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        try:
            server.wait(timeout=10)
        except subprocess.TimeoutExpired:
            try:
                os.killpg(server.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            server.wait(timeout=10)

    assert os.path.isfile(output_path), "Rust client did not create config_fixed.json"
    with open(output_path, encoding="utf-8") as f:
        actual_text = f.read()
    assert actual_text == expected, "The live pipeline did not apply the generated unified diff"
    assert json.loads(actual_text) == patched_obj
PYTEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
