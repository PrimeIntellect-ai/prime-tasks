#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import math
import os
import re
import subprocess
import pytest

SOURCE = "/home/user/analyze.c"
TRACE = "/home/user/trace.txt"
RESULTS = "/home/user/results.txt"
BINARY = "/tmp/analyze_submission"

FIXED_TRACE = [106.5, 103.2, 108.1, 104.5, 107.8, 102.1, 109.3, 105.4, 106.9, 108.2]
HIDDEN_TRACE = [108.0, 112.0, 109.0, 111.0, 107.0, 113.0, 110.0, 114.0, 106.0, 110.0]

OUTPUT_RE = re.compile(
    r"\AAnalytical Mean: ([+-]?\d+\.\d{4})\n"
    r"Analytical Variance: ([+-]?\d+\.\d{4})\n"
    r"MCMC Mean: ([+-]?\d+\.\d{4})\n"
    r"MCMC Variance: ([+-]?\d+\.\d{4})\n"
    r"P\(mu > 105\): ([+-]?\d+\.\d{4})\n?\Z"
)


def expected_posterior(values):
    precision = len(values) / (10.0 ** 2) + 1.0 / (20.0 ** 2)
    variance = 1.0 / precision
    mean = (sum(values) / (10.0 ** 2) + 100.0 / (20.0 ** 2)) / precision
    probability = 0.5 * math.erfc((105.0 - mean) / math.sqrt(2.0 * variance))
    return mean, variance, probability


def write_trace(values):
    with open(TRACE, "w") as f:
        for value in values:
            f.write(f"{value:.1f}\n")


def run_program(values):
    write_trace(values)
    if os.path.exists(RESULTS):
        os.remove(RESULTS)

    completed = subprocess.run(
        [BINARY], cwd="/home/user", stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, text=True, timeout=30
    )
    assert completed.returncode == 0, (
        f"analyze exited with status {completed.returncode}. stderr: {completed.stderr}"
    )
    assert os.path.isfile(RESULTS), "Executing analyze did not create /home/user/results.txt"

    with open(RESULTS, "r") as f:
        content = f.read()
    match = OUTPUT_RE.fullmatch(content)
    assert match is not None, "results.txt does not have exactly the required five-line, four-decimal format"
    return tuple(float(value) for value in match.groups())


@pytest.fixture(scope="session", autouse=True)
def build_and_exercise_submission():
    assert os.path.isfile(SOURCE), f"C source file {SOURCE} does not exist"
    assert os.path.getsize(SOURCE) > 0, f"C source file {SOURCE} is empty"
    with open(SOURCE, "rb") as f:
        assert b"\x00" not in f.read(), "analyze.c is not a text C source file"

    assert os.path.isfile(TRACE), f"Trace file {TRACE} does not exist"
    with open(TRACE, "r") as f:
        initial_lines = [line.strip() for line in f if line.strip()]
    assert len(initial_lines) == 10, "trace.txt must contain exactly 10 non-empty lines"
    try:
        initial_values = [float(line) for line in initial_lines]
    except ValueError:
        pytest.fail("trace.txt contains a non-numeric execution time")
    assert initial_values == FIXED_TRACE, "trace.txt does not contain the required execution times"

    compiled = subprocess.run(
        ["gcc", "-O2", SOURCE, "-o", BINARY, "-lm"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=30
    )
    assert compiled.returncode == 0, f"analyze.c did not compile with gcc: {compiled.stderr}"
    assert os.path.isfile(BINARY) and os.access(BINARY, os.X_OK), "Compilation did not produce an executable"

    # Exercise the submitted executable on data not disclosed in the task. This
    # prevents a prewritten results.txt or five fixed reported values from passing.
    analytical_mean, analytical_var, mcmc_mean, mcmc_var, p_mu = run_program(HIDDEN_TRACE)
    expected_mean, expected_var, expected_p = expected_posterior(HIDDEN_TRACE)
    assert abs(analytical_mean - expected_mean) <= 0.00011, "Analytical mean does not respond correctly to trace data"
    assert abs(analytical_var - expected_var) <= 0.00011, "Analytical variance is incorrect on the validation trace"
    assert abs(mcmc_mean - expected_mean) <= 0.30, "MCMC mean is inconsistent with the hidden posterior"
    assert abs(mcmc_var - expected_var) <= 1.25, "MCMC variance is inconsistent with the hidden posterior"
    assert abs(p_mu - expected_p) <= 0.04, "MCMC hypothesis probability is inconsistent with the hidden posterior"
    assert 0.0 <= p_mu <= 1.0, "Reported probability is outside [0, 1]"

    # Restore the required trace and leave results.txt generated by the program
    # for the original assertions below.
    run_program(FIXED_TRACE)
    yield


def test_results_file_exists():
    """Check that the results file exists."""
    results_file = "/home/user/results.txt"
    assert os.path.isfile(results_file), f"Results file {results_file} does not exist."


def test_results_content():
    """Check the contents of the results file for correct analytical and MCMC values."""
    results_file = "/home/user/results.txt"
    assert os.path.isfile(results_file), "Results file missing."

    with open(results_file, "r") as f:
        content = f.read()

    match = re.search(r"Analytical Mean:\s*([0-9\.]+)", content)
    assert match is not None, "Could not find 'Analytical Mean:' in results.txt"
    analytical_mean = float(match.group(1))
    assert abs(analytical_mean - 106.0488) < 1e-4, f"Analytical Mean incorrect. Expected ~106.0488, got {analytical_mean}"

    match = re.search(r"Analytical Variance:\s*([0-9\.]+)", content)
    assert match is not None, "Could not find 'Analytical Variance:' in results.txt"
    analytical_var = float(match.group(1))
    assert abs(analytical_var - 9.7561) < 1e-4, f"Analytical Variance incorrect. Expected ~9.7561, got {analytical_var}"

    match = re.search(r"MCMC Mean:\s*([0-9\.]+)", content)
    assert match is not None, "Could not find 'MCMC Mean:' in results.txt"
    mcmc_mean = float(match.group(1))
    assert 105.9 <= mcmc_mean <= 106.2, f"MCMC Mean {mcmc_mean} is out of expected range [105.9, 106.2]"

    match = re.search(r"MCMC Variance:\s*([0-9\.]+)", content)
    assert match is not None, "Could not find 'MCMC Variance:' in results.txt"
    mcmc_var = float(match.group(1))
    assert 9.2 <= mcmc_var <= 10.3, f"MCMC Variance {mcmc_var} is out of expected range [9.2, 10.3]"

    match = re.search(r"P\(mu > 105\):\s*([0-9\.]+)", content)
    assert match is not None, "Could not find 'P(mu > 105):' in results.txt"
    p_mu = float(match.group(1))
    assert 0.6000 <= p_mu <= 0.6600, f"P(mu > 105) {p_mu} is out of expected range [0.6000, 0.6600]"
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
