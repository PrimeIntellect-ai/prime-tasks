#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import secrets
import subprocess
from fractions import Fraction

SCRIPT_PATH = "/home/user/pipeline.sh"
RAW_PATH = "/home/user/raw_logs.csv"
OUTPUT_PATH = "/home/user/posteriors.csv"


def write_raw(lines):
    with open(RAW_PATH, "w", newline="") as f:
        f.write("server_id,requests,errors\n")
        f.write("\n".join(lines))
        f.write("\n")


def run_pipeline():
    if os.path.exists(OUTPUT_PATH):
        os.remove(OUTPUT_PATH)
    result = subprocess.run(
        [SCRIPT_PATH],
        cwd="/home/user",
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=15,
    )
    assert result.returncode == 0, (
        f"Fail: pipeline exited with status {result.returncode}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    assert os.path.isfile(OUTPUT_PATH), (
        f"Fail: {OUTPUT_PATH} was not generated by the pipeline"
    )


def formatted_rate(requests, errors):
    numerator = errors + 2
    denominator = requests + 12
    whole, remainder = divmod(numerator * 10000, denominator)
    assert remainder * 2 != denominator  # Generated tests avoid ambiguous half ties.
    if remainder * 2 > denominator:
        whole += 1
    return f"{whole // 10000}.{whole % 10000:04d}"


def expected_output(rows):
    ordered = sorted(
        rows,
        key=lambda row: (-Fraction(row[2] + 2, row[1] + 12), row[0]),
    )
    return "\n".join(
        f"{server_id},{formatted_rate(requests, errors)}"
        for server_id, requests, errors in ordered
    )


def test_pipeline_script_exists_and_executable():
    assert os.path.isfile(SCRIPT_PATH), f"Fail: {SCRIPT_PATH} not found"
    assert os.access(SCRIPT_PATH, os.X_OK), f"Fail: {SCRIPT_PATH} is not executable"
    with open(SCRIPT_PATH, "rb") as f:
        first_line = f.readline().decode("utf-8", errors="replace").strip()
    assert first_line in ("#!/bin/bash", "#!/usr/bin/bash", "#!/usr/bin/env bash"), (
        "Fail: pipeline.sh must be an executable Bash script"
    )


def test_posteriors_csv_exists_and_correct():
    write_raw([
        "srv_01,100,5",
        "srv_02,50,0",
        "srv_03,-10,5",
        "srv_04,20,25",
        "srv_05,0,0",
        "srv_06,200,15",
        "srv_07,,",
        "srv_08,abc,def",
        "srv_09,500,20",
        "srv_10,100,5",
    ])
    run_pipeline()

    expected_content = (
        "srv_06,0.0802\n"
        "srv_01,0.0625\n"
        "srv_10,0.0625\n"
        "srv_09,0.0430\n"
        "srv_02,0.0323"
    )

    with open(OUTPUT_PATH, "r") as f:
        actual_content = f.read().strip()

    assert actual_content == expected_content, (
        f"Fail: Content of {OUTPUT_PATH} does not match expected output.\n"
        f"Expected:\n{expected_content}\n\nActual:\n{actual_content}"
    )


def test_pipeline_on_fresh_unpredictable_input():
    rng = secrets.SystemRandom()
    valid_rows = [
        ("tie_alpha", 100, 5),
        ("tie_zulu", 100, 5),
        ("edge_zero_errors", 1, 0),
        ("edge_all_errors", 17, 17),
    ]

    used_rates = {Fraction(e + 2, r + 12) for _, r, e in valid_rows}
    used_rounded = {formatted_rate(r, e) for _, r, e in valid_rows}
    index = 0
    while len(valid_rows) < 18:
        requests = rng.randrange(1, 2001)
        errors = rng.randrange(0, requests + 1)
        rate = Fraction(errors + 2, requests + 12)
        scaled_remainder = ((errors + 2) * 10000) % (requests + 12)
        if scaled_remainder * 2 == requests + 12:
            continue
        rounded = formatted_rate(requests, errors)
        if rate in used_rates or rounded in used_rounded:
            continue
        valid_rows.append((f"random_{index:02d}", requests, errors))
        used_rates.add(rate)
        used_rounded.add(rounded)
        index += 1

    input_lines = [f"{sid},{requests},{errors}" for sid, requests, errors in valid_rows]
    input_lines.extend([
        "bad_missing_request,,3",
        "bad_missing_error,20,",
        "bad_text_request,not_a_number,2",
        "bad_text_error,20,not_a_number",
        "bad_partial_request,12x,2",
        "bad_partial_error,20,3x",
        "bad_zero_requests,0,0",
        "bad_negative_requests,-1,0",
        "bad_negative_errors,20,-1",
        "bad_too_many_errors,20,21",
    ])
    rng.shuffle(input_lines)
    write_raw(input_lines)
    run_pipeline()

    expected = expected_output(valid_rows)
    with open(OUTPUT_PATH, "r") as f:
        actual = f.read().strip()

    assert actual == expected, (
        "Fail: pipeline did not correctly clean, calculate, format, or sort a fresh dataset.\n"
        f"Expected:\n{expected}\n\nActual:\n{actual}"
    )
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
