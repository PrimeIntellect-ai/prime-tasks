set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import csv
import json
import math
import os
import re
import subprocess

HOME = "/home/user"
DATASET = os.path.join(HOME, "dataset.csv")
RESULTS = os.path.join(HOME, "results.json")
SOLVER = os.path.join(HOME, "solver.go")
DATAGEN = os.path.join(HOME, "datagen")


def run(cmd, timeout=90):
    proc = subprocess.run(cmd, cwd=HOME, text=True, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, timeout=timeout)
    assert proc.returncode == 0, f"Command failed ({' '.join(cmd)}):\n{proc.stdout}"
    return proc.stdout


def read_results():
    assert os.path.isfile(RESULTS), f"Missing file: {RESULTS}"
    with open(RESULTS, "r") as f:
        try:
            results = json.load(f)
        except json.JSONDecodeError as exc:
            assert False, f"{RESULTS} is not valid JSON: {exc}"
    for key in ("beta0", "beta1", "beta2", "f_stat"):
        assert key in results, f"Key '{key}' missing in {RESULTS}"
        assert isinstance(results[key], (int, float)) and not isinstance(results[key], bool), \
            f"Value for '{key}' must be a number."
        assert math.isfinite(results[key]), f"Value for '{key}' must be finite."
    return results


def derive_ols(path):
    rows = []
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        assert reader.fieldnames == ["y", "x1", "x2"], "dataset.csv must have columns y,x1,x2"
        for row in reader:
            rows.append((float(row["y"]), float(row["x1"]), float(row["x2"])))
    assert len(rows) > 3

    xtx = [[0.0] * 3 for _ in range(3)]
    xty = [0.0] * 3
    for y, x1, x2 in rows:
        x = (1.0, x1, x2)
        for i in range(3):
            xty[i] += x[i] * y
            for j in range(3):
                xtx[i][j] += x[i] * x[j]

    # Independently solve the normal equations by Cholesky decomposition.
    L = [[0.0] * 3 for _ in range(3)]
    for i in range(3):
        for j in range(i + 1):
            s = xtx[i][j] - sum(L[i][k] * L[j][k] for k in range(j))
            if i == j:
                assert s > 0, "Test dataset produced a non-positive-definite X^T X"
                L[i][j] = math.sqrt(s)
            else:
                L[i][j] = s / L[j][j]
    z = [0.0] * 3
    for i in range(3):
        z[i] = (xty[i] - sum(L[i][k] * z[k] for k in range(i))) / L[i][i]
    beta = [0.0] * 3
    for i in range(2, -1, -1):
        beta[i] = (z[i] - sum(L[k][i] * beta[k] for k in range(i + 1, 3))) / L[i][i]

    mean_y = sum(r[0] for r in rows) / len(rows)
    ss_tot = sum((r[0] - mean_y) ** 2 for r in rows)
    ss_res = sum((r[0] - (beta[0] + beta[1] * r[1] + beta[2] * r[2])) ** 2 for r in rows)
    f_stat = ((ss_tot - ss_res) / 2.0) / (ss_res / (len(rows) - 3))
    return {"beta0": beta[0], "beta1": beta[1], "beta2": beta[2], "f_stat": f_stat}


def assert_rounded_results(actual, expected):
    for key in ("beta0", "beta1", "beta2", "f_stat"):
        wanted = round(expected[key] + 0.0, 4)
        assert math.isclose(actual[key], wanted, rel_tol=0.0, abs_tol=0.00011), \
            f"Value for '{key}' is {actual[key]}, expected computed value {wanted:.4f}"


def strip_go_comments(source):
    # Preserve quoted strings while removing comments, so keywords in comments
    # cannot satisfy the structural Cholesky checks below.
    out = []
    i = 0
    quote = None
    while i < len(source):
        c = source[i]
        if quote is not None:
            out.append(c)
            if quote != '`' and c == '\\' and i + 1 < len(source):
                out.append(source[i + 1])
                i += 2
                continue
            if c == quote:
                quote = None
            i += 1
            continue
        if c in ('"', "'", '`'):
            quote = c
            out.append(c)
            i += 1
        elif source.startswith("//", i):
            end = source.find("\n", i)
            if end < 0:
                break
            out.append("\n")
            i = end + 1
        elif source.startswith("/*", i):
            end = source.find("*/", i + 2)
            assert end >= 0, "Unterminated block comment in solver.go"
            out.append("\n" * source[i:end + 2].count("\n"))
            i = end + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def test_dataset_csv_exists():
    """Test that dataset.csv was generated by an executable datagen."""
    assert os.path.isfile(DATAGEN), f"Missing executable: {DATAGEN}. Did you compile datagen.c?"
    assert os.access(DATAGEN, os.X_OK), f"{DATAGEN} is not executable"
    with open(DATAGEN, "rb") as f:
        assert f.read(4) == b"\x7fELF", "datagen must be a compiled native executable"

    run([DATAGEN])
    assert os.path.isfile(DATASET), f"Missing file: {DATASET}. Did you run datagen?"
    with open(DATASET, newline="") as f:
        rows = list(csv.reader(f))
    assert rows[0] == ["y", "x1", "x2"] and len(rows) == 101, "datagen produced an unexpected dataset"
    for i, row in enumerate(rows[1:]):
        y, x1, x2 = map(float, row)
        expected_x1 = i * 0.1
        expected_x2 = (i % 10) * 0.5
        noise = 0.1 if i % 3 == 0 else -0.1
        expected_y = 2.5 - 1.5 * expected_x1 + 3.0 * expected_x2 + noise
        assert math.isclose(x1, expected_x1, abs_tol=0.00005)
        assert math.isclose(x2, expected_x2, abs_tol=0.00005)
        assert math.isclose(y, expected_y, abs_tol=0.00005)


def test_solver_go_exists_and_uses_cholesky():
    """Test that solver.go compiles and contains actual Gonum Cholesky operations."""
    assert os.path.isfile(SOLVER), f"Missing file: {SOLVER}"
    with open(SOLVER, "r") as f:
        content = f.read()

    # Preserve the original assertions.
    assert "Cholesky" in content, "solver.go does not seem to use Cholesky decomposition as required."
    assert "gonum.org/v1/gonum/mat" in content, "solver.go does not import gonum.org/v1/gonum/mat."

    code = strip_go_comments(content)
    declarations = re.findall(r"\bvar\s+([A-Za-z_]\w*)\s+\*?\s*mat\.Cholesky\b", code)
    declarations += re.findall(r"\b([A-Za-z_]\w*)\s*:=\s*(?:&\s*)?(?:new\s*\(\s*)?mat\.Cholesky", code)
    assert declarations, "solver.go must instantiate a gonum mat.Cholesky value in executable Go code"
    assert any(re.search(r"\b" + re.escape(name) + r"\s*\.\s*Factorize\s*\(", code)
               for name in declarations), "solver.go must call Factorize on its Cholesky value"
    assert any(re.search(r"\b" + re.escape(name) + r"\s*\.\s*Solve(?:Vec)?To\s*\(", code)
               for name in declarations), "solver.go must solve the normal equations using the Cholesky factorization"

    go_mod = os.path.join(HOME, "go.mod")
    assert os.path.isfile(go_mod), "Missing /home/user/go.mod; initialize the solver module"
    with open(go_mod) as f:
        assert re.search(r"(?m)^module\s+solver\s*$", f.read()), "go.mod must declare module solver"

    run(["go", "run", SOLVER])


def test_results_json_values():
    """Preserve the fixed canonical-result assertions from the original verifier."""
    results = read_results()
    expected_values = {
        "beta0": 2.4667,
        "beta1": -1.5000,
        "beta2": 3.0000,
        "f_stat": 166724.8148
    }
    for key, expected_val in expected_values.items():
        assert math.isclose(results[key], expected_val, abs_tol=0.001), \
            f"Value for '{key}' is {results[key]}, expected approximately {expected_val}"


def test_solver_computes_from_dataset():
    """Exercise solver.go on an unseen dataset and derive the expected answers."""
    with open(DATASET, "rb") as f:
        original = f.read()
    try:
        with open(DATASET, "w", newline="") as f:
            writer = csv.writer(f, lineterminator="\n")
            writer.writerow(["y", "x1", "x2"])
            for i in range(120):
                x1 = i * 0.073 + (i % 4) * 0.011
                x2 = ((i * 7) % 17) * 0.27 + (i % 5) * 0.013
                noise = (0.07, -0.06, 0.03, -0.04, 0.01)[i % 5]
                y = 2.5 - 1.5 * x1 + 3.0 * x2 + noise
                writer.writerow([f"{y:.4f}", f"{x1:.4f}", f"{x2:.4f}"])
        expected = derive_ols(DATASET)
        run(["go", "run", SOLVER])
        assert_rounded_results(read_results(), expected)
    finally:
        with open(DATASET, "wb") as f:
            f.write(original)
        # Leave the requested canonical final output in place.
        run(["go", "run", SOLVER])

TEST_EOF

