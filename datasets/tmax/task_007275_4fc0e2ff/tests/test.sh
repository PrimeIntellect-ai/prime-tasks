#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import hashlib
import json
import os
import queue
import secrets
import socket
import stat
import subprocess
import tempfile
import threading
import time

SOURCE_DIR = "/home/user/source"
BARE_REPO = "/home/user/app.git"
HOOK = "/home/user/app.git/hooks/post-receive"
NOTIFY = "/home/user/notify.go"
MAIL_DIR = "/home/user/mail"


def expected_email(commit_hash):
    return f"To: dev@local\nSubject: Update rolled out\n\nCommit: {commit_hash}"


def assert_email(commit_hash):
    eml_file = f"{MAIL_DIR}/deployed_{commit_hash}.eml"
    assert os.path.exists(eml_file), f"Fail: Expected notification file {eml_file} does not exist."
    with open(eml_file, "r") as f:
        actual_content = f.read().strip()
    expected_content = expected_email(commit_hash)
    assert actual_content == expected_content, (
        "Fail: File content does not match expected output.\n"
        f"Expected:\n{expected_content}\nActual:\n{actual_content}"
    )


def test_git_commit_and_push():
    result = subprocess.run(
        ["git", "log", "-1", "--pretty=%B"],
        cwd=SOURCE_DIR,
        capture_output=True,
        text=True
    )
    assert result.returncode == 0, "Fail: Could not get git log."
    latest_msg = result.stdout.strip()
    assert latest_msg == "Trigger rollout", (
        "Fail: The latest commit message is not 'Trigger rollout'. "
        f"Found: '{latest_msg}'"
    )

    result_bare = subprocess.run(
        ["git", "rev-parse", "main"],
        cwd=BARE_REPO,
        capture_output=True,
        text=True
    )
    assert result_bare.returncode == 0, (
        "Fail: 'main' branch not found in bare repository. Push may have failed."
    )
    bare_hash = result_bare.stdout.strip()

    result_local = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=SOURCE_DIR,
        capture_output=True,
        text=True
    )
    assert result_local.returncode == 0, "Fail: Could not resolve local HEAD."
    local_hash = result_local.stdout.strip()
    assert bare_hash == local_hash, (
        "Fail: The latest commit in source was not pushed to app.git."
    )


def test_email_notification_file():
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=SOURCE_DIR,
        capture_output=True,
        text=True
    )
    assert result.returncode == 0, "Fail: Could not get git HEAD hash."
    assert_email(result.stdout.strip())


def test_notify_program_and_hook_behavior():
    assert os.path.isfile(NOTIFY), f"Fail: {NOTIFY} does not exist or is not a regular file."
    assert os.path.isfile(HOOK), f"Fail: {HOOK} does not exist or is not a regular file."
    hook_mode = os.stat(HOOK).st_mode
    assert stat.S_ISREG(hook_mode), f"Fail: {HOOK} is not a regular file."
    assert hook_mode & 0o111, f"Fail: {HOOK} is not executable."

    # Compile and execute the submitted Go program on a verifier-generated hash.
    direct_hash = secrets.token_hex(20)
    direct_mail = f"{MAIL_DIR}/deployed_{direct_hash}.eml"
    if os.path.exists(direct_mail):
        os.remove(direct_mail)

    with tempfile.TemporaryDirectory() as td:
        binary = os.path.join(td, "notify")
        built = subprocess.run(
            ["go", "build", "-o", binary, NOTIFY],
            capture_output=True,
            text=True,
            timeout=60
        )
        assert built.returncode == 0, f"Fail: {NOTIFY} is not a valid Go program: {built.stderr}"
        ran = subprocess.run(
            [binary, direct_hash],
            capture_output=True,
            text=True,
            timeout=15
        )
        assert ran.returncode == 0, f"Fail: compiled notify program failed: {ran.stderr}"
    assert_email(direct_hash)

    # Exercise the real hook with an unpredictable receive line and require the
    # notification to be generated by that invocation.
    hook_hash = secrets.token_hex(20)
    hook_mail = f"{MAIL_DIR}/deployed_{hook_hash}.eml"
    if os.path.exists(hook_mail):
        os.remove(hook_mail)
    hook_run = subprocess.run(
        [HOOK],
        cwd=BARE_REPO,
        input=f"{'0' * 40} {hook_hash} refs/heads/verifier-test\n",
        capture_output=True,
        text=True,
        timeout=60
    )
    assert hook_run.returncode == 0, f"Fail: post-receive hook failed: {hook_run.stderr}"
    assert_email(hook_hash)

    # Instrument the required Go source temporarily to verify that the hook
    # actually executes /home/user/notify.go and passes the received new hash.
    marker = f"/tmp/hook_notify_marker_{secrets.token_hex(12)}"
    probe_hash = secrets.token_hex(20)
    with open(NOTIFY, "rb") as f:
        original_source = f.read()
    original_mode = stat.S_IMODE(os.stat(NOTIFY).st_mode)
    probe_source = f'''package main
import "os"
func main() {{
    if len(os.Args) < 2 {{ os.Exit(2) }}
    if err := os.WriteFile({json.dumps(marker)}, []byte(os.Args[1]), 0600); err != nil {{ os.Exit(3) }}
}}
'''
    try:
        with open(NOTIFY, "w") as f:
            f.write(probe_source)
        os.chmod(NOTIFY, original_mode)
        probe_run = subprocess.run(
            [HOOK],
            cwd=BARE_REPO,
            input=f"{'0' * 40} {probe_hash} refs/heads/verifier-probe\n",
            capture_output=True,
            text=True,
            timeout=60
        )
        assert probe_run.returncode == 0, f"Fail: hook could not execute notify.go: {probe_run.stderr}"
        assert os.path.isfile(marker), (
            "Fail: post-receive hook did not execute /home/user/notify.go."
        )
        with open(marker, "r") as f:
            received_arg = f.read()
        assert received_arg == probe_hash, (
            "Fail: post-receive hook did not pass the received new commit hash "
            "as notify.go's first argument."
        )
    finally:
        with open(NOTIFY, "wb") as f:
            f.write(original_source)
        os.chmod(NOTIFY, original_mode)
        try:
            os.remove(marker)
        except FileNotFoundError:
            pass


def test_socat_port_forwarding():
    pid_file = "/home/user/port_forward.pid"
    assert os.path.exists(pid_file), f"Fail: {pid_file} does not exist."

    with open(pid_file, "r") as f:
        pid = f.read().strip()
    assert pid.isdigit(), f"Fail: PID in {pid_file} is not a valid integer."

    try:
        result = subprocess.run(
            ["ps", "-p", pid, "-o", "args="],
            capture_output=True,
            text=True,
            check=True
        )
        cmdline = result.stdout.strip()
    except subprocess.CalledProcessError:
        assert False, f"Fail: Process {pid} is not running."

    assert "socat" in cmdline, f"Fail: Process {pid} is not socat. Command line: {cmdline}"
    assert "8080" in cmdline and "9090" in cmdline, (
        "Fail: socat is not configured with the correct ports (8080 -> 9090). "
        f"Command line: {cmdline}"
    )

    payload = secrets.token_bytes(48)
    response = hashlib.sha256(payload).digest()
    observed = queue.Queue()
    ready = threading.Event()

    def backend():
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
                listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                listener.bind(("127.0.0.1", 9090))
                listener.listen(1)
                listener.settimeout(8)
                ready.set()
                conn, _ = listener.accept()
                with conn:
                    conn.settimeout(5)
                    data = b""
                    while len(data) < len(payload):
                        chunk = conn.recv(len(payload) - len(data))
                        if not chunk:
                            break
                        data += chunk
                    observed.put(("data", data))
                    conn.sendall(response)
        except Exception as exc:
            observed.put(("error", repr(exc)))
            ready.set()

    thread = threading.Thread(target=backend, daemon=True)
    thread.start()
    assert ready.wait(3), "Fail: verifier backend on port 9090 did not start."

    received = b""
    last_error = None
    for _ in range(20):
        try:
            with socket.create_connection(("127.0.0.1", 8080), timeout=1) as client:
                client.settimeout(5)
                client.sendall(payload)
                while len(received) < len(response):
                    chunk = client.recv(len(response) - len(received))
                    if not chunk:
                        break
                    received += chunk
            last_error = None
            break
        except OSError as exc:
            last_error = exc
            time.sleep(0.1)

    assert last_error is None, f"Fail: could not connect through port 8080: {last_error}"
    thread.join(8)
    assert not thread.is_alive(), "Fail: traffic sent to port 8080 did not reach port 9090."
    kind, value = observed.get_nowait()
    assert kind == "data", f"Fail: verifier backend failed: {value}"
    assert value == payload, "Fail: socat did not forward request bytes from 8080 to 9090."
    assert received == response, "Fail: socat did not forward response bytes from 9090 to 8080."
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
