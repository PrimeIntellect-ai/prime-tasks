#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import re
import secrets
import subprocess


def test_token_extracted_correctly():
    core_bin_path = "/home/user/core.bin"
    token_txt_path = "/home/user/token.txt"

    assert os.path.isfile(core_bin_path), f"File {core_bin_path} is missing."
    assert os.path.isfile(token_txt_path), f"File {token_txt_path} was not created."

    # Extract expected token from core.bin
    with open(core_bin_path, "rb") as f:
        core_data = f.read()

    match = re.search(b"SECRET_TOKEN=([a-zA-Z0-9-]+)", core_data)
    assert match is not None, "Could not find SECRET_TOKEN in core.bin."
    expected_token = match.group(1).decode("utf-8")

    with open(token_txt_path, "r", encoding="utf-8") as f:
        actual_token = f.read().strip()

    assert actual_token == expected_token, f"Token in {token_txt_path} is incorrect. Expected '{expected_token}', got '{actual_token}'."


def test_log_processor_executes_and_handles_corrupted_prefix():
    script_path = "/home/user/log_processor.sh"
    log_path = "/home/user/server.log"
    output_path = "/home/user/clean_logs.txt"

    assert os.path.isfile(script_path), f"File {script_path} is missing."
    assert os.access(script_path, os.X_OK), f"File {script_path} is not executable."

    with open(log_path, "rb") as f:
        original_log = f.read()

    marker = secrets.token_hex(16)
    input_lines = [
        f"INFO: dynamic-{marker}",
        f"@@CRITICAL: corrupted-{marker}",
        f"WARN: finished-{marker}",
    ]
    expected_lines = [
        input_lines[0],
        input_lines[1][2:],
        input_lines[2],
    ]

    try:
        with open(log_path, "w", encoding="utf-8") as f:
            f.write("\n".join(input_lines) + "\n")

        try:
            result = subprocess.run(
                [script_path],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                timeout=5,
            )
        except subprocess.TimeoutExpired:
            raise AssertionError(f"{script_path} did not complete; it may still recurse or loop forever.")

        assert result.returncode == 0, (
            f"{script_path} exited with status {result.returncode}. "
            f"stdout: {result.stdout!r}; stderr: {result.stderr!r}"
        )
        assert os.path.isfile(output_path), f"File {output_path} was not generated by the script."

        with open(output_path, "r", encoding="utf-8") as f:
            actual_lines = f.read().splitlines()
        assert actual_lines == expected_lines, (
            f"The executed script produced incorrect output for generated input. Got: {actual_lines}"
        )
    finally:
        with open(log_path, "wb") as f:
            f.write(original_log)

    # Run the repaired script on the original supplied log as required by the task.
    try:
        result = subprocess.run(
            [script_path],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=5,
        )
    except subprocess.TimeoutExpired:
        raise AssertionError(f"{script_path} did not complete on the supplied server.log.")

    assert result.returncode == 0, (
        f"{script_path} failed on the supplied server.log with status {result.returncode}. "
        f"stdout: {result.stdout!r}; stderr: {result.stderr!r}"
    )


def test_clean_logs_generated_correctly():
    clean_logs_path = "/home/user/clean_logs.txt"
    assert os.path.isfile(clean_logs_path), f"File {clean_logs_path} was not created."

    expected_logs = [
        "INFO: Service started",
        "WARN: High memory usage",
        "CRITICAL: Memory corruption detected",
        "INFO: Service stopping"
    ]

    with open(clean_logs_path, "r", encoding="utf-8") as f:
        actual_logs = [line.strip() for line in f if line.strip()]

    assert actual_logs == expected_logs, f"Logs in {clean_logs_path} do not match the expected output. Got: {actual_logs}"
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
