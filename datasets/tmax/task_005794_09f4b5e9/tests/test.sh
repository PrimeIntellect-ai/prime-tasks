PRIMER_TOOL = "/home/user/primer_tool.py"
PROFILE = "/home/user/profile_baseline.txt"
RESULT = "/home/user/result.json"


def test_profile_baseline_exists():
    assert os.path.exists(PROFILE), f"Baseline profile {PROFILE} was not created."

    with open(PROFILE, "r") as f:
        content = f.read()

    # Retain the original checks.
    assert "function calls" in content, "Profile output does not seem to be generated by cProfile."
    assert "evaluate_primer_loss" in content, "Profile output does not contain expected function traces."

    # A complete profile of the original implementation has 500 iterations with
    # four expensive evaluations each, and standard cProfile table headings.
    assert all(h in content for h in ("ncalls", "tottime", "percall", "cumtime")), \
        "Baseline does not contain a complete cProfile statistics table."

    total_match = re.search(r"([0-9]+) function calls(?: \([^)]+\))? in ([0-9.]+) seconds", content)
    assert total_match, "Could not parse the cProfile summary."
    assert int(total_match.group(1)) >= 2000, "Baseline profile has too few calls for the original optimizer."
    assert float(total_match.group(2)) >= 8.0, "Baseline profile is not from a complete run of the slow original tool."

    evaluation_counts = []
    for line in content.splitlines():
        if "evaluate_primer_loss" in line:
            match = re.match(r"\s*([0-9]+)(?:/[0-9]+)?\s+", line)
            if match:
                evaluation_counts.append(int(match.group(1)))
    assert evaluation_counts and max(evaluation_counts) >= 2000, \
        "Baseline profile does not show all 2000 original objective evaluations."


def test_primer_tool_modifications():
    assert os.path.exists(PRIMER_TOOL), f"{PRIMER_TOOL} is missing."

    with open(PRIMER_TOOL, "r") as f:
        content = f.read()

    # Retain the original source assertions.
    assert "Nelder-Mead" in content, "The optimization method 'Nelder-Mead' was not found in the script."
    assert "minimize" in content, "scipy.optimize.minimize was not found in the script."

    tree = ast.parse(content, filename=PRIMER_TOOL)
    optimize_nodes = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == "optimize"]
    assert len(optimize_nodes) == 1, "A single optimize() function is required."
    assert not any(isinstance(n, (ast.For, ast.AsyncFor, ast.While)) for n in ast.walk(optimize_nodes[0])), \
        "The custom iterative optimization logic remains in optimize()."


def _load_with_tracked_scipy():
    real_minimize = scipy.optimize.minimize
    calls = []

    def tracked_minimize(fun, x0, *args, **kwargs):
        bound = inspect.signature(real_minimize).bind_partial(fun, x0, *args, **kwargs)
        result = real_minimize(fun, x0, *args, **kwargs)
        calls.append({
            "x0": np.asarray(x0, dtype=float).copy(),
            "method": bound.arguments.get("method"),
            "result": np.asarray(result.x, dtype=float).copy(),
        })
        return result

    scipy.optimize.minimize = tracked_minimize
    try:
        sys.path.insert(0, "/home/user")
        spec = importlib.util.spec_from_file_location("verified_primer_tool", PRIMER_TOOL)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        scipy.optimize.minimize = real_minimize
        if sys.path and sys.path[0] == "/home/user":
            sys.path.pop(0)

    return module, calls, real_minimize


def test_optimize_genuinely_uses_nelder_mead():
    module, calls, real_minimize = _load_with_tracked_scipy()
    rng = secrets.SystemRandom()

    try:
        for _ in range(3):
            target = np.array([rng.uniform(57.0, 73.0), rng.uniform(0.38, 0.68)])
            weights = np.array([rng.uniform(0.7, 2.0), rng.uniform(400.0, 1600.0)])

            def dynamic_loss(params, target=target, weights=weights):
                params = np.asarray(params, dtype=float)
                return float(np.sum(weights * (params - target) ** 2))

            module.evaluate_primer_loss = dynamic_loss
            calls.clear()
            start = time.monotonic()
            returned = np.asarray(module.optimize(), dtype=float)
            elapsed = time.monotonic() - start

            assert calls, "optimize() did not call scipy.optimize.minimize."
            call = calls[-1]
            assert call["method"] == "Nelder-Mead", "minimize was not called with method='Nelder-Mead'."
            assert np.allclose(call["x0"], [50.0, 0.3], rtol=0, atol=1e-12), \
                f"Initial guess changed: {call['x0']}"
            assert returned.shape == (2,), "optimize() must return two optimized parameters."
            assert np.allclose(returned, call["result"], rtol=0, atol=1e-7), \
                "optimize() did not return the parameters produced by scipy.optimize.minimize."
            assert np.allclose(returned, target, rtol=0, atol=0.01), \
                f"Optimizer failed a derived objective: expected {target}, got {returned}."
            assert elapsed < 1.0, f"Optimization took too long: {elapsed}s"
    finally:
        scipy.optimize.minimize = real_minimize


def test_result_json():
    assert os.path.exists(RESULT), f"Result file {RESULT} was not created."

    with open(RESULT, "r") as f:
        stored_output = f.read()
        try:
            data = json.loads(stored_output)
        except json.JSONDecodeError:
            pytest.fail(f"{RESULT} does not contain valid JSON.")

    # Retain the original result assertions.
    assert "temperature" in data, "Result JSON missing 'temperature' key."
    assert "gc_ratio" in data, "Result JSON missing 'gc_ratio' key."
    assert abs(data["temperature"] - 65.0) < 0.1, f"Expected temperature near 65.0, got {data['temperature']}"
    assert abs(data["gc_ratio"] - 0.5) < 0.05, f"Expected gc_ratio near 0.5, got {data['gc_ratio']}"

    # Execute the submitted artifact and require result.json to be exactly its stdout.
    completed = subprocess.run(
        [sys.executable, PRIMER_TOOL], capture_output=True, text=True, timeout=3
    )
    assert completed.returncode == 0, f"primer_tool.py failed:\n{completed.stdout}\n{completed.stderr}"
    assert completed.stderr == "", f"primer_tool.py wrote unexpected stderr:\n{completed.stderr}"
    assert stored_output == completed.stdout, \
        "result.json is not the exact standard output produced by primer_tool.py."


