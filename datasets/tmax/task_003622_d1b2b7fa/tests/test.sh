#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import secrets
import stat
import subprocess
import tempfile
from pathlib import Path

import pytest

INPUT_FILE = Path('/home/user/intercepted_payloads.txt')
OUTPUT_FILE = Path('/home/user/redacted_payloads.log')
SOURCE_FILE = Path('/home/user/analyze_payloads.cpp')

ORIGINAL_PLAINTEXTS = [
    'CMD:SCAN|TARGET_IP:10.0.0.5|USER:root|PASS:toor|ACTION:PING',
    'CMD:EXEC|TARGET_IP:172.16.1.10|USER:admin|PASS:P@ssw0rd1|ACTION:DROP',
    'CMD:LATERAL|TARGET_IP:192.168.100.45|USER:svc_account|PASS:M%4K9!xZ|ACTION:WMI',
]


def encode_payload(plaintext):
    return ''.join(f'{ord(c) ^ 0x2B:02X}' for c in plaintext)


def redact_payload(plaintext):
    redacted_fields = []
    for field in plaintext.split('|'):
        if ':' in field:
            key, value = field.split(':', 1)
            if key in ('TARGET_IP', 'USER', 'PASS'):
                redacted_fields.append(f'{key}:[REDACTED]')
            else:
                redacted_fields.append(field)
        else:
            redacted_fields.append(field)
    return '|'.join(redacted_fields)


ORIGINAL_FIXTURE = ''.join(encode_payload(p) + '\n' for p in ORIGINAL_PLAINTEXTS).encode()


def remove_output():
    if os.path.lexists(OUTPUT_FILE):
        assert not OUTPUT_FILE.is_dir(), f'{OUTPUT_FILE} must be a file, not a directory.'
        OUTPUT_FILE.unlink()


def run_program(executable):
    result = subprocess.run(
        [str(executable)],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=10,
    )
    assert result.returncode == 0, (
        f'Compiled program exited with status {result.returncode}.\n'
        f'stdout:\n{result.stdout}\nstderr:\n{result.stderr}'
    )
    assert OUTPUT_FILE.exists(), f'Output file {OUTPUT_FILE} was not generated by the program.'
    assert stat.S_ISREG(os.lstat(OUTPUT_FILE).st_mode), f'{OUTPUT_FILE} is not a regular file.'


def read_nonempty_output_lines():
    with OUTPUT_FILE.open('r') as f:
        return [line.strip() for line in f if line.strip()]


def test_01_cpp_program_compiles_and_processes_payloads():
    assert INPUT_FILE.exists(), f'Input file {INPUT_FILE} is missing.'
    assert stat.S_ISREG(os.lstat(INPUT_FILE).st_mode), f'{INPUT_FILE} is not a regular file.'
    assert INPUT_FILE.read_bytes() == ORIGINAL_FIXTURE, (
        f'Input fixture {INPUT_FILE} was modified from its original contents.'
    )

    assert SOURCE_FILE.exists(), f'C++ source file {SOURCE_FILE} is missing.'
    assert stat.S_ISREG(os.lstat(SOURCE_FILE).st_mode), f'{SOURCE_FILE} is not a regular file.'
    assert SOURCE_FILE.stat().st_size > 0, f'C++ source file {SOURCE_FILE} is empty.'

    with tempfile.TemporaryDirectory(prefix='payload_verifier_') as tmpdir:
        executable = Path(tmpdir) / 'analyze_payloads'
        compile_result = subprocess.run(
            ['g++', '-std=c++17', '-O2', str(SOURCE_FILE), '-o', str(executable)],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=30,
        )
        assert compile_result.returncode == 0, (
            f'Failed to compile {SOURCE_FILE} as C++.\n'
            f'stdout:\n{compile_result.stdout}\nstderr:\n{compile_result.stderr}'
        )

        token1 = secrets.token_hex(6).upper()
        token2 = secrets.token_hex(7).upper()
        token3 = secrets.token_hex(5).upper()
        dynamic_plaintexts = [
            f'CMD:PROBE_{token1}|TARGET_IP:10.23.45.67|USER:user_{token2}|PASS:pw_{token3}|ACTION:CHECK_{token2}',
            f'CMD:EXEC_{token2}|TARGET_IP:172.20.30.40|USER:operator_{token1}|PASS:key_{token2}|ACTION:RUN_{token3}',
            f'CMD:SCAN_{token3}|TARGET_IP:192.0.2.55|USER:svc_{token3}|PASS:secret_{token1}|ACTION:PING_{token1}',
        ]
        encoded = [encode_payload(p) for p in dynamic_plaintexts]
        encoded[1] = encoded[1].lower()
        encoded[2] = ''.join(ch.lower() if i % 3 else ch for i, ch in enumerate(encoded[2]))
        dynamic_fixture = ''.join(line + '\n' for line in encoded).encode()
        dynamic_expected = [redact_payload(p) for p in dynamic_plaintexts]

        try:
            INPUT_FILE.write_bytes(dynamic_fixture)
            remove_output()
            run_program(executable)
            assert read_nonempty_output_lines() == dynamic_expected, (
                'The compiled C++ program did not correctly decode and redact '
                'the verifier-supplied payloads.'
            )
        finally:
            INPUT_FILE.write_bytes(ORIGINAL_FIXTURE)

        remove_output()
        run_program(executable)

    assert INPUT_FILE.read_bytes() == ORIGINAL_FIXTURE, (
        f'The program modified the original input fixture {INPUT_FILE}.'
    )
    assert SOURCE_FILE.exists() and stat.S_ISREG(os.lstat(SOURCE_FILE).st_mode), (
        f'C++ source file {SOURCE_FILE} must remain present as a regular file.'
    )


def test_redacted_payloads_log():
    """
    Verifies that /home/user/redacted_payloads.log exists and contains the correctly
    decrypted and redacted payloads from /home/user/intercepted_payloads.txt.
    """
    input_file = '/home/user/intercepted_payloads.txt'
    output_file = '/home/user/redacted_payloads.log'

    assert os.path.exists(input_file), f'Input file {input_file} is missing.'
    assert os.path.exists(output_file), f'Output file {output_file} was not generated.'
    assert Path(input_file).read_bytes() == ORIGINAL_FIXTURE, (
        f'Input fixture {input_file} was modified from its original contents.'
    )

    # Compute expected output
    expected_lines = []
    with open(input_file, 'r') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue

            # Decode hex
            try:
                raw_bytes = bytes.fromhex(line)
            except ValueError:
                pytest.fail(f'Input file contains invalid hex: {line}')

            # XOR decrypt
            decrypted_chars = [chr(b ^ 0x2B) for b in raw_bytes]
            plaintext = ''.join(decrypted_chars)

            # Redact TARGET_IP, USER, PASS
            # The format is KEY:VALUE separated by |
            fields = plaintext.split('|')
            redacted_fields = []
            for field in fields:
                if ':' in field:
                    k, v = field.split(':', 1)
                    if k in ('TARGET_IP', 'USER', 'PASS'):
                        redacted_fields.append(f'{k}:[REDACTED]')
                    else:
                        redacted_fields.append(field)
                else:
                    redacted_fields.append(field)

            expected_lines.append('|'.join(redacted_fields))

    # Read actual output
    with open(output_file, 'r') as f:
        actual_lines = [line.strip() for line in f if line.strip()]

    assert len(actual_lines) == len(expected_lines), (
        f'Expected {len(expected_lines)} lines in {output_file}, '
        f'but found {len(actual_lines)}.'
    )

    for i, (expected, actual) in enumerate(zip(expected_lines, actual_lines)):
        assert actual == expected, (
            f'Line {i+1} mismatch.\n'
            f'Expected: {expected}\n'
            f'Actual:   {actual}'
        )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
