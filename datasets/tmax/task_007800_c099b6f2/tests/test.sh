#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import secrets
import shutil
import subprocess
import tempfile

import yaml


def test_provision_out_dir_exists():
    assert os.path.isdir("/home/user/provision_out"), "Directory /home/user/provision_out does not exist."


def test_git_repo_is_bare():
    repo_path = "/home/user/edge-config.git"
    assert os.path.isdir(repo_path), f"Git repository directory {repo_path} does not exist."
    res = subprocess.run(
        ["git", "-C", repo_path, "rev-parse", "--is-bare-repository"],
        capture_output=True,
        text=True,
    )
    assert res.stdout.strip() == "true", f"{repo_path} is not a bare git repository."


def test_post_receive_hook_executable():
    hook_path = "/home/user/edge-config.git/hooks/post-receive"
    assert os.path.isfile(hook_path), "post-receive hook does not exist."
    assert os.access(hook_path, os.X_OK), "post-receive hook is not executable."
    with open(hook_path, "r") as f:
        first_line = f.readline().strip()
    assert "python3" in first_line, "post-receive hook must use a python3 shebang."


def expected_netplan(router_data):
    ethernets = {}
    for iface_name, iface_data in router_data["interfaces"].items():
        entry = {"addresses": [iface_data["ip"]]}
        if "gateway" in iface_data:
            entry["routes"] = [{"to": "default", "via": iface_data["gateway"]}]
        ethernets[iface_name] = entry
    return {"network": {"version": 2, "ethernets": ethernets}}


def expected_nftables(router_data):
    return [
        "add rule ip nat PREROUTING tcp dport "
        f"{rule['in_port']} counter dnat to {rule['out_ip']}:{rule['out_port']}"
        for rule in router_data["port_forwarding"]
    ]


def assert_exact_generated_files(router_data):
    netplan_path = "/home/user/provision_out/netplan.yaml"
    nftables_path = "/home/user/provision_out/nftables.conf"
    assert os.path.isfile(netplan_path), f"{netplan_path} was not generated by the hook."
    assert os.path.isfile(nftables_path), f"{nftables_path} was not generated by the hook."

    with open(netplan_path, "r") as f:
        try:
            actual_netplan = yaml.safe_load(f)
        except yaml.YAMLError as exc:
            raise AssertionError(f"netplan.yaml is not valid YAML: {exc}")
    assert actual_netplan == expected_netplan(router_data), (
        f"netplan.yaml has the wrong structure or values. "
        f"Expected {expected_netplan(router_data)!r}, got {actual_netplan!r}"
    )

    with open(nftables_path, "r") as f:
        raw_nftables = f.read()
    expected_lines = expected_nftables(router_data)
    assert raw_nftables.splitlines() == expected_lines, (
        f"nftables.conf must contain exactly the generated forwarding lines. "
        f"Expected {expected_lines!r}, got {raw_nftables.splitlines()!r}"
    )


def test_gitops_pipeline():
    temp_dir = tempfile.mkdtemp()
    try:
        # Clone the repo.
        clone_res = subprocess.run(
            ["git", "clone", "/home/user/edge-config.git", temp_dir],
            capture_output=True,
        )
        assert clone_res.returncode == 0, "Failed to clone the bare repository."

        # Preserve the original fixed-payload test and its assertions.
        router_data = {
            "interfaces": {
                "eth0": {
                    "ip": "192.168.10.5/24",
                    "gateway": "192.168.10.1",
                },
                "eth1": {
                    "ip": "10.0.5.1/24",
                },
            },
            "port_forwarding": [
                {
                    "in_port": 80,
                    "out_ip": "10.0.5.100",
                    "out_port": 8080,
                },
                {
                    "in_port": 443,
                    "out_ip": "10.0.5.101",
                    "out_port": 8443,
                },
            ],
        }
        with open(os.path.join(temp_dir, "router.json"), "w") as f:
            json.dump(router_data, f)

        subprocess.run(["git", "config", "user.email", "test@example.com"], cwd=temp_dir, check=True)
        subprocess.run(["git", "config", "user.name", "Test User"], cwd=temp_dir, check=True)
        subprocess.run(["git", "checkout", "-b", "master"], cwd=temp_dir, capture_output=True)
        subprocess.run(["git", "add", "router.json"], cwd=temp_dir, check=True)
        subprocess.run(["git", "commit", "-m", "Test push"], cwd=temp_dir, check=True)

        push_res = subprocess.run(
            ["git", "push", "origin", "master"],
            cwd=temp_dir,
            capture_output=True,
            text=True,
        )
        assert push_res.returncode == 0, f"Git push failed: {push_res.stderr}"

        netplan_path = "/home/user/provision_out/netplan.yaml"
        assert os.path.isfile(netplan_path), f"{netplan_path} was not generated by the hook."
        with open(netplan_path, "r") as f:
            netplan_content = f.read()
        assert "network:" in netplan_content, "Missing 'network:' root key in netplan.yaml"
        assert "ethernets:" in netplan_content, "Missing 'ethernets:' key in netplan.yaml"
        assert "eth0:" in netplan_content, "Missing 'eth0:' interface in netplan.yaml"
        assert "192.168.10.5/24" in netplan_content, "Missing IP address for eth0 in netplan.yaml"
        assert "via: 192.168.10.1" in netplan_content, "Missing gateway route for eth0 in netplan.yaml"
        assert "eth1:" in netplan_content, "Missing 'eth1:' interface in netplan.yaml"
        assert "10.0.5.1/24" in netplan_content, "Missing IP address for eth1 in netplan.yaml"

        nftables_path = "/home/user/provision_out/nftables.conf"
        assert os.path.isfile(nftables_path), f"{nftables_path} was not generated by the hook."
        with open(nftables_path, "r") as f:
            nftables_lines = [line.strip() for line in f.readlines() if line.strip()]
        expected_lines = [
            "add rule ip nat PREROUTING tcp dport 80 counter dnat to 10.0.5.100:8080",
            "add rule ip nat PREROUTING tcp dport 443 counter dnat to 10.0.5.101:8443",
        ]
        assert nftables_lines == expected_lines, (
            f"nftables.conf contents are incorrect. Expected {expected_lines}, got {nftables_lines}"
        )
        assert_exact_generated_files(router_data)

        # Push a runtime-random payload to a non-master ref. This requires the hook
        # to consume the pushed newrev rather than emitting the known fixed answer.
        token = secrets.token_hex(4)
        octet = secrets.randbelow(180) + 20
        base_port = secrets.randbelow(30000) + 20000
        random_router_data = {
            "interfaces": {
                f"wan{token}": {
                    "ip": f"10.{octet}.1.7/24",
                    "gateway": f"10.{octet}.1.1",
                },
                f"lan{token}": {
                    "ip": f"172.20.{octet}.1/25",
                },
                f"dmz{token}": {
                    "ip": f"192.168.{octet}.9/28",
                    "gateway": f"192.168.{octet}.1",
                },
            },
            "port_forwarding": [
                {
                    "in_port": base_port,
                    "out_ip": f"172.20.{octet}.10",
                    "out_port": base_port + 101,
                },
                {
                    "in_port": base_port + 1,
                    "out_ip": f"192.168.{octet}.11",
                    "out_port": base_port + 202,
                },
                {
                    "in_port": base_port + 2,
                    "out_ip": f"10.{octet}.1.12",
                    "out_port": base_port + 303,
                },
            ],
        }

        branch = f"verification-{token}"
        subprocess.run(["git", "checkout", "-b", branch], cwd=temp_dir, check=True)
        with open(os.path.join(temp_dir, "router.json"), "w") as f:
            json.dump(random_router_data, f)
        subprocess.run(["git", "add", "router.json"], cwd=temp_dir, check=True)
        subprocess.run(["git", "commit", "-m", "Randomized verification payload"], cwd=temp_dir, check=True)
        push_res = subprocess.run(
            ["git", "push", "origin", f"HEAD:refs/heads/{branch}"],
            cwd=temp_dir,
            capture_output=True,
            text=True,
        )
        assert push_res.returncode == 0, f"Randomized Git push failed: {push_res.stderr}"
        assert_exact_generated_files(random_router_data)
    finally:
        shutil.rmtree(temp_dir)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
