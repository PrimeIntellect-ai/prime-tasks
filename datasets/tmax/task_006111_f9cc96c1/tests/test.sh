cat << 'TEST_EOF' > /tmp/test_final_state.py
import importlib.util
import json
import os
import random
import subprocess
import tempfile

import pytest

SCRIPT = '/home/user/process_telemetry.py'
TELEMETRY = '/home/user/telemetry.dat'
RESULTS = '/home/user/results.json'


@pytest.fixture(scope='session', autouse=True)
def execute_submission():
    """Run the submitted Python program and require it to generate fresh output."""
    assert os.path.exists(SCRIPT), f"File {SCRIPT} does not exist."
    assert os.path.isfile(SCRIPT), f"File {SCRIPT} is not a regular file."

    if os.path.lexists(RESULTS):
        os.remove(RESULTS)

    proc = subprocess.run(
        ['python3', SCRIPT],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert proc.returncode == 0, (
        f"Running {SCRIPT} failed with exit code {proc.returncode}.\n"
        f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )
    assert os.path.isfile(RESULTS), f"File {RESULTS} was not generated by the script."


@pytest.fixture(scope='session')
def submitted_module(execute_submission):
    spec = importlib.util.spec_from_file_location('submitted_process_telemetry', SCRIPT)
    assert spec is not None and spec.loader is not None, f"Could not load {SCRIPT}."
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert callable(getattr(module, 'parse_stream', None)), "parse_stream is not callable."
    assert callable(getattr(module, 'calculate_metrics', None)), "calculate_metrics is not callable."
    return module


def test_telemetry_dat_content():
    """Verify that telemetry.dat exists and has the correct content."""
    filepath = TELEMETRY
    assert os.path.exists(filepath), f"File {filepath} does not exist."

    expected_content = (
        "HEAD\n"
        "0A 14 1E\n"
        "05 0F\n"
        "END\n"
        "HEAD\n"
        "FF 00\n"
        "ERROR_LINE\n"
        "END\n"
        "HEAD\n"
        "02 04 06 08\n"
        "END\n"
    )

    with open(filepath, 'r') as f:
        content = f.read()

    assert content.strip() == expected_content.strip(), f"Content of {filepath} does not match expected."


def test_process_telemetry_script_exists():
    """Verify that process_telemetry.py exists."""
    assert os.path.exists(SCRIPT), f"File {SCRIPT} does not exist."


def test_parse_stream_on_derived_input(submitted_module):
    """Exercise the upgraded byte/string state machine on runtime-generated data."""
    rng = random.SystemRandom()
    first = [rng.randrange(0, 256) for _ in range(rng.randrange(3, 9))]
    discarded = [rng.randrange(0, 256) for _ in range(3)]
    replacement = [rng.randrange(0, 256) for _ in range(rng.randrange(2, 7))]

    lines = [
        'IGNORED',
        'HEAD',
        ' '.join(f'{value:02X}' for value in first[:2]),
        ' '.join(f'{value:02X}' for value in first[2:]),
        'END',
        'HEAD',
        ' '.join(f'{value:02X}' for value in discarded),
        'NOT_HEX',
        'END',
        'HEAD',
        'END',
        'HEAD',
        '01 02 03',
        'HEAD',
        ' '.join(f'{value:02X}' for value in replacement),
        'END',
        'HEAD',
        'AA BB',
    ]

    fd, path = tempfile.mkstemp(prefix='telemetry_dynamic_', suffix='.dat')
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(('\n'.join(lines) + '\n').encode('ascii'))
        actual = submitted_module.parse_stream(path)
    finally:
        os.unlink(path)

    assert actual == [first, [], replacement]


def test_calculate_metrics_on_derived_frames(submitted_module):
    """Check mean and population variance using answers derived at verification time."""
    assert submitted_module.calculate_metrics([]) == {'mean': 0.0, 'variance': 0.0}

    rng = random.SystemRandom()
    for _ in range(8):
        frame = [rng.randrange(-500, 501) for _ in range(rng.randrange(1, 18))]
        expected_mean = sum(frame) / len(frame)
        expected_variance = sum((value - expected_mean) ** 2 for value in frame) / len(frame)
        metrics = submitted_module.calculate_metrics(frame)

        assert isinstance(metrics, dict)
        assert set(metrics) == {'mean', 'variance'}
        assert metrics['mean'] == pytest.approx(expected_mean, abs=1e-9)
        assert metrics['variance'] == pytest.approx(expected_variance, abs=1e-9)


def test_results_json():
    """Verify that freshly generated results.json contains the correct metrics."""
    filepath = RESULTS
    assert os.path.exists(filepath), f"File {filepath} does not exist. Did you run the script?"

    with open(filepath, 'r') as f:
        try:
            results = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"File {filepath} is not valid JSON.")

    assert isinstance(results, list), f"Expected results.json to contain a list, got {type(results).__name__}."
    assert len(results) == 2, f"Expected 2 frames in results.json, found {len(results)}."

    frame_0 = results[0]
    assert frame_0.get('frame_id') == 0, f"Expected frame_id 0, got {frame_0.get('frame_id')}."
    metrics_0 = frame_0.get('metrics', {})
    assert abs(metrics_0.get('mean', 0) - 16.0) < 1e-6, f"Expected mean 16.0 for frame 0, got {metrics_0.get('mean')}."
    assert abs(metrics_0.get('variance', 0) - 74.0) < 1e-6, f"Expected variance 74.0 for frame 0, got {metrics_0.get('variance')}."

    frame_1 = results[1]
    assert frame_1.get('frame_id') == 1, f"Expected frame_id 1, got {frame_1.get('frame_id')}."
    metrics_1 = frame_1.get('metrics', {})
    assert abs(metrics_1.get('mean', 0) - 5.0) < 1e-6, f"Expected mean 5.0 for frame 1, got {metrics_1.get('mean')}."
    assert abs(metrics_1.get('variance', 0) - 5.0) < 1e-6, f"Expected variance 5.0 for frame 1, got {metrics_1.get('variance')}."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
