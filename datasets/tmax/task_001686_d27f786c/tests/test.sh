#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import math
import os
import random
import re
import sqlite3
import subprocess
import tempfile

import pandas as pd
import pytest

DB_PATH = '/home/user/graph.db'
CSV_PATH = '/home/user/pagerank_results.csv'
SOURCE_PATH = '/home/user/graph_analyzer.cpp'
EXECUTABLE_PATH = '/home/user/graph_analyzer'


def canonical_edges():
    random.seed(42)
    result = set()
    for _ in range(5000):
        result.add((random.randint(0, 100), random.randint(0, 100)))
    return result


def expected_pagerank(edges):
    adjacency = {}
    for src, dst in edges:
        adjacency.setdefault(src, []).append(dst)

    reachable = {0}
    pending = [0]
    while pending:
        src = pending.pop()
        for dst in adjacency.get(src, []):
            if dst not in reachable:
                reachable.add(dst)
                pending.append(dst)

    active_edges = {(src, dst) for src, dst in edges
                    if src in reachable and dst in reachable}
    nodes = set(reachable)
    n = len(nodes)
    pr = {node: 1.0 / n for node in nodes}
    out_degree = {}
    for src, _ in active_edges:
        out_degree[src] = out_degree.get(src, 0) + 1

    for _ in range(25):
        new_pr = {node: (1.0 - 0.85) / n for node in nodes}
        for src, dst in active_edges:
            new_pr[dst] += 0.85 * (pr[src] / out_degree[src])
        pr = new_pr

    return nodes, active_edges, pr


def validate_database(expected_edges):
    assert os.path.isfile(DB_PATH), f'Database {DB_PATH} does not exist.'
    conn = sqlite3.connect(DB_PATH)
    try:
        integrity = conn.execute('PRAGMA integrity_check').fetchone()[0]
        assert integrity == 'ok', f'Database is not repaired: {integrity}'

        columns = conn.execute('PRAGMA table_info(edges)').fetchall()
        assert len(columns) == 2, 'edges must contain exactly two columns.'
        assert [column[1] for column in columns] == ['src', 'dst'], \
            'edges must have src and dst columns.'
        assert all('INT' in (column[2] or '').upper() for column in columns), \
            'src and dst must be INTEGER columns.'

        rows = conn.execute('SELECT src, dst FROM edges NOT INDEXED').fetchall()
        actual = {(int(src), int(dst)) for src, dst in rows}
        assert len(rows) == len(actual), 'edges contains duplicate rows.'
        assert actual == expected_edges, \
            'graph.db no longer contains the graph generated by legacy_etl with 5000 edges.'

        indexes = {row[1] for row in conn.execute("PRAGMA index_list('edges')")}
        if 'idx_src' in indexes:
            indexed = {(int(src), int(dst)) for src, dst in
                       conn.execute('SELECT src, dst FROM edges INDEXED BY idx_src')}
            assert indexed == expected_edges, 'idx_src still returns stale or ghost edges.'

        # Preserve the original verifier's repair/read path and recursive-CTE assertion.
        conn.execute('REINDEX;')
        query = '''
        WITH RECURSIVE reachable(node) AS (
            SELECT 0
            UNION
            SELECT e.dst FROM edges e
            JOIN reachable r ON e.src = r.node
        )
        SELECT src, dst FROM edges WHERE src IN reachable AND dst IN reachable;
        '''
        queried_edges = {(int(src), int(dst)) for src, dst in conn.execute(query)}
        return queried_edges
    finally:
        conn.close()


def validate_csv(nodes, expected_pr):
    assert os.path.isfile(CSV_PATH), f'CSV results {CSV_PATH} do not exist.'
    try:
        agent_df = pd.read_csv(CSV_PATH)
    except Exception as exc:
        pytest.fail(f'Could not read {CSV_PATH} as CSV: {exc}')

    assert 'node' in agent_df.columns and 'pagerank' in agent_df.columns, \
        "CSV must contain 'node' and 'pagerank' columns."
    assert len(agent_df) == len(nodes), 'CSV must contain exactly one row per active node.'

    try:
        csv_nodes = [int(value) for value in agent_df['node']]
        csv_scores = [float(value) for value in agent_df['pagerank']]
    except (TypeError, ValueError, OverflowError) as exc:
        pytest.fail(f'CSV contains invalid node or pagerank values: {exc}')

    assert len(set(csv_nodes)) == len(csv_nodes), 'CSV contains duplicate node rows.'
    assert set(csv_nodes) == nodes, 'CSV node set does not equal the active subgraph.'
    assert all(math.isfinite(score) for score in csv_scores), \
        'PageRank values must be finite numbers.'

    agent_pr = dict(zip(csv_nodes, csv_scores))
    mse = sum((expected_pr[node] - agent_pr.get(node, 0.0)) ** 2
              for node in nodes) / len(nodes)
    threshold = 1e-8
    assert mse <= threshold, \
        f'MSE {mse} exceeds threshold {threshold}. The PageRank scores are incorrect.'


def run_program(path):
    if os.path.exists(CSV_PATH):
        os.remove(CSV_PATH)
    try:
        completed = subprocess.run(
            [path], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, timeout=60, check=False)
    except subprocess.TimeoutExpired:
        pytest.fail(f'{path} did not finish within 60 seconds.')
    assert completed.returncode == 0, \
        f'{path} failed with exit code {completed.returncode}: {completed.stderr}'


def test_pagerank_mse():
    assert os.path.isfile(SOURCE_PATH), f'C++ source {SOURCE_PATH} does not exist.'
    assert os.path.isfile(EXECUTABLE_PATH), f'Executable {EXECUTABLE_PATH} does not exist.'
    assert os.access(EXECUTABLE_PATH, os.X_OK), f'{EXECUTABLE_PATH} is not executable.'
    with open(EXECUTABLE_PATH, 'rb') as executable:
        assert executable.read(4) == b'\x7fELF', \
            'graph_analyzer must be a compiled executable.'

    with open(SOURCE_PATH, 'r', encoding='utf-8', errors='replace') as source_file:
        source = source_file.read()
    assert re.search(r'\bWITH\s+RECURSIVE\b', source, re.IGNORECASE), \
        'graph_analyzer.cpp must use a recursive CTE.'

    generated_edges = canonical_edges()
    nodes, active_edges, expected_pr = expected_pagerank(generated_edges)
    queried_edges = validate_database(generated_edges)
    assert queried_edges == active_edges, \
        'Recursive CTE extraction from graph.db returned the wrong active subgraph.'

    # Execute and assess the submitted executable.
    run_program(EXECUTABLE_PATH)
    validate_database(generated_edges)
    validate_csv(nodes, expected_pr)

    # Compile the submitted C++ source independently and assess that artifact too.
    fd, rebuilt_path = tempfile.mkstemp(prefix='graph_analyzer_rebuilt_', dir='/tmp')
    os.close(fd)
    os.unlink(rebuilt_path)
    try:
        compilation = subprocess.run(
            ['g++', '-std=c++17', '-O2', SOURCE_PATH, '-o', rebuilt_path, '-lsqlite3'],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
            timeout=60, check=False)
        assert compilation.returncode == 0, \
            f'graph_analyzer.cpp does not compile: {compilation.stderr}'
        run_program(rebuilt_path)
        validate_database(generated_edges)
        validate_csv(nodes, expected_pr)
    finally:
        if os.path.exists(rebuilt_path):
            os.remove(rebuilt_path)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
