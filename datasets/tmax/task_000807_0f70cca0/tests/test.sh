#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import json
import os
import runpy
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.axes
import matplotlib.image
import numpy as np
import scipy.stats

SCRIPT_PATH = '/home/user/als_nmf.py'
CSV_PATH = '/home/user/gene_expression.csv'
JSON_PATH = '/home/user/results.json'
PLOT_PATH = '/home/user/convergence.png'


def als_nmf_correct(V, k, max_iter=1000, tol=1e-4, lam=0.1):
    np.random.seed(42)
    n, m = V.shape
    W = np.random.rand(n, k)
    H = np.random.rand(k, m)
    prev_loss = float('inf')
    losses = []

    for _ in range(max_iter):
        H = np.linalg.solve(W.T @ W + lam * np.eye(k), W.T @ V)
        H[H < 0] = 0

        W = np.linalg.solve(H @ H.T + lam * np.eye(k), H @ V.T).T
        W[W < 0] = 0

        loss = np.sum((V - W @ H) ** 2)
        losses.append(float(loss))
        if abs(prev_loss - loss) < tol:
            break
        prev_loss = loss

    return W, H, float(loss), np.asarray(losses)


def unpack_factors(result):
    assert isinstance(result, (tuple, list)) and len(result) >= 2, \
        'als_nmf must return W and H as its first two return values.'
    return np.asarray(result[0]), np.asarray(result[1])


def test_modified_script_and_outputs():
    assert os.path.isfile(SCRIPT_PATH), f'{SCRIPT_PATH} is missing.'
    assert os.path.isfile(CSV_PATH), f'{CSV_PATH} is missing.'
    V = np.loadtxt(CSV_PATH, delimiter=',')

    # Remove stale artifacts, then execute the required script itself.
    for path in (JSON_PATH, PLOT_PATH):
        if os.path.lexists(path):
            os.unlink(path)

    captured_lines = []
    original_plot = matplotlib.axes.Axes.plot

    def recording_plot(ax, *args, **kwargs):
        lines = original_plot(ax, *args, **kwargs)
        for line in lines:
            try:
                captured_lines.append(np.asarray(line.get_ydata(), dtype=float).copy())
            except (TypeError, ValueError):
                pass
        return lines

    matplotlib.axes.Axes.plot = recording_plot
    old_argv = sys.argv
    sys.argv = [SCRIPT_PATH]
    try:
        namespace = runpy.run_path(SCRIPT_PATH, run_name='__main__')
    finally:
        sys.argv = old_argv
        matplotlib.axes.Axes.plot = original_plot

    assert 'als_nmf' in namespace and callable(namespace['als_nmf']), \
        'als_nmf.py must define the als_nmf function.'
    submitted = namespace['als_nmf']

    # Exercise the submitted function directly. One iteration checks that both
    # regularized update steps are implemented; the full run checks the required
    # loss-based early stopping behavior rather than merely output fabrication.
    for k in (3, 4):
        expected_W1, expected_H1, _, _ = als_nmf_correct(V, k, max_iter=1)
        actual_W1, actual_H1 = unpack_factors(submitted(V.copy(), k, max_iter=1))
        assert np.allclose(actual_W1, expected_W1, rtol=1e-9, atol=1e-10), \
            f'als_nmf k={k} does not perform the required regularized W update.'
        assert np.allclose(actual_H1, expected_H1, rtol=1e-9, atol=1e-10), \
            f'als_nmf k={k} does not perform the required regularized H update.'

        expected_W, expected_H, _, _ = als_nmf_correct(V, k)
        actual_W, actual_H = unpack_factors(submitted(V.copy(), k, max_iter=1000))
        assert np.allclose(actual_W, expected_W, rtol=1e-8, atol=1e-9), \
            f'als_nmf k={k} does not stop at the required loss convergence point.'
        assert np.allclose(actual_H, expected_H, rtol=1e-8, atol=1e-9), \
            f'als_nmf k={k} does not stop at the required loss convergence point.'

    expected_W3, expected_H3, loss3, losses3 = als_nmf_correct(V, 3)
    expected_W4, expected_H4, loss4, losses4 = als_nmf_correct(V, 4)

    # Keep the original existence assertion, and additionally require a real,
    # nonempty PNG generated by a plot containing both complete loss histories.
    assert os.path.isfile(PLOT_PATH), f'{PLOT_PATH} is missing or not a file.'
    assert os.path.getsize(PLOT_PATH) > 100, 'convergence.png is empty or invalid.'
    with open(PLOT_PATH, 'rb') as f:
        assert f.read(8) == b'\x89PNG\r\n\x1a\n', 'convergence.png is not a PNG file.'
    image = matplotlib.image.imread(PLOT_PATH)
    assert image.ndim in (2, 3) and image.shape[0] > 10 and image.shape[1] > 10, \
        'convergence.png is not a usable plot image.'
    assert np.ptp(np.asarray(image, dtype=float)) > 0, 'convergence.png is blank.'

    def history_was_plotted(expected):
        return any(
            line.ndim == 1 and len(line) == len(expected)
            and np.allclose(line, expected, rtol=1e-7, atol=1e-10)
            for line in captured_lines
        )

    assert history_was_plotted(losses3), 'The plot does not contain the k=3 loss at each iteration.'
    assert history_was_plotted(losses4), 'The plot does not contain the k=4 loss at each iteration.'

    # Preserve the original results assertions and derive all expected values
    # independently from the input data.
    assert os.path.isfile(JSON_PATH), f'{JSON_PATH} is missing.'
    with open(JSON_PATH, 'r') as f:
        try:
            results = json.load(f)
        except json.JSONDecodeError:
            assert False, f'{JSON_PATH} is not a valid JSON file.'

    assert 'k3_loss' in results, "'k3_loss' missing from results.json"
    assert 'k4_loss' in results, "'k4_loss' missing from results.json"
    assert 'p_value' in results, "'p_value' missing from results.json"
    for key in ('k3_loss', 'k4_loss', 'p_value'):
        assert type(results[key]) is float, f'{key} must be stored as a JSON float.'
        assert np.isfinite(results[key]), f'{key} must be finite.'

    err3 = np.sum((V - expected_W3 @ expected_H3) ** 2, axis=1)
    err4 = np.sum((V - expected_W4 @ expected_H4) ** 2, axis=1)
    _, p_val = scipy.stats.ttest_rel(err3, err4)

    assert abs(results['k3_loss'] - loss3) < 1e-3, \
        f"k3_loss is incorrect. Expected ~{loss3:.5f}, got {results['k3_loss']}"
    assert abs(results['k4_loss'] - loss4) < 1e-3, \
        f"k4_loss is incorrect. Expected ~{loss4:.5f}, got {results['k4_loss']}"
    assert abs(results['p_value'] - p_val) < 1e-3, \
        f"p_value is incorrect. Expected ~{p_val:.5f}, got {results['p_value']}"
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
