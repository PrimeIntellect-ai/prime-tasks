#!/bin/bash
mkdir -p /logs/verifier

# The required artifact must be a real Python file, not a symlink, and must
# recreate the output successfully when executed.
if [ ! -f /home/user/sanitize.py ] || [ -L /home/user/sanitize.py ]; then
    echo "0" > /logs/verifier/reward.txt
    exit 0
fi

rm -rf /home/user/logs/clean
if ! timeout 30s runuser -u user -- bash -c 'cd /home/user && exec python3 /home/user/sanitize.py'; then
    echo "0" > /logs/verifier/reward.txt
    exit 0
fi

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import stat


def expected_sanitized_lines():
    lines = []

    # Full backup generated by the task setup.
    for i in range(1, 2001):
        if i % 100 == 0:
            line = f"Log entry {i}: User attempted to access ../../../etc/passwd MALICIOUS_ENTRY\n"
        elif i % 75 == 0:
            line = f"Log entry {i}: Normal access to ../assets/image.png\n"
        else:
            line = f"Log entry {i}: System running normally.\n"

        if "MALICIOUS_ENTRY" not in line:
            lines.append(line.replace("../", "[REDACTED]"))

    # Differential backup generated by the task setup and merged in chunk order.
    for i in range(2001, 3501):
        if i % 50 == 0:
            line = f"Log entry {i}: Download ../../data/secret.txt\n"
        elif i % 110 == 0:
            line = f"Log entry {i}: Exploit payload ../ MALICIOUS_ENTRY\n"
        else:
            line = f"Log entry {i}: Background task completed.\n"

        if "MALICIOUS_ENTRY" not in line:
            lines.append(line.replace("../", "[REDACTED]"))

    return lines


def test_sanitize_script_exists():
    path = '/home/user/sanitize.py'
    assert os.path.isfile(path), f"{path} does not exist."
    assert not os.path.islink(path), f"{path} must be a regular file, not a symlink."
    assert stat.S_ISREG(os.lstat(path).st_mode), f"{path} is not a regular file."


def test_clean_logs_exist_and_named_correctly():
    clean_dir = '/home/user/logs/clean/'
    assert os.path.isdir(clean_dir), f"{clean_dir} directory is missing."

    expected_files = ['clean.log.000', 'clean.log.001', 'clean.log.002', 'clean.log.003']
    actual_files = sorted(os.listdir(clean_dir))

    for filename in expected_files:
        assert filename in actual_files, f"Expected file {filename} is missing in {clean_dir}."

    assert len(actual_files) == len(expected_files), (
        f"Expected exactly {len(expected_files)} files in {clean_dir}, "
        f"but found {len(actual_files)}: {actual_files}"
    )


def test_clean_logs_line_counts():
    clean_dir = '/home/user/logs/clean/'
    expected_counts = {
        'clean.log.000': 1000,
        'clean.log.001': 1000,
        'clean.log.002': 1000,
        'clean.log.003': 470,
    }

    total_lines = 0
    for filename, expected_count in expected_counts.items():
        filepath = os.path.join(clean_dir, filename)
        assert os.path.isfile(filepath), f"{filepath} is missing."
        with open(filepath, 'r', encoding='utf-8') as handle:
            lines = handle.readlines()
        assert len(lines) == expected_count, (
            f"Expected {expected_count} lines in {filename}, got {len(lines)}."
        )
        total_lines += len(lines)

    assert total_lines == 3470, (
        f"Expected total lines across all clean logs to be 3470, got {total_lines}."
    )


def test_clean_logs_sanitization():
    clean_dir = '/home/user/logs/clean/'
    expected_files = ['clean.log.000', 'clean.log.001', 'clean.log.002', 'clean.log.003']
    redacted_found = False

    for filename in expected_files:
        filepath = os.path.join(clean_dir, filename)
        if not os.path.isfile(filepath):
            continue

        with open(filepath, 'r', encoding='utf-8') as handle:
            for line_num, line in enumerate(handle, 1):
                assert "MALICIOUS_ENTRY" not in line, (
                    f"Found 'MALICIOUS_ENTRY' in {filename} at line {line_num}."
                )
                assert "../" not in line, (
                    f"Found '../' in {filename} at line {line_num}."
                )
                if "[REDACTED]" in line:
                    redacted_found = True

    assert redacted_found, "Expected to find '[REDACTED]' in the sanitized logs, but found none."


def test_clean_logs_exact_content_and_order():
    clean_dir = '/home/user/logs/clean/'
    expected = expected_sanitized_lines()
    filenames = ['clean.log.000', 'clean.log.001', 'clean.log.002', 'clean.log.003']

    assert len(expected) == 3470
    for index, filename in enumerate(filenames):
        filepath = os.path.join(clean_dir, filename)
        with open(filepath, 'r', encoding='utf-8') as handle:
            actual_chunk = handle.readlines()

        expected_chunk = expected[index * 1000:(index + 1) * 1000]
        assert actual_chunk == expected_chunk, (
            f"{filename} does not contain the correctly merged, sanitized, "
            "and ordered source log lines."
        )
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
