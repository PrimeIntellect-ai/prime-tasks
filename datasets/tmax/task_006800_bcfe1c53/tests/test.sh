#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import csv
import json
import math
import os
import subprocess
import sys
import pytest

SCRIPT = '/home/user/etl_pipeline.py'
INPUT = '/home/user/sensor_data.csv'
CLEANED = '/home/user/cleaned_data.csv'
REPORT = '/home/user/report.json'


def get_expected_state():
    """Compute the required result directly from the supplied input."""
    if not os.path.exists(INPUT):
        pytest.fail(f"Input file {INPUT} is missing, cannot compute expected state.")

    with open(INPUT, 'r', newline='') as f:
        reader = csv.reader(f)
        try:
            header = next(reader)
        except StopIteration:
            pytest.fail(f"Input file {INPUT} is empty.")
        data = []
        for row in reader:
            try:
                floats = [float(x) for x in row]
                if len(floats) == len(header) and all(math.isfinite(x) and -100.0 <= x <= 100.0 for x in floats):
                    data.append(floats)
            except ValueError:
                pass

    cols = list(zip(*data))
    n = len(data)
    means = [sum(c) / n for c in cols]
    stdevs = [math.sqrt(sum((x - m) ** 2 for x in c)) for c, m in zip(cols, means)]

    corrs = {}
    for i in range(len(header)):
        for j in range(i + 1, len(header)):
            cov = sum((cols[i][k] - means[i]) * (cols[j][k] - means[j]) for k in range(n))
            corrs[(header[i], header[j])] = cov / (stdevs[i] * stdevs[j]) if stdevs[i] and stdevs[j] else 0

    to_drop = set()
    sorted_headers = sorted(header)
    for i in range(len(sorted_headers)):
        for j in range(i + 1, len(sorted_headers)):
            h1, h2 = sorted_headers[i], sorted_headers[j]
            idx1, idx2 = header.index(h1), header.index(h2)
            key = (header[idx1], header[idx2]) if idx1 < idx2 else (header[idx2], header[idx1])
            if abs(corrs[key]) > 0.90:
                to_drop.add(h2)

    retained_headers = [h for h in header if h not in to_drop]
    retained_indices = [header.index(h) for h in retained_headers]
    retained_values = {h: [row[idx] for row in data] for idx, h in zip(retained_indices, retained_headers)}

    total_anomalies = 0
    anomalies_by_col = {h: [] for h in retained_headers}

    def norm_pdf(x):
        return math.exp(-0.5 * (x / 10.0) ** 2) / (10.0 * math.sqrt(2 * math.pi))

    for row in data:
        for idx, h in zip(retained_indices, retained_headers):
            val = row[idx]
            p_n = norm_pdf(val)
            post_f = (0.005 * 0.05) / (0.005 * 0.05 + p_n * 0.95)
            flag = 1 if post_f > 0.5 else 0
            anomalies_by_col[h].append(flag)
            total_anomalies += flag

    return {
        'retained_headers': retained_headers,
        'retained_values': retained_values,
        'dropped_columns': sorted(to_drop),
        'total_anomalies': total_anomalies,
        'data_len': n,
        'anomalies_by_col': anomalies_by_col,
    }


@pytest.fixture(scope='module')
def expected_state():
    assert os.path.isfile(SCRIPT), f"Required pipeline script {SCRIPT} does not exist."
    # Outputs must be reproducibly generated by the submitted script, rather than
    # merely being prewritten artifacts.
    for path in (CLEANED, REPORT):
        if os.path.lexists(path):
            os.remove(path)
    result = subprocess.run([sys.executable, SCRIPT], cwd='/home/user', capture_output=True, text=True, timeout=120)
    assert result.returncode == 0, f"Pipeline failed with exit code {result.returncode}.\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    assert os.path.isfile(CLEANED), f"Pipeline did not create {CLEANED}."
    assert os.path.isfile(REPORT), f"Pipeline did not create {REPORT}."
    return get_expected_state()


def test_report_json(expected_state):
    with open(REPORT, 'r') as f:
        try:
            report = json.load(f)
        except json.JSONDecodeError:
            pytest.fail(f"File {REPORT} is not valid JSON.")

    assert set(report.keys()) == {'dropped_columns', 'total_anomalies'}, 'Report JSON must have the exact required structure.'
    assert sorted(report['dropped_columns']) == expected_state['dropped_columns']
    assert report['total_anomalies'] == expected_state['total_anomalies']


def test_cleaned_data_csv(expected_state):
    with open(CLEANED, 'r', newline='') as f:
        reader = csv.reader(f)
        try:
            header = next(reader)
        except StopIteration:
            pytest.fail(f"File {CLEANED} is empty.")
        expected_headers = expected_state['retained_headers'] + [f"failure_flag_{h}" for h in expected_state['retained_headers']]
        assert len(header) == len(expected_headers) and set(header) == set(expected_headers), \
            f"Expected headers {set(expected_headers)}, but got {header}."
        data = list(reader)

    assert len(data) == expected_state['data_len']
    sensor_indices = {h: header.index(h) for h in expected_state['retained_headers']}
    flag_indices = {h: header.index(f'failure_flag_{h}') for h in expected_state['retained_headers']}

    for i, row in enumerate(data):
        assert len(row) == len(header), f"Row {i + 1} has the wrong number of fields."
        for h in expected_state['retained_headers']:
            try:
                actual_value = float(row[sensor_indices[h]])
                actual_flag = int(float(row[flag_indices[h]]))
            except (ValueError, OverflowError) as exc:
                pytest.fail(f"Row {i + 1} contains invalid numeric data: {exc}")
            expected_value = expected_state['retained_values'][h][i]
            assert math.isfinite(actual_value) and math.isclose(actual_value, expected_value, rel_tol=1e-12, abs_tol=1e-12), \
                f"Row {i + 1}, column {h}: expected {expected_value}, got {actual_value}."
            expected_flag = expected_state['anomalies_by_col'][h][i]
            assert actual_flag == expected_flag, \
                f"Row {i + 1}, column failure_flag_{h}: expected {expected_flag}, got {actual_flag}."
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
