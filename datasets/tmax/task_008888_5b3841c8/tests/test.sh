#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import secrets
import shutil
import subprocess
import tempfile

import pytest

PROJECT = "/home/user/quota_monitor"
MANIFEST = os.path.join(PROJECT, "Cargo.toml")
MAIN_RS = os.path.join(PROJECT, "src/main.rs")
FSTAB = "/home/user/custom_fstab"
PASSWD = "/home/user/mock_passwd"
LOG = "/home/user/quota_alerts.log"


def run_monitor():
    if os.path.lexists(LOG):
        assert os.path.isfile(LOG), f"{LOG} exists but is not a regular file"
        os.remove(LOG)

    result = subprocess.run(
        ["cargo", "run", "--offline", "--quiet", "--manifest-path", MANIFEST],
        cwd=PROJECT,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, (
        "The Rust project failed to compile or run.\n"
        f"stdout:\n{result.stdout}\n"
        f"stderr:\n{result.stderr}"
    )
    assert os.path.isfile(LOG), f"Output log file {LOG} was not generated by the Rust program."


def expected_alerts(fstab_path, passwd_path):
    uid_to_user = {}
    with open(passwd_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split(":")
            if len(parts) >= 3:
                uid_to_user[parts[2]] = parts[0]

    alerts = []
    with open(fstab_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 4:
                continue

            mount_point = parts[1]
            uid = None
            quota = None
            for option in parts[3].split(","):
                if option.startswith("uid="):
                    uid = option.split("=", 1)[1]
                elif option.startswith("quota="):
                    quota = int(option.split("=", 1)[1])

            if uid and quota is not None and uid in uid_to_user:
                data_file = os.path.join(mount_point, "data.bin")
                if os.path.isfile(data_file):
                    usage = os.path.getsize(data_file)
                    if usage > quota:
                        username = uid_to_user[uid]
                        alert = (
                            f"ALERT: User {username} exceeded quota on {mount_point}. "
                            f"Usage: {usage} bytes, Limit: {quota} bytes."
                        )
                        alerts.append((username, alert))

    alerts.sort(key=lambda item: item[0])
    return [alert for _, alert in alerts]


def read_actual_lines():
    with open(LOG, "r") as f:
        return [line.strip() for line in f if line.strip()]


def test_rust_project_exists():
    assert os.path.isfile(MANIFEST), f"Rust project file {MANIFEST} is missing. Did you create the project?"
    assert os.path.isfile(MAIN_RS), f"Rust source file {MAIN_RS} is missing."


def test_quota_alerts_log():
    assert os.path.isfile(FSTAB), f"File {FSTAB} is missing."
    assert os.path.isfile(PASSWD), f"File {PASSWD} is missing."

    expected_lines = expected_alerts(FSTAB, PASSWD)
    run_monitor()
    actual_lines = read_actual_lines()

    assert actual_lines == expected_lines, (
        f"The contents of {LOG} do not match the expected output.\n"
        f"Expected:\n{chr(10).join(expected_lines)}\n\n"
        f"Actual:\n{chr(10).join(actual_lines)}"
    )


def test_program_handles_unseen_inputs_and_strict_limit():
    token = secrets.token_hex(6)
    root = tempfile.mkdtemp(prefix="quota_monitor_verify_")

    saved_fstab = open(FSTAB, "rb").read()
    saved_passwd = open(PASSWD, "rb").read()
    log_existed = os.path.isfile(LOG)
    saved_log = open(LOG, "rb").read() if log_existed else None

    try:
        quota = 31000 + secrets.randbelow(7000)
        cases = [
            (f"zeta_{token}", "71001", quota, quota + 137),
            (f"alpha_{token}", "71002", quota + 19, quota + 19),
            (f"middle_{token}", "71003", quota + 41, quota - 23),
            (f"beta_{token}", "71004", quota + 83, quota + 284),
        ]

        mounts = {}
        for username, uid, limit, usage in cases:
            mount = os.path.join(root, f"mount_{uid}_{token}")
            os.makedirs(mount)
            with open(os.path.join(mount, "data.bin"), "wb") as data:
                data.truncate(usage)
            mounts[uid] = mount

        with open(PASSWD, "w") as f:
            for username, uid, _, _ in reversed(cases):
                f.write(f"{username}:x:{uid}:{uid}::/home/{username}:/bin/bash\n")

        with open(FSTAB, "w") as f:
            # Deliberately shuffle entries and option order.
            for index in (2, 0, 3, 1):
                username, uid, limit, usage = cases[index]
                f.write(
                    f"/dev/test{index} {mounts[uid]} ext4 "
                    f"rw,quota={limit},nodev,uid={uid} 0 0\n"
                )

        expected_lines = expected_alerts(FSTAB, PASSWD)
        assert len(expected_lines) == 2

        run_monitor()
        actual_lines = read_actual_lines()
        assert actual_lines == expected_lines, (
            "The compiled Rust program did not correctly process unseen configuration, "
            "file sizes, strict quota boundaries, or username sorting.\n"
            f"Expected:\n{chr(10).join(expected_lines)}\n\n"
            f"Actual:\n{chr(10).join(actual_lines)}"
        )
    finally:
        with open(FSTAB, "wb") as f:
            f.write(saved_fstab)
        with open(PASSWD, "wb") as f:
            f.write(saved_passwd)
        if log_existed:
            with open(LOG, "wb") as f:
                f.write(saved_log)
        elif os.path.lexists(LOG):
            os.remove(LOG)
        shutil.rmtree(root, ignore_errors=True)
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
