mkdir -p /logs/verifier

cat << 'GO_EOF' > /tmp/inspect_process_dataset.go
package main

import (
    "fmt"
    "go/ast"
    "go/parser"
    "go/token"
    "os"
)

func main() {
    path := os.Args[len(os.Args)-1]
    fset := token.NewFileSet()
    file, err := parser.ParseFile(fset, path, nil, 0)
    if err != nil {
        fmt.Fprintln(os.Stderr, err)
        os.Exit(1)
    }

    var hasGo, hasFlock, hasLockEX, hasRename, hasTempDir bool
    ast.Inspect(file, func(n ast.Node) bool {
        switch x := n.(type) {
        case *ast.GoStmt:
            hasGo = true
        case *ast.CallExpr:
            if sel, ok := x.Fun.(*ast.SelectorExpr); ok {
                switch sel.Sel.Name {
                case "Flock":
                    hasFlock = true
                case "Rename", "Renameat", "Renameat2":
                    hasRename = true
                case "MkdirTemp", "TempDir":
                    hasTempDir = true
                }
            }
        case *ast.SelectorExpr:
            if x.Sel.Name == "LOCK_EX" {
                hasLockEX = true
            }
        }
        return true
    })

    checks := []struct {
        ok  bool
        msg string
    }{
        {hasGo, "no Go goroutine statement found"},
        {hasFlock && hasLockEX, "no exclusive OS-level Flock operation found"},
        {hasRename, "no atomic rename operation found"},
        {hasTempDir, "no standard temporary-directory creation call found"},
    }
    for _, check := range checks {
        if !check.ok {
            fmt.Fprintln(os.Stderr, check.msg)
            os.Exit(1)
        }
    }
}
GO_EOF

cat << 'TEST_EOF' > /tmp/test_final_state.py
import io
import os
import pathlib
import secrets
import subprocess
import tarfile
import zipfile


def test_final_summary_file():
    """Preserve the original final-state assertions."""
    final_summary_path = "/home/user/final_summary.txt"
    go_program_path = "/home/user/process_dataset.go"

    assert os.path.isfile(go_program_path), f"Go program missing: {go_program_path}"
    assert os.path.isfile(final_summary_path), f"Final summary file missing: {final_summary_path}"

    expected_lines = [
        "sensor_A1.txt:42",
        "sensor_A2.txt:15",
        "sensor_B1.txt:99",
        "sensor_B2.txt:7"
    ]
    with open(final_summary_path, "r") as f:
        actual_lines = [line.strip() for line in f if line.strip()]

    assert actual_lines == expected_lines, (
        f"Contents of {final_summary_path} do not match the expected sorted output.\n"
        f"Expected: {expected_lines}\nActual: {actual_lines}"
    )


def test_go_program_has_required_mechanisms():
    result = subprocess.run(
        ["go", "run", "/tmp/inspect_process_dataset.go", "--", "/home/user/process_dataset.go"],
        text=True, capture_output=True, timeout=30
    )
    assert result.returncode == 0, result.stdout + result.stderr


def make_tar(entries):
    data = io.BytesIO()
    with tarfile.open(fileobj=data, mode="w:gz") as tf:
        for archive_name, value in entries:
            payload = (str(value) + "\n").encode()
            info = tarfile.TarInfo(archive_name)
            info.size = len(payload)
            info.mode = 0o644
            tf.addfile(info, io.BytesIO(payload))
    return data.getvalue()


def test_compiled_program_processes_fresh_archives():
    source = "/home/user/process_dataset.go"
    binary = "/tmp/process_dataset_verifier_bin"
    build = subprocess.run(
        ["go", "build", "-o", binary, source],
        text=True, capture_output=True, timeout=45
    )
    assert build.returncode == 0, "Go program did not compile:\n" + build.stdout + build.stderr

    # Values are generated by the verifier so a hardcoded summary cannot pass.
    records = [
        ("group_c/readings/sensor_C1.txt", secrets.randbelow(900000) + 100000),
        ("group_c/readings/sensor_C2.txt", secrets.randbelow(900000) + 100000),
        ("group_d/sensor_D1.txt", secrets.randbelow(900000) + 100000),
        ("group_d/deeper/sensor_D2.txt", secrets.randbelow(900000) + 100000),
        ("group_e/sensor_E1.txt", secrets.randbelow(900000) + 100000),
    ]
    first = records[:2]
    second = records[2:]

    dataset = "/home/user/raw_data/dataset.zip"
    with zipfile.ZipFile(dataset, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("nested/level_one/batch_c.tar.gz", make_tar(first))
        zf.writestr("another/level/two/batch_de.tar.gz", make_tar(second))
        zf.writestr("another/ignored.bin", b"not sensor data")

    final_path = "/home/user/final_summary.txt"
    log_path = "/home/user/aggregated_log.tmp"
    for path in (final_path, log_path):
        try:
            os.remove(path)
        except FileNotFoundError:
            pass

    # A pre-existing destination lets us verify that the final file was replaced,
    # rather than merely opened and truncated in place.
    with open(final_path, "w") as f:
        f.write("sentinel\n")
    old_inode = os.stat(final_path).st_ino

    run = subprocess.run(
        [binary], cwd="/home/user", text=True, capture_output=True, timeout=30
    )
    assert run.returncode == 0, "Compiled program failed:\n" + run.stdout + run.stderr

    assert os.path.isfile(final_path), "Program did not generate final_summary.txt"
    assert os.stat(final_path).st_ino != old_inode, (
        "final_summary.txt was modified in place instead of being atomically replaced"
    )

    expected = sorted(f"{pathlib.PurePosixPath(name).name}:{value}" for name, value in records)
    with open(final_path) as f:
        actual = [line.strip() for line in f if line.strip()]
    assert actual == expected, f"Fresh archive output mismatch. Expected {expected}, got {actual}"

    assert os.path.isfile(log_path), "Shared aggregated_log.tmp was not created"
    with open(log_path) as f:
        logged = [line.strip() for line in f if line.strip()]
    assert sorted(logged) == expected, (
        "The shared log does not contain exactly one entry for every extracted sensor file"
    )
TEST_EOF

