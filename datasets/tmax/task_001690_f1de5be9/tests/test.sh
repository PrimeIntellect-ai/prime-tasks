def test_run_telemetry_sh_modified_and_functional():
    wrapper = '/home/user/run_telemetry.sh'
    collector = '/home/user/collect.sh'
    marker = '/tmp/verifier_collect_env'
    assert os.path.isfile(wrapper), f'{wrapper} is missing.'

    with open(wrapper, 'r') as f:
        content = f.read()

    # Preserve the original textual assertions.
    assert 'HOME="/home/user"' in content or 'HOME=/home/user' in content, \
        f'{wrapper} does not set HOME to /home/user.'
    assert '/sbin' in content and '/usr/sbin' in content, \
        f'{wrapper} does not include /sbin and /usr/sbin in PATH.'

    # Replace collect.sh briefly with an instrumented collector. This proves the
    # wrapper actually invokes it with the required runtime environment.
    with open(collector, 'rb') as f:
        original = f.read()
    original_mode = stat.S_IMODE(os.stat(collector).st_mode)
    try:
        with open(collector, 'w') as f:
            f.write('#!/bin/bash\nprintf \'%s\\n%s\\n\' "$HOME" "$PATH" > ' + marker + '\n')
        os.chmod(collector, 0o755)
        if os.path.exists(marker):
            os.unlink(marker)
        subprocess.run([wrapper], check=True, timeout=15,
                       env={'HOME': '/tmp/verifier-hostile-home',
                            'PATH': '/usr/bin:/bin'})
    finally:
        with open(collector, 'wb') as f:
            f.write(original)
        os.chmod(collector, original_mode)

    assert os.path.isfile(marker), 'run_telemetry.sh did not invoke collect.sh.'
    with open(marker, 'r') as f:
        values = f.read().splitlines()
    assert len(values) >= 2
    assert values[0] == '/home/user', 'Wrapper did not set HOME at runtime.'
    path_parts = values[1].split(':')
    assert '/sbin' in path_parts and '/usr/sbin' in path_parts, \
        'Wrapper PATH does not contain /sbin and /usr/sbin at runtime.'

    # Run the real collector from a hostile parent environment and require the
    # exact requested output file, rather than accepting a similarly named file.
    log_dir = '/home/user/logs'
    log_path = '/home/user/logs/telemetry.log'
    os.makedirs(log_dir, exist_ok=True)
    if os.path.exists(log_path):
        os.unlink(log_path)
    subprocess.run([wrapper], check=True, timeout=15,
                   env={'HOME': '/tmp/verifier-hostile-home',
                        'PATH': '/usr/bin:/bin'})
    assert os.path.isfile(log_path), f'{log_path} was not generated by the wrapper.'
    with open(log_path, 'r') as f:
        log_content = f.read()
    assert re.search(r'^Telemetry collected at .+', log_content, re.MULTILINE), \
        'The real collector did not write telemetry output.'
    assert 'Network command failed' not in log_content, \
        'telemetry.log contains Network command failed, meaning PATH was not fixed.'


def test_extract_routes_sh_exists_and_executes_dynamically():
    script = '/home/user/extract_routes.sh'
    config = '/home/user/net_config.ini'
    routes = '/home/user/routes.txt'
    assert os.path.isfile(script), f'{script} is missing.'
    with open(script, 'rb') as f:
        assert b'\x00' not in f.read(), f'{script} is not a text bash script.'

    with open(config, 'rb') as f:
        original_config = f.read()

    suffix = uuid.uuid4().hex[:8]
    iface1 = 'test' + suffix
    iface2 = 'wan' + suffix
    gateway1 = f'198.51.100.{int(suffix[:2], 16) % 200 + 1}'
    gateway2 = f'203.0.113.{int(suffix[2:4], 16) % 200 + 1}'
    dynamic_config = f'''[{iface1}]
address=10.10.10.10
gateway={gateway1}

[no_gateway_{suffix}]
address=192.0.2.20

[{iface2}]
gateway={gateway2}
'''

    try:
        with open(config, 'w') as f:
            f.write(dynamic_config)
        if os.path.exists(routes):
            os.unlink(routes)
        subprocess.run(['/bin/bash', script], check=True, timeout=15)
        assert os.path.isfile(routes), f'{script} did not generate {routes}.'
        with open(routes, 'r') as f:
            dynamic_lines = [line.strip() for line in f if line.strip()]
        expected_dynamic = [f'{iface1}:{gateway1}', f'{iface2}:{gateway2}']
        assert dynamic_lines == expected_dynamic, \
            f'{script} did not parse the supplied configuration: {dynamic_lines}'
    finally:
        with open(config, 'wb') as f:
            f.write(original_config)

    # Re-run against the original input and preserve the original routes check.
    subprocess.run(['/bin/bash', script], check=True, timeout=15)
    assert os.path.isfile(routes), f'{routes} is missing.'
    with open(routes, 'r') as f:
        lines = [line.strip() for line in f if line.strip()]
    expected = ['eth0:10.0.0.1', 'wlan0:172.16.0.1']
    assert lines == expected, \
        f'{routes} does not contain the correct routes. Expected {expected}, got {lines}.'


def _target_block_directives(content, target):
    # Remove comments before interpreting blocks, so directives in comments do
    # not satisfy the test.
    cleaned_lines = [line.split('#', 1)[0] for line in content.splitlines()]
    blocks = []
    header = None
    body = []
    for raw in cleaned_lines:
        line = raw.strip()
        if header is None:
            if '{' in line:
                before, after = line.split('{', 1)
                header = before.strip()
                body = [after]
        else:
            if '}' in line:
                before, _ = line.split('}', 1)
                body.append(before)
                blocks.append((header, body))
                header, body = None, []
            else:
                body.append(line)

    for block_header, block_body in blocks:
        try:
            targets = shlex.split(block_header)
        except ValueError:
            continue
        if target in targets:
            parsed = []
            for line in block_body:
                try:
                    tokens = shlex.split(line)
                except ValueError:
                    continue
                if tokens:
                    parsed.append(tokens)
            return parsed
    return None


def test_logrotate_conf_is_active_and_valid():
    path = '/home/user/logrotate.conf'
    target = '/home/user/logs/telemetry.log'
    assert os.path.isfile(path), f'{path} is missing.'
    with open(path, 'r') as f:
        content = f.read()

    # Preserve the original assertions.
    assert target in content, 'logrotate.conf does not target telemetry.log'
    for directive in ['daily', 'rotate 4', 'compress', 'missingok']:
        pattern = re.compile(r'\b' + directive.replace(' ', r'\s+') + r'\b')
        assert pattern.search(content), f'logrotate.conf is missing directive: {directive}'

    directives = _target_block_directives(content, target)
    assert directives is not None, 'No active logrotate block targets telemetry.log.'
    names = [tokens[0] for tokens in directives]
    assert 'daily' in names, 'The telemetry block lacks an active daily directive.'
    assert not any(x in names for x in ('hourly', 'weekly', 'monthly', 'yearly')), \
        'The telemetry block contains a conflicting rotation interval.'
    rotate_values = [tokens[1] for tokens in directives
                     if tokens[0] == 'rotate' and len(tokens) >= 2]
    assert rotate_values and rotate_values[-1] == '4', \
        'The effective rotate directive is not rotate 4.'
    assert 'compress' in names and 'nocompress' not in names, \
        'Compression is not actively enabled for telemetry.log.'
    assert 'missingok' in names and 'nomissingok' not in names, \
        'missingok is not actively enabled for telemetry.log.'

    # Ask logrotate itself to parse the submitted configuration.
    with tempfile.TemporaryDirectory() as td:
        state = os.path.join(td, 'state')
        result = subprocess.run(
            ['logrotate', '-d', '-s', state, path],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, timeout=15)
        assert result.returncode == 0, \
            'logrotate rejected logrotate.conf:\n' + result.stdout


