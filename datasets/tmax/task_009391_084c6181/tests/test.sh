#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
# test_final_state.py

import os
import csv
import math
import subprocess

RAW_FILE = '/home/user/raw_sensor.csv'
SOURCE_FILE = '/home/user/filter.c'
EXEC_FILE = '/home/user/filter_exec'
OUTPUT_FILE = '/home/user/smoothed_sensor.csv'
MSE_FILE = '/home/user/mse.txt'


def compute_expected(raw_file=RAW_FILE):
    x = 20.0
    p = 5.0
    r = 2.0
    q = 0.1

    expected_rows = []
    mse_sum = 0.0
    count = 0

    with open(raw_file, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            time_val = float(row['Time'])
            measurement = float(row['Measurement'])

            # Predict
            x_pred = x
            p_pred = p + q

            # Update
            k = p_pred / (p_pred + r)
            x = x_pred + k * (measurement - x_pred)
            p = (1.0 - k) * p_pred

            expected_rows.append((time_val, measurement, x))
            mse_sum += (measurement - x) ** 2
            count += 1

    mse = mse_sum / count if count > 0 else 0.0
    return expected_rows, mse


def remove_generated_outputs():
    for path in (OUTPUT_FILE, MSE_FILE):
        try:
            os.remove(path)
        except FileNotFoundError:
            pass


def run_filter():
    result = subprocess.run(
        [EXEC_FILE],
        cwd='/home/user',
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=15,
    )
    assert result.returncode == 0, (
        f'filter_exec exited with status {result.returncode}. stderr: {result.stderr}'
    )


def validate_generated_files(expected_rows, expected_mse):
    assert os.path.exists(OUTPUT_FILE), f'The file {OUTPUT_FILE} was not generated by filter_exec.'
    with open(OUTPUT_FILE, 'r') as f:
        reader = csv.reader(f)
        header = next(reader, None)
        assert header == ['Time', 'Measurement', 'Smoothed'], f'Incorrect header in {OUTPUT_FILE}.'
        output_rows = list(reader)

    assert len(output_rows) == len(expected_rows), 'Output file does not have the same number of rows as the input file.'
    for i, (out_row, exp_row) in enumerate(zip(output_rows, expected_rows)):
        assert len(out_row) == 3, f'Row {i+1} does not have exactly 3 columns.'
        out_time, out_meas, out_smooth = map(float, out_row)
        exp_time, exp_meas, exp_smooth = exp_row
        assert math.isclose(out_time, exp_time, rel_tol=1e-4, abs_tol=1e-4), f'Row {i+1}: Time mismatch.'
        assert math.isclose(out_meas, exp_meas, rel_tol=1e-4, abs_tol=1e-4), f'Row {i+1}: Measurement mismatch.'
        assert math.isclose(out_smooth, exp_smooth, rel_tol=1e-4, abs_tol=1e-4), f'Row {i+1}: Smoothed value mismatch.'

    assert os.path.exists(MSE_FILE), f'The file {MSE_FILE} was not generated by filter_exec.'
    with open(MSE_FILE, 'r') as f:
        content = f.read().strip()
    try:
        actual_mse = float(content)
    except ValueError:
        assert False, f'Content of {MSE_FILE} is not a valid float.'
    assert math.isclose(actual_mse, expected_mse, rel_tol=1e-4, abs_tol=1e-4), (
        f'MSE value mismatch. Expected {expected_mse:.4f}, got {actual_mse:.4f}.'
    )


def test_filter_c_exists():
    assert os.path.exists(SOURCE_FILE), 'The file /home/user/filter.c does not exist.'


def test_compile_and_execute_filter_c():
    assert os.path.isfile(SOURCE_FILE), '/home/user/filter.c is not a regular file.'
    try:
        os.remove(EXEC_FILE)
    except FileNotFoundError:
        pass

    build = subprocess.run(
        ['gcc', '-std=c11', '-O2', SOURCE_FILE, '-lm', '-o', EXEC_FILE],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=30,
    )
    assert build.returncode == 0, f'filter.c did not compile successfully: {build.stderr}'
    assert os.path.isfile(EXEC_FILE), 'Compilation did not create /home/user/filter_exec.'
    assert os.access(EXEC_FILE, os.X_OK), '/home/user/filter_exec is not executable.'
    with open(EXEC_FILE, 'rb') as f:
        assert f.read(4) == b'\x7fELF', '/home/user/filter_exec is not a compiled ELF executable.'

    with open(RAW_FILE, 'rb') as f:
        original_raw = f.read()

    try:
        with open(RAW_FILE, 'r', newline='') as f:
            original_rows = list(csv.DictReader(f))

        # Use an altered, verifier-derived data set to ensure the compiled C
        # artifact really reads and processes its input rather than relying on
        # previously generated output files.
        with open(RAW_FILE, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(['Time', 'Measurement'])
            for i, row in enumerate(original_rows):
                measurement = float(row['Measurement']) + ((i % 9) - 4) * 0.137
                writer.writerow([row['Time'], f'{measurement:.4f}'])

        challenge_rows, challenge_mse = compute_expected()
        remove_generated_outputs()
        run_filter()
        validate_generated_files(challenge_rows, challenge_mse)
    finally:
        with open(RAW_FILE, 'wb') as f:
            f.write(original_raw)
        remove_generated_outputs()
        run_filter()


def test_smoothed_sensor_csv():
    output_file = '/home/user/smoothed_sensor.csv'
    assert os.path.exists(output_file), f'The file {output_file} does not exist.'

    expected_rows, _ = compute_expected()

    with open(output_file, 'r') as f:
        reader = csv.reader(f)
        header = next(reader, None)
        assert header == ['Time', 'Measurement', 'Smoothed'], f'Incorrect header in {output_file}.'

        output_rows = list(reader)
        assert len(output_rows) == len(expected_rows), 'Output file does not have the same number of rows as the input file.'

        for i, (out_row, exp_row) in enumerate(zip(output_rows, expected_rows)):
            assert len(out_row) == 3, f'Row {i+1} does not have exactly 3 columns.'

            out_time = float(out_row[0])
            out_meas = float(out_row[1])
            out_smooth = float(out_row[2])

            exp_time, exp_meas, exp_smooth = exp_row

            assert math.isclose(out_time, exp_time, rel_tol=1e-4, abs_tol=1e-4), f'Row {i+1}: Time mismatch.'
            assert math.isclose(out_meas, exp_meas, rel_tol=1e-4, abs_tol=1e-4), f'Row {i+1}: Measurement mismatch.'
            assert math.isclose(out_smooth, exp_smooth, rel_tol=1e-4, abs_tol=1e-4), f'Row {i+1}: Smoothed value mismatch. Expected {exp_smooth:.4f}, got {out_smooth:.4f}.'


def test_mse_txt():
    mse_file = '/home/user/mse.txt'
    assert os.path.exists(mse_file), f'The file {mse_file} does not exist.'

    _, expected_mse = compute_expected()

    with open(mse_file, 'r') as f:
        content = f.read().strip()

    try:
        actual_mse = float(content)
    except ValueError:
        assert False, f'Content of {mse_file} is not a valid float.'

    assert math.isclose(actual_mse, expected_mse, rel_tol=1e-4, abs_tol=1e-4), f'MSE value mismatch. Expected {expected_mse:.4f}, got {actual_mse:.4f}.'
TEST_EOF

if python3 -m pytest --noconftest -c /dev/null -p no:cacheprovider /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
