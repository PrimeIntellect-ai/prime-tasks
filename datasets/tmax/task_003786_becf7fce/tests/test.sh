#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import os
import re
import shutil
import stat
import subprocess
import tempfile

SOURCE = b'''#include <stdio.h>\n#include <stdlib.h>\n#include <math.h>\n\ndouble f(double t) {\n    return exp(-t) * sin(t);\n}\n\nint main(int argc, char *argv[]) {\n    if (argc != 2) {\n        return 1;\n    }\n    double x = atof(argv[1]);\n    if (x <= 0) {\n        printf("0.000000\\n");\n        return 0;\n    }\n    int n = 1000;\n    double h = x / n;\n    double sum = 0.5 * (f(0) + f(x));\n    for (int i = 1; i < n; i++) {\n        sum += f(i * h);\n    }\n    printf("%.8f\\n", sum * h);\n    return 0;\n}\n'''

BINARY = "/home/user/thermal_sim"
SCRIPT = "/home/user/solve_time.sh"
RESULT = "/home/user/result.txt"
SOURCE_PATH = "/home/user/thermal_sim.c"


def run_script():
    return subprocess.run(
        [SCRIPT], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True, timeout=30
    )


def test_compiled_binary_exists():
    """Test that the C program was compiled to the specified path and is executable."""
    assert os.path.isfile(BINARY), f"Compiled binary not found at {BINARY}"
    assert os.access(BINARY, os.X_OK), f"Compiled binary at {BINARY} is not executable"

    with open(SOURCE_PATH, "rb") as f:
        assert f.read() == SOURCE, "The supplied C source was modified"

    with tempfile.TemporaryDirectory() as td:
        reference = os.path.join(td, "thermal_sim")
        subprocess.run(
            ["gcc", "-O3", SOURCE_PATH, "-o", reference, "-lm"],
            check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=30
        )
        with open(BINARY, "rb") as actual, open(reference, "rb") as expected:
            assert actual.read() == expected.read(), (
                "thermal_sim is not the binary produced from the supplied source "
                "using gcc -O3 and -lm"
            )


def test_bash_script_exists_and_executable():
    """Test that the bash script exists and is executable."""
    assert os.path.isfile(SCRIPT), f"Bash script not found at {SCRIPT}"
    assert os.access(SCRIPT, os.X_OK), f"Bash script at {SCRIPT} is not executable"
    with open(SCRIPT, "rb") as f:
        first_line = f.readline().decode("utf-8", "replace")
    assert "bash" in first_line, "solve_time.sh must be a Bash script"


def test_result_file_content():
    """Test that the result file exists and contains the correct formatted value."""
    assert os.path.isfile(RESULT), f"Result file not found at {RESULT}"
    with open(RESULT, "r") as f:
        content = f.read().strip()
    assert content == "1.0136", f"Expected result '1.0136', but got '{content}'"


def test_script_generates_real_result():
    """The checked result must actually be generated by executing the script."""
    if os.path.exists(RESULT):
        os.unlink(RESULT)
    proc = run_script()
    assert proc.returncode == 0, f"solve_time.sh failed: {proc.stderr}"
    assert os.path.isfile(RESULT), "solve_time.sh did not create result.txt"
    with open(RESULT, "r") as f:
        content = f.read().strip()
    assert content == "1.0136", f"Expected generated result '1.0136', but got '{content}'"


def test_five_newton_iterations_with_central_difference():
    """Exercise the script against an instrumented nonlinear thermal-load program."""
    backup = BINARY + ".verifier-backup"
    log = "/tmp/thermal_sim_calls.log"
    if os.path.exists(log):
        os.unlink(log)
    shutil.copy2(BINARY, backup)

    wrapper = '''#!/usr/bin/python3
import sys
x = float(sys.argv[1])
with open("/tmp/thermal_sim_calls.log", "a") as f:
    f.write("%.17g\\n" % x)
print("%.12f" % (0.25 + (x - 2.0) ** 3))
'''

    proc = None
    generated = None
    calls = []
    try:
        with open(BINARY, "w") as f:
            f.write(wrapper)
        os.chmod(BINARY, 0o755)
        if os.path.exists(RESULT):
            os.unlink(RESULT)

        proc = run_script()
        if os.path.isfile(RESULT):
            with open(RESULT, "r") as f:
                generated = f.read().strip()
        if os.path.isfile(log):
            with open(log, "r") as f:
                calls = [float(line.strip()) for line in f if line.strip()]
    finally:
        shutil.move(backup, BINARY)
        os.chmod(BINARY, 0o755)
        # Leave the required real result in the final container state.
        if os.path.exists(RESULT):
            os.unlink(RESULT)
        restore = run_script()
        assert restore.returncode == 0, f"Could not restore real result: {restore.stderr}"

    assert proc is not None and proc.returncode == 0, (
        "solve_time.sh failed with the instrumented binary: " +
        (proc.stderr if proc is not None else "not executed")
    )
    assert generated is not None, "solve_time.sh did not create result.txt"
    assert re.fullmatch(r"-?[0-9]+\.[0-9]{4}", generated), (
        "result.txt must contain exactly four decimal places"
    )

    # Mirror five Newton updates. The wrapper rounds every binary result to the
    # same 12 decimal places it prints, just as the script receives it.
    x = 1.0
    required_calls = []
    for _ in range(5):
        required_calls.extend((x, x + 0.001, x - 0.001))

        def F(v):
            printed = float(f"{0.25 + (v - 2.0) ** 3:.12f}")
            return printed - 0.25

        derivative = (F(x + 0.001) - F(x - 0.001)) / 0.002
        x = x - F(x) / derivative

    assert generated == f"{x:.4f}", (
        f"Expected five Newton-Raphson iterations to produce {x:.4f}, "
        f"but got {generated}"
    )

    assert len(calls) >= 15, "The script did not execute the binary for all five iterations"
    unmatched = list(calls)
    for expected in required_calls:
        candidates = [
            (abs(value - expected), i)
            for i, value in enumerate(unmatched)
            if abs(value - expected) <= 0.0002
        ]
        assert candidates, (
            f"Missing thermal_sim evaluation near {expected:.10f}; each iteration "
            "must evaluate F(x), F(x+0.001), and F(x-0.001)"
        )
        _, index = min(candidates)
        unmatched.pop(index)

    with open(RESULT, "r") as f:
        assert f.read().strip() == "1.0136"
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
