import os
import re
import secrets
import socket
import subprocess
import urllib.parse
import pytest

WORKSPACE = "/home/user/workspace"
BINARY = os.path.join(WORKSPACE, "sanitizer")
SOURCE = os.path.join(WORKSPACE, "sanitizer.c")


def run_case(binary, raw, expected_rc, expected_output):
    proc = subprocess.run(
        [binary], input=raw, capture_output=True, timeout=5, check=False
    )
    assert proc.returncode == expected_rc, (
        f"{binary} returned {proc.returncode}, expected {expected_rc}, "
        f"for input {raw!r}; stderr={proc.stderr!r}"
    )
    allowed = {expected_output, expected_output + b"\n", expected_output + b"\r\n"}
    assert proc.stdout in allowed, (
        f"{binary} printed {proc.stdout!r}, expected exactly "
        f"{expected_output!r} (optionally followed by one newline)"
    )


@pytest.fixture(scope="session")
def rebuilt_binary(tmp_path_factory):
    out = tmp_path_factory.mktemp("build") / "sanitizer-from-source"
    proc = subprocess.run(
        ["gcc", "-std=c11", "-O2", "-Wall", "-Wextra", SOURCE, "-o", str(out)],
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    assert proc.returncode == 0, f"sanitizer.c does not compile as C:\n{proc.stderr}"
    assert out.read_bytes().startswith(b"\x7fELF"), "Rebuilt sanitizer is not an ELF binary"
    return str(out)


def test_binary_exists():
    assert os.path.isfile(BINARY), f"Binary {BINARY} not found."
    assert os.access(BINARY, os.X_OK), f"Binary {BINARY} is not executable."
    with open(BINARY, "rb") as f:
        assert f.read(4) == b"\x7fELF", "sanitizer must be a compiled native binary"
    assert os.path.isfile(SOURCE), f"C source {SOURCE} not found."
    assert not os.path.islink(SOURCE), "sanitizer.c must be a real source file"


def test_config_updated():
    config_path = os.path.join(WORKSPACE, "config.env")
    assert os.path.isfile(config_path), f"{config_path} not found."
    with open(config_path, "r") as f:
        content = f.read()
    assert "FILTER_BIN=/home/user/workspace/sanitizer" in content, "config.env not updated correctly to point to the new binary."

    active = {}
    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        active[key.strip()] = value.strip()
    assert active.get("FILTER_BIN") == BINARY, "The active FILTER_BIN setting is incorrect"


def test_report_exists():
    report_path = os.path.join(WORKSPACE, "test_report.log")
    assert os.path.isfile(report_path), f"{report_path} not found. Did you run the generate_report.sh script?"
    with open(report_path, "r", errors="replace") as f:
        report = f.read()
    assert "Report generated" in report, "test_report.log was not generated by generate_report.sh"


def test_clean_corpus():
    clean_path = "/app/corpus/clean.txt"
    assert os.path.isfile(clean_path), f"{clean_path} not found."

    with open(clean_path, "r") as f:
        lines = [line.strip() for line in f if line.strip()]

    failed_lines = []
    for line in lines:
        expected_decoded = urllib.parse.unquote_plus(line)
        expected_stdout = f"ACCEPTED: {expected_decoded}"

        proc = subprocess.run([BINARY], input=line.encode("utf-8"), capture_output=True)
        stdout = proc.stdout.decode("utf-8", errors="replace").strip()

        if proc.returncode != 0 or stdout != expected_stdout:
            failed_lines.append(line)

    assert not failed_lines, f"{len(failed_lines)} of {len(lines)} clean modified/rejected. Offending lines: {failed_lines[:5]}"


def test_evil_corpus():
    evil_path = "/app/corpus/evil.txt"
    assert os.path.isfile(evil_path), f"{evil_path} not found."

    with open(evil_path, "r") as f:
        lines = [line.strip() for line in f if line.strip()]

    failed_lines = []
    for line in lines:
        proc = subprocess.run([BINARY], input=line.encode("utf-8"), capture_output=True)
        stdout = proc.stdout.decode("utf-8", errors="replace").strip()

        if proc.returncode != 1 or stdout != "REJECTED":
            failed_lines.append(line)

    assert not failed_lines, f"{len(failed_lines)} of {len(lines)} evil bypassed. Offending lines: {failed_lines[:5]}"


def vary_hex_case(encoded):
    def change(match):
        token = match.group(0)
        return token.lower() if secrets.randbelow(2) else token.upper()
    return re.sub(r"%[0-9A-Fa-f]{2}", change, encoded)


def test_unpredictable_url_decoding_and_security_rules(rebuilt_binary):
    nonce = secrets.token_hex(18)
    clean_decoded = [
        nonce,
        f"alpha beta/{nonce}",
        f"punctuation !@$%^&*()_-=,.;:/{nonce}",
        f"dot..safe/{nonce}",
        f"literal-percent-%-value-{nonce}",
        "A" * 4096,
    ]

    clean_cases = []
    for decoded in clean_decoded:
        if len(decoded) == 4096:
            encoded = decoded
        else:
            encoded = vary_hex_case(urllib.parse.quote_plus(decoded, safe=""))
        clean_cases.append((encoded.encode("ascii"), decoded.encode("utf-8")))

    # One URL-decoding pass must not recursively decode a remaining %XX sequence.
    nested = f"nested-%253C-{nonce}"
    nested_expected = urllib.parse.unquote_plus(nested).encode("utf-8")
    clean_cases.append((nested.encode("ascii"), nested_expected))

    evil_cases = []
    for marker in ("<", ">", "../", "\x00"):
        decoded = f"prefix-{nonce}-{marker}-suffix"
        encoded = vary_hex_case(urllib.parse.quote_plus(decoded, safe=""))
        evil_cases.append(encoded.encode("ascii"))

    # Exercise mixed literal and encoded forms at positions unknown before verification.
    evil_cases.extend([
        (nonce + "%3c" + secrets.token_hex(7)).encode("ascii"),
        (secrets.token_hex(9) + "..%2f" + nonce).encode("ascii"),
        (nonce + "%00" + secrets.token_hex(5)).encode("ascii"),
    ])

    for candidate in (BINARY, rebuilt_binary):
        for raw, decoded in clean_cases:
            run_case(candidate, raw, 0, b"ACCEPTED: " + decoded)
        for raw in evil_cases:
            run_case(candidate, raw, 1, b"REJECTED")


def assert_listening(port):
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=2):
            pass
    except OSError as exc:
        pytest.fail(f"Required service is not listening on port {port}: {exc}")


def test_services_remain_running():
    assert_listening(8080)
    assert_listening(8081)

    try:
        with socket.create_connection(("127.0.0.1", 6379), timeout=2) as sock:
            sock.sendall(b"*1\r\n$4\r\nPING\r\n")
            response = sock.recv(128)
    except OSError as exc:
        pytest.fail(f"Redis is not running on port 6379: {exc}")
    assert response.startswith(b"+PONG"), f"Port 6379 did not respond as Redis: {response!r}"
TEST_EOF

