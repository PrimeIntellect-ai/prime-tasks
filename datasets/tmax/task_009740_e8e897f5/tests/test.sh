#!/bin/bash
set -e
mkdir -p /logs/verifier

cat << 'TEST_EOF' > /tmp/test_final_state.py
import glob
import os
import re
import shutil
import subprocess
import tempfile
import uuid


def read_log(log_path):
    with open(log_path, "r") as lf:
        return [line.strip() for line in lf if line.strip()]


def test_corrupted_archives_log():
    log_path = "/home/user/corrupted_archives.log"
    assert os.path.isfile(log_path), f"Log file {log_path} does not exist. Did you run the Rust program?"

    toml_path = "/home/user/project_files.toml"
    assert os.path.isfile(toml_path), f"Config file {toml_path} does not exist."

    with open(toml_path, "r") as f:
        content = f.read()

    # Extract file paths from the TOML configuration
    files_match = re.search(r'files\s*=\s*\[(.*?)\]', content, re.DOTALL)
    assert files_match is not None, "Could not parse 'files' array from TOML."

    file_paths = re.findall(r'"([^"]+)"', files_match.group(1))

    # Recompute the expected corrupted archives
    expected_corrupted = []
    for path in file_paths:
        if not os.path.isfile(path):
            expected_corrupted.append(path)
            continue

        size = os.path.getsize(path)
        if size < 17:
            expected_corrupted.append(path)
            continue

        with open(path, "rb") as bf:
            bf.seek(-17, os.SEEK_END)
            signature = bf.read(17)
            if signature != b"VALID_ARCHIVE_EOF":
                expected_corrupted.append(path)

    expected_corrupted.sort()

    # Read the actual log file generated by the student's program
    log_lines = read_log(log_path)

    assert log_lines == expected_corrupted, (
        f"Contents of {log_path} do not match the expected corrupted archives.\n"
        f"Expected: {expected_corrupted}\n"
        f"Found: {log_lines}"
    )


def test_rust_memmap_program_on_fresh_inputs():
    project = "/home/user/verifier"
    manifest = os.path.join(project, "Cargo.toml")
    src_dir = os.path.join(project, "src")

    assert os.path.isdir(project), "The required Rust project /home/user/verifier does not exist."
    assert os.path.isfile(manifest), "The Rust project is missing Cargo.toml."
    assert os.path.isdir(src_dir), "The Rust project is missing its src directory."

    with open(manifest, "r", encoding="utf-8") as f:
        manifest_text = f.read()
    assert re.search(r'(?m)^\s*memmap2\s*=', manifest_text) or re.search(
        r'(?m)^\s*\[dependencies\.memmap2\]\s*$', manifest_text
    ), "Cargo.toml must declare memmap2 as a dependency."

    rust_files = glob.glob(os.path.join(src_dir, "**", "*.rs"), recursive=True)
    assert rust_files, "No Rust source files were found in the project's src directory."
    source = "\n".join(open(path, "r", encoding="utf-8").read() for path in rust_files)
    assert re.search(r'\bmemmap2\b', source), "The Rust source does not use the memmap2 crate."
    assert re.search(r'\bMmap(?:Mut|Options)?\b', source), (
        "The Rust source does not use a memmap2 mapping type."
    )

    config_path = "/home/user/project_files.toml"
    log_path = "/home/user/corrupted_archives.log"
    with open(config_path, "rb") as f:
        original_config = f.read()
    with open(log_path, "rb") as f:
        original_log = f.read()

    test_dir = tempfile.mkdtemp(prefix="archive_verifier_")
    os.chmod(test_dir, 0o755)
    token = uuid.uuid4().hex
    paths = {
        "invalid": os.path.join(test_dir, f"a_invalid_{token}.bin"),
        "valid": os.path.join(test_dir, f"z_valid_{token}.bin"),
        "short": os.path.join(test_dir, f"m_short_{token}.bin"),
        "trailing": os.path.join(test_dir, f"b_trailing_{token}.bin"),
    }

    try:
        with open(paths["valid"], "wb") as f:
            f.write(os.urandom(89) + b"VALID_ARCHIVE_EOF")
        with open(paths["invalid"], "wb") as f:
            f.write(os.urandom(71) + b"INVALID_ARCHV_EOF")
        with open(paths["short"], "wb") as f:
            f.write(b"too short")
        with open(paths["trailing"], "wb") as f:
            f.write(os.urandom(43) + b"VALID_ARCHIVE_EOF" + b"X")

        configured_paths = [
            paths["valid"], paths["short"], paths["trailing"], paths["invalid"]
        ]
        config = "[archives]\nfiles = [\n" + "".join(
            f'    "{path}",\n' for path in configured_paths
        ) + "]\n"
        with open(config_path, "w", encoding="utf-8") as f:
            f.write(config)

        if os.path.exists(log_path):
            os.remove(log_path)

        env = os.environ.copy()
        env["HOME"] = "/home/user"
        result = subprocess.run(
            ["cargo", "run", "--quiet", "--manifest-path", manifest],
            cwd=project,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=180,
        )
        assert result.returncode == 0, (
            "The Rust program failed when executed on fresh archive inputs.\n"
            f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )
        assert os.path.isfile(log_path), "The executed Rust program did not create the log file."

        expected = sorted([paths["invalid"], paths["short"], paths["trailing"]])
        actual = read_log(log_path)
        assert actual == expected, (
            "The executed Rust program produced an incorrect log for fresh inputs.\n"
            f"Expected: {expected}\nFound: {actual}"
        )
    finally:
        with open(config_path, "wb") as f:
            f.write(original_config)
        with open(log_path, "wb") as f:
            f.write(original_log)
        shutil.rmtree(test_dir, ignore_errors=True)
TEST_EOF

if python3 -m pytest /tmp/test_final_state.py -x --tb=short 2>&1; then
    echo "1" > /logs/verifier/reward.txt
else
    echo "0" > /logs/verifier/reward.txt
fi
